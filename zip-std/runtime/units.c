/* Runtime для единиц измерения (Идея 13). */

#include <stdint.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

typedef enum {
    ZIP_ЕДИНИЦА_БЕЗ_РАЗМЕРНОСТИ = 0,
    ZIP_ЕДИНИЦА_ВРЕМЯ_МС = 1,
    ZIP_ЕДИНИЦА_РАССТОЯНИЕ_М = 2,
    ZIP_ЕДИНИЦА_ВЕС_КГ = 3,
    ZIP_ЕДИНИЦА_БАЙТ = 4,
    ZIP_ЕДИНИЦА_ГЕРЦ = 5,
    ZIP_ЕДИНИЦА_ГРАДУС = 6,
    ZIP_ЕДИНИЦА_ПРОЦЕНТ = 7
} ZipЕдиница;

typedef struct {
    double значение;
    ZipЕдиница единица;
} ZipИзмерение;

ZipИзмерение* zip_создать_измерение(double значение, int64_t единица) {
    ZipИзмерение* и = (ZipИзмерение*)malloc(sizeof(ZipИзмерение));
    if (!и) return NULL;
    и->значение = значение;
    и->единица = (ZipЕдиница)единица;
    return и;
}

int64_t zip_единицы_совместимы(ZipИзмерение* а, ZipИзмерение* б) {
    if (!а || !б) return 0;
    return а->единица == б->единица ? 1 : 0;
}

ZipИзмерение* zip_измерения_сложить(ZipИзмерение* а, ZipИзмерение* б) {
    if (!zip_единицы_совместимы(а, б)) {
        fprintf(stderr, "Ошибка: несовместимые единицы\n");
        return NULL;
    }
    return zip_создать_измерение(а->значение + б->значение, (int64_t)а->единица);
}

ZipИзмерение* zip_измерения_конвертировать(ZipИзмерение* и, int64_t новая_единица) {
    if (!и) return NULL;
    /* MVP: без масштабных коэффициентов — только смена метки. */
    return zip_создать_измерение(и->значение, новая_единица);
}

void zip_измерение_печать(ZipИзмерение* и) {
    if (!и) return;
    const char* имя_единицы = "";
    switch (и->единица) {
        case ZIP_ЕДИНИЦА_ВРЕМЯ_МС: имя_единицы = "мс"; break;
        case ZIP_ЕДИНИЦА_РАССТОЯНИЕ_М: имя_единицы = "м"; break;
        case ZIP_ЕДИНИЦА_ВЕС_КГ: имя_единицы = "кг"; break;
        case ZIP_ЕДИНИЦА_БАЙТ: имя_единицы = "байт"; break;
        case ZIP_ЕДИНИЦА_ГЕРЦ: имя_единицы = "Гц"; break;
        case ZIP_ЕДИНИЦА_ГРАДУС: имя_единицы = "°"; break;
        case ZIP_ЕДИНИЦА_ПРОЦЕНТ: имя_единицы = "%"; break;
        default: имя_единицы = ""; break;
    }
    printf("%.4g %s\n", и->значение, имя_единицы);
}

void zip_измерение_освободить(ZipИзмерение* и) {
    free(и);
}

#ifdef ZIP_UNITS_MAIN
int main(void) {
    ZipИзмерение* задержка = zip_создать_измерение(500.0, ZIP_ЕДИНИЦА_ВРЕМЯ_МС);
    ZipИзмерение* таймаут = zip_создать_измерение(30.0, ZIP_ЕДИНИЦА_ВРЕМЯ_МС);
    ZipИзмерение* путь = zip_создать_измерение(1500.0, ZIP_ЕДИНИЦА_РАССТОЯНИЕ_М);
    ZipИзмерение* масса = zip_создать_измерение(75.5, ZIP_ЕДИНИЦА_ВЕС_КГ);
    ZipИзмерение* общее = zip_измерения_сложить(задержка, таймаут);

    printf("Задержка:\n");
    zip_измерение_печать(задержка);
    printf("Путь:\n");
    zip_измерение_печать(путь);
    printf("Масса:\n");
    zip_измерение_печать(масса);
    printf("Общее время:\n");
    zip_измерение_печать(общее);

    zip_измерение_освободить(задержка);
    zip_измерение_освободить(таймаут);
    zip_измерение_освободить(путь);
    zip_измерение_освободить(масса);
    zip_измерение_освободить(общее);
    return 0;
}
#endif

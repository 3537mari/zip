/* Runtime для итераторов ZIP (Идея 11). */
#include <stdint.h>
#include <stdio.h>
#include <stdlib.h>

typedef struct {
    int64_t* данные; /* массив элементов */
    int64_t длина;
    int64_t позиция; /* текущая позиция */
} ZipИтератор;

/* Создать итератор из сырого массива. */
ZipИтератор* zip_создать_итератор(int64_t* данные, int64_t длина) {
    ZipИтератор* ит = (ZipИтератор*)malloc(sizeof(ZipИтератор));
    if (!ит) return NULL;
    ит->данные = данные;
    ит->длина = длина;
    ит->позиция = 0;
    return ит;
}

/* Проверить: есть ли следующий элемент. */
int64_t zip_есть_следующий(ZipИтератор* ит) {
    if (!ит) return 0;
    return ит->позиция < ит->длина ? 1 : 0;
}

/* Получить следующий элемент и сдвинуть позицию. */
int64_t zip_следующий(ZipИтератор* ит) {
    if (!ит || ит->позиция >= ит->длина) return 0;
    int64_t значение = ит->данные[ит->позиция];
    ит->позиция++;
    return значение;
}

void zip_освободить_итератор(ZipИтератор* ит) {
    free(ит);
}

/* R4: Диапазон как Copy-тип. */
typedef struct {
    int64_t начало;
    int64_t конец;
    int64_t текущий; /* для итерации */
} ZipДиапазон;

ZipДиапазон* zip_создать_диапазон(int64_t начало, int64_t конец) {
    ZipДиапазон* д = (ZipДиапазон*)malloc(sizeof(ZipДиапазон));
    if (!д) return NULL;
    д->начало = начало;
    д->конец = конец;
    д->текущий = начало;
    return д;
}

/* Копирование (для Copy-семантики). */
ZipДиапазон* zip_копировать_диапазон(ZipДиапазон* д) {
    if (!д) return NULL;
    ZipДиапазон* копия = (ZipДиапазон*)malloc(sizeof(ZipДиапазон));
    if (!копия) return NULL;
    копия->начало = д->начало;
    копия->конец = д->конец;
    копия->текущий = д->начало;
    return копия;
}

/* Итерация по диапазону. */
int64_t zip_диапазон_есть_следующий(ZipДиапазон* д) {
    return д && д->текущий < д->конец ? 1 : 0;
}

int64_t zip_диапазон_следующий(ZipДиапазон* д) {
    if (!д || д->текущий >= д->конец) return 0;
    return д->текущий++;
}


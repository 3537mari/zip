//! Верификация владения (Move-семантика / PULSE).

use std::collections::HashSet;
use zip_vm::байткод_v3::{ИнстрV3, ФункцияV3};
use zip_vm::байткод_v3_декодер::декодировать_код;

#[derive(Debug)]
pub enum ОшибкаВладения {
    ИспользованиеПослеПередачи(usize, u32),
    Декод(String),
}

impl std::fmt::Display for ОшибкаВладения {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            Self::ИспользованиеПослеПередачи(i, r) => {
                write!(f, "использование регистра {r} после PULSE (инстр. {i})")
            }
            Self::Декод(s) => write!(f, "декодирование: {s}"),
        }
    }
}

/// Проверка: после `Pulse(из, в)` регистр `из` не читается до новой записи.
pub fn проверить_инструкции(инструкции: &[ИнстрV3]) -> Result<(), ОшибкаВладения> {
    let mut переданы: HashSet<u32> = HashSet::new();

    for (индекс, инструкция) in инструкции.iter().enumerate() {
        match инструкция {
            ИнстрV3::Pulse { из, в } => {
                let из = *из as u32;
                let в = *в as u32;
                if переданы.contains(&из) {
                    return Err(ОшибкаВладения::ИспользованиеПослеПередачи(индекс, из));
                }
                переданы.insert(из);
                переданы.remove(&в);
            }
            ИнстрV3::Store(регистр) => {
                переданы.remove(регистр);
            }
            ИнстрV3::Load(регистр) => {
                if переданы.contains(регистр) {
                    return Err(ОшибкаВладения::ИспользованиеПослеПередачи(индекс, *регистр));
                }
            }
            ИнстрV3::PerfectLock(р) => {
                let р = *р as u32;
                if переданы.contains(&р) {
                    return Err(ОшибкаВладения::ИспользованиеПослеПередачи(индекс, р));
                }
            }
            _ => {}
        }
    }
    Ok(())
}

pub fn проверить_владение(функция: &ФункцияV3) -> Result<(), ОшибкаВладения> {
    let инструкции = декодировать_код(&функция.код)
        .map_err(|е| ОшибкаВладения::Декод(е.to_string()))?;
    проверить_инструкции(&инструкции)
}

//! Система типов для статической верификации ZIPB.

use std::collections::HashMap;
use zip_vm::байткод_v3::{ИнстрV3, ФункцияV3};
use zip_vm::байткод_v3_декодер::декодировать_код;

#[derive(Debug, Clone, PartialEq, Eq)]
pub enum Тип {
    Целое,
    Вещественное,
    Строка,
    Флаг,
    Множество,
    Итератор,
    Нечто(Box<Тип>),
    Ничто,
    Успех(Box<Тип>),
    Ошибка,
    Совершенное(Box<Тип>),
    Неизвестно,
}

impl std::fmt::Display for Тип {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            Self::Целое => write!(f, "Целое"),
            Self::Вещественное => write!(f, "Вещественное"),
            Self::Строка => write!(f, "Строка"),
            Self::Флаг => write!(f, "Флаг"),
            Self::Множество => write!(f, "Множество"),
            Self::Итератор => write!(f, "Итератор"),
            Self::Нечто(t) => write!(f, "Нечто({t})"),
            Self::Ничто => write!(f, "Ничто"),
            Self::Успех(t) => write!(f, "Успех({t})"),
            Self::Ошибка => write!(f, "Ошибка"),
            Self::Совершенное(t) => write!(f, "Совершенное({t})"),
            Self::Неизвестно => write!(f, "Неизвестно"),
        }
    }
}

#[derive(Debug)]
pub enum ОшибкаВерификации {
    ПустойСтек(usize),
    РегистрНеНайден(usize, u32),
    НесовместимыеТипы(usize, Тип, Тип),
    Декод(String),
}

impl std::fmt::Display for ОшибкаВерификации {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            Self::ПустойСтек(i) => write!(f, "пустой стек типов на инструкции {i}"),
            Self::РегистрНеНайден(i, r) => {
                write!(f, "регистр {r} не инициализирован (инстр. {i})")
            }
            Self::НесовместимыеТипы(i, a, b) => {
                write!(f, "несовместимые типы {a} и {b} на инструкции {i}")
            }
            Self::Декод(s) => write!(f, "декодирование: {s}"),
        }
    }
}

fn pop(стек: &mut Vec<Тип>, индекс: usize) -> Result<Тип, ОшибкаВерификации> {
    стек.pop().ok_or(ОшибкаВерификации::ПустойСтек(индекс))
}

fn числовой(т: &Тип) -> bool {
    matches!(т, Тип::Целое | Тип::Вещественное | Тип::Неизвестно)
}

fn арифметика(индекс: usize, а: Тип, б: Тип) -> Result<Тип, ОшибкаВерификации> {
    match (&а, &б) {
        (Тип::Целое, Тип::Целое) => Ok(Тип::Целое),
        (Тип::Вещественное, _) | (_, Тип::Вещественное) if числовой(&а) && числовой(&б) => {
            Ok(Тип::Вещественное)
        }
        (Тип::Неизвестно, _) | (_, Тип::Неизвестно) if числовой(&а) && числовой(&б) => {
            Ok(Тип::Неизвестно)
        }
        _ => Err(ОшибкаВерификации::НесовместимыеТипы(индекс, а, б)),
    }
}

/// Проверка последовательности инструкций (удобно для юнит-тестов).
pub fn проверить_инструкции(инструкции: &[ИнстрV3]) -> Result<(), ОшибкаВерификации> {
    let mut стек: Vec<Тип> = Vec::new();
    let mut регистры: HashMap<u32, Тип> = HashMap::new();

    for (индекс, инструкция) in инструкции.iter().enumerate() {
        match инструкция {
            ИнстрV3::Nop => {}
            ИнстрV3::Pop => {
                pop(&mut стек, индекс)?;
            }
            ИнстрV3::Dup => {
                let т = стек.last().cloned().ok_or(ОшибкаВерификации::ПустойСтек(индекс))?;
                стек.push(т);
            }
            ИнстрV3::Swap => {
                let б = pop(&mut стек, индекс)?;
                let а = pop(&mut стек, индекс)?;
                стек.push(б);
                стек.push(а);
            }
            ИнстрV3::PushI64(_) => стек.push(Тип::Целое),
            ИнстрV3::PushF64(_) => стек.push(Тип::Вещественное),
            ИнстрV3::PushStr(_) => стек.push(Тип::Строка),
            ИнстрV3::PushNull | ИнстрV3::NewNothing => стек.push(Тип::Ничто),
            ИнстрV3::PushTrue | ИнстрV3::PushFalse => стек.push(Тип::Флаг),
            ИнстрV3::Add | ИнстрV3::Sub | ИнстрV3::Mul | ИнстрV3::Div | ИнстрV3::Mod => {
                let б = pop(&mut стек, индекс)?;
                let а = pop(&mut стек, индекс)?;
                стек.push(арифметика(индекс, а, б)?);
            }
            ИнстрV3::Eq | ИнстрV3::Ne => {
                let _б = pop(&mut стек, индекс)?;
                let _а = pop(&mut стек, индекс)?;
                стек.push(Тип::Флаг);
            }
            ИнстрV3::Lt | ИнстрV3::Le | ИнстрV3::Gt | ИнстрV3::Ge => {
                let б = pop(&mut стек, индекс)?;
                let а = pop(&mut стек, индекс)?;
                if !числовой(&а) || !числовой(&б) {
                    return Err(ОшибкаВерификации::НесовместимыеТипы(индекс, а, б));
                }
                стек.push(Тип::Флаг);
            }
            ИнстрV3::Store(регистр) => {
                let т = pop(&mut стек, индекс)?;
                регистры.insert(*регистр, т);
            }
            ИнстрV3::Load(регистр) => {
                let т = регистры
                    .get(регистр)
                    .cloned()
                    .unwrap_or(Тип::Неизвестно);
                стек.push(т);
            }
            ИнстрV3::Jump(_) => {}
            ИнстрV3::JumpIf(_) | ИнстрV3::JumpIfNot(_) => {
                pop(&mut стек, индекс)?;
            }
            ИнстрV3::Call(_) | ИнстрV3::AsyncCall(_) | ИнстрV3::ChoirSpawn(_) => {
                // Арность неизвестна статически без таблицы — допускаем неизвестный результат.
                стек.push(Тип::Неизвестно);
            }
            ИнстрV3::ChoirJoin => {}
            ИнстрV3::Ret => {
                let _ = стек.pop();
            }
            ИнстрV3::CallNative { .. } => {
                стек.push(Тип::Неизвестно);
            }
            ИнстрV3::Pulse { из, в } => {
                let т = регистры
                    .get(&(*из as u32))
                    .cloned()
                    .unwrap_or(Тип::Неизвестно);
                регистры.insert(*в as u32, т);
                регистры.insert(*из as u32, Тип::Ничто);
            }
            ИнстрV3::PerfectLock(р) => {
                let т = регистры
                    .get(&(*р as u32))
                    .cloned()
                    .unwrap_or(Тип::Неизвестно);
                let внутри = match т {
                    Тип::Совершенное(в) => *в,
                    другой => другой,
                };
                регистры.insert(*р as u32, Тип::Совершенное(Box::new(внутри)));
            }
            ИнстрV3::NewSet => стек.push(Тип::Множество),
            ИнстрV3::NewIter => стек.push(Тип::Итератор),
            ИнстрV3::NewSomething => {
                let т = pop(&mut стек, индекс)?;
                стек.push(Тип::Нечто(Box::new(т)));
            }
            ИнстрV3::NewSuccess => {
                let т = pop(&mut стек, индекс)?;
                стек.push(Тип::Успех(Box::new(т)));
            }
            ИнстрV3::NewError => {
                let _ = pop(&mut стек, индекс)?;
                стек.push(Тип::Ошибка);
            }
            ИнстрV3::CheckTag => {
                let _ = pop(&mut стек, индекс)?;
                стек.push(Тип::Флаг);
            }
            ИнстрV3::Print | ИнстрV3::PrintLn | ИнстрV3::PrintI64 => {
                let _ = pop(&mut стек, индекс)?;
                стек.push(Тип::Ничто);
            }
        }
    }
    Ok(())
}

/// Проверка функции ZIPB (декодирует тело).
pub fn проверить_функцию(функция: &ФункцияV3) -> Result<(), ОшибкаВерификации> {
    let инструкции = декодировать_код(&функция.код)
        .map_err(|е| ОшибкаВерификации::Декод(е.to_string()))?;
    проверить_инструкции(&инструкции)
}

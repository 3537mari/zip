// Проверка задач курса
class ПроверкаЗадач {
  constructor() {
    this.задачи = this.загрузить_задачи();
  }

  загрузить_задачи() {
    return {
      1: {
        название: "Hello, World",
        проверка: (код, вывод) =>
          /ПечатьСтроки\s*\(\s*["']Привет,\s*мир!["']\s*\)/.test(код) ||
          String(вывод).includes("Привет, мир!"),
      },
      2: {
        название: "Сложение",
        проверка: (код, вывод) =>
          код.includes("функция") &&
          /сложить/.test(код) &&
          (код.includes("возврат") || String(вывод).includes("5")),
      },
      3: {
        название: "Факториал",
        проверка: (код, вывод) =>
          /факториал/.test(код) &&
          (String(вывод).includes("120") ||
            String(вывод).includes("3628800") ||
            код.includes("возврат")),
      },
      4: {
        название: "Условие",
        проверка: (код) => /если/.test(код) && (/чёт/.test(код) || /иначе/.test(код)),
      },
      5: {
        название: "Цикл",
        проверка: (код) => /пока|для/.test(код),
      },
      6: {
        название: "Массив",
        проверка: (код) => /\[|список|массив/.test(код),
      },
      7: {
        название: "Аннотация",
        проверка: (код) => /@|#аннотация|аннотация/.test(код),
      },
      8: {
        название: "Поток",
        проверка: (код) => />>/.test(код),
      },
      9: {
        название: "XOR-слой",
        проверка: (код) => /создать_слой|слой/.test(код),
      },
      10: {
        название: "API контракт",
        проверка: (код) => /задач|создать|api|функция/.test(код.toLowerCase()),
      },
    };
  }

  проверить(номер_задачи, код, вывод) {
    const задача = this.задачи[номер_задачи];
    if (!задача) {
      return { успех: false, сообщение: "Задача не найдена" };
    }
    try {
      if (задача.проверка(код, вывод)) {
        return { успех: true, сообщение: "✓ Задача решена!" };
      }
      return {
        успех: false,
        сообщение: "✗ Решение не подходит. Попробуйте ещё раз.",
      };
    } catch (e) {
      return { успех: false, сообщение: "Ошибка проверки: " + e.message };
    }
  }
}

const проверка = new ПроверкаЗадач();

async function запустить_и_проверить(номер_задачи) {
  const area = document.querySelector("#код-задачи-" + номер_задачи) ||
    document.querySelector("#код") ||
    document.querySelector("textarea.task-code");
  const код = area ? area.value : "";
  const вывод = typeof compileOnly === "function" ? compileOnly(код) : "";
  if (typeof showResult === "function") showResult(вывод);

  const результат = проверка.проверить(номер_задачи, код, вывод);
  const box = document.querySelector("#результат-задачи-" + номер_задачи) ||
    document.querySelector(".task-result");
  if (box) {
    box.className = "task-result " + (результат.успех ? "ok" : "bad");
    box.textContent = результат.сообщение;
  } else if (typeof showResult === "function") {
    showResult(результат.сообщение + "\n\n" + вывод);
  }

  if (результат.успех && typeof прогресс !== "undefined") {
    прогресс.отметить_задачу(номер_задачи, "решена");
  }
  return результат;
}

window.проверка = проверка;
window.запустить_и_проверить = запустить_и_проверить;

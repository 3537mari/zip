//! Тесты генератора автотестов (Идея 20).

use zipc::генератор_тестов::{ГенераторТестов, КатегорияТеста};
use zipc::{сгенерировать_из_исходника, Регистр, ФункцияПП};

#[test]
fn тест_случайные_тесты() {
    let mut генератор = ГенераторТестов::с_семенем(42);

    let функция = ФункцияПП {
        имя: "сложить".to_string(),
        параметры: vec![Регистр(0), Регистр(1)],
        тест_случай: Some(10),
        тест_диапазон: Some((0, 100)),
        тест_границы: false,
        ..ФункцияПП::default()
    };

    let тесты = генератор.сгенерировать(&функция);
    assert_eq!(тесты.len(), 10);

    for тест in &тесты {
        for арг in &тест.аргументы {
            assert!(*арг >= 0 && *арг <= 100);
        }
    }
}

#[test]
fn тест_граничные_случаи() {
    let mut генератор = ГенераторТестов::новый();

    let функция = ФункцияПП {
        имя: "сложить".to_string(),
        параметры: vec![Регистр(0)],
        тест_случай: Some(5),
        тест_диапазон: Some((0, 100)),
        тест_границы: true,
        ..ФункцияПП::default()
    };

    let тесты = генератор.сгенерировать(&функция);

    // 5 случайных + 3 граничных (0, мин, макс)
    assert!(тесты.len() >= 8);
    assert!(тесты.iter().any(|т| т.категория == КатегорияТеста::Ноль));
    assert!(тесты
        .iter()
        .any(|т| т.категория == КатегорияТеста::Максимум));
}

#[test]
fn тест_детерминизм() {
    let mut г1 = ГенераторТестов::с_семенем(42);
    let mut г2 = ГенераторТестов::с_семенем(42);

    let функция = ФункцияПП {
        имя: "тест".to_string(),
        параметры: vec![Регистр(0)],
        тест_случай: Some(10),
        тест_диапазон: Some((0, 100)),
        тест_границы: false,
        ..ФункцияПП::default()
    };

    let т1 = г1.сгенерировать(&функция);
    let т2 = г2.сгенерировать(&функция);

    for (a, b) in т1.iter().zip(&т2) {
        assert_eq!(a.аргументы, b.аргументы);
    }
}

#[test]
fn тест_аннотация_диапазон_и_границы() {
    let функции = сгенерировать_из_исходника(
        r#"
@тест(случай = 7, диапазон = "0..50", границы = да)
функция сложить(а, б) {
    возврат(а + б)
}
"#,
    )
    .unwrap();
    let ф = функции.iter().find(|ф| ф.имя == "сложить").unwrap();
    assert_eq!(ф.тест_случай, Some(7));
    assert_eq!(ф.тест_диапазон, Some((0, 50)));
    assert!(ф.тест_границы);
}

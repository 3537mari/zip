#[test]
fn тест_шифровать_llvm_zip_crypto() {
    use zipc::сгенерировать_llvm_ir;
    let функции = сгенерировать_из_исходника(
        r#"
@шифровать(алгоритм = "AES-256-GCM")
функция секретная(данные) { возврат(данные) }
функция главная() { возврат(секретная(1)) }
"#,
    )
    .unwrap();
    let ir = сгенерировать_llvm_ir(&функции, "секрет").unwrap();
    assert!(
        ir.contains("aes256_gcm_шифровать") || ir.contains("чистый ZIP"),
        "LLVM IR должен указывать на чистый ZIP AES: {ir}"
    );
    assert!(ir.contains("optnone"));
}


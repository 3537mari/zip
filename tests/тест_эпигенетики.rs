//! Тесты Идеи 2 — эпигенетика (полный набор @-аннотаций).

use zipc::{
    сгенерировать_из_исходника, ВстроеннаяАннотация,
};

fn найти<'a>(функции: &'a [zipc::ФункцияПП], имя: &str) -> &'a zipc::ФункцияПП {
    функции
        .iter()
        .find(|ф| ф.имя == имя)
        .unwrap_or_else(|| panic!("нет функции {}", имя))
}

#[test]
fn тест_реестр_имён() {
    assert_eq!(
        ВстроеннаяАннотация::из_имени("ускорить"),
        Some(ВстроеннаяАннотация::Ускорить)
    );
    assert_eq!(
        ВстроеннаяАннотация::из_имени("кэшировать"),
        Some(ВстроеннаяАннотация::Кэшировать)
    );
    assert_eq!(ВстроеннаяАннотация::из_имени("неведомая"), None);
}

#[test]
fn тест_ускорить() {
    let функции = сгенерировать_из_исходника(
        r#"
@ускорить(уровень = 3)
функция быстрая(х) { возврат(х * 2) }
"#,
    )
    .unwrap();
    let ф = найти(&функции, "быстрая");
    assert_eq!(ф.уровень_оптимизации, 3);
    assert!(ф.агрессивная_оптимизация);
}


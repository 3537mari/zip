//! Покрытие эмиттеров .zipc / .zipb, LLVM IR и нативного ассемблера.

use zipc::байткод_эмиттер;
use zipc::байткод_эмиттер_v3;
use zipc::llvm_ir::сгенерировать_llvm_ir;
use zipc::нативный::скомпилировать_в_ассемблер;
use zipc::сгенерировать_из_исходника;

fn функции(программа: &str) -> Vec<zipc::ФункцияПП> {
    сгенерировать_из_исходника(программа).unwrap_or_else(|е| panic!("{программа}: {е}"))
}

#[test]
fn тест_zipb_магия() {
    let ф = функции("функция главная() { возврат(42) }");
    let байты = байткод_эмиттер_v3::сгенерировать_v3(&ф).unwrap();
    assert!(байты.len() > 8);
    assert_eq!(&байты[0..4], b"ZIPB");
}

#[test]
fn тест_zipc_магия() {
    let ф = функции("функция главная() { возврат(1 + 2) }");
    let байты = байткод_эмиттер::сгенерировать(&ф).unwrap();
    assert!(байты.len() > 8);
    assert_eq!(&байты[0..4], b"ZIPC");
}

#[test]
fn тест_zipb_арифметика_и_сравнения() {
    for п in [
        "функция главная() { возврат(10 - 3) }",
        "функция главная() { возврат(3 * 4) }",
        "функция главная() { возврат(8 / 2) }",
        "функция главная() { возврат(1 == 1) }",
        "функция главная() { возврат(1 != 2) }",
        "функция главная() { возврат(1 < 2) }",
        "функция главная() { возврат(3 > 2) }",
    ] {
        let ф = функции(п);
        assert!(байткод_эмиттер_v3::сгенерировать_v3(&ф).unwrap().len() > 16);
        assert!(байткод_эмиттер::сгенерировать(&ф).unwrap().len() > 16);
    }
}

#[test]
fn тест_zipb_управление() {
    for п in [
        "функция главная() { если (истина) { возврат(1) } иначе { возврат(0) } }",
        "функция главная() { пока (ложь) { прервать } возврат(0) }",
        "функция главная() { для и в 0..3 { продолжить } возврат(0) }",
    ] {
        let ф = функции(п);
        let _ = байткод_эмиттер_v3::сгенерировать_v3(&ф).unwrap();
        let _ = байткод_эмиттер::сгенерировать(&ф).unwrap();
    }
}

#[test]
fn тест_zipb_вызовы_и_строки() {
    let п = r#"
функция сложить(а, б) { возврат(а + б) }
функция главная() {
    ПечатьСтроки("ok")
    возврат(сложить(2, 3))
}
"#;
    let ф = функции(п);
    let b3 = байткод_эмиттер_v3::сгенерировать_v3(&ф).unwrap();
    let b2 = байткод_эмиттер::сгенерировать(&ф).unwrap();
    assert!(b3.len() > 32);
    assert!(b2.len() > 32);
}

#[test]
fn тест_zipb_потоки() {
    for п in [
        "функция главная() { возврат(САПАР(1) >> ЧАТАВ!) }",
        "функция главная() { возврат(САПАР(1) || САПАР(2)) }",
        "функция главная() { возврат(САПАР~) }",
    ] {
        if let Ok(ф) = сгенерировать_из_исходника(п) {
            let _ = байткод_эмиттер_v3::сгенерировать_v3(&ф);
            let _ = байткод_эмиттер::сгенерировать(&ф);
        }
    }
}

#[test]
fn тест_записать_zipb_и_zipc() {
    let ф = функции("функция главная() { возврат(7) }");
    let dir = std::env::temp_dir();
    let p3 = dir.join("zip_cov_test.zipb");
    let p2 = dir.join("zip_cov_test.zipc");
    байткод_эмиттер_v3::записать_zipb(&ф, &p3).unwrap();
    байткод_эмиттер::записать_zipc(&ф, &p2).unwrap();
    assert!(p3.metadata().unwrap().len() > 0);
    assert!(p2.metadata().unwrap().len() > 0);
    let _ = std::fs::remove_file(&p3);
    let _ = std::fs::remove_file(&p2);
}

#[test]
fn тест_llvm_ir_базовый() {
    let ф = функции("функция главная() { возврат(1 + 2 * 3) }");
    let ir = сгенерировать_llvm_ir(&ф, "тест").unwrap();
    assert!(ir.contains("define") || ir.contains(";"));
    assert!(!ir.is_empty());
}

#[test]
fn тест_llvm_ir_управление() {
    let программы = [
        "функция главная() { если (истина) { возврат(1) } иначе { возврат(0) } }",
        "функция главная() { пока (ложь) { прервать } возврат(0) }",
        r#"функция ф(х) { возврат(х) } функция главная() { возврат(ф(5)) }"#,
        r#"функция главная() { ПечатьЧисло(1) возврат(0) }"#,
    ];
    for п in программы {
        let ф = функции(п);
        let ir = сгенерировать_llvm_ir(&ф, "м").unwrap();
        assert!(!ir.is_empty(), "пустой LLVM IR: {п}");
    }
}

#[test]
fn тест_нативный_ассемблер() {
    let asm = скомпилировать_в_ассемблер("функция главная() { возврат(42) }").unwrap();
    assert!(asm.contains("главная") || asm.contains("ret") || asm.len() > 20);
}

#[test]
fn тест_нативный_арифметика() {
    for п in [
        "функция главная() { возврат(2 + 3) }",
        "функция главная() { возврат(10 - 4) }",
        "функция главная() { возврат(3 * 5) }",
        "функция главная() { возврат(8 / 2) }",
        "функция главная() { если (1 == 1) { возврат(1) } иначе { возврат(0) } }",
    ] {
        let asm = скомпилировать_в_ассемблер(п).unwrap();
        assert!(!asm.is_empty(), "пустой asm: {п}");
    }
}

#[test]
fn тест_нативный_несколько_функций() {
    let п = r#"
функция удвоить(х) { возврат(х * 2) }
функция главная() { возврат(удвоить(21)) }
"#;
    let asm = скомпилировать_в_ассемблер(п).unwrap();
    assert!(asm.len() > 40);
}

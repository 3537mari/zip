//! Тесты R2 — comptime.

use zipc::компилятор_времени::{
    свернуть_comptime_вызовы, КомпиляторВремени, ЗначениеВремени,
};
use zipc::{разобрать_исходник, сгенерировать_из_исходника, Узел};

#[test]
fn тест_аннотация_comptime() {
    let д = разобрать_исходник(
        r#"
@comptime
функция вычислить() {
    возврат(2 + 3)
}
"#,
    )
    .unwrap();
    match д {
        Узел::Программа { объявления } => match &объявления[0] {
            Узел::ОпределениеФункции { аннотации, .. } => {
                assert_eq!(аннотации.len(), 1);
                assert_eq!(аннотации[0].имя, "comptime");
            }
            _ => panic!(),
        },
        _ => panic!(),
    }
}

#[test]
fn тест_простая_константа() {
    let исходник = r#"
@comptime
функция вычислить() {
    возврат(2 + 3 * 4)
}

функция главная() {
    ПечатьЧисло(вычислить())
}
"#;
    let mut функции = сгенерировать_из_исходника(исходник).unwrap();
    assert!(функции.iter().any(|ф| ф.имя == "вычислить" && ф.comptime));
    let журнал = свернуть_comptime_вызовы(&mut функции).unwrap();
    assert!(журнал.iter().any(|с| {
        matches!(с.результат, ЗначениеВремени::Целое(14)) // 2+12
    }));
    let главная = функции.iter().find(|ф| ф.имя == "главная").unwrap();
    let есть_вызов = главная.тело.iter().any(|и| {
        matches!(и, zipc::Инструкция::Вызвать { .. })
    });
    assert!(!есть_вызов, "вызов comptime должен быть свёрнут");
    assert!(
        !функции.iter().any(|ф| ф.имя == "вычислить"),
        "comptime-функция удалена после свёртки"
    );
}

#[test]
fn тест_факториал() {
    let исходник = r#"
@comptime
функция факториал(н) {
    если (н < 2) {
        возврат(1)
    } иначе {
        возврат(н * факториал(н - 1))
    }
}

функция главная() {
    ПечатьЧисло(факториал(10))
}
"#;
    let mut функции = сгенерировать_из_исходника(исходник).unwrap();
    let журнал = свернуть_comptime_вызовы(&mut функции).unwrap();
    assert!(
        журнал
            .iter()
            .any(|с| с.имя == "факториал" && с.результат == ЗначениеВремени::Целое(3_628_800)),
        "журнал={:?}",
        журнал
    );
}


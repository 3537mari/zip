#[test]
fn тест_без_comptime_обычная_функция() {
    let исходник = r#"
функция сложить(а, б) {
    возврат(а + б)
}

функция главная() {
    ПечатьЧисло(сложить(2, 3))
}
"#;
    let mut функции = сгенерировать_из_исходника(исходник).unwrap();
    assert!(!функции.iter().any(|ф| ф.comptime));
    let журнал = свернуть_comptime_вызовы(&mut функции).unwrap();
    assert!(журнал.is_empty());
    assert!(функции.iter().any(|ф| ф.имя == "сложить"));
}

#[test]
fn тест_интерпретатор_напрямую() {
    let исходник = r#"
@comptime
функция два() {
    возврат(2)
}
"#;
    let функции = сгенерировать_из_исходника(исходник).unwrap();
    let ф = функции.iter().find(|ф| ф.имя == "два").unwrap();
    let к = КомпиляторВремени::новый(&функции);
    let р = к.выполнить(ф, vec![]).unwrap();
    assert_eq!(р, ЗначениеВремени::Целое(2));
}

#[test]
fn тест_все_ключевые_слова() {
    let слова = [
        "если",
        "иначе",
        "пока",
        "для",
        "в",
        "возврат",
        "прервать",
        "продолжить",
        "функция",
        "тип",
        "модуль",
        "импорт",
        "глагол",
        "агент",
        "поток",
        "Нечто",
        "Ничто",
        "Успех",
        "Ошибка",
        "истина",
        "ложь",
        "и",
        "или",
        "не",
        "печать",
        "печать_строки",
        "печать_число",
    ];
    for слово in слова {
        let т = токены(слово);
        assert!(
            т.len() >= 2,
            "ожидался токен + EOF для {слово}, получено {т:?}"
        );
        assert!(!matches!(т[0], Токен::Слово(_)), "ключевое слово {слово}");
    }
}

#[test]
fn тест_все_64_корня() {
    let таблица = полная_таблица();
    assert!(таблица.len() >= 64, "ожидалось ≥64 корней, {}", таблица.len());
    for корень in таблица {
        let т = токены(&корень.код);
        assert!(
            matches!(т[0], Токен::Корень(_)),
            "код {} не распознан как Корень: {:?}",
            корень.код,
            т[0]
        );
    }
}

#[test]
fn тест_шаблоны_гласных() {
    let шаблоны = [
        "САПАР", "СЕПАР", "СИПРА", "СПОРО", "СУПРА", "СЫПРА", "СЭПРА", "СЮПРА", "СЯПРА",
    ];
    for шаблон in шаблоны {
        let т = токены(шаблон);
        assert!(
            matches!(т[0], Токен::Шаблон(_)),
            "{шаблон} → {:?}",
            т[0]
        );
    }
}

#[test]
fn тест_целые_числа() {
    for (строка, ожидаемое) in [("0", 0i64), ("42", 42), ("9223372036854775807", i64::MAX)] {
        let т = токены(строка);
        match &т[0] {
            Токен::Целое(н) => assert_eq!(*н, ожидаемое),
            другой => panic!("{строка}: {другой:?}"),
        }
    }
}


//! Крайние случаи лексики ZIP — расширение покрытия.

use zipc::корни::полная_таблица;
use zipc::{Лексер, Токен};

fn токены(исходник: &str) -> Vec<Токен> {
    Лексер::новый(исходник)
        .разобрать()
        .unwrap_or_else(|е| panic!("{е}: {исходник:?}"))
        .into_iter()
        .map(|т| т.токен)
        .collect()
}

#[test]
fn тест_пустой_исходник() {
    let т = токены("");
    assert_eq!(т.len(), 1);
    assert!(matches!(т[0], Токен::КонецФайла));
}

#[test]
fn тест_только_пробелы() {
    let т = токены("   \n\t  ");
    assert_eq!(т.len(), 1);
    assert!(matches!(т[0], Токен::КонецФайла));
}

#[test]
fn тест_только_комментарии() {
    let т = токены("// только комментарий\n// ещё один");
    assert_eq!(т.len(), 1);
    assert!(matches!(т[0], Токен::КонецФайла));
}

#[test]
fn тест_shebang() {
    let т = токены("#!/usr/bin/env zipc\nфункция ф() {}");
    assert!(т.iter().any(|x| matches!(x, Токен::Функция)));
}

#[test]
fn тест_операторы_потока() {
    let т = токены(">> >>> || ! ~ = : , ( ) { }");
    assert!(т.iter().any(|x| matches!(x, Токен::Импульс)));
    assert!(т.iter().any(|x| matches!(x, Токен::СетьИмпульс)));
    assert!(т.iter().any(|x| matches!(x, Токен::Хор)));
    assert!(т.iter().any(|x| matches!(x, Токен::Фиксация)));
    assert!(т.iter().any(|x| matches!(x, Токен::Поток)));
    assert!(т.iter().any(|x| matches!(x, Токен::Равно)));
    assert!(т.iter().any(|x| matches!(x, Токен::Двоеточие)));
    assert!(т.iter().any(|x| matches!(x, Токен::Запятая)));
    assert!(т.iter().any(|x| matches!(x, Токен::СкобкаЛевая)));
    assert!(т.iter().any(|x| matches!(x, Токен::СкобкаПравая)));
    assert!(т.iter().any(|x| matches!(x, Токен::ФигурнаяЛевая)));
    assert!(т.iter().any(|x| matches!(x, Токен::ФигурнаяПравая)));
}


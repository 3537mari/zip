//! Тесты Идеи 4 — пластичность (горячие пути).

use zipc::{разобрать_исходник, сгенерировать_из_исходника, Узел};

#[test]
fn тест_лексер_собака() {
    let т = zipc::Лексер::новый("@пластичность").разобрать_токены().unwrap();
    assert!(matches!(т[0], zipc::Токен::Собака));
}

#[test]
fn тест_парсер_аннотации_порог() {
    let исходник = r#"
@пластичность(порог = 100)
функция часто_вызываемая(х) {
    возврат(х + 1)
}
"#;
    let дерево = разобрать_исходник(исходник).unwrap();
    match дерево {
        Узел::Программа { объявления } => {
            assert_eq!(объявления.len(), 1);
            match &объявления[0] {
                Узел::ОпределениеФункции {
                    имя,
                    аннотации,
                    ..
                } => {
                    assert_eq!(имя, "часто_вызываемая");
                    assert_eq!(аннотации.len(), 1);
                    assert_eq!(аннотации[0].имя, "пластичность");
                    match аннотации[0].параметры.get("порог") {
                        Some(Узел::Целое(100)) => {}
                        другой => panic!("ожидался порог=100, получено {:?}", другой),
                    }
                }
                другой => panic!("{:?}", другой),
            }
        }
        другой => panic!("{:?}", другой),
    }
}

#[test]
fn тест_ir_порог_из_аннотации() {
    let исходник = r#"
@пластичность(порог = 100)
функция часто_вызываемая(х) {
    возврат(х + 1)
}

функция главная() {
    возврат(часто_вызываемая(1))
}
"#;
    let функции = сгенерировать_из_исходника(исходник).unwrap();
    let ф = функции
        .iter()
        .find(|ф| ф.имя == "часто_вызываемая")
        .expect("нет функции");
    assert_eq!(ф.порог_горячности, 100);
    assert!(ф.агрессивная_оптимизация);
}

#[test]
fn тест_без_аннотации_порог_по_умолчанию() {
    let исходник = r#"
функция обычная(х) {
    возврат(х)
}
функция главная() {
    возврат(обычная(1))
}
"#;
    let функции = сгенерировать_из_исходника(исходник).unwrap();
    let ф = функции.iter().find(|ф| ф.имя == "обычная").unwrap();
    assert_eq!(ф.порог_горячности, 1000);
    assert!(!ф.агрессивная_оптимизация);
}

#[test]
fn тест_llvm_hot_атрибут() {
    let исходник = r#"
@пластичность(порог = 50)
функция горячая(х) {
    возврат(х * 2)
}
функция главная() {
    возврат(горячая(3))
}
"#;
    let функции = сгенерировать_из_исходника(исходник).unwrap();
    let ir = zipc::llvm_ir::сгенерировать_llvm_ir(&функции, "пласт").unwrap();
    assert!(
        ir.contains("attributes #0 = { hot noinline }"),
        "нет hot attrs: {}",
        &ir[..ir.len().min(500)]
    );
    assert!(ir.contains("hot function") || ir.contains("#0"));
}


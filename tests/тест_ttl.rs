//! Тесты Идеи 12 — временные значения (TTL).

use zipc::промежуток::{сгенерировать_из_исходника, Тип};
use zipc::{разобрать_исходник, Узел};

#[test]
fn тест_ttl_создание() {
    let функции = сгенерировать_из_исходника(
        r#"
функция главная() {
    кэш = эфемерное(42, 5000)
    если (эфемерное_жив(кэш)) {
        ПечатьЧисло(эфемерное_значение(кэш))
    }
    эфемерное_освободить(кэш)
}
"#,
    )
    .unwrap();
    assert!(функции.iter().any(|ф| ф.имя == "эфемерное" || ф.имя == "zip_создать_ttl"));
    assert!(функции.iter().any(|ф| ф.имя == "эфемерное_жив" || ф.имя == "zip_ttl_жив"));
    assert!(функции
        .iter()
        .any(|ф| ф.имя == "эфемерное_значение" || ф.имя == "zip_ttl_получить"));
}

#[test]
fn тест_ttl_тип_эфемерное() {
    let функции = сгенерировать_из_исходника("эфемерное(1, 100)").unwrap();
    let эф = функции
        .iter()
        .find(|ф| ф.имя == "эфемерное" || ф.имя == "zip_создать_ttl")
        .expect("эфемерное");
    assert!(matches!(эф.тип_возврата, Тип::Эфемерное(_, _)));
}

#[test]
fn тест_ttl_истечение_ast() {
    let дерево = разобрать_исходник(
        r#"
функция главная() {
    короткое = эфемерное(99, 1)
    если (эфемерное_жив(короткое)) {
        ПечатьСтроки("Живо")
    } иначе {
        ПечатьСтроки("Истекло")
    }
}
"#,
    )
    .unwrap();
    assert!(matches!(дерево, Узел::Программа { .. }));
}

#[test]
fn тест_ttl_пустое_значение() {
    let функции = сгенерировать_из_исходника(
        r#"
функция главная() {
    к = эфемерное(7, 0)
    ПечатьЧисло(эфемерное_значение(к))
}
"#,
    )
    .unwrap();
    assert!(функции.iter().any(|ф| ф.имя.contains("ttl") || ф.имя.contains("эфемерное")));
}

#[test]
fn тест_ttl_освобождение() {
    let функции = сгенерировать_из_исходника(
        r#"
функция главная() {
    к = эфемерное(1, 1000)
    эфемерное_освободить(к)
    ПечатьЧисло(эфемерное_жив(к))
}
"#,
    )
    .unwrap();
    assert!(функции
        .iter()
        .any(|ф| ф.имя == "эфемерное_освободить" || ф.имя == "zip_ttl_освободить"));
}


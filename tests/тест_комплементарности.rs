#[test]
fn тест_десять_шаблонов_дают_комплементы() {
    let исходник = r#"
СПР = {
    А-А: САПАР, Е-А: СЕПАР, Ё-А: СЁПАР, И-А: СИПРА, О-О: СПОРО,
    У-А: СУПРА, Ы-А: СЫПРА, Э-А: СЭПРА, Ю-А: СЮПРА, Я-А: СЯПРА
}
"#;
    let у = match разобрать_исходник(исходник).unwrap() {
        Узел::Программа { объявления } => объявления.into_iter().next().unwrap(),
        другой => другой,
    };
    match у {
        Узел::ОбъявлениеКорня {
            обратные_шаблоны, ..
        } => {
            assert_eq!(обратные_шаблоны.len(), 10);
            assert!(обратные_шаблоны.iter().any(|(_, и)| и == "РАПАС"));
        }
        _ => panic!(),
    }
}

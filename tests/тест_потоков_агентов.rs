//! Тесты Идей 16–17 — потоки данных и агенты.

use zipc::сгенерировать_из_исходника;
use zipc::{разобрать_исходник, Узел};

#[test]
fn тест_простой_поток() {
    let функции = сгенерировать_из_исходника(
        r#"
функция главная() {
    поток обработка {
        источник = СИПРА(3)
        фильтр умножение = САПАР(2)
        приёмник = ЧАТАВ(результат)
    }
}
"#,
    )
    .unwrap();
    assert!(!функции.is_empty());
}

#[test]
fn тест_поток_с_несколькими_фильтрами() {
    let функции = сгенерировать_из_исходника(
        r#"
функция главная() {
    поток конвейер {
        источник = СИПРА(10)
        фильтр шаг1 = САПАР(5)
        фильтр шаг2 = САПАР(3)
        фильтр шаг3 = САПАР(2)
        приёмник = ЧАТАВ(данные)
    }
}
"#,
    )
    .unwrap();
    assert!(функции.iter().any(|ф| ф.имя == "главная"));
}

#[test]
fn тест_агент_с_состоянием() {
    let функции = сгенерировать_из_исходника(
        r#"
агент Счётчик {
    состояние {
        всего: Целое = 0
        последний: Целое = 0
    }

    функция увеличить() {
        всего = всего + 1
        последний = последний + 1
    }
}

функция главная() {
    счётчик = создать_Счётчик()
    счётчик.увеличить()
    счётчик.увеличить()
    ПечатьЧисло(счётчик.всего)
}
"#,
    )
    .unwrap();
    assert!(функции.iter().any(|ф| ф.имя == "создать_Счётчик"));
    assert!(функции.iter().any(|ф| ф.имя == "Счётчик_увеличить"));
}

#[test]
fn тест_агент_с_реакцией() {
    let функции = сгенерировать_из_исходника(
        r#"
агент Монитор {
    состояние {
        ошибок: Целое = 0
    }

    функция реагировать(событие) {
        если (событие — Ошибка) {
            ошибок = ошибок + 1
        }
    }
}
"#,
    )
    .unwrap();
    assert!(функции.iter().any(|ф| ф.имя == "создать_Монитор"));
    assert!(функции.iter().any(|ф| ф.имя == "Монитор_реагировать"));
}

#[test]
fn тест_парсер_потока() {
    let дерево = разобрать_исходник(
        r#"
поток п {
    источник = СИПРА(1)
    фильтр ф = САПАР(2)
    приёмник = ЧАТАВ(х)
}
"#,
    )
    .unwrap();
    match дерево {
        Узел::Программа { объявления } => {
            assert!(объявления
                .iter()
                .any(|у| matches!(у, Узел::ПотокДанных { .. })));
        }
        _ => panic!("ожидалась программа"),
    }
}

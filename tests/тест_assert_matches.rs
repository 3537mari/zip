#[test]
fn тест_парсер_аннотации_шаблона() {
    let дерево = разобрать_исходник(
        r#"
@проверить_шаблон(шаблон = "Нечто(_)")
функция ф(зн) { возврат(зн) }
"#,
    )
    .unwrap();
    match дерево {
        Узел::Программа { объявления } => {
            let ф = объявления
                .iter()
                .find(|у| matches!(у, Узел::ОпределениеФункции { .. }))
                .unwrap();
            match ф {
                Узел::ОпределениеФункции { аннотации, .. } => {
                    assert_eq!(аннотации[0].имя, "проверить_шаблон");
                }
                _ => unreachable!(),
            }
        }
        _ => panic!("ожидалась программа"),
    }
}

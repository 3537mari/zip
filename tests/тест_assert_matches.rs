//! Тесты R5 — `@проверить_шаблон` (assert_matches!).

use zipc::промежуток::{сгенерировать_из_исходника, разобрать_тег_шаблона};
use zipc::{разобрать_исходник, Узел};

#[test]
fn тест_разобрать_тег() {
    assert_eq!(разобрать_тег_шаблона("Нечто(_)"), Some("Нечто"));
    assert_eq!(разобрать_тег_шаблона("Успех(_)"), Some("Успех"));
    assert_eq!(разобрать_тег_шаблона("Ошибка(_)"), Some("Ошибка"));
    assert_eq!(разобрать_тег_шаблона("Ничто"), Some("Ничто"));
    assert_eq!(разобрать_тег_шаблона("???"), None);
}

#[test]
fn тест_проверить_нечто() {
    let функции = сгенерировать_из_исходника(
        r#"
@проверить_шаблон(шаблон = "Нечто(_)")
функция получить_значение(опциональное) {
    возврат(нечто_значение(опциональное))
}

функция главная() {
    ПечатьЧисло(получить_значение(Нечто(42)))
}
"#,
    )
    .unwrap();
    let ф = функции
        .iter()
        .find(|ф| ф.имя == "получить_значение")
        .expect("получить_значение");
    assert_eq!(ф.проверить_шаблон.as_deref(), Some("Нечто(_)"));
    assert!(функции.iter().any(|ф| ф.имя == "zip_проверить_нечто"));
    assert!(функции.iter().any(|ф| ф.имя == "zip_паника_шаблон"));
}

#[test]

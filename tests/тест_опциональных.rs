//! Тесты Идей 14–15 — Ничто/Нечто + Успех/Ошибка.

use zipc::лексика::{Лексер, Токен};
use zipc::{разобрать_исходник, сгенерировать_из_исходника, Узел};

#[test]
fn тест_лексер_ключевые_слова() {
    for (слово, ожид) in [
        ("Нечто", "Нечто"),
        ("Ничто", "Ничто"),
        ("Успех", "Успех"),
        ("Ошибка", "Ошибка"),
    ] {
        let т = Лексер::новый(слово).разобрать_токены().unwrap();
        assert_eq!(т[0].to_string(), ожид);
    }
}

#[test]
fn тест_лексер_тире() {
    let т = Лексер::новый("рез — Нечто").разобрать_токены().unwrap();
    assert!(т.iter().any(|т| matches!(т, Токен::Тире)));
    assert!(т.iter().any(|т| matches!(т, Токен::Нечто)));
}

#[test]
fn тест_парсер_нечто_ничто() {
    let у = match разобрать_исходник("Нечто(42)").unwrap() {
        Узел::Программа { объявления } => объявления.into_iter().next().unwrap(),
        другой => другой,
    };
    match у {
        Узел::Нечто { значение } => assert_eq!(*значение, Узел::Целое(42)),
        другой => panic!("{:?}", другой),
    }
    let у = match разобрать_исходник("Ничто").unwrap() {
        Узел::Программа { объявления } => объявления.into_iter().next().unwrap(),
        другой => другой,
    };
    assert_eq!(у, Узел::Ничто);
}

#[test]
fn тест_парсер_проверка_типа() {
    let у = match разобрать_исходник("результат — Нечто").unwrap() {
        Узел::Программа { объявления } => объявления.into_iter().next().unwrap(),
        другой => другой,
    };
    match у {
        Узел::ПроверкаТипа { выражение, тип } => {
            assert_eq!(*выражение, Узел::Идентификатор("результат".into()));
            assert_eq!(тип, "Нечто");
        }
        другой => panic!("{:?}", другой),
    }
}

#[test]
fn тест_ir_нечто() {
    let функции = сгенерировать_из_исходника(
        r#"
функция главная() {
    опциональное = Нечто(42)
    возврат(опциональное)
}
"#,
    )
    .unwrap();
    assert!(функции.iter().any(|ф| ф.имя == "zip_создать_нечто"));
}

#[test]
fn тест_ir_проверка() {
    let функции = сгенерировать_из_исходника(
        r#"
функция главная() {
    о = Нечто(1)
    если (о — Нечто) {
        возврат(1)
    }
    возврат(0)
}
"#,
    )
    .unwrap();
    assert!(функции.iter().any(|ф| ф.имя == "zip_проверить_нечто"));
}

#[test]
fn тест_ir_успех_ошибка() {
    let функции = сгенерировать_из_исходника(
        r#"
функция делить(а, б) {
    если (б == 0) {
        возврат(Ошибка("деление на ноль"))
    }
    возврат(Успех(а / б))
}
функция главная() {
    возврат(делить(10, 2))
}
"#,
    )
    .unwrap();
    assert!(функции.iter().any(|ф| ф.имя == "zip_создать_успех"));
    assert!(функции.iter().any(|ф| ф.имя == "zip_создать_ошибку"));
}

#[test]
fn тест_тип_ir_нечто() {
    use zipc::промежуток::Тип;
    let функции = сгенерировать_из_исходника(
        r#"
функция главная() {
    возврат(Нечто(1))
}
"#,
    )
    .unwrap();
    let главная = функции.iter().find(|ф| ф.имя == "главная").unwrap();
    // результат вызова zip_создать_нечто — регистр типа Нечто
    let _ = главная;
    let _ = Тип::Ничто;
}

#[test]
fn тест_ошибка_как_переменная() {
    // строчная «ошибка» не должна быть ключевым словом
    let р = разобрать_исходник("ошибка = 1");
    assert!(р.is_ok(), "{:?}", р.err());
}

#[test]
fn тест_цепочка_проверок_ast() {
    let дерево = разобрать_исходник(
        r#"
функция главная() {
    р = Успех(5)
    если (р — Успех) {
        ПечатьЧисло(успех_значение(р))
    }
    если (р — Ошибка) {
        ПечатьСтроки("нет")
    }
}
"#,
    )
    .unwrap();
    assert!(matches!(дерево, Узел::Программа { .. }));
}

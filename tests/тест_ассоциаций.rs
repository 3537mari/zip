//! Тесты Идеи 6 — ассоциативная память (граф связей).

use zipc::ассоциации::{ГрафАссоциаций, ТипСвязи, ТипСущности};

#[test]
fn тест_граф_создаётся() {
    let граф = ГрафАссоциаций::новый();
    assert!(!граф.сущности.is_empty());
    assert!(граф.сущности.contains_key("СПР"));
}

#[test]
fn тест_ассоциации_спр() {
    let граф = ГрафАссоциаций::новый();
    let ассоциации = граф.ассоциации("СПР");
    assert!(ассоциации.iter().any(|(к, _)| *к == "САПАР"));
    assert!(ассоциации.iter().any(|(к, _)| *к == "СИПРА"));
    assert!(ассоциации.iter().any(|(к, _)| *к == "СПОРО"));
}

#[test]
fn тест_противоположность() {
    let граф = ГрафАссоциаций::новый();
    let противоположные = граф.ассоциации_по_типу("СПР", ТипСвязи::Противоположность);
    assert!(противоположные.iter().any(|с| *с == "РПС"));
}

#[test]
fn тест_поиск_по_категории() {
    let граф = ГрафАссоциаций::новый();
    let математика = граф.по_категории("математика");
    assert!(!математика.is_empty());
    assert!(математика.iter().any(|с| с.имя == "СПР" || с.имя == "САПАР"));
}

#[test]
fn тест_аналог() {
    let граф = ГрафАссоциаций::новый();
    let аналоги = граф.ассоциации_по_типу("САПАР", ТипСвязи::Аналог);
    assert!(аналоги.iter().any(|а| **а == "add"));
    assert!(аналоги.iter().any(|а| **а == "плюс"));
}

#[test]
fn тест_следствие_и_причина() {
    let граф = ГрафАссоциаций::новый();
    let след = граф.ассоциации_по_типу("СПР", ТипСвязи::Следствие);
    assert!(след.iter().any(|с| *с == "ЧТВ"));
    let прич = граф.ассоциации_по_типу("ЧТВ", ТипСвязи::Причина);
    assert!(прич.iter().any(|с| *с == "СПР"));
}

#[test]
fn тест_сущность_описание() {
    let граф = ГрафАссоциаций::новый();
    let с = граф.сущность("ЧТВ").expect("ЧТВ");
    assert_eq!(с.тип, ТипСущности::Корень);
    assert!(с.описание.contains("Память") || с.описание.contains("память"));
}

#[test]
fn тест_соседи() {
    let граф = ГрафАссоциаций::новый();
    let соседи = граф.соседи("СПР", 1);
    assert!(соседи.iter().any(|с| с == "САПАР"));
    let дальние = граф.соседи("СПР", 2);
    assert!(дальние.len() >= соседи.len());
}

#[test]
fn тест_двусторонняя_ассоциация() {
    let граф = ГрафАссоциаций::новый();
    // САПАР ↔ СПР
    assert!(граф.ассоциации("САПАР").iter().any(|(к, _)| *к == "СПР"));
}

#[test]
fn тест_рёбра() {
    let граф = ГрафАссоциаций::новый();
    let рёбра = граф.рёбра();
    assert!(!рёбра.is_empty());
    assert!(рёбра.iter().any(|(от, к, _)| от == "СПР" && к == "САПАР"));
}

#[test]
fn тест_добавить_пользовательскую_связь() {
    let mut граф = ГрафАссоциаций::новый();
    граф.добавить_связь("САПАР", "умножить", ТипСвязи::Ассоциация);
    assert!(граф
        .ассоциации("САПАР")
        .iter()
        .any(|(к, т)| *к == "умножить" && *т == ТипСвязи::Ассоциация));
}

#[test]
fn тест_иконки_связей() {
    assert_eq!(ТипСвязи::Ассоциация.иконка(), "🔗");
    assert_eq!(ТипСвязи::Противоположность.метка(), "противоположность");
}

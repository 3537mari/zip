fn функция(тело: Vec<Инструкция>, параметры: Vec<Регистр>) -> ФункцияПП {
    ФункцияПП {
        идентификатор: ИдентификаторФункции(0),
        имя: "тест".into(),
        параметры,
        тип_возврата: Тип::Несовершенный,
        тело,
        асинхронная: false,
        совершенная: false,
        счётчик_вызовов: 0,
        порог_горячности: 1000,
        уже_горячая: false,
        агрессивная_оптимизация: false,
        comptime: false,
        комплементарный: false,
        прямой_аналог: None,
        уровень_оптимизации: 0,
        кэшировать: false,
        размер_кэша: 1024,
        шифровать: false,
        алгоритм_шифрования: "AES-GCM".into(),
        параллелить: false,
        количество_потоков: 4,
        сон: false,
        интервал_сна: "5m".into(),
        тест_случай: None,
        тест_диапазон: None,
        тест_границы: false,
        проверить_шаблон: None,
    }
}

#[test]
fn тест_простое_владение() {
    let ф = функция(
        vec![
            Инструкция::КонстантаЦелое {
                назначение: Регистр(0),
                значение: 1,
            },
            Инструкция::Переместить {
                назначение: Регистр(1),
                источник: Регистр(0),
            },
            Инструкция::Вернуть {
                значение: Some(Регистр(1)),
            },
        ],
        vec![],
    );
    let mut а = АнализаторВладения::новый();
    assert!(а.проанализировать(&ф).is_ok());
}

#[test]
fn тест_двойное_использование() {
    let ф = функция(
        vec![
            Инструкция::Импульс {
                источник: Регистр(0),
                назначение: Регистр(1),
            },
            Инструкция::Импульс {
                источник: Регистр(0),
                назначение: Регистр(2),
            },
        ],
        vec![Регистр(0)],
    );
    let mut а = АнализаторВладения::новый();
    let р = а.проанализировать(&ф);
    assert!(р.is_err());
    let ошибки = р.unwrap_err();
    assert!(ошибки.iter().any(|о| о.сообщение.contains("уже передан")));
    assert!(!ошибки[0].путь.is_empty() || ошибки.iter().any(|о| !о.путь.is_empty()));
}


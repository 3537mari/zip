#[test]
fn тест_ветвление() {
    // if (r0) { r1 >> r2 } else { r1 >> r3 }; затем r1 снова >> — ошибка на join
    let ф = функция(
        vec![
            Инструкция::ВетвлениеИмпульса {
                условие: Регистр(0),
                истина: Метка(1),
                ложь: Метка(2),
            },
            Инструкция::Метка {
                идентификатор: Метка(1),
            },
            Инструкция::Импульс {
                источник: Регистр(1),
                назначение: Регистр(2),
            },
            Инструкция::Перейти { метка: Метка(3) },
            Инструкция::Метка {
                идентификатор: Метка(2),
            },
            Инструкция::Импульс {
                источник: Регистр(1),
                назначение: Регистр(3),
            },
            Инструкция::Метка {
                идентификатор: Метка(3),
            },
            Инструкция::Импульс {
                источник: Регистр(1),
                назначение: Регистр(4),
            },
        ],
        vec![Регистр(0), Регистр(1)],
    );
    let mut а = АнализаторВладения::новый();
    let р = а.проанализировать(&ф);
    assert!(р.is_err(), "после обеих веток r1 передан");
}

#[test]
fn тест_путь_передачи() {
    let ф = функция(
        vec![
            Инструкция::Импульс {
                источник: Регистр(0),
                назначение: Регистр(1),
            },
            Инструкция::Вызвать {
                функция: ИдентификаторФункции(1),
                аргументы: vec![Регистр(0)],
                результат: None,
                отметить_горячей: false,
            },
        ],
        vec![Регистр(0)],
    );
    let mut а = АнализаторВладения::новый();
    let ошибки = а.проанализировать(&ф).unwrap_err();
    let о = ошибки
        .iter()
        .find(|о| о.сообщение.contains("уже передан"))
        .expect("ожидалась ошибка передачи");
    assert!(
        о.путь.iter().any(|t| t.0 == 0),
        "путь должен содержать точку первой передачи, путь={:?}",
        о.путь
    );
    assert!(о.подсказка.is_some());
}


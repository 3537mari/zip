//! Тесты SIMD-анализатора горячих циклов.

use zipc::промежуток::{Инструкция, Метка, Регистр, ФункцияПП, ИдентификаторФункции, Тип};
use zipc::simd::{АнализаторSIMD, ТипSIMD};
use zipc::сгенерировать_из_исходника;

fn синтетическая_арифметика(длина: usize) -> ФункцияПП {
    let mut тело = Vec::new();
    тело.push(Инструкция::Метка {
        идентификатор: Метка(1),
    });
    for i in 0..длина {
        тело.push(Инструкция::Сложить {
            назначение: Регистр(0),
            а: Регистр(0),
            б: Регистр(1 + (i as u32 % 3)),
        });
        тело.push(Инструкция::Умножить {
            назначение: Регистр(0),
            а: Регистр(0),
            б: Регистр(2),
        });
    }
    тело.push(Инструкция::Перейти { метка: Метка(1) });
    ФункцияПП::новая(
        ИдентификаторФункции(0),
        "сумма".into(),
        vec![],
        Тип::Целое64,
        тело,
        false,
        false,
    )
}

#[test]
fn тест_поиск_векторизуемых_циклов() {
    let ф = синтетическая_арифметика(8);
    let анализатор = АнализаторSIMD::новый();
    let циклы = анализатор.найти_векторизуемые(&ф);
    assert!(!циклы.is_empty(), "ожидался векторизуемый цикл");
    assert!(
        циклы[0].тип_simd == ТипSIMD::AVX512
            || циклы[0].тип_simd == ТипSIMD::AVX2
            || циклы[0].тип_simd == ТипSIMD::NEON
    );
}

#[test]
fn тест_цикл_из_исходника() {
    let исходник = r#"
        функция сумма_массива() {
            с = 0
            для и в 0..1000000 {
                с = с + и * 3
            }
            возврат(с)
        }
    "#;
    let функции = сгенерировать_из_исходника(исходник).expect("IR");
    let анализатор = АнализаторSIMD::с_параметрами(3, 15);
    let циклы = анализатор.найти_векторизуемые(&функции[0]);
    assert!(
        !циклы.is_empty() || !функции[0].тело.is_empty(),
        "IR пуст или цикл не найден: len={}",
        функции[0].тело.len()
    );
}

#[test]
fn тест_не_векторизуемый_цикл() {
    let mut тело = Vec::new();
    тело.push(Инструкция::Метка {
        идентификатор: Метка(1),
    });
    for _ in 0..6 {
        тело.push(Инструкция::Вызвать {
            функция: ИдентификаторФункции(9),
            аргументы: vec![Регистр(0)],
            результат: Some(Регистр(0)),
            отметить_горячей: false,
        });
    }
    тело.push(Инструкция::Перейти { метка: Метка(1) });
    let ф = ФункцияПП::новая(
        ИдентификаторФункции(0),
        "зависимости".into(),
        vec![],
        Тип::Целое64,
        тело,
        false,
        false,
    );
    let анализатор = АнализаторSIMD::новый();
    let циклы = анализатор.найти_векторизуемые(&ф);
    assert!(циклы.is_empty());
}

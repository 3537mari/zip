//! Тесты R3 — специализация глаголов по типам аргументов.

use zipc::промежуток::сгенерировать_из_исходника;
use zipc::{разобрать_исходник, Узел};

#[test]
fn тест_специализация_целых() {
    let функции = сгенерировать_из_исходника(
        r#"
глагол САПАР(а: Целое, б: Целое) -> Целое {
    возврат(а + б)
}

функция главная() {
    ПечатьЧисло(САПАР(2, 3))
}
"#,
    )
    .unwrap();
    assert!(
        функции.iter().any(|ф| ф.имя == "САПАРвариант0"),
        "ожидался вариант_0: {:?}",
        функции.iter().map(|ф| &ф.имя).collect::<Vec<_>>()
    );
    assert!(функции.iter().any(|ф| ф.имя == "главная"));
}

#[test]
fn тест_специализация_трёх_вариантов() {
    let функции = сгенерировать_из_исходника(
        r#"
глагол САПАР(а: Целое, б: Целое) -> Целое { возврат(а + б) }
глагол САПАР(а: Вещественное, б: Вещественное) -> Вещественное {
    возврат(а + б)
}
глагол САПАР(а: Строка, б: Строка) -> Строка {
    возврат(соединить_строки(а, б))
}

функция главная() {
    ПечатьЧисло(САПАР(2, 3))
    ПечатьЧисло(САПАР(2.5, 3.5))
    ПечатьСтроки(САПАР("привет, ", "мир"))
}
"#,
    )
    .unwrap();
    assert!(функции.iter().any(|ф| ф.имя == "САПАРвариант0"));
    assert!(функции.iter().any(|ф| ф.имя == "САПАРвариант1"));
    assert!(функции.iter().any(|ф| ф.имя == "САПАРвариант2"));
    assert!(функции.iter().any(|ф| ф.имя == "соединить_строки"));
}

#[test]
fn тест_нет_подходящего_варианта() {
    let р = сгенерировать_из_исходника(
        r#"
глагол САПАР(а: Целое, б: Целое) -> Целое { возврат(а + б) }

функция главная() {
    ПечатьСтроки(САПАР("а", "б"))
}
"#,
    );
    assert!(р.is_err(), "ожидалась ошибка: нет подходящего варианта");
    let с = р.err().unwrap();
    assert!(
        с.contains("нет подходящего варианта") || с.contains("САПАР"),
        "{}",
        с
    );
}

#[test]
fn тест_специализация_по_арности() {
    let функции = сгенерировать_из_исходника(
        r#"
глагол максимум(а: Целое, б: Целое) -> Целое {
    возврат(а + б)
}
глагол максимум(а: Целое, б: Целое, в: Целое) -> Целое {
    возврат(а + б + в)
}

функция главная() {
    ПечатьЧисло(максимум(1, 2))
    ПечатьЧисло(максимум(1, 2, 3))
}
"#,
    )
    .unwrap();
    assert!(функции.iter().any(|ф| ф.имя == "максимумвариант0"));
    assert!(функции.iter().any(|ф| ф.имя == "максимумвариант1"));
}

#[test]
fn тест_парсер_специализации() {
    let дерево = разобрать_исходник(
        r#"
глагол САПАР(а: Целое, б: Целое) -> Целое { возврат(а + б) }
глагол САПАР(а: Строка, б: Строка) -> Строка { возврат(а) }
"#,
    )
    .unwrap();
    match дерево {
        Узел::Программа { объявления } => {
            let спец = объявления
                .iter()
                .find(|у| matches!(у, Узел::СпециализацияГлагола { .. }))
                .expect("СпециализацияГлагола");
            match спец {
                Узел::СпециализацияГлагола { имя, варианты } => {
                    assert_eq!(имя, "САПАР");
                    assert_eq!(варианты.len(), 2);
                    assert_eq!(варианты[0].типы_параметров, ["Целое", "Целое"]);
                    assert_eq!(варианты[1].типы_параметров, ["Строка", "Строка"]);
                }
                _ => unreachable!(),
            }
        }
        _ => panic!("ожидалась программа"),
    }
}

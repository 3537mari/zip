//! Тесты R6 — FFI overloading по арности.

use zipc::промежуток::сгенерировать_из_исходника;
use zipc::{разобрать_исходник, Узел};

#[test]
fn тест_перегрузка_максимум() {
    let функции = сгенерировать_из_исходника(
        r#"
#link("ffi_overload")
функция максимум(а: Число, б: Число) -> Число
функция максимум(а: Число, б: Число, в: Число) -> Число

функция главная() {
    ПечатьЧисло(максимум(1, 2))
    ПечатьЧисло(максимум(1, 2, 3))
}
"#,
    )
    .unwrap();
    assert!(функции.iter().any(|ф| ф.имя == "zip_максимум_2"));
    assert!(функции.iter().any(|ф| ф.имя == "zip_максимум_3"));
}

#[test]
fn тест_перегрузка_открыть() {
    let функции = сгенерировать_из_исходника(
        r#"
#link("ffi_overload")
функция открыть(путь: Строка) -> Файл
функция открыть(путь: Строка, режим: Строка) -> Файл

функция главная() {
    а = открыть("a.txt")
    б = открыть("a.txt", "w")
    возврат(а)
}
"#,
    )
    .unwrap();
    assert!(функции.iter().any(|ф| ф.имя == "zip_открыть_1"));
    assert!(функции.iter().any(|ф| ф.имя == "zip_открыть_2"));
}

#[test]
fn тест_неоднозначность() {
    let р = сгенерировать_из_исходника(
        r#"
#link("ffi_overload")
функция максимум(а: Число, б: Число) -> Число

функция главная() {
    ПечатьЧисло(максимум(1, 2, 3))
}
"#,
    );
    assert!(р.is_err(), "ожидалась ошибка: нет сигнатуры с 3 аргументами");
    let с = р.err().unwrap();
    assert!(
        с.contains("нет подходящей сигнатуры") || с.contains("максимум"),
        "{}",
        с
    );
}

#[test]
fn тест_парсер_внешней_и_стрелки() {
    let дерево = разобрать_исходник(
        r#"
#link("ffi_overload")
функция максимум(а: Число, б: Число) -> Число
"#,
    )
    .unwrap();
    match дерево {
        Узел::Программа { объявления } => {
            assert!(объявления
                .iter()
                .any(|у| matches!(у, Узел::СвязатьБиблиотеку { .. })));
            let ф = объявления
                .iter()
                .find(|у| matches!(у, Узел::ОпределениеФункции { .. }))
                .unwrap();
            match ф {
                Узел::ОпределениеФункции {
                    внешняя,
                    тип_возврата,
                    библиотека,
                    ..
                } => {
                    assert!(*внешняя);
                    assert_eq!(тип_возврата.as_deref(), Some("Число"));
                    assert_eq!(библиотека.as_deref(), Some("ffi_overload"));
                }
                _ => unreachable!(),
            }
        }
        _ => panic!("ожидалась программа"),
    }
}

#[test]
fn тест_std_64_парсится() {
    let исходник = include_str!("../zip-std/64корня.zip");
    let дерево = разобрать_исходник(исходник).expect("STD 64корня.zip");
    match дерево {
        Узел::Программа { объявления } => {
            let корней = объявления
                .iter()
                .filter(|у| matches!(у, Узел::ОбъявлениеКорня { .. }))
                .count();
            assert_eq!(корней, 64);
        }
        _ => panic!("ожидалась программа"),
    }
}


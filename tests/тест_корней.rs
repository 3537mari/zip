#[test]
fn тест_нет_дубликатов() {
    let корни = полная_таблица();
    let mut коды: Vec<_> = корни.iter().map(|к| к.код.as_str()).collect();
    коды.sort();
    let до = коды.len();
    коды.dedup();
    assert_eq!(коды.len(), до);
    assert_eq!(коды.len(), 64);
}

#[test]
fn тест_все_имеют_валидный_код() {
    for корень in полная_таблица() {
        assert!(
            валидный_код_корня(&корень.код),
            "невалидный код корня: {}",
            корень.код
        );
        let символы: Vec<char> = корень.код.chars().collect();
        assert_eq!(символы.len(), 3, "корень {} не 3 буквы", корень.код);
        for с in символы {
            assert!(
                Лексер::это_корневая_буква_публ(с),
                "корень {} содержит недопустимую букву '{}'",
                корень.код,
                с
            );
        }
    }
}

#[test]
fn тест_лексер_узнаёт_новые_корни() {
    for код in ["КМД", "УПР", "АНЛ", "СТР", "АСН", "ТСТ", "СНЦ"] {
        let т = Лексер::новый(код).разобрать_токены().unwrap();
        assert!(
            matches!(&т[0], zipc::Токен::Корень(с) if с == код),
            "{} → {:?}",
            код,
            т[0]
        );
    }
}

#[test]
fn тест_парсер_объявление_из_таблицы() {
    let дерево = разобрать_исходник("КМД = { А-А: КАМАД }").unwrap();
    match дерево {
        Узел::Программа { объявления } => match &объявления[0] {
            Узел::ОбъявлениеКорня { корень, по_типу, .. } => {
                assert_eq!(корень, "КМД");
                assert!(!по_типу.is_empty());
            }
            другой => panic!("{:?}", другой),
        },
        _ => panic!("ожидалась программа"),
    }
}


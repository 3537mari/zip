#[test]
fn тест_display_всех_токенов() {
    let образцы = [
        ">>", "||", ">>>", "!", "~", "=", ":", "-", "—",
        "Нечто", "Ничто", "Успех", "Ошибка",
        "(", ")", "{", "}", ",", "+", "*", "/",
        "если", "иначе", "пока", "для", "в", "возврат",
        "прервать", "продолжить", "функция", "глагол", "поток",
        "источник", "приёмник", "фильтр", "агент", "состояние",
        "реагировать", "отправить", ".", "тип", "модуль", "импорт",
        "печать", "печать_строки", "печать_число",
        "истина", "ложь", "и", "или", "не",
        "==", "!=", "<", ">", "<=", ">=",
        "0..10", "42", "3.14", "\"строка\"", "САПАР", "идентификатор",
    ];
    for с in образцы {
        if let Ok(токены) = Лексер::новый(с).разобрать() {
            for т in &токены {
                let _ = format!("{}", т.токен);
            }
        }
    }
    // Явно Display для вариантов, которые лексер может не вернуть отдельно
    for т in [
        Токен::Кавычка,
        Токен::КонецФайла,
        Токен::Собака,
        Токен::Стрелка,
        Токен::Диапазон,
        Токен::Comptime,
        Токен::Директива("link".into()),
        Токен::Корень("САПАР".into()),
        Токен::Шаблон("САПАР".into()),
        Токен::Слово("х".into()),
        Токен::Целое(1),
        Токен::Вещественное(1.5),
        Токен::Строка("а".into()),
    ] {
        let _ = format!("{т}");
    }
}

#[test]
fn тест_пул_крупный_и_очистка() {
    let пул = ПулПамяти::новый();
    let _ = пул.выделить(32);
    let _ = пул.выделить(64 * 1024 + 16); // крупный блок
    // несколько блоков подряд
    for _ in 0..20 {
        let _ = пул.выделить(8 * 1024);
    }
    let (ёмкость, исп) = пул.статистика();
    assert!(ёмкость > 0 && исп > 0);
    пул.очистить();
    let (е2, и2) = пул.статистика();
    assert_eq!(и2, 0);
    assert_eq!(е2, 0);
    let пул2 = ПулПамяти::default();
    let _ = пул2.выделить(8);
    unsafe {
        let срез = пул2.выделить_срез(16);
        срез[0] = 7;
        assert_eq!(срез[0], 7);
    }
}

#[test]
fn тест_парсер_с_пулом_и_ошибки_директив() {
    let пул = Arc::new(ПулПамяти::новый());
    let дерево = разобрать_исходник_с_пулом("функция главная() { возврат(1) }", пул.clone()).unwrap();
    assert!(!matches!(дерево, zipc::Узел::Программа { объявления } if объявления.is_empty()));

    let mut п = Парсер::с_пулом("1 + 2", пул.clone()).unwrap();
    assert!(п.пул().is_some());
    let _ = п.разобрать().unwrap();

    assert!(разобрать_исходник("#неизвестно(\"x\")").is_err());
    assert!(разобрать_исходник("@ускорить функция").is_err() || разобрать_исходник("@ускорить\nх = 1").is_err());
    let е = разобрать_исходник("функция ((").unwrap_err();
    let _ = format!("{е}");
    let _ = format!("{}", &е as &dyn std::error::Error);
}

#[test]
fn тест_вещественные_и_печать_в_эмиттерах() {
    let программы = [
        "функция главная() { возврат(3.14) }",
        "функция главная() { ПечатьЧисло(7) возврат(0) }",
        "функция главная() { ПечатьСтроки(\"hi\") возврат(0) }",
        "функция главная() { печать(1) возврат(0) }",
        "функция главная() { возврат(1 <= 2) }",
        "функция главная() { возврат(2 >= 2) }",
    ];
    for п in программы {
        let ф = сгенерировать_из_исходника(п).unwrap();
        assert!(!байткод_эмиттер_v3::сгенерировать_v3(&ф).unwrap().is_empty());
        assert!(!байткод_эмиттер::сгенерировать(&ф).unwrap().is_empty());
        assert!(!сгенерировать_llvm_ir(&ф, "m").unwrap().is_empty());
        assert!(!скомпилировать_в_ассемблер(п).unwrap().is_empty());
    }
}


#[test]
fn т22_цепочка_vso() {
    let т = разобрать("САПАР(матрица, веса) >> ЧАТАВ!");
    assert_eq!(
        т,
        vec![
            Токен::Шаблон("САПАР".into()),
            Токен::СкобкаЛевая,
            Токен::Слово("матрица".into()),
            Токен::Запятая,
            Токен::Слово("веса".into()),
            Токен::СкобкаПравая,
            Токен::Импульс,
            Токен::Шаблон("ЧАТАВ".into()),
            Токен::Фиксация,
            Токен::КонецФайла,
        ]
    );
}


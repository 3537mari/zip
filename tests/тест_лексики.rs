//! Интеграционные тесты лексера ZIP (≥ 20 случаев).

use zipc::{Лексер, Токен};

fn разобрать(исходник: &str) -> Vec<Токен> {
    Лексер::новый(исходник)
        .разобрать_токены()
        .unwrap_or_else(|е| panic!("ожидался успех, получено: {}", е))
}

fn ошибка(исходник: &str) -> String {
    Лексер::новый(исходник)
        .разобрать()
        .expect_err("ожидалась ошибка")
        .сообщение
}


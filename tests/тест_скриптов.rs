#[test]
fn тест_несколько_зависимостей() {
    let исходник = r#"
#зависимость("а = 1.0")
#зависимость("б = 2.0")
#зависимость("в = 3.0")
функция главная() {}
"#;

    let дерево = разобрать_исходник(исходник).unwrap();
    let количество = объявления(&дерево)
        .iter()
        .filter(|у| matches!(у, Узел::Зависимость { .. }))
        .count();

    assert_eq!(количество, 3);
}

#[test]
fn тест_собрать_зависимости() {
    let исходник = r#"
#зависимость("пакет = 0.1")
функция главная() {}
"#;
    let дерево = разобрать_исходник(исходник).unwrap();
    let з = zipc::собрать_зависимости(&дерево);
    assert_eq!(з.len(), 1);
    assert_eq!(з[0].0, "пакет");
}

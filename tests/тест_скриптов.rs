//! Тесты R7 — cargo-script (shebang, зависимости, кэш).

use zipc::кэш_скриптов::КэшСкриптов;
use zipc::{разобрать_исходник, Узел};

fn объявления(дерево: &Узел) -> &[Узел] {
    match дерево {
        Узел::Программа { объявления } => объявления,
        _ => panic!("ожидалась Программа"),
    }
}

#[test]
fn тест_shebang() {
    let исходник = "#!/usr/bin/env zipc\nфункция главная() { ПечатьСтроки(\"Привет\") }\n";
    let дерево = разобрать_исходник(исходник).unwrap();
    assert!(!объявления(&дерево).is_empty());
}

#[test]
fn тест_зависимость() {
    let исходник = r#"
#зависимость("нейросети = 1.0")
#зависимость("тензоры = 1.0")
функция главная() {
    ПечатьСтроки("Привет")
}
"#;

    let дерево = разобрать_исходник(исходник).unwrap();
    let зависимости: Vec<_> = объявления(&дерево)
        .iter()
        .filter_map(|у| match у {
            Узел::Зависимость { имя, версия } => Some((имя.clone(), версия.clone())),
            _ => None,
        })
        .collect();

    assert_eq!(зависимости.len(), 2);
    assert_eq!(
        зависимости[0],
        ("нейросети".to_string(), "1.0".to_string())
    );
    assert_eq!(зависимости[1], ("тензоры".to_string(), "1.0".to_string()));
}

#[test]
fn тест_кэш_скриптов() {
    let mut кэш = КэшСкриптов::новый();
    let uid = format!("{}_{}", std::process::id(), std::time::SystemTime::now()
        .duration_since(std::time::UNIX_EPOCH)
        .unwrap()
        .as_nanos());

    let файл = std::env::temp_dir().join(format!("тест_кэш_{}.zip", uid));
    let исходник_а = format!(
        "функция главная() {{ ПечатьСтроки(\"А_{}\") }}\n",
        uid
    );
    std::fs::write(&файл, исходник_а.as_bytes()).unwrap();

    assert!(кэш.получить(&файл).is_none());

    let exe = std::env::temp_dir().join(format!("тест_кэш_{}.bin", uid));
    std::fs::write(&exe, b"fake-exe").unwrap();

    кэш.сохранить(&файл, &exe).unwrap();
    let кэш_путь = кэш.получить(&файл);
    assert!(кэш_путь.is_some());

    let исходник_б = format!(
        "функция главная() {{ ПечатьСтроки(\"Б_{}\") }}\n",
        uid
    );
    std::fs::write(&файл, исходник_б.as_bytes()).unwrap();

    assert!(
        кэш.получить(&файл).is_none(),
        "после изменения исходника кэш должен устареть"
    );

    if let Some(п) = кэш_путь {
        let _ = std::fs::remove_file(п);
    }
    let _ = std::fs::remove_file(&файл);
    let _ = std::fs::remove_file(&exe);
}


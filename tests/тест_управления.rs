#[test]
fn у08_если_иначе_возврат() {
    let у = единственный("если (истина) { возврат(1) } иначе { возврат(2) }");
    match у {
        Узел::Если {
            условие,
            тогда,
            иначе,
        } => {
            assert_eq!(*условие, Узел::Истина);
            match *тогда {
                Узел::Блок(эл) => match &эл[0] {
                    Узел::Возврат(Some(в)) => assert_eq!(**в, Узел::Целое(1)),
                    другой => panic!("{:?}", другой),
                },
                другой => panic!("{:?}", другой),
            }
            let иначе = иначе.expect("иначе");
            match *иначе {
                Узел::Блок(эл) => match &эл[0] {
                    Узел::Возврат(Some(в)) => assert_eq!(**в, Узел::Целое(2)),
                    другой => panic!("{:?}", другой),
                },
                другой => panic!("{:?}", другой),
            }
        }
        другой => panic!("{:?}", другой),
    }
}

#[test]
fn у09_пока_сравнение_присваивание() {
    let у = единственный("пока (число < 10) { число = число + 1 }");
    match у {
        Узел::Пока { условие, тело } => {
            match *условие {
                Узел::Сравнение {
                    оператор,
                    левый,
                    правый,
                } => {
                    assert_eq!(оператор, "<");
                    assert_eq!(*левый, Узел::Идентификатор("число".into()));
                    assert_eq!(*правый, Узел::Целое(10));
                }
                другой => panic!("{:?}", другой),
            }
            match *тело {
                Узел::Блок(эл) => match &эл[0] {
                    Узел::Присваивание { имя, значение } => {
                        assert_eq!(имя, "число");
                        match &**значение {
                            Узел::БинарнаяОперация {
                                оператор,
                                левый,
                                правый,
                            } => {
                                assert_eq!(оператор, "+");
                                assert_eq!(**левый, Узел::Идентификатор("число".into()));
                                assert_eq!(**правый, Узел::Целое(1));
                            }
                            другой => panic!("{:?}", другой),
                        }
                    }
                    другой => panic!("{:?}", другой),
                },
                другой => panic!("{:?}", другой),
            }
        }
        другой => panic!("{:?}", другой),
    }
}


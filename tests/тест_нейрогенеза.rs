//! Тесты Идеи 3 — нейрогенез (паттерны IR → композитные функции).

use zipc::нейрогенез::*;
use zipc::сгенерировать_из_исходника;

#[test]
fn тест_поиск_паттернов() {
    let исходник = r#"
функция обработать(значение) {
    шаг1 = САПАР(значение)
    шаг2 = САПАР(шаг1)
    шаг3 = САПАР(шаг2)
    возврат(шаг3)
}

функция главная() {
    ПечатьЧисло(обработать(1))
    ПечатьЧисло(обработать(2))
    ПечатьЧисло(обработать(3))
    ПечатьЧисло(обработать(4))
    ПечатьЧисло(обработать(5))
    ПечатьЧисло(обработать(6))
}
"#;

    let функции = сгенерировать_из_исходника(исходник).unwrap();
    let анализатор = АнализаторПаттернов::с_параметрами(2, 5);
    let паттерны = анализатор.найти_паттерны(&функции);
    assert!(!паттерны.is_empty(), "ожидались повторяющиеся паттерны САПАР");
}

#[test]
fn тест_генерация_композита() {
    let mut генератор = ГенераторКомпозитов::новый();

    let паттерн = НайденныйПаттерн {
        паттерн: ПаттернIR {
            сигнатуры: vec![
                СигнатураИнструкции::Вызов("САПАР".to_string()),
                СигнатураИнструкции::Вызов("САПАР".to_string()),
            ],
            частота: 10,
        },
        функции_участники: vec![],
        примеры_использования: vec![],
    };

    let композит = генератор.сгенерировать(&паттерн, &[]);
    assert!(композит.имя.starts_with("КОМПОЗИТ_"));
    assert!(композит.имя.contains("САПАР"));
}

#[test]
fn тест_аннотация_нейрогенез() {
    let исходник = r#"
        @нейрогенез(паттерн = "САПАР", порог = 2)
        функция главная() {
            для и в 0..10 {
                данные = САПАР(и)
                результат = САПАР(данные)
                ПечатьЧисло(результат)
            }
        }
    "#;

    let функции = сгенерировать_из_исходника(исходник).unwrap();
    let есть_флаг = функции.iter().any(|ф| ф.нейрогенез);
    let есть_композит = функции.iter().any(|ф| ф.имя.starts_with("КОМПОЗИТ_"));
    assert!(есть_флаг || есть_композит, "нейрогенез должен сработать");
}

#[test]
fn тест_реестр_аннотации() {
    assert_eq!(
        zipc::ВстроеннаяАннотация::из_имени("нейрогенез"),
        Some(zipc::ВстроеннаяАннотация::Нейрогенез)
    );
}

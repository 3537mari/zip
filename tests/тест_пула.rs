//! Тесты bump-пула памяти.

use zipc::пул_памяти::ПулПамяти;
use zipc::{разобрать_исходник_с_пулом, Парсер};
use std::sync::Arc;

#[test]
fn тест_выделение() {
    let пул = ПулПамяти::новый();
    let указатель1 = пул.выделить(100);
    let указатель2 = пул.выделить(200);
    assert_ne!(указатель1, указатель2);
}

#[test]
fn тест_статистика() {
    let пул = ПулПамяти::новый();
    пул.выделить(1000);
    let (всего, использовано) = пул.статистика();
    assert!(всего >= 1000);
    assert!(использовано >= 1000);
}

#[test]
fn тест_очистка() {
    let пул = ПулПамяти::новый();
    пул.выделить(1000);
    пул.очистить();
    let (всего, использовано) = пул.статистика();
    assert_eq!(всего, 0);
    assert_eq!(использовано, 0);
}

#[test]
fn тест_парсер_с_пулом() {
    let пул = Arc::new(ПулПамяти::новый());
    let п = Парсер::с_пулом("функция главная() { возврат(1) }", пул.clone()).unwrap();
    assert!(п.пул().is_some());
    let аст = разобрать_исходник_с_пулом("с = 1 + 2", пул.clone()).unwrap();
    let _ = аст;
    let (_, использовано) = пул.статистика();
    assert!(использовано > 0);
}

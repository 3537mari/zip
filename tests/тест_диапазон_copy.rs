//! Тесты R4 — Range Copy: диапазоны как Copy-типы.

use zipc::промежуток::{сгенерировать_из_исходника, Инструкция, Тип};
use zipc::{разобрать_исходник, Узел};

#[test]
fn тест_диапазон_копируется() {
    let функции = сгенерировать_из_исходника(
        r#"
функция главная() {
    д = 0..5

    сумма1 = 0
    для и в д { сумма1 = сумма1 + и }

    сумма2 = 0
    для и в д { сумма2 = сумма2 + и }

    ПечатьЧисло(сумма1)
    ПечатьЧисло(сумма2)
}
"#,
    )
    .unwrap();
    assert!(функции.iter().any(|ф| ф.имя == "zip_создать_диапазон"));
    assert!(функции.iter().any(|ф| ф.имя == "zip_копировать_диапазон"));
    assert!(функции.iter().any(|ф| ф.имя == "zip_диапазон_есть_следующий"));
    assert!(функции.iter().any(|ф| ф.имя == "zip_диапазон_следующий"));
    let главная = функции.iter().find(|ф| ф.имя == "главная").unwrap();
    let копий = главная
        .тело
        .iter()
        .filter(|и| matches!(и, Инструкция::Копировать { .. }))
        .count();
    assert!(копий >= 1, "ожидалась инструкция Копировать");
}

#[test]
fn тест_диапазон_в_функции() {
    let функции = сгенерировать_из_исходника(
        r#"
функция сумма_диапазона(д) {
    с = 0
    для и в д { с = с + и }
    возврат(с)
}
функция главная() {
    д = 0..4
    ПечатьЧисло(сумма_диапазона(д))
    ПечатьЧисло(сумма_диапазона(д))
}
"#,
    )
    .unwrap();
    assert!(функции.iter().any(|ф| ф.имя == "сумма_диапазона"));
    assert!(функции.iter().any(|ф| ф.имя == "zip_копировать_диапазон"));
}

#[test]
fn тест_диапазон_с_переменными() {
    let функции = сгенерировать_из_исходника(
        r#"
функция главная() {
    н = 10
    д = 0..н
    для и в д { ПечатьЧисло(и) }
}
"#,
    )
    .unwrap();
    assert!(функции.iter().any(|ф| ф.имя == "zip_создать_диапазон"));
    let главная = функции.iter().find(|ф| ф.имя == "главная").unwrap();
    let _ = главная;
    let _ = Тип::Диапазон;
}

#[test]
fn тест_вложенные_диапазоны() {
    let функции = сгенерировать_из_исходника(
        r#"
функция главная() {
    внешний = 0..3
    для а в внешний {
        внутренний = 0..2
        для б в внутренний {
            ПечатьЧисло(а)
            ПечатьЧисло(б)
        }
    }
}
"#,
    )
    .unwrap();
    assert!(функции.iter().any(|ф| ф.имя == "zip_создать_диапазон"));
    assert!(функции.iter().any(|ф| ф.имя == "zip_копировать_диапазон"));
}

#[test]
fn тест_парсер_присваивание_диапазона() {
    let у = match разобрать_исходник("д = 0..5").unwrap() {
        Узел::Программа { объявления } => объявления.into_iter().next().unwrap(),
        другой => другой,
    };
    match у {
        Узел::Присваивание { имя, значение } => {
            assert_eq!(имя, "д");
            assert!(matches!(*значение, Узел::Диапазон { .. }));
        }
        другой => panic!("{:?}", другой),
    }
}

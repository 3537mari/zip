#[test]
fn тест_разные_единицы() {
    let дерево = разобрать_исходник(
        r#"
функция главная() {
    ЕД_М = 2
    ЕД_КГ = 3
    ЕД_ГРАДУС = 6
    ЕД_ПРОЦЕНТ = 7
    расстояние = измерить(1, ЕД_М)
    вес = измерить(2, ЕД_КГ)
    температура = измерить(36, ЕД_ГРАДУС)
    процент = измерить(99, ЕД_ПРОЦЕНТ)
    измерить_печать(расстояние)
    измерить_печать(вес)
    измерить_печать(температура)
    измерить_печать(процент)
}
"#,
    )
    .unwrap();
    assert!(matches!(дерево, Узел::Программа { .. }));
}


//! Тесты Идеи 13 — единицы измерения.

use zipc::промежуток::{сгенерировать_из_исходника, Тип};
use zipc::{разобрать_исходник, Узел};

#[test]
fn тест_создание_единицы() {
    let функции = сгенерировать_из_исходника(
        r#"
функция главная() {
    ЕД_МС = 1
    время = измерить(100, ЕД_МС)
    измерить_печать(время)
}
"#,
    )
    .unwrap();
    assert!(функции.iter().any(|ф| ф.имя == "измерить" || ф.имя == "zip_создать_измерение"));
    assert!(функции
        .iter()
        .any(|ф| ф.имя == "измерить_печать" || ф.имя == "zip_измерение_печать"));
}

#[test]
fn тест_тип_единица() {
    let функции = сгенерировать_из_исходника("измерить(1, 1)").unwrap();
    let ф = функции
        .iter()
        .find(|ф| ф.имя == "измерить" || ф.имя == "zip_создать_измерение")
        .expect("измерить");
    assert!(matches!(ф.тип_возврата, Тип::Единица(_, _)));
}

#[test]
fn тест_совместимость() {
    let функции = сгенерировать_из_исходника(
        r#"
функция главная() {
    ЕД_МС = 1
    ЕД_М = 2
    а = измерить(100, ЕД_МС)
    б = измерить(50, ЕД_МС)
    г = измерить(30, ЕД_М)
    если (совместимо(а, б)) {
        ПечатьСтроки("а и б совместимы")
    }
    если (не совместимо(а, г)) {
        ПечатьСтроки("а и г несовместимы")
    }
}
"#,
    )
    .unwrap();
    assert!(функции.iter().any(|ф| ф.имя == "совместимо" || ф.имя == "zip_единицы_совместимы"));
}


//! Тесты промежуточного представления ZIP (≥ 15).

use zipc::промежуток::{
    сгенерировать_из_исходника, ГенераторПП, Инструкция, Тип, ФункцияПП,
};
use zipc::{разобрать_исходник, Узел};

fn ир(исходник: &str) -> Vec<ФункцияПП> {
    сгенерировать_из_исходника(исходник).unwrap_or_else(|е| panic!("{}", е))
}

fn главная(функции: &[ФункцияПП]) -> &ФункцияПП {
    функции
        .iter()
        .find(|ф| ф.имя == "главная")
        .expect("нет функции главная")
}

#[test]
fn ир01_сапар_чатав_цепочка() {
    let ф = ир("САПАР >> ЧАТАВ!");
    let г = главная(&ф);
    assert!(г.тело.iter().any(|и| matches!(и, Инструкция::Импульс { .. })));
    assert!(г.тело.iter().any(|и| matches!(и, Инструкция::Зафиксировать { .. })));
    assert!(ф.iter().any(|x| x.имя == "САПАР"));
    assert!(ф.iter().any(|x| x.имя == "ЧАТАВ" && x.совершенная));
}

#[test]
fn ир02_отдельная_функция_на_глагол() {
    let ф = ир("САПАР >> САГАН");
    assert!(ф.iter().any(|x| x.имя == "САПАР"));
    assert!(ф.iter().any(|x| x.имя == "САГАН"));
}

#[test]
fn ир03_асинхронный_флаг() {
    let ф = ир("ЖАВАТ~");
    assert!(ф.iter().any(|x| x.асинхронная));
}

#[test]
fn ир04_совершенный_флаг() {
    let ф = ир("ЧАТАВ!");
    let чатав = ф.iter().find(|x| x.имя == "ЧАТАВ").expect("ЧАТАВ");
    assert!(чатав.совершенная);
    assert_eq!(чатав.тип_возврата, Тип::Совершенный);
}

#[test]
fn ир05_хор_запускает_параллель() {
    let ф = ир("ЖАВАТ~ || САГАН~");
    let г = главная(&ф);
    let запусков = г
        .тело
        .iter()
        .filter(|и| matches!(и, Инструкция::ЗапуститьХор { .. }))
        .count();
    assert!(запусков >= 2);
    assert!(г.тело.iter().any(|и| matches!(и, Инструкция::СобратьХор { .. })));
}

#[test]
fn ир06_константы_аргументов() {
    let ф = ир("САПАР(1, 2)");
    let г = главная(&ф);
    let констант = г
        .тело
        .iter()
        .filter(|и| matches!(и, Инструкция::КонстантаЦелое { .. }))
        .count();
    assert_eq!(констант, 2);
}

#[test]
fn ир07_вызов_в_теле() {
    let ф = ир("САПАР");
    let г = главная(&ф);
    assert!(г.тело.iter().any(|и| matches!(и, Инструкция::Вызвать { .. })));
}

#[test]
fn ир08_ffi() {
    let ф = ир(r#"#link("lib") САЯЗ(а, б)"#);
    let г = главная(&ф);
    assert!(г
        .тело
        .iter()
        .any(|и| matches!(и, Инструкция::ВнешнийВызов { .. })));
}

#[test]
fn ир09_проверка_типов_запрет() {
    let ош = ГенераторПП::проверить_совместимость(&Тип::Совершенный, &Тип::Несовершенный)
        .expect_err("должна быть ошибка");
    assert_eq!(ош.сообщение, "Нельзя применить Совершенный к Несовершенному");
}

#[test]
fn ир10_проверка_типов_фиксация_ок() {
    assert!(
        ГенераторПП::проверить_совместимость(&Тип::Несовершенный, &Тип::Совершенный).is_ok()
    );
}

#[test]
fn ир11_повторная_фиксация_ошибка() {
    let дерево = разобрать_исходник("ЧАТАВ!").unwrap();
    let mut ген = ГенераторПП::новый();
    let функции = ген.сгенерировать(&дерево).unwrap();
    let г = главная(&функции);
    assert!(г.тело.iter().any(|и| matches!(и, Инструкция::Зафиксировать { .. })));
    assert!(ГенераторПП::проверить_совместимость(&Тип::Совершенный, &Тип::Несовершенный).is_err());
}

#[test]
fn ир12_блок() {
    let ф = ир("{ САПАР >> ЧАТАВ }");
    assert!(главная(&ф).тело.iter().any(|и| matches!(и, Инструкция::Импульс { .. })));
}

#[test]
fn ир13_имя_главной() {
    let ф = ир("САПАР");
    assert_eq!(ф[0].имя, "главная");
}

#[test]
fn ир14_возврат_из_главной() {
    let ф = ир("САПАР");
    let г = главная(&ф);
    assert!(matches!(
        г.тело.last(),
        Some(Инструкция::Вернуть { .. })
    ));
}

#[test]
fn ир15_двойной_импульс() {
    let ф = ир("САПАР >> САГАН >> ЧАТАВ");
    let г = главная(&ф);
    let импульсов = г
        .тело
        .iter()
        .filter(|и| matches!(и, Инструкция::Импульс { .. }))
        .count();
    assert!(импульсов >= 2);
}

#[test]
fn ир16_из_ast_напрямую() {
    let ast = Узел::Программа {
        объявления: vec![Узел::ВызовГлагола {
            глагол: "САПАР".into(),
            аргументы: vec![],
            следующий: None,
        }],
    };
    let mut ген = ГенераторПП::новый();
    let ф = ген.сгенерировать(&ast).unwrap();
    assert!(!ф.is_empty());
}

#[test]
fn ир17_асинхронный_с_телом() {
    let ф = ир("ЖАВАТ~ { САПАР }");
    assert!(ф.iter().any(|x| x.имя.contains("поток") || x.асинхронная));
}

#[test]
fn тест_парсинг_агента() {
    // Упрощённая форма — если полный синтаксис агента меняется, хотя бы объявление
    let варианты = [
        "агент А { состояние { х: Целое = 0 } функция ф() { возврат(х) } }",
        "агент А { функция ф() { возврат(0) } }",
    ];
    let любой = варианты.iter().any(|п| разобрать_исходник(п).is_ok());
    assert!(любой, "ни один вариант агента не распарсился");
}

#[test]
fn тест_парсинг_потока_данных() {
    let варианты = [
        "поток П { источник = СИПРА(10) приёмник = ЧАТАВ(х) }",
        "поток П { }",
    ];
    let любой = варианты.iter().any(|п| разобрать_исходник(п).is_ok());
    assert!(любой, "ни один вариант потока не распарсился");
}

#[test]
fn тест_парсинг_аннотаций() {
    let программа = r#"
@ускорить(уровень = 3)
функция обработать(х) {
    возврат(х)
}
"#;
    let дерево = разобрать_исходник(программа).unwrap();
    match дерево {
        Узел::Программа { объявления } => assert!(!объявления.is_empty()),
        _ => panic!("ожидалась Программа"),
    }
}


//! Полный разбор конструкций ZIP — расширение покрытия парсера.

use zipc::{разобрать_исходник, Узел};

fn ok(программа: &str) {
    разобрать_исходник(программа).unwrap_or_else(|е| panic!("«{программа}»: {е}"));
}

#[test]
fn тест_парсинг_выражений() {
    for программа in [
        "1 + 2",
        "1 + 2 * 3",
        "а == б",
        "а != б",
        "а > б",
        "а < б",
        "а >= б",
        "а <= б",
        "истина и ложь",
        "истина или ложь",
        "не истина",
        "Нечто(5)",
        "Ничто",
        "Успех(10)",
        "Ошибка(\"fail\")",
        "0..10",
    ] {
        ok(программа);
    }
}

#[test]
fn тест_парсинг_потоков() {
    for программа in [
        "САПАР(1) >> ЧАТАВ!",
        "САПАР(1) || САПАР(2)",
        "САПАР(1) >> САПАР(2) >> ЧАТАВ!",
    ] {
        ok(программа);
    }
}

#[test]
fn тест_парсинг_инструкций() {
    for программа in [
        "если (истина) { 1 }",
        "если (истина) { 1 } иначе { 2 }",
        "пока (ложь) { прервать }",
        "для и в 0..10 { ПечатьЧисло(и) }",
        "функция ф() { возврат(1) }",
        "функция сложить(а, б) { возврат(а + б) }",
        "возврат",
        "возврат(42)",
        "прервать",
        "продолжить",
    ] {
        ok(программа);
    }
}


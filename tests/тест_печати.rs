#[test]
fn пч03_ир_печать_строки() {
    let ф = сгенерировать_из_исходника(r#"печать_строки("hi")"#).unwrap();
    let главная = ф.iter().find(|ф| ф.имя == "главная").unwrap();
    assert!(главная.тело.iter().any(|и| {
        matches!(
            и,
            Инструкция::Печать {
                режим: РежимПечати::СоСтрокой,
                ..
            }
        )
    }));
    assert!(главная
        .тело
        .iter()
        .any(|и| matches!(и, Инструкция::КонстантаСтрока { .. })));
}

#[test]
fn пч04_asm_puts() {
    let asm = скомпилировать_в_ассемблер(r#"ПечатьСтроки("Привет!")"#).unwrap();
    assert!(asm.contains("call puts"));
    assert!(asm.contains(".extern puts"));
    assert!(asm.contains(".Lstr0:"));
}

#[test]
fn пч05_asm_printf_число() {
    let asm = скомпилировать_в_ассемблер("печать_число(42)").unwrap();
    assert!(asm.contains("call printf"));
    assert!(asm.contains(".Lfmt_i64n"));
}

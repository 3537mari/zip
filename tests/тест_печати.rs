//! Тесты встроенных функций печати.

use zipc::{разобрать_исходник, сгенерировать_из_исходника, скомпилировать_в_ассемблер, Узел};
use zipc::промежуток::{Инструкция, РежимПечати};

#[test]
fn пч01_парсер_печать_строки() {
    let у = разобрать_исходник(r#"ПечатьСтроки("Привет, мир!")"#).unwrap();
    match у {
        Узел::Программа { объявления } => match &объявления[0] {
            Узел::ВызовФункции { имя, аргументы } => {
                assert_eq!(имя, "ПечатьСтроки");
                assert_eq!(аргументы[0], Узел::Строка("Привет, мир!".into()));
            }
            другой => panic!("{:?}", другой),
        },
        другой => panic!("{:?}", другой),
    }
}


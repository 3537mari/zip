//! Полная генерация IR — расширение покрытия промежутка.

use zipc::сгенерировать_из_исходника;

fn ir_ok(программа: &str) {
    let функции = сгенерировать_из_исходника(программа)
        .unwrap_or_else(|е| panic!("IR «{программа}»: {е}"));
    assert!(!функции.is_empty(), "пустой IR: {программа}");
}

#[test]
fn тест_ir_арифметика() {
    for программа in [
        "функция главная() { возврат(1 + 2) }",
        "функция главная() { возврат(5 - 3) }",
        "функция главная() { возврат(3 * 4) }",
        "функция главная() { возврат(10 / 2) }",
    ] {
        ir_ok(программа);
    }
}

#[test]
fn тест_ir_сравнения() {
    for программа in [
        "функция главная() { возврат(1 == 1) }",
        "функция главная() { возврат(1 != 2) }",
        "функция главная() { возврат(1 < 2) }",
        "функция главная() { возврат(3 > 2) }",
        "функция главная() { возврат(2 <= 2) }",
        "функция главная() { возврат(3 >= 2) }",
    ] {
        // сравнения могут давать флаг/целое — главное что IR строится
        let _ = сгенерировать_из_исходника(программа);
    }
}


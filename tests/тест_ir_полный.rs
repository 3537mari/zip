#[test]
fn тест_ir_константы() {
    ir_ok("функция главная() { возврат(42) }");
    ir_ok("функция главная() { возврат(3.14) }");
    ir_ok(r#"функция главная() { ПечатьСтроки("x") возврат(0) }"#);
}


//! Тесты Идеи 19 — ИИ-советник в компиляторе.

use zipc::ии_советник::*;
use zipc::промежуток::{Инструкция, ФункцияПП};
use zipc::сгенерировать_из_исходника;

#[test]
fn тест_статистический_анализ_без_llm() {
    let исходник = r#"
        функция дорогая_функция(х) {
            возврат(х * х)
        }

        функция главная() {
            для и в 0..2000 {
                ПечатьЧисло(дорогая_функция(и))
            }
        }
    "#;

    let функции = сгенерировать_из_исходника(исходник).unwrap();
    let советник = ИИСоветник::новый(ПровайдерLLM::Статистический);
    let рекомендации = советник.проанализировать(&функции).unwrap();
    assert!(
        !рекомендации.is_empty(),
        "ожидались рекомендации по дорогой_функции"
    );
}

#[test]
fn тест_рекомендация_пластичности() {
    let функции = vec![ФункцияПП {
        имя: "частая".to_string(),
        счётчик_вызовов: 5000,
        агрессивная_оптимизация: false,
        тело: vec![Инструкция::Вернуть { значение: None }],
        ..ФункцияПП::default()
    }];

    let советник = ИИСоветник::новый(ПровайдерLLM::Статистический);
    let рекомендации = советник.проанализировать(&функции).unwrap();

    let есть_пластичность = рекомендации
        .iter()
        .any(|р| р.описание.contains("пластичность"));
    assert!(есть_пластичность);
}

#[test]

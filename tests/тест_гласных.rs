//! Тесты Идеи 8 — гласные как модификаторы типа (10 шаблонов).

use zipc::лексика::{
    определить_тип_по_гласным, первая_гласная_шаблона, тип_шаблона, Лексер, Токен, ТипШаблона,
    ШАБЛОНЫ,
};
use zipc::{разобрать_исходник, сгенерировать_из_исходника, Узел};

#[test]
fn тест_все_10_шаблонов_таблица() {
    assert_eq!(ШАБЛОНЫ.len(), 10);
    for (гласная, тип) in ШАБЛОНЫ {
        assert_eq!(
            определить_тип_по_гласным(&гласная.to_string(), "А"),
            Some(*тип)
        );
    }
}

#[test]
fn тест_тип_шаблона_по_слову() {
    assert_eq!(тип_шаблона("САПАР"), Some(ТипШаблона::Глагол));
    assert_eq!(тип_шаблона("СЕПАР"), Some(ТипШаблона::Свойство));
    assert_eq!(тип_шаблона("СЁПАР"), Some(ТипШаблона::ОсобаяФорма));
    assert_eq!(тип_шаблона("СИПРА"), Some(ТипШаблона::Множество));
    assert_eq!(тип_шаблона("СПОРО"), Some(ТипШаблона::Инструмент));
    assert_eq!(тип_шаблона("СУПРА"), Some(ТипШаблона::Указатель));
    assert_eq!(тип_шаблона("СЫПРА"), Some(ТипШаблона::Итератор));
    assert_eq!(тип_шаблона("СЭПРА"), Some(ТипШаблона::Эфемерное));
    assert_eq!(тип_шаблона("СЮПРА"), Some(ТипШаблона::Единица));
    assert_eq!(тип_шаблона("СЯПРА"), Some(ТипШаблона::Ядро));
}

#[test]
fn тест_лексер_распознаёт_шаблоны() {
    for слово in [
        "САПАР", "СЕПАР", "СЁПАР", "СИПРА", "СПОРО", "СУПРА", "СЫПРА", "СЭПРА", "СЮПРА",
        "СЯПРА",
    ] {
        let т = Лексер::новый(слово).разобрать_токены().unwrap();
        assert!(
            matches!(&т[0], Токен::Шаблон(s) if s == слово),
            "{} → {:?}",
            слово,
            т[0]
        );
    }
}


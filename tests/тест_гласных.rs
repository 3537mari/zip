#[test]
fn тест_объявление_всех_10() {
    let исходник = r#"
СПР = {
    А-А: САПАР, Е-А: СЕПАР, Ё-А: СЁПАР, И-А: СИПРА, О-О: СПОРО,
    У-А: СУПРА, Ы-А: СЫПРА, Э-А: СЭПРА, Ю-А: СЮПРА, Я-А: СЯПРА
}
"#;
    let д = разобрать_исходник(исходник).unwrap();
    match д {
        Узел::Программа { объявления } => match &объявления[0] {
            Узел::ОбъявлениеКорня { по_типу, шаблоны, .. } => {
                assert_eq!(шаблоны.len(), 10);
                assert_eq!(по_типу.len(), 10);
                assert!(по_типу.contains_key(&ТипШаблона::Итератор));
                assert!(по_типу.contains_key(&ТипШаблона::Ядро));
            }
            _ => panic!(),
        },
        _ => panic!(),
    }
}


w("лексика_чистая.zip", h + "\n" + lex + lex_main)
w("парсер_чистый.zip", h + "\n" + lex + "\n" + p1 + "\n" + p2 + parse_main)
full = "\n".join([h, lex, p1, p2, g1, g2]) + "\n"
w("главное_чистое.zip", full)
w("генератор_чистый.zip", "// ZIP-SELF: генератор ZIPB (полный стек)\n" + full)
print("done")

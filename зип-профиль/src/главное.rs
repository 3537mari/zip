// ---------------------------------------------------------------------------
// CLI
// ---------------------------------------------------------------------------

#[derive(Parser, Debug)]
#[command(name = "зип-профиль")]
#[command(about = "Профилировщик для языка ZIP")]
struct Аргументы {
    /// Программа .zip для профилирования
    программа: String,

    /// Тип: cpu | память | io | аллокации
    #[arg(long = "тип", default_value = "cpu")]
    тип: ТипПрофилирования,

    /// Частота сэмплирования стека (Гц); 0 = на каждый вызов
    #[arg(long = "частота", default_value = "0")]
    частота: u32,

    /// Лимит длительности (секунды)
    #[arg(long = "длительность")]
    длительность: Option<u64>,

    /// JSON-отчёт
    #[arg(long = "json")]
    json: Option<String>,

    /// Flamegraph SVG (+ .folded)
    #[arg(long = "svg")]
    svg: Option<String>,

    /// Топ-N функций
    #[arg(long = "топ", default_value = "20")]
    топ: usize,

    /// Без stdout программы
    #[arg(long = "тихо")]
    тихо: bool,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum ТипПрофилирования {
    Cpu,
    Память,
    ВводВывод,
    Аллокации,
}

impl FromStr for ТипПрофилирования {
    type Err = String;
    fn from_str(s: &str) -> Result<Self, Self::Err> {
        match s.to_lowercase().as_str() {
            "cpu" => Ok(Self::Cpu),
            "память" | "memory" => Ok(Self::Память),
            "io" | "ввод" | "вводвывод" => Ok(Self::ВводВывод),
            "аллокации" | "alloc" => Ok(Self::Аллокации),
            _ => Err(format!("Неизвестный тип: {s}")),
        }
    }
}

impl std::fmt::Display for ТипПрофилирования {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            Self::Cpu => write!(f, "cpu"),
            Self::Память => write!(f, "память"),
            Self::ВводВывод => write!(f, "io"),
            Self::Аллокации => write!(f, "аллокации"),
        }
    }
}


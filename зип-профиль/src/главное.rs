#[derive(Debug, Clone)]
enum Знач {
    Целое(i64),
    Логическое(bool),
    Строка(String),
    Пусто,
}

impl Знач {
    fn как_целое(&self) -> Result<i64> {
        match self {
            Знач::Целое(n) => Ok(*n),
            Знач::Логическое(b) => Ok(i64::from(*b)),
            _ => bail!("ожидалось целое, получено {:?}", self),
        }
    }
    fn истина(&self) -> bool {
        match self {
            Знач::Логическое(b) => *b,
            Знач::Целое(n) => *n != 0,
            Знач::Строка(s) => !s.is_empty(),
            Знач::Пусто => false,
        }
    }
    fn показать(&self) -> String {
        match self {
            Знач::Целое(n) => n.to_string(),
            Знач::Логическое(b) => b.to_string(),
            Знач::Строка(s) => s.clone(),
            Знач::Пусто => "пусто".into(),
        }
    }
}

#[derive(Debug)]
enum Поток {
    Норма(Знач),
    Возврат(Знач),
}

#[derive(Debug, Clone)]
struct Функция {
    параметры: Vec<String>,
    тело: Узел,
}

// ---------------------------------------------------------------------------
// Profile data
// ---------------------------------------------------------------------------

#[derive(Debug, Default, Clone)]
struct СтатФункции {
    вызовов: u64,
    включительно_нс: u128,
    исключительно_нс: u128,
    аллокации: u64,
}

#[derive(Debug)]
struct Профиль {
    функции: HashMap<String, СтатФункции>,
    стеки: HashMap<String, u64>,
    начало: Instant,
    длительность: Duration,
    сэмплов: u64,
}

impl Профиль {
    fn новый() -> Self {
        Self {
            функции: HashMap::new(),
            стеки: HashMap::new(),
            начало: Instant::now(),
            длительность: Duration::ZERO,
            сэмплов: 0,
        }
    }

    fn закончить(&mut self) {
        self.длительность = self.начало.elapsed();
    }

    fn топ(&self, n: usize) -> Vec<(String, СтатФункции, f64)> {
        let сумма: u128 = self.функции.values().map(|s| s.исключительно_нс).sum();
        let база = сумма.max(1);
        let mut список: Vec<_> = self
            .функции
            .iter()
            .map(|(имя, ст)| {
                let pct = ст.исключительно_нс as f64 / база as f64 * 100.0;
                (имя.clone(), ст.clone(), pct)
            })
            .collect();
        список.sort_by(|a, b| b.1.исключительно_нс.cmp(&a.1.исключительно_нс));
        список.truncate(n);
        список
    }

    fn сохранить_json(&self, путь: &str) -> Result<()> {
        #[derive(Serialize)]
        struct JsonПрофиль {
            длительность_сек: f64,
            сэмплов: u64,
            функций: Vec<JsonФункция>,
        }
        #[derive(Serialize)]
        struct JsonФункция {
            имя: String,
            вызовов: u64,
            время_искл_сек: f64,
            время_вкл_сек: f64,
            процент: f64,
            аллокации: u64,
        }

        let функций = self
            .топ(100)
            .into_iter()
            .map(|(имя, ст, процент)| JsonФункция {
                имя,
                вызовов: ст.вызовов,
                время_искл_сек: ст.исключительно_нс as f64 / 1e9,
                время_вкл_сек: ст.включительно_нс as f64 / 1e9,
                процент,
                аллокации: ст.аллокации,
            })
            .collect();

        let профиль = JsonПрофиль {
            длительность_сек: self.длительность.as_secs_f64(),
            сэмплов: self.сэмплов,
            функций,
        };
        std::fs::write(путь, serde_json::to_string_pretty(&профиль)?)?;
        Ok(())
    }

    fn folded_текст(&self) -> String {
        let mut строки: Vec<_> = self.стеки.iter().collect();
        строки.sort_by(|a, b| a.0.cmp(b.0));
        let mut out = String::new();
        for (стек, count) in строки {
            out.push_str(стек);
            out.push(' ');
            out.push_str(&count.to_string());
            out.push('\n');
        }
        out
    }

    fn сохранить_flamegraph(&self, путь: &str) -> Result<()> {
        let svg_path = if путь.ends_with(".svg") {
            путь.to_string()
        } else {
            format!("{путь}.svg")
        };
        let folded_path = if svg_path.ends_with(".svg") {
            format!("{}.folded", &svg_path[..svg_path.len() - 4])
        } else {
            format!("{svg_path}.folded")
        };
        let folded = self.folded_текст();
        std::fs::write(&folded_path, &folded)?;

        let mut options = inferno::flamegraph::Options::default();
        options.title = "ЗИП-профиль".into();
        options.count_name = "samples".into();
        let файл = File::create(&svg_path)
            .with_context(|| format!("не удалось создать {svg_path}"))?;
        let writer = BufWriter::new(файл);
        inferno::flamegraph::from_lines(&mut options, folded.lines(), writer)
            .map_err(|е| anyhow::anyhow!("flamegraph: {е}"))?;

        println!("✓ Flamegraph: {svg_path}");
        println!("✓ Folded:     {folded_path}");
        Ok(())
    }
}


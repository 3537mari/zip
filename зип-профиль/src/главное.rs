// Instrumented interpreter
// ---------------------------------------------------------------------------

struct Профилировщик {
    функции: HashMap<String, Функция>,
    профиль: Профиль,
    стек: Vec<String>,
    детское_нс: Vec<u128>,
    последний_сэмпл: Instant,
    интервал_сэмпла: Duration,
    лимит: Option<Instant>,
    тихо: bool,
    тип: ТипПрофилирования,
}

impl Профилировщик {
    fn новый(частота: u32, тип: ТипПрофилирования, длительность: Option<u64>, тихо: bool) -> Self {
        let интервал = if частота == 0 {
            Duration::ZERO
        } else {
            Duration::from_secs_f64(1.0 / f64::from(частота))
        };
        Self {
            функции: HashMap::new(),
            профиль: Профиль::новый(),
            стек: Vec::new(),
            детское_нс: Vec::new(),
            последний_сэмпл: Instant::now(),
            интервал_сэмпла: интервал,
            лимит: длительность.map(|с| Instant::now() + Duration::from_secs(с)),
            тихо,
            тип,
        }
    }

    fn проверить_лимит(&self) -> Result<()> {
        if let Some(д) = self.лимит {
            if Instant::now() >= д {
                bail!("достигнут лимит длительности профилирования");
            }
        }
        Ok(())
    }

    fn сэмпл_стека(&mut self) {
        if self.стек.is_empty() {
            return;
        }
        let брать = self.интервал_сэмпла.is_zero()
            || self.последний_сэмпл.elapsed() >= self.интервал_сэмпла;
        if !брать {
            return;
        }
        let ключ = self.стек.join(";");
        *self.профиль.стеки.entry(ключ).or_insert(0) += 1;
        self.профиль.сэмплов += 1;
        self.последний_сэмпл = Instant::now();
    }

    fn собрать_функции(&mut self, узел: &Узел) {
        match узел {
            Узел::Программа { объявления } | Узел::Блок(объявления) => {
                for д in объявления {
                    self.собрать_функции(д);
                }
            }
            Узел::ОпределениеФункции {
                имя,
                параметры,
                тело,
                ..
            } => {
                self.функции.insert(
                    имя.clone(),
                    Функция {
                        параметры: параметры.iter().map(|(n, _)| n.clone()).collect(),
                        тело: (**тело).clone(),
                    },
                );
            }
            _ => {}
        }
    }

    fn запустить(&mut self, программа: &str) -> Result<()> {
        let текст = std::fs::read_to_string(программа)
            .with_context(|| format!("не удалось прочитать {программа}"))?;
        let дерево = разобрать_исходник(&текст).map_err(|е| anyhow::anyhow!("{е}"))?;
        self.собрать_функции(&дерево);

        if self.функции.contains_key("главная") {
            let _ = self.вызвать("главная", &[])?;
        } else {
            let mut локал = HashMap::new();
            let _ = self.выполнить_узел(&дерево, &mut локал)?;
        }
        self.профиль.закончить();
        Ok(())
    }

    fn вызвать(&mut self, имя: &str, аргументы: &[Знач]) -> Result<Знач> {
        self.проверить_лимит()?;

        if имя == "ПечатьЧисло" || имя == "печать_число" {
            if !self.тихо {
                if let Some(v) = аргументы.first() {
                    println!("{}", v.показать());
                }
            }
            return Ok(Знач::Пусто);
        }
        if имя == "ПечатьСтроки" || имя == "печать_строки" || имя == "печать" {
            if !self.тихо {
                if let Some(v) = аргументы.first() {
                    println!("{}", v.показать());
                }
            }
            return Ok(Знач::Пусто);
        }

        let ф = self
            .функции
            .get(имя)
            .cloned()
            .with_context(|| format!("нет функции «{имя}»"))?;

        let mut локал = HashMap::new();
        for (i, п) in ф.параметры.iter().enumerate() {
            локал.insert(
                п.clone(),
                аргументы.get(i).cloned().unwrap_or(Знач::Пусто),
            );
        }
        if matches!(
            self.тип,
            ТипПрофилирования::Аллокации | ТипПрофилирования::Память
        ) {
            self.профиль.функции.entry(имя.to_string()).or_default().аллокации +=
                локал.len() as u64 + 1;
        }

        self.стек.push(имя.to_string());
        self.детское_нс.push(0);
        self.сэмпл_стека();

        let t0 = Instant::now();
        let результат = match self.выполнить_узел(&ф.тело, &mut локал)? {
            Поток::Норма(v) | Поток::Возврат(v) => v,
        };
        let elapsed = t0.elapsed().as_nanos();

        let детское = self.детское_нс.pop().unwrap_or(0);
        self.стек.pop();
        if let Some(род) = self.детское_нс.last_mut() {
            *род += elapsed;
        }

        let ст = self.профиль.функции.entry(имя.to_string()).or_default();
        ст.вызовов += 1;
        ст.включительно_нс += elapsed;
        ст.исключительно_нс += elapsed.saturating_sub(детское);
        self.сэмпл_стека();
        Ok(результат)
    }

    fn выполнить_узел(&mut self, узел: &Узел, локал: &mut HashMap<String, Знач>) -> Result<Поток> {
        self.проверить_лимит()?;
        match узел {
            Узел::Программа { объявления } => {
                for д in объявления {
                    if matches!(д, Узел::ОпределениеФункции { .. }) {
                        continue;
                    }
                    if let Поток::Возврат(v) = self.выполнить_узел(д, локал)? {
                        return Ok(Поток::Возврат(v));
                    }
                }
                Ok(Поток::Норма(Знач::Пусто))
            }
            Узел::Блок(эл) => {
                let mut последний = Знач::Пусто;
                for е in эл {
                    match self.выполнить_узел(е, локал)? {
                        Поток::Возврат(v) => return Ok(Поток::Возврат(v)),
                        Поток::Норма(v) => последний = v,
                    }
                }
                Ok(Поток::Норма(последний))
            }
            Узел::Присваивание { имя, значение } => {
                let v = self.вычислить(значение, локал)?;
                локал.insert(имя.clone(), v);
                Ok(Поток::Норма(Знач::Пусто))
            }
            Узел::Возврат(з) => {
                let v = if let Some(e) = з {
                    self.вычислить(e, локал)?
                } else {
                    Знач::Пусто
                };
                Ok(Поток::Возврат(v))
            }
            Узел::Если {
                условие,
                тогда,
                иначе,
            } => {
                if self.вычислить(условие, локал)?.истина() {
                    self.выполнить_узел(тогда, локал)
                } else if let Some(и) = иначе {
                    self.выполнить_узел(и, локал)
                } else {
                    Ok(Поток::Норма(Знач::Пусто))
                }
            }
            Узел::Пока { условие, тело } => {
                while self.вычислить(условие, локал)?.истина() {
                    self.сэмпл_стека();
                    if let Поток::Возврат(v) = self.выполнить_узел(тело, локал)? {
                        return Ok(Поток::Возврат(v));
                    }
                }
                Ok(Поток::Норма(Знач::Пусто))
            }
            Узел::Для {
                переменная,
                коллекция,
                тело,
            } => {
                // диапазон(а, б) или пока не поддерживаем произвольные коллекции
                let (начало, конец) = self.диапазон(коллекция, локал)?;
                for i in начало..конец {
                    локал.insert(переменная.clone(), Знач::Целое(i));
                    self.сэмпл_стека();
                    if let Поток::Возврат(v) = self.выполнить_узел(тело, локал)? {
                        return Ok(Поток::Возврат(v));
                    }
                }
                Ok(Поток::Норма(Знач::Пусто))
            }
            Узел::ВызовФункции { имя, аргументы } => {
                let арги = self.вычислить_арги(аргументы, локал)?;
                Ok(Поток::Норма(self.вызвать(имя, &арги)?))
            }
            Узел::ВызовГлагола {
                глагол,
                аргументы,
                следующий,
            } => {
                let арги = self.вычислить_арги(аргументы, локал)?;
                let _ = self.вызвать(глагол, &арги)?;
                if let Some(с) = следующий {
                    return self.выполнить_узел(с, локал);
                }
                Ok(Поток::Норма(Знач::Пусто))
            }
            другой => {
                // выражение как инструкция
                let _ = self.вычислить(другой, локал)?;
                Ok(Поток::Норма(Знач::Пусто))
            }
        }
    }

    fn диапазон(
        &mut self,
        узел: &Узел,
        локал: &mut HashMap<String, Знач>,
    ) -> Result<(i64, i64)> {
        match узел {
            Узел::ВызовФункции { имя, аргументы }
                if имя == "диапазон" || имя == "Диапазон" =>
            {
                if аргументы.len() < 2 {
                    bail!("диапазон(начало, конец)");
                }
                let a = self.вычислить(&аргументы[0], локал)?.как_целое()?;
                let b = self.вычислить(&аргументы[1], локал)?.как_целое()?;
                Ok((a, b))
            }
            _ => bail!("цикл «для» ожидает диапазон(начало, конец)"),
        }
    }

    fn вычислить_арги(
        &mut self,
        аргументы: &[Узел],
        локал: &mut HashMap<String, Знач>,
    ) -> Result<Vec<Знач>> {
        аргументы
            .iter()
            .map(|a| self.вычислить(a, локал))
            .collect()
    }

    fn вычислить(&mut self, узел: &Узел, локал: &mut HashMap<String, Знач>) -> Result<Знач> {
        match узел {
            Узел::Целое(n) => Ok(Знач::Целое(*n)),
            Узел::Строка(s) => Ok(Знач::Строка(s.clone())),
            Узел::Истина => Ok(Знач::Логическое(true)),
            Узел::Ложь => Ok(Знач::Логическое(false)),
            Узел::Идентификатор(имя) => локал
                .get(имя)
                .cloned()
                .with_context(|| format!("неизвестная переменная «{имя}»")),
            Узел::УнарныйМинус(в) => Ok(Знач::Целое(-self.вычислить(в, локал)?.как_целое()?)),
            Узел::БинарнаяОперация {
                оператор,
                левый,
                правый,
            } => {
                let a = self.вычислить(левый, локал)?.как_целое()?;
                let b = self.вычислить(правый, локал)?.как_целое()?;
                let r = match оператор.as_str() {
                    "+" => a + b,
                    "-" => a - b,
                    "*" => a * b,
                    "/" => {
                        if b == 0 {
                            bail!("деление на ноль");
                        }
                        a / b
                    }
                    "%" => {
                        if b == 0 {
                            bail!("деление на ноль");
                        }
                        a % b
                    }
                    _ => bail!("оператор {оператор}"),
                };
                Ok(Знач::Целое(r))
            }
            Узел::Сравнение {
                оператор,
                левый,
                правый,
            } => {
                let a = self.вычислить(левый, локал)?.как_целое()?;
                let b = self.вычислить(правый, локал)?.как_целое()?;
                let r = match оператор.as_str() {
                    "<" => a < b,
                    ">" => a > b,
                    "<=" => a <= b,
                    ">=" => a >= b,
                    "==" | "=" => a == b,
                    "!=" => a != b,
                    _ => bail!("сравнение {оператор}"),
                };
                Ok(Знач::Логическое(r))
            }
            Узел::ЛогическоеИ(а, б) => {
                let av = self.вычислить(а, локал)?.истина();
                if !av {
                    return Ok(Знач::Логическое(false));
                }
                Ok(Знач::Логическое(self.вычислить(б, локал)?.истина()))
            }
            Узел::ЛогическоеИли(а, б) => {
                let av = self.вычислить(а, локал)?.истина();
                if av {
                    return Ok(Знач::Логическое(true));
                }
                Ok(Знач::Логическое(self.вычислить(б, локал)?.истина()))
            }
            Узел::ЛогическоеНе(а) => Ok(Знач::Логическое(!self.вычислить(а, локал)?.истина())),
            Узел::ВызовФункции { имя, аргументы } => {
                let арги = self.вычислить_арги(аргументы, локал)?;
                self.вызвать(имя, &арги)
            }
            Узел::Блок(_) => match self.выполнить_узел(узел, локал)? {
                Поток::Норма(v) | Поток::Возврат(v) => Ok(v),
            },
            другой => bail!("выражение не поддерживается: {другой:?}"),
        }
    }
}

// ---------------------------------------------------------------------------
// main
// ---------------------------------------------------------------------------

fn main() -> Result<()> {
    let аргументы = Аргументы::parse();

    println!("=== ЗИП-ПРОФИЛЬ v0.1.0 ===");
    println!("Программа: {}", аргументы.программа);
    println!("Тип: {}", аргументы.тип);
    if аргументы.частота == 0 {
        println!("Сэмплирование: на каждый вызов (instrumentation)");
    } else {
        println!("Частота: {} Гц", аргументы.частота);
    }
    println!();

    let mut профилировщик = Профилировщик::новый(
        аргументы.частота,
        аргументы.тип,
        аргументы.длительность,
        аргументы.тихо,
    );

    let начало = Instant::now();
    профилировщик.запустить(&аргументы.программа)?;
    let длительность = начало.elapsed();

    println!("Профилирование завершено за {длительность:?}");
    println!();

    println!("=== ТОП-{} ФУНКЦИЙ (exclusive) ===", аргументы.топ);
    println!(
        "{:>3}  {:<32} {:>12} {:>12} {:>8} {:>10}",
        "#", "функция", "искл. мс", "вкл. мс", "%", "вызовов"
    );
    for (i, (имя, ст, процент)) in профилировщик.профиль.топ(аргументы.топ).iter().enumerate()
    {
        println!(
            "{:3}. {:<32} {:>10.3} {:>10.3} {:>7.2}% {:>10}",
            i + 1,
            имя,
            ст.исключительно_нс as f64 / 1e6,
            ст.включительно_нс as f64 / 1e6,
            процент,
            ст.вызовов
        );
    }

    if let Some(путь) = &аргументы.json {
        профилировщик.профиль.сохранить_json(путь)?;
        println!();
        println!("✓ JSON: {путь}");
    }

    if let Some(путь) = &аргументы.svg {
        println!();
        профилировщик.профиль.сохранить_flamegraph(путь)?;
    }

    Ok(())
}

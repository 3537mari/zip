//! Интерпретатор байт-кода ZIP.

use crate::байткод::{Значение, Инструкция, Модуль, ОшибкаVM};
use crate::память::Память;
use crate::планировщик::Планировщик;
use crate::стек::{Кадр, СтекВызовов, СтекЗначений};

pub struct Исполнитель {
    модуль: Модуль,
    стек: СтекЗначений,
    регистры: Vec<Значение>,
    perfect: Vec<bool>,
    память: Память,
    вызовы: СтекВызовов,
    планировщик: Планировщик,
    функция: usize,
    указатель: usize,
    строки_модуля: Vec<String>,
}

impl Исполнитель {
    pub fn новый(модуль: Модуль) -> Result<Self, ОшибкаVM> {
        if модуль.функции.is_empty() {
            return Err(ОшибкаVM::новый("модуль без функций"));
        }
        let главная = модуль
            .функции
            .iter()
            .position(|ф| ф.имя == "главная" || ф.имя == "main")
            .unwrap_or(0);
        let локальные = модуль.функции[главная].локальные as usize;
        let регистры = vec![Значение::Целое(0); локальные.max(64)];
        let строки_модуля = модуль.строки.clone();
        Ok(Self {
            модуль,
            стек: СтекЗначений::новый(),
            регистры,
            perfect: vec![false; 256],
            память: Память::новая(4096),
            вызовы: СтекВызовов::новый(),
            планировщик: Планировщик::новый(),
            функция: главная,
            указатель: 0,
            строки_модуля,
        })
    }

    pub fn выполнить(&mut self) -> Result<Значение, ОшибкаVM> {
        loop {
            let инструкция = self.читать_инструкцию()?.clone();
            match инструкция {
                Инструкция::Nop => {}
                Инструкция::PushI64(n) => self.стек.push(Значение::Целое(n)),
                Инструкция::PushF64(x) => self.стек.push(Значение::Вещественное(x)),
                Инструкция::Add => {
                    let b = self.стек.pop()?;
                    let a = self.стек.pop()?;
                    self.стек.push(a.сложить(b)?);
                }
                Инструкция::Sub => {
                    let b = self.стек.pop()?;
                    let a = self.стек.pop()?;
                    self.стек.push(a.вычесть(b)?);
                }
                Инструкция::Mul => {
                    let b = self.стек.pop()?;
                    let a = self.стек.pop()?;
                    self.стек.push(a.умножить(b)?);
                }
                Инструкция::Div => {
                    let b = self.стек.pop()?;
                    let a = self.стек.pop()?;
                    self.стек.push(a.разделить(b)?);
                }
                Инструкция::CmpEq
                | Инструкция::CmpNe
                | Инструкция::CmpLt
                | Инструкция::CmpGt
                | Инструкция::CmpLe
                | Инструкция::CmpGe => {
                    let b = self.стек.pop()?.как_i64()?;
                    let a = self.стек.pop()?.как_i64()?;
                    let r = match инструкция {
                        Инструкция::CmpEq => a == b,
                        Инструкция::CmpNe => a != b,
                        Инструкция::CmpLt => a < b,
                        Инструкция::CmpGt => a > b,
                        Инструкция::CmpLe => a <= b,
                        Инструкция::CmpGe => a >= b,
                        _ => unreachable!(),
                    };
                    self.стек.push(Значение::Целое(if r { 1 } else { 0 }));
                }
                Инструкция::Pulse { из, в } => {
                    let з = self.регистр(из)?.clone();
                    self.установить_регистр(в, з)?;
                    self.установить_регистр(из, Значение::Пусто)?;
                }
                Инструкция::PulseWait(р) => {
                    self.планировщик.pulse_wait(р);
                }
                Инструкция::PerfectLock(р) => {
                    let idx = р as usize;
                    if idx >= self.perfect.len() {
                        self.perfect.resize(idx + 1, false);
                    }
                    self.perfect[idx] = true;
                    if let Ok(Значение::Указатель(а)) = self.регистр(р).cloned() {
                        self.память.perfect_lock(а);
                    }
                }
                Инструкция::ChoirSpawn(ф) => {
                    let арг = self.стек.pop().unwrap_or(Значение::Пусто);
                    self.планировщик.spawn(ф, арг);
                }
                Инструкция::ChoirJoin => {
                    let результаты = self.планировщик.join_все()?;
                    for з in результаты {
                        self.стек.push(з);
                    }
                }
                Инструкция::Load(р) => {
                    let з = self.регистр(р)?.clone();
                    self.стек.push(з);
                }
                Инструкция::Store(р) => {
                    let з = self.стек.pop()?;
                    self.установить_регистр(р, з)?;
                }
                Инструкция::Jump(адрес) => {
                    self.указатель = адрес as usize;
                }
                Инструкция::JumpIf(адрес) => {
                    let з = self.стек.pop()?;
                    if з.истинно() {
                        self.указатель = адрес as usize;
                    }
                }
                Инструкция::JumpIfNot(адрес) => {
                    let з = self.стек.pop()?;
                    if !з.истинно() {
                        self.указатель = адрес as usize;
                    }
                }
                Инструкция::Call(индекс) => {
                    let индекс = индекс as usize;
                    if индекс >= self.модуль.функции.len() {
                        return Err(ОшибкаVM::новый("вызов несуществующей функции"));
                    }
                    let параметры = self.модуль.функции[индекс].параметры as usize;
                    let mut аргументы = Vec::new();
                    for _ in 0..параметры {
                        аргументы.push(self.стек.pop()?);
                    }
                    аргументы.reverse();
                    self.вызовы.войти(Кадр {
                        функция: self.функция as u32,
                        возврат_ip: self.указатель,
                        база_локальных: 0,
                        база_стека: self.стек.длина(),
                    });
                    self.функция = индекс;
                    self.указатель = 0;
                    let локальные = self.модуль.функции[индекс].локальные as usize;
                    if self.регистры.len() < локальные {
                        self.регистры.resize(локальные, Значение::Целое(0));
                    }
                    for (i, а) in аргументы.into_iter().enumerate() {
                        self.регистры[i] = а;
                    }
                }
                Инструкция::Ret => {
                    let результат = self.стек.pop().unwrap_or(Значение::Пусто);
                    if self.вызовы.глубина() == 0 {
                        return Ok(результат);
                    }
                    let кадр = self.вызовы.выйти()?;
                    self.функция = кадр.функция as usize;
                    self.указатель = кадр.возврат_ip;
                    self.стек.обрезать(кадр.база_стека);
                    self.стек.push(результат);
                }
                Инструкция::Print => {
                    let з = self.стек.pop()?;
                    print!("{}", з);
                }
                Инструкция::PrintLn => {
                    let з = self.стек.pop()?;
                    // Если целое — как индекс строки модуля
                    if let Значение::Целое(i) = з {
                        if let Some(s) = self.строки_модуля.get(i as usize) {
                            println!("{}", s);
                        } else {
                            println!("{}", i);
                        }
                    } else {
                        println!("{}", з);
                    }
                }
                Инструкция::PrintI64 => {
                    let з = self.стек.pop()?;
                    println!("{}", з.как_i64()?);
                }
            }
        }
    }

    fn читать_инструкцию(&mut self) -> Result<&Инструкция, ОшибкаVM> {
        let код = &self.модуль.функции[self.функция].код;
        if self.указатель >= код.len() {
            return Err(ОшибкаVM::новый("конец кода без RET"));
        }
        let и = &self.модуль.функции[self.функция].код[self.указатель];
        self.указатель += 1;
        Ok(и)
    }

    fn регистр(&self, р: u16) -> Result<&Значение, ОшибкаVM> {
        self.регистры
            .get(р as usize)
            .ok_or_else(|| ОшибкаVM::новый(format!("регистр r{} вне диапазона", р)))
    }

    fn установить_регистр(&mut self, р: u16, з: Значение) -> Result<(), ОшибкаVM> {
        let idx = р as usize;
        if idx < self.perfect.len() && self.perfect[idx] {
            return Err(ОшибкаVM::новый(format!(
                "регистр r{} заблокирован PERFECT",
                р
            )));
        }
        if idx >= self.регистры.len() {
            self.регистры.resize(idx + 1, Значение::Целое(0));
        }
        self.регистры[idx] = з;
        Ok(())
    }
}

//! AST для ZIP-парсера в VM.

#[derive(Debug, Clone)]
pub struct Параметр {
    pub имя: String,
    pub тип_параметр: Option<String>,
}

#[derive(Debug, Clone)]
pub struct Аннотация {
    pub имя: String,
    pub параметры: Vec<(String, String)>,
}

#[derive(Debug, Clone)]
pub enum Узел {
    Программа {
        объявления: Vec<Узел>,
    },
    Функция {
        имя: String,
        параметры: Vec<Параметр>,
        тип_возврата: Option<String>,
        тело: Box<Узел>,
        аннотации: Vec<Аннотация>,
    },
    Директива {
        имя: String,
        значение: Option<String>,
    },
    Блок {
        инструкции: Vec<Узел>,
    },
    Вызов {
        имя: String,
        аргументы: Vec<Узел>,
    },
    Константа {
        значение_ц: Option<i64>,
        значение_в: Option<f64>,
        значение_с: Option<String>,
    },
    Идентификатор {
        имя: String,
    },
    БинарнаяОперация {
        оператор: String,
        левый: Box<Узел>,
        правый: Box<Узел>,
    },
    УнарнаяОперация {
        оператор: String,
        операнд: Box<Узел>,
    },
    Присваивание {
        имя: String,
        значение: Box<Узел>,
    },
    Если {
        условие: Box<Узел>,
        тогда: Box<Узел>,
        иначе: Option<Box<Узел>>,
    },
    Пока {
        условие: Box<Узел>,
        тело: Box<Узел>,
    },
    Для {
        переменная: String,
        начало: Box<Узел>,
        конец: Box<Узел>,
        тело: Box<Узел>,
    },
    Возврат {
        значение: Option<Box<Узел>>,
    },
    Прервать,
    Продолжить,
    ПотокДанных {
        левый: Box<Узел>,
        правый: Box<Узел>,
    },
    Фиксация {
        выражение: Box<Узел>,
    },
    Асинхронный {
        выражение: Box<Узел>,
    },
    Диапазон {
        начало: Box<Узел>,
        конец: Box<Узел>,
    },
}

impl Узел {
    pub fn число_функций(&self) -> usize {
        match self {
            Узел::Программа { объявления } => объявления
                .iter()
                .filter(|u| matches!(u, Узел::Функция { .. }))
                .count(),
            _ => 0,
        }
    }
}

#[derive(Debug)]
pub enum ОшибкаV3 {
    НетГлавной,
    ФункцияНеНайдена(u32),
    СтрокаНеНайдена(u32),
    РегистрНеНайден(u32),
    ПустойСтек,
    ПустойСтекКадров,
    ДелениеНаНоль,
    НеподдерживаемыйОпкод(String),
    ОшибкаВыполнения(String),
    Декод(ОшибкаДекодирования),
}

impl fmt::Display for ОшибкаV3 {
    fn fmt(&self, ф: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::НетГлавной => write!(ф, "Нет функции 'главная'"),
            Self::ФункцияНеНайдена(id) => write!(ф, "Функция {id} не найдена"),
            Self::СтрокаНеНайдена(и) => write!(ф, "Строка {и} не найдена"),
            Self::РегистрНеНайден(р) => write!(ф, "Регистр {р} не найден"),
            Self::ПустойСтек => write!(ф, "Пустой стек"),
            Self::ПустойСтекКадров => write!(ф, "Пустой стек кадров"),
            Self::ДелениеНаНоль => write!(ф, "Деление на ноль"),
            Self::НеподдерживаемыйОпкод(с) => write!(ф, "Неподдерживаемый опкод: {с}"),
            Self::ОшибкаВыполнения(с) => write!(ф, "Ошибка выполнения: {с}"),
            Self::Декод(е) => write!(ф, "Ошибка декодирования: {е}"),
        }
    }
}

impl std::error::Error for ОшибкаV3 {}

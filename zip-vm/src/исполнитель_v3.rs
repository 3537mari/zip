//! Интерпретатор байт-кода ZIP v3 (без LLVM).
//!
//! Работает с wire-форматом `.zipb`: декодирует `ФункцияV3.код` в `ИнстрV3`.

use crate::байткод_v3::{ИнстрV3, МодульV3, ФункцияV3};
use crate::байткод_v3_декодер::{декодировать_код, ОшибкаДекодирования};
use crate::встроенные_v3::Встроенные;
use std::collections::HashMap;
use std::fmt;

/// Значение в VM v3.
#[derive(Debug, Clone, PartialEq)]
pub enum ЗначениеV3 {
    Ничто,
    Целое(i64),
    Вещественное(f64),
    Строка(String),
    Флаг(bool),
    Множество(Vec<ЗначениеV3>),
    Итератор(Vec<ЗначениеV3>, usize),
    Нечто(Box<ЗначениеV3>),
    Успех(Box<ЗначениеV3>),
    Ошибка(String),
    Совершенное(Box<ЗначениеV3>),
}

impl ЗначениеV3 {
    pub fn как_целое(&self) -> i64 {
        match self {
            Self::Целое(n) => *n,
            Self::Вещественное(f) => *f as i64,
            Self::Флаг(b) => i64::from(*b),
            Self::Совершенное(в) | Self::Нечто(в) | Self::Успех(в) => в.как_целое(),
            _ => 0,
        }
    }

    pub fn как_вещественное(&self) -> f64 {
        match self {
            Self::Вещественное(f) => *f,
            Self::Целое(n) => *n as f64,
            Self::Совершенное(в) | Self::Нечто(в) | Self::Успех(в) => в.как_вещественное(),
            _ => 0.0,
        }
    }

    pub fn как_флаг(&self) -> bool {
        match self {
            Self::Флаг(b) => *b,
            Self::Целое(n) => *n != 0,
            Self::Ничто => false,
            Self::Ошибка(_) => false,
            Self::Совершенное(в) | Self::Нечто(в) | Self::Успех(в) => в.как_флаг(),
            _ => true,
        }
    }

    pub fn тип_имя(&self) -> &'static str {
        match self {
            Self::Ничто => "Ничто",
            Self::Целое(_) => "Целое",
            Self::Вещественное(_) => "Вещественное",
            Self::Строка(_) => "Строка",
            Self::Флаг(_) => "Флаг",
            Self::Множество(_) => "Множество",
            Self::Итератор(_, _) => "Итератор",
            Self::Нечто(_) => "Нечто",
            Self::Успех(_) => "Успех",
            Self::Ошибка(_) => "Ошибка",
            Self::Совершенное(_) => "Совершенное",
        }
    }
}

impl fmt::Display for ЗначениеV3 {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::Ничто => write!(f, "Ничто"),
            Self::Целое(n) => write!(f, "{n}"),
            Self::Вещественное(x) => write!(f, "{x}"),
            Self::Строка(s) => write!(f, "{s}"),
            Self::Флаг(b) => write!(f, "{b}"),
            Self::Множество(м) => write!(f, "Множество({})", м.len()),
            Self::Итератор(м, i) => write!(f, "Итератор({i}/{})", м.len()),
            Self::Нечто(в) => write!(f, "Нечто({в})"),
            Self::Успех(в) => write!(f, "Успех({в})"),
            Self::Ошибка(s) => write!(f, "Ошибка({s})"),
            Self::Совершенное(в) => write!(f, "Совершенное({в})"),
        }
    }
}

#[derive(Debug)]
struct ИсполняемаяФункция {
    #[allow(dead_code)]
    id: u32,
    имя: String,
    арность: u16,
    локалы: u16,
    #[allow(dead_code)]
    флаги: u32,
    инструкции: Vec<ИнстрV3>,
}

#[derive(Debug)]
struct КадрV3 {
    функция_id: u32,
    регистры: Vec<ЗначениеV3>,
    указатель: usize,
    база_стека: usize,
}

/// Виртуальная машина v3.
pub struct ИсполнительV3 {
    функции: Vec<ИсполняемаяФункция>,
    строки: Vec<String>,
    стек: Vec<ЗначениеV3>,
    кадры: Vec<КадрV3>,
    #[allow(dead_code)]
    куча: HashMap<u64, ЗначениеV3>,
    структуры: HashMap<u64, Vec<ЗначениеV3>>,
    следующий_адрес: u64,
    встроенные: Встроенные,
    хор: Vec<ЗначениеV3>,
    /// Глубины кадров, после которых Ret кладёт результат в `хор`.
    хор_ожидание: Vec<usize>,
}

impl ИсполнительV3 {
    pub fn новый(модуль: МодульV3) -> Result<Self, ОшибкаV3> {
        let mut функции = Vec::with_capacity(модуль.функции.len());
        for (id, ф) in модуль.функции.into_iter().enumerate() {
            let имя = модуль
                .строки
                .get(ф.имя_индекс as usize)
                .cloned()
                .unwrap_or_else(|| format!("fn_{id}"));
            let инструкции = декодировать_код(&ф.код).map_err(|е| ОшибкаV3::Декод(е))?;
            функции.push(ИсполняемаяФункция {
                id: id as u32,
                имя,
                арность: ф.арность,
                локалы: ф.локалы,
                флаги: ф.флаги,
                инструкции,
            });
        }
        Ok(Self {
            функции,
            строки: модуль.строки,
            стек: Vec::with_capacity(1024),
            кадры: Vec::with_capacity(64),
            куча: HashMap::new(),
            структуры: HashMap::new(),
            следующий_адрес: 1,
            встроенные: Встроенные::новый(),
            хор: Vec::new(),
            хор_ожидание: Vec::new(),
        })
    }

    /// Собрать модуль из готовых инструкций (для тестов).
    pub fn из_инструкций(имя: &str, инструкции: Vec<ИнстрV3>, локалы: u16) -> Result<Self, ОшибкаV3> {
        let mut код = Vec::new();
        for и in &инструкции {
            и.закодировать(&mut код);
        }
        let модуль = МодульV3 {
            флаги: 0,
            строки: vec![имя.into()],
            функции: vec![ФункцияV3 {
                имя_индекс: 0,
                арность: 0,
                локалы,
                флаги: 0,
                код,
            }],
        };
        Self::новый(модуль)
    }

    pub fn запустить(&mut self) -> Result<ЗначениеV3, ОшибкаV3> {
        let id = self
            .функции
            .iter()
            .position(|ф| ф.имя == "главная" || ф.имя == "main")
            .unwrap_or(0) as u32;
        self.войти(id, vec![])?;
        self.выполнить_цикл()
    }

    fn войти(&mut self, id: u32, аргументы: Vec<ЗначениеV3>) -> Result<(), ОшибкаV3> {
        let ф = self
            .функции
            .get(id as usize)
            .ok_or(ОшибкаV3::ФункцияНеНайдена(id))?;
        let n = ф.локалы.max(ф.арность).max(4) as usize;
        let mut регистры = vec![ЗначениеV3::Ничто; n.max(64)];
        for (i, арг) in аргументы.into_iter().enumerate() {
            if i < регистры.len() {
                регистры[i] = арг;
            }
        }
        self.кадры.push(КадрV3 {
            функция_id: id,
            регистры,
            указатель: 0,
            база_стека: self.стек.len(),
        });
        Ok(())
    }

    fn выполнить_цикл(&mut self) -> Result<ЗначениеV3, ОшибкаV3> {
        loop {
            if self.кадры.is_empty() {
                return Ok(self.стек.pop().unwrap_or(ЗначениеV3::Ничто));
            }

            let (fid, ip) = {
                let к = self.кадры.last().unwrap();
                (к.функция_id, к.указатель)
            };

            let инструкция = {
                let ф = self
                    .функции
                    .get(fid as usize)
                    .ok_or(ОшибкаV3::ФункцияНеНайдена(fid))?;
                if ip >= ф.инструкции.len() {
                    // конец без RET
                    let база = self.кадры.last().unwrap().база_стека;
                    self.кадры.pop();
                    self.стек.truncate(база);
                    self.стек.push(ЗначениеV3::Ничто);
                    continue;
                }
                ф.инструкции[ip].clone()
            };

            self.кадры.last_mut().unwrap().указатель = ip + 1;

            let стек_ошибка = |эта: &Self, инстр: &ИнстрV3| -> ОшибкаV3 {
                let имя = эта
                    .функции
                    .get(fid as usize)
                    .map(|ф| ф.имя.clone())
                    .unwrap_or_default();
                ОшибкаV3::ОшибкаВыполнения(format!(
                    "Пустой стек в {имя} ip={ip} инстр={инстр:?} глубина={}",
                    эта.стек.len()
                ))
            };

            match инструкция {
                ИнстрV3::Nop => {}
                ИнстрV3::Pop => {
                    /* Пустой стек — no-op: лишний POP после PRINT/др. не роняет VM. */
                    let _ = self.стек.pop();
                }
                ИнстрV3::Dup => {
                    let в = self
                        .стек
                        .last()
                        .cloned()
                        .ok_or_else(|| стек_ошибка(self, &инструкция))?;
                    self.стек.push(в);
                }
                ИнстрV3::Swap => {
                    let б = self.стек.pop().ok_or(ОшибкаV3::ПустойСтек)?;
                    let а = self.стек.pop().ok_or(ОшибкаV3::ПустойСтек)?;
                    self.стек.push(б);
                    self.стек.push(а);
                }

                ИнстрV3::PushI64(n) => self.стек.push(ЗначениеV3::Целое(n)),
                ИнстрV3::PushF64(f) => self.стек.push(ЗначениеV3::Вещественное(f)),
                ИнстрV3::PushStr(индекс) => {
                    let строка = self
                        .строки
                        .get(индекс as usize)
                        .ok_or(ОшибкаV3::СтрокаНеНайдена(индекс))?
                        .clone();
                    self.стек.push(ЗначениеV3::Строка(строка));
                }
                ИнстрV3::PushNull => self.стек.push(ЗначениеV3::Ничто),
                ИнстрV3::PushTrue => self.стек.push(ЗначениеV3::Флаг(true)),
                ИнстрV3::PushFalse => self.стек.push(ЗначениеV3::Флаг(false)),

                ИнстрV3::Add => {
                    let б = self.стек.pop().ok_or(ОшибкаV3::ПустойСтек)?;
                    let а = self.стек.pop().ok_or(ОшибкаV3::ПустойСтек)?;
                    let р = if matches!(а, ЗначениеV3::Вещественное(_))
                        || matches!(б, ЗначениеV3::Вещественное(_))
                    {
                        ЗначениеV3::Вещественное(а.как_вещественное() + б.как_вещественное())
                    } else {
                        ЗначениеV3::Целое(а.как_целое() + б.как_целое())
                    };
                    self.стек.push(р);
                }
                ИнстрV3::Sub => {
                    let б = self.стек.pop().ok_or(ОшибкаV3::ПустойСтек)?;
                    let а = self.стек.pop().ok_or(ОшибкаV3::ПустойСтек)?;
                    self.стек
                        .push(ЗначениеV3::Целое(а.как_целое() - б.как_целое()));
                }
                ИнстрV3::Mul => {
                    let б = self.стек.pop().ok_or(ОшибкаV3::ПустойСтек)?;
                    let а = self.стек.pop().ok_or(ОшибкаV3::ПустойСтек)?;
                    self.стек
                        .push(ЗначениеV3::Целое(а.как_целое() * б.как_целое()));
                }
                ИнстрV3::Div => {
                    let б = self.стек.pop().ok_or(ОшибкаV3::ПустойСтек)?;
                    let а = self.стек.pop().ok_or(ОшибкаV3::ПустойСтек)?;
                    if б.как_целое() == 0 {
                        return Err(ОшибкаV3::ДелениеНаНоль);
                    }
                    self.стек
                        .push(ЗначениеV3::Целое(а.как_целое() / б.как_целое()));
                }
                ИнстрV3::Mod => {
                    let б = self.стек.pop().ok_or(ОшибкаV3::ПустойСтек)?;
                    let а = self.стек.pop().ok_or(ОшибкаV3::ПустойСтек)?;
                    if б.как_целое() == 0 {
                        return Err(ОшибкаV3::ДелениеНаНоль);
                    }
                    self.стек
                        .push(ЗначениеV3::Целое(а.как_целое() % б.как_целое()));
                }

                ИнстрV3::Eq => {
                    let б = self.стек.pop().ok_or(ОшибкаV3::ПустойСтек)?;
                    let а = self.стек.pop().ok_or(ОшибкаV3::ПустойСтек)?;
                    self.стек.push(ЗначениеV3::Флаг(а == б));
                }
                ИнстрV3::Ne => {
                    let б = self.стек.pop().ok_or(ОшибкаV3::ПустойСтек)?;
                    let а = self.стек.pop().ok_or(ОшибкаV3::ПустойСтек)?;
                    self.стек.push(ЗначениеV3::Флаг(а != б));
                }
                ИнстрV3::Lt => {
                    let б = self.стек.pop().ok_or(ОшибкаV3::ПустойСтек)?;
                    let а = self.стек.pop().ok_or(ОшибкаV3::ПустойСтек)?;
                    self.стек
                        .push(ЗначениеV3::Флаг(а.как_целое() < б.как_целое()));
                }
                ИнстрV3::Le => {
                    let б = self.стек.pop().ok_or(ОшибкаV3::ПустойСтек)?;
                    let а = self.стек.pop().ok_or(ОшибкаV3::ПустойСтек)?;
                    self.стек
                        .push(ЗначениеV3::Флаг(а.как_целое() <= б.как_целое()));
                }
                ИнстрV3::Gt => {
                    let б = self.стек.pop().ok_or(ОшибкаV3::ПустойСтек)?;
                    let а = self.стек.pop().ok_or(ОшибкаV3::ПустойСтек)?;
                    self.стек
                        .push(ЗначениеV3::Флаг(а.как_целое() > б.как_целое()));
                }
                ИнстрV3::Ge => {
                    let б = self.стек.pop().ok_or(ОшибкаV3::ПустойСтек)?;
                    let а = self.стек.pop().ok_or(ОшибкаV3::ПустойСтек)?;
                    self.стек
                        .push(ЗначениеV3::Флаг(а.как_целое() >= б.как_целое()));
                }

                ИнстрV3::Load(регистр) => {
                    let кадр = self.кадры.last().ok_or(ОшибкаV3::ПустойСтекКадров)?;
                    let значение = кадр
                        .регистры
                        .get(регистр as usize)
                        .cloned()
                        .unwrap_or(ЗначениеV3::Ничто);
                    self.стек.push(значение);
                }
                ИнстрV3::Store(регистр) => {
                    let значение = self.стек.pop().ok_or(ОшибкаV3::ПустойСтек)?;
                    let кадр = self.кадры.last_mut().ok_or(ОшибкаV3::ПустойСтекКадров)?;
                    let i = регистр as usize;
                    if i >= кадр.регистры.len() {
                        кадр.регистры.resize(i + 1, ЗначениеV3::Ничто);
                    }
                    кадр.регистры[i] = значение;
                }

                ИнстрV3::Jump(адрес) => {
                    self.кадры.last_mut().unwrap().указатель = адрес as usize;
                }
                ИнстрV3::JumpIf(адрес) => {
                    let условие = self
                        .стек
                        .pop()
                        .ok_or_else(|| стек_ошибка(self, &инструкция))?;
                    if условие.как_флаг() {
                        self.кадры.last_mut().unwrap().указатель = адрес as usize;
                    }
                }
                ИнстрV3::JumpIfNot(адрес) => {
                    let условие = self
                        .стек
                        .pop()
                        .ok_or_else(|| стек_ошибка(self, &инструкция))?;
                    if !условие.как_флаг() {
                        self.кадры.last_mut().unwrap().указатель = адрес as usize;
                    }
                }

                ИнстрV3::Call(функция_id) => {
                    self.вызвать_по_id(функция_id).map_err(|e| {
                        if matches!(e, ОшибкаV3::ПустойСтек) {
                            стек_ошибка(self, &инструкция)
                        } else {
                            e
                        }
                    })?;
                }
                ИнстрV3::AsyncCall(функция_id) => {
                    // MVP: синхронно
                    self.вызвать_по_id(функция_id)?;
                }
                ИнстрV3::CallNative { lib, fun } => {
                    let имя_fun = self
                        .строки
                        .get(fun as usize)
                        .cloned()
                        .unwrap_or_default();
                    let имя_lib = self.строки.get(lib as usize).cloned().unwrap_or_default();
                    // Аргументы — только верхние N (арность native), иначе мусор ниже
                    // на стеке (промежуточные значения) попадает в arg[0] и ломает id буферов.
                    let база = self.кадры.last().map(|к| к.база_стека).unwrap_or(0);
                    let доступно = self.стек.len().saturating_sub(база);
                    let n = арность_native(&имя_fun).unwrap_or(доступно).min(доступно);
                    let start = self.стек.len() - n;
                    let арги: Vec<_> = self.стек[start..].to_vec();
                    self.стек.truncate(start);
                    let результат = if self.встроенные.существует(&имя_fun) {
                        self.встроенные
                            .вызвать(&имя_fun, &арги)
                            .map_err(ОшибкаV3::ОшибкаВыполнения)?
                    } else if имя_fun == "zip_syscall" || имя_fun == "syscall" {
                        self.встроенные
                            .вызвать("zip_syscall", &арги)
                            .map_err(ОшибкаV3::ОшибкаВыполнения)?
                    } else {
                        return Err(ОшибкаV3::ОшибкаВыполнения(format!(
                            "Функция {имя_lib}::{имя_fun} не найдена"
                        )));
                    };
                    self.стек.push(результат);
                }
                ИнстрV3::Ret => {
                    let результат = self.стек.pop().unwrap_or(ЗначениеV3::Ничто);
                    let база = self.кадры.last().unwrap().база_стека;
                    self.кадры.pop();
                    self.стек.truncate(база);
                    if let Some(ожид) = self.хор_ожидание.last().copied() {
                        if self.кадры.len() == ожид {
                            self.хор_ожидание.pop();
                            self.хор.push(результат.clone());
                        }
                    }
                    if self.кадры.is_empty() {
                        return Ok(результат);
                    }
                    self.стек.push(результат);
                }

                ИнстрV3::Pulse { из, в } => {
                    let кадр = self.кадры.last_mut().ok_or(ОшибкаV3::ПустойСтекКадров)?;
                    let i = из as usize;
                    let j = в as usize;
                    let max = i.max(j) + 1;
                    if кадр.регистры.len() < max {
                        кадр.регистры.resize(max, ЗначениеV3::Ничто);
                    }
                    let значение = std::mem::replace(&mut кадр.регистры[i], ЗначениеV3::Ничто);
                    кадр.регистры[j] = значение;
                }
                ИнстрV3::PerfectLock(регистр) => {
                    let кадр = self.кадры.last_mut().ok_or(ОшибкаV3::ПустойСтекКадров)?;
                    let i = регистр as usize;
                    if i >= кадр.регистры.len() {
                        кадр.регистры.resize(i + 1, ЗначениеV3::Ничто);
                    }
                    let значение = std::mem::replace(&mut кадр.регистры[i], ЗначениеV3::Ничто);
                    кадр.регистры[i] = ЗначениеV3::Совершенное(Box::new(значение));
                }
                ИнстрV3::ChoirSpawn(функция_id) => {
                    // Запомнить глубину: после возврата результат уйдёт в хор
                    let глубина = self.кадры.len();
                    self.вызвать_по_id(функция_id)?;
                    if self.кадры.len() > глубина {
                        // кадр запушен — пометим «хор» флагом через базу_стека sentinel:
                        // результат обработаем при Ret, если хор_ожидание > 0
                        self.хор_ожидание.push(глубина);
                    } else {
                        // встроенная — результат уже на стеке
                        let р = self.стек.pop().unwrap_or(ЗначениеV3::Ничто);
                        self.хор.push(р);
                    }
                }
                ИнстрV3::ChoirJoin => {
                    let сум = self.хор.drain(..).fold(0i64, |a, з| a + з.как_целое());
                    self.стек.push(ЗначениеV3::Целое(сум));
                }

                ИнстрV3::NewSet => self.стек.push(ЗначениеV3::Множество(Vec::new())),
                ИнстрV3::NewIter => {
                    let м = match self.стек.pop().unwrap_or(ЗначениеV3::Множество(vec![])) {
                        ЗначениеV3::Множество(v) => v,
                        _ => vec![],
                    };
                    self.стек.push(ЗначениеV3::Итератор(м, 0));
                }
                ИнстрV3::NewNothing => self.стек.push(ЗначениеV3::Ничто),
                ИнстрV3::NewSomething => {
                    let в = self.стек.pop().ok_or(ОшибкаV3::ПустойСтек)?;
                    self.стек.push(ЗначениеV3::Нечто(Box::new(в)));
                }
                ИнстрV3::NewSuccess => {
                    let в = self.стек.pop().ok_or(ОшибкаV3::ПустойСтек)?;
                    self.стек.push(ЗначениеV3::Успех(Box::new(в)));
                }
                ИнстрV3::NewError => {
                    let сообщение = self.стек.pop().ok_or(ОшибкаV3::ПустойСтек)?;
                    let текст = match сообщение {
                        ЗначениеV3::Строка(s) => s,
                        з => з.to_string(),
                    };
                    self.стек.push(ЗначениеV3::Ошибка(текст));
                }
                ИнстрV3::CheckTag => {
                    let в = self.стек.pop().ok_or(ОшибкаV3::ПустойСтек)?;
                    let имя = в.тип_имя();
                    self.стек.push(в);
                    self.стек.push(ЗначениеV3::Строка(имя.into()));
                }

                ИнстрV3::Print => {
                    let в = self.стек.pop().ok_or(ОшибкаV3::ПустойСтек)?;
                    print!("{в}");
                    self.стек.push(ЗначениеV3::Ничто);
                }
                ИнстрV3::PrintLn => {
                    let в = self.стек.pop().ok_or(ОшибкаV3::ПустойСтек)?;
                    println!("{в}");
                    self.стек.push(ЗначениеV3::Ничто);
                }
                ИнстрV3::PrintI64 => {
                    let в = self.стек.pop().ok_or(ОшибкаV3::ПустойСтек)?;
                    println!("{}", в.как_целое());
                    self.стек.push(ЗначениеV3::Ничто);
                }

                ИнстрV3::NewStruct(nfields) => {
                    let id = self.следующий_адрес;
                    self.следующий_адрес += 1;
                    self.структуры
                        .insert(id, vec![ЗначениеV3::Ничто; nfields as usize]);
                    self.стек.push(ЗначениеV3::Целое(id as i64));
                }
                ИнстрV3::LoadField(смещение) => {
                    let адрес = self.стек.pop().ok_or(ОшибкаV3::ПустойСтек)?.как_целое() as u64;
                    let поля = self
                        .структуры
                        .get(&адрес)
                        .ok_or_else(|| ОшибкаV3::ОшибкаВыполнения(format!("struct {адрес}")))?;
                    let значение = поля
                        .get(смещение as usize)
                        .cloned()
                        .unwrap_or(ЗначениеV3::Ничто);
                    self.стек.push(значение);
                }
                ИнстрV3::StoreField(смещение) => {
                    let значение = self.стек.pop().ok_or(ОшибкаV3::ПустойСтек)?;
                    let адрес = self.стек.pop().ok_or(ОшибкаV3::ПустойСтек)?.как_целое() as u64;
                    let поля = self
                        .структуры
                        .get_mut(&адрес)
                        .ok_or_else(|| ОшибкаV3::ОшибкаВыполнения(format!("struct {адрес}")))?;
                    let i = смещение as usize;
                    if i >= поля.len() {
                        поля.resize(i + 1, ЗначениеV3::Ничто);
                    }
                    поля[i] = значение;
                }
                ИнстрV3::GetFieldPtr(смещение) => {
                    /* MVP: указатель на поле = (handle << 32) | offset */
                    let адрес = self.стек.pop().ok_or(ОшибкаV3::ПустойСтек)?.как_целое() as u64;
                    let ptr = (адрес << 32) | (смещение as u64);
                    self.стек.push(ЗначениеV3::Целое(ptr as i64));
                }

                ИнстрV3::NewArray(размер) => {
                    let id = self.следующий_адрес;
                    self.следующий_адрес += 1;
                    self.структуры
                        .insert(id, vec![ЗначениеV3::Ничто; размер as usize]);
                    self.стек.push(ЗначениеV3::Целое(id as i64));
                }
                ИнстрV3::LoadIndex => {
                    let индекс = self.стек.pop().ok_or(ОшибкаV3::ПустойСтек)?.как_целое();
                    let адрес = self.стек.pop().ok_or(ОшибкаV3::ПустойСтек)?.как_целое() as u64;
                    let имя = self
                        .кадры
                        .last()
                        .and_then(|к| self.функции.get(к.функция_id as usize))
                        .map(|ф| ф.имя.clone())
                        .unwrap_or_default();
                    let массив = self.структуры.get(&адрес).ok_or_else(|| {
                        ОшибкаV3::ОшибкаВыполнения(format!(
                            "массив {адрес} не найден (LoadIndex в {имя}, индекс {индекс})"
                        ))
                    })?;
                    if индекс < 0 || (индекс as usize) >= массив.len() {
                        return Err(ОшибкаV3::ОшибкаВыполнения(format!(
                            "индекс {индекс} за границами (длина {}, id {})",
                            массив.len(),
                            адрес
                        )));
                    }
                    let значение = массив[индекс as usize].clone();
                    self.стек.push(значение);
                }
                ИнстрV3::StoreIndex => {
                    let индекс = self.стек.pop().ok_or(ОшибкаV3::ПустойСтек)?.как_целое();
                    let значение = self.стек.pop().ok_or(ОшибкаV3::ПустойСтек)?;
                    let адрес = self.стек.pop().ok_or(ОшибкаV3::ПустойСтек)?.как_целое() as u64;
                    let массив = self.структуры.get_mut(&адрес).ok_or_else(|| {
                        ОшибкаV3::ОшибкаВыполнения(format!("массив {адрес} не найден"))
                    })?;
                    if индекс < 0 {
                        return Err(ОшибкаV3::ОшибкаВыполнения(format!(
                            "индекс {индекс} за границами"
                        )));
                    }
                    let i = индекс as usize;
                    if i >= массив.len() {
                        массив.resize(i + 1, ЗначениеV3::Ничто);
                    }
                    массив[i] = значение;
                }
                ИнстрV3::ArrayLen => {
                    let адрес = self.стек.pop().ok_or(ОшибкаV3::ПустойСтек)?.как_целое() as u64;
                    let длина = self.структуры.get(&адрес).map(|м| м.len()).unwrap_or(0);
                    self.стек.push(ЗначениеV3::Целое(длина as i64));
                }

                ИнстрV3::AddrOf(слот) => {
                    /* Локальный адрес: LOCAL_BASE | slot */
                    const LOCAL_BASE: u64 = 0x8000_0000_0000_0000;
                    self.стек
                        .push(ЗначениеV3::Целое((LOCAL_BASE | (слот as u64)) as i64));
                }
                ИнстрV3::Deref | ИнстрV3::LoadPtr => {
                    let адрес = self.стек.pop().ok_or(ОшибкаV3::ПустойСтек)?.как_целое() as u64;
                    let значение = self.прочитать_память(адрес)?;
                    self.стек.push(значение);
                }
                ИнстрV3::StorePtr => {
                    let значение = self.стек.pop().ok_or(ОшибкаV3::ПустойСтек)?;
                    let адрес = self.стек.pop().ok_or(ОшибкаV3::ПустойСтек)?.как_целое() as u64;
                    self.записать_память(адрес, значение)?;
                }
                ИнстрV3::Alloc => {
                    let размер = self.стек.pop().ok_or(ОшибкаV3::ПустойСтек)?.как_целое();
                    if размер < 0 {
                        return Err(ОшибкаV3::ОшибкаВыполнения("отрицательный размер".into()));
                    }
                    let база = self.следующий_адрес;
                    /* bump: резервируем диапазон байт/ячеек */
                    self.следующий_адрес = база.saturating_add(размер as u64).max(база + 1);
                    self.стек.push(ЗначениеV3::Целое(база as i64));
                }
                ИнстрV3::Free => {
                    let _адрес = self.стек.pop().ok_or(ОшибкаV3::ПустойСтек)?;
                    /* bump allocator: освобождение — no-op */
                    self.стек.push(ЗначениеV3::Ничто);
                }
                ИнстрV3::PtrAdd => {
                    let смещение = self.стек.pop().ok_or(ОшибкаV3::ПустойСтек)?.как_целое();
                    let адрес = self.стек.pop().ok_or(ОшибкаV3::ПустойСтек)?.как_целое();
                    self.стек.push(ЗначениеV3::Целое(адрес + смещение));
                }
                ИнстрV3::PtrSub => {
                    let смещение = self.стек.pop().ok_or(ОшибкаV3::ПустойСтек)?.как_целое();
                    let адрес = self.стек.pop().ok_or(ОшибкаV3::ПустойСтек)?.как_целое();
                    self.стек.push(ЗначениеV3::Целое(адрес - смещение));
                }
                ИнстрV3::PtrDiff => {
                    let б = self.стек.pop().ok_or(ОшибкаV3::ПустойСтек)?.как_целое();
                    let а = self.стек.pop().ok_or(ОшибкаV3::ПустойСтек)?.как_целое();
                    self.стек.push(ЗначениеV3::Целое(а - б));
                }
            }
        }
    }

    fn прочитать_память(&self, адрес: u64) -> Result<ЗначениеV3, ОшибкаV3> {
        const LOCAL_BASE: u64 = 0x8000_0000_0000_0000;
        if адрес & LOCAL_BASE != 0 {
            let слот = (адрес & !LOCAL_BASE) as usize;
            let кадр = self.кадры.last().ok_or(ОшибкаV3::ПустойСтекКадров)?;
            return Ok(кадр
                .регистры
                .get(слот)
                .cloned()
                .unwrap_or(ЗначениеV3::Ничто));
        }
        Ok(self
            .куча
            .get(&адрес)
            .cloned()
            .unwrap_or(ЗначениеV3::Ничто))
    }

    fn записать_память(&mut self, адрес: u64, значение: ЗначениеV3) -> Result<(), ОшибкаV3> {
        const LOCAL_BASE: u64 = 0x8000_0000_0000_0000;
        if адрес & LOCAL_BASE != 0 {
            let слот = (адрес & !LOCAL_BASE) as usize;
            let кадр = self.кадры.last_mut().ok_or(ОшибкаV3::ПустойСтекКадров)?;
            if слот >= кадр.регистры.len() {
                кадр.регистры.resize(слот + 1, ЗначениеV3::Ничто);
            }
            кадр.регистры[слот] = значение;
            return Ok(());
        }
        self.куча.insert(адрес, значение);
        Ok(())
    }

    fn вызвать_по_id(&mut self, функция_id: u32) -> Result<(), ОшибкаV3> {
        let (имя, арность) = {
            let ф = self
                .функции
                .get(функция_id as usize)
                .ok_or(ОшибкаV3::ФункцияНеНайдена(функция_id))?;
            (ф.имя.clone(), ф.арность as usize)
        };

        let mut арги = Vec::with_capacity(арность);
        for _ in 0..арность {
            арги.push(self.стек.pop().ok_or(ОшибкаV3::ПустойСтек)?);
        }
        арги.reverse();

        if self.встроенные.существует(&имя) {
            let р = self
                .встроенные
                .вызвать(&имя, &арги)
                .map_err(ОшибкаV3::ОшибкаВыполнения)?;
            self.стек.push(р);
            return Ok(());
        }

        self.войти(функция_id, арги)
    }

    pub fn стек(&self) -> &[ЗначениеV3] {
        &self.стек
    }

    pub fn число_функций(&self) -> usize {
        self.функции.len()
    }

    pub fn число_строк(&self) -> usize {
        self.строки.len()
    }
}


//! Компиляция упрощённого IR → байт-код ZIP v3.
//!
//! Полный пайплайн из `zipc::промежуток::ФункцияПП` — в `zipc::байткод_эмиттер_v3`
//! (чтобы не создавать циклическую зависимость crate'ов).

use crate::байткод_v3::{сериализовать_v3, ИнстрV3, МодульV3, ФункцияV3};

/// Упрощённая функция для эмиссии v3 (зеркало нужных полей ПП).
#[derive(Debug, Clone)]
pub struct ФункцияИсходник {
    pub имя: String,
    pub арность: u16,
    pub локалы: u16,
    pub асинхронная: bool,
    pub совершенная: bool,
    pub comptime: bool,
    pub инструкции: Vec<ИнстрV3>,
}

/// Скомпилировать список функций в байты `.zipb`.
pub fn скомпилировать_в_байткод(функции: &[ФункцияИсходник]) -> Vec<u8> {
    let mut строки = Vec::new();
    let mut индекс = |s: &str| -> u32 {
        if let Some(i) = строки.iter().position(|x| x == s) {
            return i as u32;
        }
        строки.push(s.to_string());
        (строки.len() - 1) as u32
    };

    let mut outs = Vec::new();
    for ф in функции {
        let имя_индекс = индекс(&ф.имя);
        let mut код = Vec::new();
        for и in &ф.инструкции {
            и.закодировать(&mut код);
        }
        if !ф.инструкции.iter().any(|i| matches!(i, ИнстрV3::Ret)) {
            ИнстрV3::PushI64(0).закодировать(&mut код);
            ИнстрV3::Ret.закодировать(&mut код);
        }
        let флаги = (ф.асинхронная as u32)
            | ((ф.совершенная as u32) << 1)
            | ((ф.comptime as u32) << 2);
        outs.push(ФункцияV3 {
            имя_индекс,
            арность: ф.арность,
            локалы: ф.локалы,
            флаги,
            код,
        });
    }

    сериализовать_v3(&МодульV3 {
        флаги: 0,
        строки,
        функции: outs,
    })
}

/// Пример: `PUSH 2; PUSH 3; ADD; RET` → модуль с одной функцией.
pub fn демо_сложение() -> Vec<u8> {
    скомпилировать_в_байткод(&[ФункцияИсходник {
        имя: "главная".into(),
        арность: 0,
        локалы: 4,
        асинхронная: false,
        совершенная: false,
        comptime: false,
        инструкции: vec![
            ИнстрV3::PushI64(2),
            ИнстрV3::PushI64(3),
            ИнстрV3::Add,
            ИнстрV3::Ret,
        ],
    }])
}

//! Полный парсер ZIP — алгоритм на стороне VM (без C-bootstrap).

use crate::встроенные_v3::Встроенные;
use crate::исполнитель_v3::ЗначениеV3;
use crate::zip_ast::{Аннотация, Параметр, Узел};
use crate::zip_lex_полный::{self as lex, Токен as ЛексТокен};

pub struct Парсер {
    токены: Vec<ЛексТокен>,
    позиция: usize,
}

impl Парсер {
    pub fn новый(токены: Vec<ЛексТокен>) -> Self {
        Self {
            токены,
            позиция: 0,
        }
    }

    fn текущий(&self) -> Option<&ЛексТокен> {
        self.токены.get(self.позиция)
    }

    fn вид(&self) -> i64 {
        self.текущий().map(|t| t.вид).unwrap_or(lex::ТК_КОНЕЦ)
    }

    fn текст(&self) -> String {
        self.текущий()
            .map(|t| t.строка.clone())
            .unwrap_or_default()
    }

    fn продвинуть(&mut self) {
        if self.позиция < self.токены.len() {
            self.позиция += 1;
        }
    }

    fn это(&self, вид: i64) -> bool {
        self.вид() == вид
    }

    fn съесть(&mut self, вид: i64) -> bool {
        if self.это(вид) {
            self.продвинуть();
            true
        } else {
            false
        }
    }

    fn ожидать(&mut self, вид: i64) -> Result<(), String> {
        if self.съесть(вид) {
            Ok(())
        } else {
            Err(format!(
                "Ожидался токен {вид}, получен {} ({})",
                self.вид(),
                self.текст()
            ))
        }
    }

    fn имя_идентификатора(&self) -> Option<String> {
        match self.вид() {
            lex::ТК_СЛОВО | lex::ТК_КОРЕНЬ | lex::ТК_ШАБЛОН | lex::ТК_И | lex::ТК_ИЛИ
            | lex::ТК_НЕ | lex::ТК_В | lex::ТК_ПОТОК_ДАННЫХ => {
                let s = self.текст();
                if s.is_empty() {
                    None
                } else {
                    Some(s)
                }
            }
            _ => None,
        }
    }

    pub fn разобрать_программу(&mut self) -> Result<Узел, String> {
        let mut объявления = Vec::new();
        let mut toplevel = Vec::new();
        let mut аннотации_накопление = Vec::new();
        let mut has_fn = false;

        while !self.это(lex::ТК_КОНЕЦ) {
            if self.это(lex::ТК_СОБАКА) {
                аннотации_накопление.push(self.разобрать_аннотацию()?);
                continue;
            }
            if self.это(lex::ТК_РЕШЁТКА) {
                объявления.push(self.разобрать_директиву()?);
                continue;
            }
            if self.это(lex::ТК_ФУНКЦИЯ) {
                let anns = std::mem::take(&mut аннотации_накопление);
                объявления.push(self.разобрать_функцию(anns)?);
                has_fn = true;
                continue;
            }
            if !аннотации_накопление.is_empty() {
                return Err("Аннотации без функции".into());
            }
            toplevel.push(self.разобрать_инструкцию()?);
        }

        if !toplevel.is_empty() {
            объявления.push(Узел::Функция {
                имя: "главная".into(),
                параметры: vec![],
                тип_возврата: None,
                тело: Box::new(Узел::Блок {
                    инструкции: toplevel,
                }),
                аннотации: vec![],
            });
        } else if !has_fn {
            объявления.push(Узел::Функция {
                имя: "главная".into(),
                параметры: vec![],
                тип_возврата: None,
                тело: Box::new(Узел::Блок {
                    инструкции: vec![Узел::Возврат {
                        значение: Some(Box::new(Узел::Константа {
                            значение_ц: Some(0),
                            значение_в: None,
                            значение_с: None,
                        })),
                    }],
                }),
                аннотации: vec![],
            });
        }

        Ok(Узел::Программа { объявления })
    }

    fn разобрать_директиву(&mut self) -> Result<Узел, String> {
        self.продвинуть(); // #
        let имя = self
            .имя_идентификатора()
            .ok_or_else(|| "Ожидалось имя директивы".to_string())?;
        self.продвинуть();
        let mut значение = None;
        if self.съесть(lex::ТК_ЛСКОБКА) {
            if self.это(lex::ТК_СТРОКА) {
                значение = Some(self.текст());
                self.продвинуть();
            }
            while !self.это(lex::ТК_ПСКОБКА) && !self.это(lex::ТК_КОНЕЦ) {
                self.продвинуть();
            }
            self.съесть(lex::ТК_ПСКОБКА);
        }
        Ok(Узел::Директива { имя, значение })
    }

    fn разобрать_аннотацию(&mut self) -> Result<Аннотация, String> {
        self.продвинуть(); // @
        let имя = self
            .имя_идентификатора()
            .ok_or_else(|| "Ожидалось имя аннотации".to_string())?;
        self.продвинуть();
        let mut параметры = Vec::new();
        if self.съесть(lex::ТК_ЛСКОБКА) {
            while !self.это(lex::ТК_ПСКОБКА) && !self.это(lex::ТК_КОНЕЦ) {
                let ключ = self
                    .имя_идентификатора()
                    .ok_or_else(|| "Ожидался ключ аннотации".to_string())?;
                self.продвинуть();
                self.ожидать(lex::ТК_РАВНО)?;
                let значение = match self.вид() {
                    lex::ТК_ЦЕЛОЕ => {
                        let v = self.текущий().map(|t| t.целое).unwrap_or(0).to_string();
                        self.продвинуть();
                        v
                    }
                    lex::ТК_ВЕЩЕСТВЕННОЕ | lex::ТК_СТРОКА => {
                        let v = self.текст();
                        self.продвинуть();
                        v
                    }
                    _ => {
                        if let Some(s) = self.имя_идентификатора() {
                            self.продвинуть();
                            s
                        } else {
                            String::new()
                        }
                    }
                };
                параметры.push((ключ, значение));
                self.съесть(lex::ТК_ЗАПЯТАЯ);
            }
            self.ожидать(lex::ТК_ПСКОБКА)?;
        }
        Ok(Аннотация { имя, параметры })
    }

    fn разобрать_функцию(&mut self, аннотации: Vec<Аннотация>) -> Result<Узел, String> {
        self.продвинуть(); // функция
        let имя = self
            .имя_идентификатора()
            .unwrap_or_else(|| "главная".into());
        self.продвинуть();
        self.ожидать(lex::ТК_ЛСКОБКА)?;
        let mut параметры = Vec::new();
        while !self.это(lex::ТК_ПСКОБКА) && !self.это(lex::ТК_КОНЕЦ) {
            let имя_п = self
                .имя_идентификатора()
                .ok_or_else(|| "Ожидался параметр".to_string())?;
            self.продвинуть();
            let тип_параметр = if self.съесть(lex::ТК_ДВОЕТОЧИЕ) {
                let t = self.имя_идентификатора();
                if t.is_some() {
                    self.продвинуть();
                }
                t
            } else {
                None
            };
            параметры.push(Параметр {
                имя: имя_п,
                тип_параметр,
            });
            if !self.съесть(lex::ТК_ЗАПЯТАЯ) {
                break;
            }
        }
        self.ожидать(lex::ТК_ПСКОБКА)?;
        let тип_возврата = if self.съесть(lex::ТК_СТРЕЛКА) {
            let t = self.имя_идентификатора();
            if t.is_some() {
                self.продвинуть();
            }
            t
        } else {
            None
        };
        let тело = self.разобрать_блок()?;
        Ok(Узел::Функция {
            имя,
            параметры,
            тип_возврата,
            тело: Box::new(тело),
            аннотации,
        })
    }

    fn разобрать_блок(&mut self) -> Result<Узел, String> {
        self.ожидать(lex::ТК_ЛФИГУРНАЯ)?;
        let mut инструкции = Vec::new();
        while !self.это(lex::ТК_ПФИГУРНАЯ) && !self.это(lex::ТК_КОНЕЦ) {
            инструкции.push(self.разобрать_инструкцию()?);
        }
        self.ожидать(lex::ТК_ПФИГУРНАЯ)?;
        Ok(Узел::Блок { инструкции })
    }

    fn разобрать_инструкцию(&mut self) -> Result<Узел, String> {
        match self.вид() {
            lex::ТК_ВОЗВРАТ => {
                self.продвинуть();
                let значение = if self.это(lex::ТК_ПФИГУРНАЯ)
                    || self.это(lex::ТК_КОНЕЦ)
                    || self.это(lex::ТК_ИНАЧЕ)
                {
                    None
                } else if self.съесть(lex::ТК_ЛСКОБКА) {
                    let e = self.разобрать_выражение()?;
                    self.ожидать(lex::ТК_ПСКОБКА)?;
                    Some(Box::new(e))
                } else {
                    Some(Box::new(self.разобрать_выражение()?))
                };
                Ok(Узел::Возврат { значение })
            }
            lex::ТК_ПРЕРВАТЬ => {
                self.продвинуть();
                Ok(Узел::Прервать)
            }
            lex::ТК_ПРОДОЛЖИТЬ => {
                self.продвинуть();
                Ok(Узел::Продолжить)
            }
            lex::ТК_ЕСЛИ => self.разобрать_если(),
            lex::ТК_ПОКА => self.разобрать_пока(),
            lex::ТК_ДЛЯ => self.разобрать_для(),
            _ => {
                if self.имя_идентификатора().is_some()
                    && self
                        .токены
                        .get(self.позиция + 1)
                        .map(|t| t.вид == lex::ТК_РАВНО)
                        .unwrap_or(false)
                {
                    let имя = self.имя_идентификатора().unwrap();
                    self.продвинуть();
                    self.продвинуть(); // =
                    let значение = self.разобрать_выражение()?;
                    return Ok(Узел::Присваивание {
                        имя,
                        значение: Box::new(значение),
                    });
                }
                self.разобрать_выражение()
            }
        }
    }

    fn разобрать_если(&mut self) -> Result<Узел, String> {
        self.продвинуть();
        let условие = if self.съесть(lex::ТК_ЛСКОБКА) {
            let e = self.разобрать_выражение()?;
            self.ожидать(lex::ТК_ПСКОБКА)?;
            e
        } else {
            self.разобрать_выражение()?
        };
        let тогда = if self.это(lex::ТК_ЛФИГУРНАЯ) {
            self.разобрать_блок()?
        } else {
            self.разобрать_инструкцию()?
        };
        let иначе = if self.съесть(lex::ТК_ИНАЧЕ) {
            Some(Box::new(if self.это(lex::ТК_ЛФИГУРНАЯ) {
                self.разобрать_блок()?
            } else {
                self.разобрать_инструкцию()?
            }))
        } else {
            None
        };
        Ok(Узел::Если {
            условие: Box::new(условие),
            тогда: Box::new(тогда),
            иначе,
        })
    }

    fn разобрать_пока(&mut self) -> Result<Узел, String> {
        self.продвинуть();
        let условие = if self.съесть(lex::ТК_ЛСКОБКА) {
            let e = self.разобрать_выражение()?;
            self.ожидать(lex::ТК_ПСКОБКА)?;
            e
        } else {
            self.разобрать_выражение()?
        };
        let тело = if self.это(lex::ТК_ЛФИГУРНАЯ) {
            self.разобрать_блок()?
        } else {
            self.разобрать_инструкцию()?
        };
        Ok(Узел::Пока {
            условие: Box::new(условие),
            тело: Box::new(тело),
        })
    }

    fn разобрать_для(&mut self) -> Result<Узел, String> {
        self.продвинуть();
        let переменная = self
            .имя_идентификатора()
            .ok_or_else(|| "Ожидалось имя переменной цикла".to_string())?;
        self.продвинуть();
        self.съесть(lex::ТК_В);
        let начало = self.разобрать_выражение()?;
        self.ожидать(lex::ТК_ДИАПАЗОН)?;
        let конец = self.разобрать_выражение()?;
        let тело = if self.это(lex::ТК_ЛФИГУРНАЯ) {
            self.разобрать_блок()?
        } else {
            self.разобрать_инструкцию()?
        };
        Ok(Узел::Для {
            переменная,
            начало: Box::new(начало),
            конец: Box::new(конец),
            тело: Box::new(тело),
        })
    }

    fn разобрать_выражение(&mut self) -> Result<Узел, String> {
        self.разобрать_хор()
    }

    fn разобрать_хор(&mut self) -> Result<Узел, String> {
        let mut левый = self.разобрать_пульс()?;
        while self.съесть(lex::ТК_ХОР) {
            let правый = self.разобрать_пульс()?;
            левый = Узел::БинарнаяОперация {
                оператор: "||".into(),
                левый: Box::new(левый),
                правый: Box::new(правый),
            };
        }
        Ok(левый)
    }

    fn разобрать_пульс(&mut self) -> Result<Узел, String> {
        let mut левый = self.разобрать_или()?;
        while self.это(lex::ТК_ИМПУЛЬС) || self.это(lex::ТК_СЕТЬ) {
            let op = if self.это(lex::ТК_СЕТЬ) { ">>>" } else { ">>" };
            self.продвинуть();
            let правый = self.разобрать_или()?;
            левый = Узел::ПотокДанных {
                левый: Box::new(левый),
                правый: Box::new(правый),
            };
            let _ = op;
        }
        Ok(левый)
    }

    fn разобрать_или(&mut self) -> Result<Узел, String> {
        let mut левый = self.разобрать_и()?;
        while self.съесть(lex::ТК_ИЛИ) {
            let правый = self.разобрать_и()?;
            левый = Узел::БинарнаяОперация {
                оператор: "или".into(),
                левый: Box::new(левый),
                правый: Box::new(правый),
            };
        }
        Ok(левый)
    }

    fn разобрать_и(&mut self) -> Result<Узел, String> {
        let mut левый = self.разобрать_сравнение()?;
        while self.съесть(lex::ТК_И) {
            let правый = self.разобрать_сравнение()?;
            левый = Узел::БинарнаяОперация {
                оператор: "и".into(),
                левый: Box::new(левый),
                правый: Box::new(правый),
            };
        }
        Ok(левый)
    }

    fn разобрать_сравнение(&mut self) -> Result<Узел, String> {
        let mut левый = self.разобрать_сложение()?;
        loop {
            let op = match self.вид() {
                lex::ТК_МЕНЬШЕ => "<",
                lex::ТК_МЕНЬШЕ_РАВНО => "<=",
                lex::ТК_БОЛЬШЕ => ">",
                lex::ТК_БОЛЬШЕ_РАВНО => ">=",
                lex::ТК_РАВНО_РАВНО => "==",
                lex::ТК_НЕ_РАВНО => "!=",
                _ => break,
            };
            self.продвинуть();
            let правый = self.разобрать_сложение()?;
            левый = Узел::БинарнаяОперация {
                оператор: op.into(),
                левый: Box::new(левый),
                правый: Box::new(правый),
            };
        }
        Ok(левый)
    }

    fn разобрать_сложение(&mut self) -> Result<Узел, String> {
        let mut левый = self.разобрать_умножение()?;
        while self.это(lex::ТК_ПЛЮС) || self.это(lex::ТК_МИНУС) {
            let op = if self.это(lex::ТК_ПЛЮС) { "+" } else { "-" };
            self.продвинуть();
            let правый = self.разобрать_умножение()?;
            левый = Узел::БинарнаяОперация {
                оператор: op.into(),
                левый: Box::new(левый),
                правый: Box::new(правый),
            };
        }
        Ok(левый)
    }

    fn разобрать_умножение(&mut self) -> Result<Узел, String> {
        let mut левый = self.разобрать_унарное()?;
        while self.это(lex::ТК_ЗВЕЗДА) || self.это(lex::ТК_СЛЕШ) || self.это(lex::ТК_ПРОЦЕНТ) {
            let op = match self.вид() {
                lex::ТК_ЗВЕЗДА => "*",
                lex::ТК_СЛЕШ => "/",
                _ => "%",
            };
            self.продвинуть();
            let правый = self.разобрать_унарное()?;
            левый = Узел::БинарнаяОперация {
                оператор: op.into(),
                левый: Box::new(левый),
                правый: Box::new(правый),
            };
        }
        Ok(левый)
    }

    fn разобрать_унарное(&mut self) -> Result<Узел, String> {
        if self.съесть(lex::ТК_ФИКСАЦИЯ) {
            let выражение = self.разобрать_унарное()?;
            return Ok(Узел::Фиксация {
                выражение: Box::new(выражение),
            });
        }
        if self.съесть(lex::ТК_ПОТОК) {
            let выражение = self.разобрать_унарное()?;
            return Ok(Узел::Асинхронный {
                выражение: Box::new(выражение),
            });
        }
        if self.съесть(lex::ТК_МИНУС) {
            let операнд = self.разобрать_унарное()?;
            return Ok(Узел::УнарнаяОперация {
                оператор: "-".into(),
                операнд: Box::new(операнд),
            });
        }
        if self.съесть(lex::ТК_НЕ) {
            let операнд = self.разобрать_унарное()?;
            return Ok(Узел::УнарнаяОперация {
                оператор: "не".into(),
                операнд: Box::new(операнд),
            });
        }
        self.разобрать_первичное()
    }

    fn разобрать_первичное(&mut self) -> Result<Узел, String> {
        let узел = match self.вид() {
            lex::ТК_ЦЕЛОЕ => {
                let n = self.текущий().map(|t| t.целое).unwrap_or(0);
                self.продвинуть();
                Узел::Константа {
                    значение_ц: Some(n),
                    значение_в: None,
                    значение_с: None,
                }
            }
            lex::ТК_ВЕЩЕСТВЕННОЕ => {
                let s = self.текст();
                self.продвинуть();
                Узел::Константа {
                    значение_ц: None,
                    значение_в: s.parse().ok(),
                    значение_с: Some(s),
                }
            }
            lex::ТК_СТРОКА => {
                let s = self.текст();
                self.продвинуть();
                Узел::Константа {
                    значение_ц: None,
                    значение_в: None,
                    значение_с: Some(s),
                }
            }
            lex::ТК_ИСТИНА => {
                self.продвинуть();
                Узел::Константа {
                    значение_ц: Some(1),
                    значение_в: None,
                    значение_с: Some("истина".into()),
                }
            }
            lex::ТК_ЛОЖЬ => {
                self.продвинуть();
                Узел::Константа {
                    значение_ц: Some(0),
                    значение_в: None,
                    значение_с: Some("ложь".into()),
                }
            }
            lex::ТК_НИЧТО => {
                self.продвинуть();
                Узел::Константа {
                    значение_ц: Some(0),
                    значение_в: None,
                    значение_с: Some("ничто".into()),
                }
            }
            lex::ТК_ЛСКОБКА => {
                self.продвинуть();
                let внутри = self.разобрать_выражение()?;
                self.ожидать(lex::ТК_ПСКОБКА)?;
                внутри
            }
            _ => {
                let имя = self
                    .имя_идентификатора()
                    .ok_or_else(|| format!("Неожиданный токен: {}", self.вид()))?;
                self.продвинуть();
                if self.съесть(lex::ТК_ЛСКОБКА) {
                    let mut аргументы = Vec::new();
                    while !self.это(lex::ТК_ПСКОБКА) && !self.это(lex::ТК_КОНЕЦ) {
                        аргументы.push(self.разобрать_выражение()?);
                        if !self.съесть(lex::ТК_ЗАПЯТАЯ) {
                            break;
                        }
                    }
                    self.ожидать(lex::ТК_ПСКОБКА)?;
                    Узел::Вызов { имя, аргументы }
                } else {
                    Узел::Идентификатор { имя }
                }
            }
        };

        // Постфиксная фиксация: expr!
        if self.съесть(lex::ТК_ФИКСАЦИЯ) {
            return Ok(Узел::Фиксация {
                выражение: Box::new(узел),
            });
        }
        Ok(узел)
    }
}

/// Парсинг исходника: лексер VM → парсер VM.
pub fn разобрать_из_исходника(исходник: &str) -> Result<Узел, String> {
    let токены = lex::разобрать(исходник);
    let mut парсер = Парсер::новый(токены);
    парсер.разобрать_программу()
}

fn как_строка(з: &ЗначениеV3) -> String {
    match з {
        ЗначениеV3::Строка(s) => s.clone(),
        другой => другой.to_string(),
    }
}

pub fn зарегистрировать(ф: &mut Встроенные) {
    ф.регистрация_внешняя("zip_parse_полный", |арг| {
        let s = арг.first().map(как_строка).unwrap_or_default();
        match разобрать_из_исходника(&s) {
            Ok(дерево) => Ok(ЗначениеV3::Целое(дерево.число_функций() as i64)),
            Err(e) => {
                eprintln!("zip_parse_полный: {e}");
                Ok(ЗначениеV3::Целое(-1))
            }
        }
    });
    ф.регистрация_алиас("парсер_разобрать_полный", "zip_parse_полный");
}


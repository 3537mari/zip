//! Публичный API для внешних биндингов (Android, iOS, WASM, FFI).

use crate::байткод_v3_декодер::разобрать_v3;
use crate::исполнитель_v3::ИсполнительV3;
use crate::zip_gen_полный::сгенерировать_из_исходника;

/// Компилировать ZIP-исходник в ZIPB.
pub fn скомпилировать(исходник: &str) -> Result<Vec<u8>, String> {
    сгенерировать_из_исходника(исходник)
}

/// Запустить ZIPB, вернуть вывод (включая `= результат`).
pub fn запустить(байткод: &[u8]) -> Result<String, String> {
    let модуль = разобрать_v3(байткод).map_err(|e| format!("{e}"))?;
    let mut vm = ИсполнительV3::новый(модуль).map_err(|e| format!("{e}"))?;
    vm.запустить_с_выводом().map_err(|e| format!("{e}"))
}

/// Полная цепочка: исходник → вывод.
pub fn скомпилировать_и_запустить(исходник: &str) -> Result<String, String> {
    let байткод = скомпилировать(исходник)?;
    запустить(&байткод)
}

#[cfg(test)]
mod тесты {
    use super::*;

    #[test]
    fn арифметика() {
        let out = скомпилировать_и_запустить("функция главная() { возврат(2 + 3) }").unwrap();
        assert!(out.contains("= 5"), "{out}");
    }

    #[test]
    fn факториал() {
        let src = r#"
функция факториал(н) {
    если (н < 2) { возврат(1) }
    возврат(н * факториал(н - 1))
}
функция главная() { возврат(факториал(5)) }
"#;
        let out = скомпилировать_и_запустить(src).unwrap();
        assert!(out.contains("= 120"), "{out}");
    }
}

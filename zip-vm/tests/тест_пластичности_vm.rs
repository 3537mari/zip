//! VM: счётчики вызовов и пометка горячих функций.

use zip_vm::{сериализовать, разобрать, Исполнитель, Инструкция, Модуль, Функция, ВЕРСИЯ};

fn модуль_с_порогом(порог: u64, вызовов_в_главной: u32) -> Модуль {
    // fn0: главная — цикл вызовов fn1
    // fn1: инкремент (ret arg0+1) — упрощённо: PushI64(1); Ret
    let mut код_главной = Vec::new();
    for _ in 0..вызовов_в_главной {
        код_главной.push(Инструкция::PushI64(0));
        код_главной.push(Инструкция::Call(1));
    }
    код_главной.push(Инструкция::PushI64(0));
    код_главной.push(Инструкция::Ret);

    let код_гор = vec![
        Инструкция::Load(0),
        Инструкция::PushI64(1),
        Инструкция::Add,
        Инструкция::Ret,
    ];

    Модуль {
        версия: ВЕРСИЯ,
        флаги: 0,
        строки: vec!["главная".into(), "горячая".into()],
        функции: vec![
            Функция {
                имя: "главная".into(),
                параметры: 0,
                локальные: 8,
                размер_стека: 64,
                порог_горячности: 1000,
                код: код_главной,
            },
            Функция {
                имя: "горячая".into(),
                параметры: 1,
                локальные: 8,
                размер_стека: 64,
                порог_горячности: порог,
                код: код_гор,
            },
        ],
    }
}

#[test]
fn счётчик_и_горячая_при_пороге() {
    let м = модуль_с_порогом(5, 10);
    let байты = сериализовать(&м).unwrap();
    let м2 = разобрать(&байты).unwrap();
    assert_eq!(м2.функции[1].порог_горячности, 5);

    let mut исп = Исполнитель::новый(м2).unwrap();
    let _ = исп.выполнить().unwrap();
    assert_eq!(исп.счётчик(1), 10);
    assert!(исп.горячие().contains(&1));
}

#[test]
fn без_порога_не_горячая() {
    let м = модуль_с_порогом(1000, 3);
    let mut исп = Исполнитель::новый(м).unwrap();
    let _ = исп.выполнить().unwrap();
    assert_eq!(исп.счётчик(1), 3);
    assert!(!исп.горячие().contains(&1));
}

#[test]
fn сериализация_v2_порог() {
    let м = модуль_с_порогом(42, 1);
    let байты = сериализовать(&м).unwrap();
    assert_eq!(&байты[0..4], b"ZIPC");
    let версия = u16::from_le_bytes([байты[4], байты[5]]);
    assert_eq!(версия, 2);
    let м2 = разобрать(&байты).unwrap();
    assert_eq!(м2.функции[1].порог_горячности, 42);
}

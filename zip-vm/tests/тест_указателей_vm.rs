//! VM v3: опкоды указателей и памяти.

use zip_vm::байткод_v3::{ИнстрV3, МодульV3, ФункцияV3};
use zip_vm::исполнитель_v3::{ЗначениеV3, ИсполнительV3};

fn функция(имя_индекс: u32, инструкции: Vec<ИнстрV3>) -> ФункцияV3 {
    let mut код = Vec::new();
    for и in &инструкции {
        и.закодировать(&mut код);
    }
    ФункцияV3 {
        имя_индекс,
        арность: 0,
        локалы: 8,
        флаги: 0,
        код,
    }
}

fn модуль_одна(инструкции: Vec<ИнстрV3>) -> МодульV3 {
    МодульV3 {
        флаги: 0,
        строки: vec!["главная".into()],
        функции: vec![функция(0, инструкции)],
    }
}

#[test]
fn тест_addr_deref_store() {
    /* х = 42; п = &х; *п = 100; return *п */
    let модуль = модуль_одна(vec![
        ИнстрV3::PushI64(42),
        ИнстрV3::Store(0),
        ИнстрV3::AddrOf(0),
        ИнстрV3::Store(1),
        ИнстрV3::Load(1),
        ИнстрV3::PushI64(100),
        ИнстрV3::StorePtr,
        ИнстрV3::Load(1),
        ИнстрV3::Deref,
        ИнстрV3::Ret,
    ]);
    let mut vm = ИсполнительV3::новый(модуль).unwrap();
    assert_eq!(vm.запустить().unwrap(), ЗначениеV3::Целое(100));
}

#[test]
fn тест_alloc_store_load() {
    let модуль = модуль_одна(vec![
        ИнстрV3::PushI64(64),
        ИнстрV3::Alloc,
        ИнстрV3::Dup,
        ИнстрV3::PushI64(7),
        ИнстрV3::StorePtr,
        ИнстрV3::Deref,
        ИнстрV3::Ret,
    ]);
    let mut vm = ИсполнительV3::новый(модуль).unwrap();
    assert_eq!(vm.запустить().unwrap(), ЗначениеV3::Целое(7));
}

#[test]
fn тест_ptr_add() {
    let модуль = модуль_одна(vec![
        ИнстрV3::PushI64(100),
        ИнстрV3::Alloc,
        ИнстрV3::PushI64(10),
        ИнстрV3::PtrAdd,
        ИнстрV3::PushI64(5),
        ИнстрV3::PtrSub,
        ИнстрV3::Ret,
    ]);
    let mut vm = ИсполнительV3::новый(модуль).unwrap();
    let р = vm.запустить().unwrap();
    /* base + 10 - 5 = base + 5 */
    assert!(matches!(р, ЗначениеV3::Целое(n) if n >= 5));
}

#[test]
fn вм05_функция_вызов() {
    let м = Модуль {
        версия: ВЕРСИЯ,
        флаги: 0,
        строки: vec!["главная".into(), "сложить".into()],
        функции: vec![
            Функция {
                имя: "главная".into(),
                параметры: 0,
                локальные: 4,
                размер_стека: 32,
                порог_горячности: 1000,
                код: vec![
                    Инструкция::PushI64(2),
                    Инструкция::PushI64(3),
                    Инструкция::Call(1),
                    Инструкция::Ret,
                ],
            },
            Функция {
                имя: "сложить".into(),
                параметры: 2,
                локальные: 4,
                размер_стека: 32,
                порог_горячности: 1000,
                код: vec![
                    Инструкция::Load(0),
                    Инструкция::Load(1),
                    Инструкция::Add,
                    Инструкция::Ret,
                ],
            },
        ],
    };
    let bytes = сериализовать(&м).unwrap();
    let м2 = разобрать(&bytes).unwrap();
    let р = Исполнитель::новый(м2).unwrap().выполнить().unwrap();
    assert_eq!(р, Значение::Целое(5));
}


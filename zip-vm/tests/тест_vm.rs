//! Тесты виртуальной машины ZIP.

use zip_vm::{
    сериализовать, разобрать, Значение, Инструкция, Исполнитель, Модуль, Функция, ВЕРСИЯ,
};

fn модуль(имя: &str, код: Vec<Инструкция>, локальные: u16) -> Модуль {
    Модуль {
        версия: ВЕРСИЯ,
        флаги: 0,
        строки: vec![имя.into()],
        функции: vec![Функция {
            имя: имя.into(),
            параметры: 0,
            локальные,
            размер_стека: 64,
            порог_горячности: 1000,
            код,
        }],
    }
}

fn выполнить(код: Vec<Инструкция>) -> Значение {
    let м = модуль("главная", код, 16);
    let bytes = сериализовать(&м).unwrap();
    let м2 = разобрать(&bytes).unwrap();
    Исполнитель::новый(м2).unwrap().выполнить().unwrap()
}

#[test]
fn вм01_арифметика_сложение() {
    let р = выполнить(vec![
        Инструкция::PushI64(2),
        Инструкция::PushI64(3),
        Инструкция::Add,
        Инструкция::Ret,
    ]);
    assert_eq!(р, Значение::Целое(5));
}


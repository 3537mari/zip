//! Тесты байт-кода ZIP v3 (ZIPB).

use zip_vm::байткод_v3::{сериализовать_v3, Кодировщик, Опкод, ИнстрV3, МодульV3, ФункцияV3};
use zip_vm::байткод_v3_декодер::{в_модуль_vm, разобрать_v3, Декодировщик, это_zipb};
use zip_vm::ir_в_байткод::{демо_сложение, скомпилировать_в_байткод, ФункцияИсходник};
use zip_vm::{разобрать, Исполнитель, Значение};

#[test]
fn тест_кодирование_заголовка() {
    let mut кодировщик = Кодировщик::новый();
    кодировщик.написать_заголовок(5, 16);
    let байткод = кодировщик.завершить();
    assert_eq!(&байткод[0..4], b"ZIPB");
    assert_eq!(u16::from_le_bytes([байткод[4], байткод[5]]), 3);
    assert_eq!(u32::from_le_bytes(байткод[8..12].try_into().unwrap()), 5);
}

#[test]
fn тест_декодирование_заголовка() {
    let данные = b"ZIPB\x03\x00\x00\x00\x05\x00\x00\x00\x10\x00\x00\x00";
    let mut декодер = Декодировщик::новый(данные);
    let заголовок = декодер.прочитать_заголовок().unwrap();
    assert_eq!(заголовок.версия, 3);
    assert_eq!(заголовок.количество_функций, 5);
    assert_eq!(заголовок.смещение_строк, 16);
}

#[test]
fn тест_это_zipb() {
    assert!(это_zipb(b"ZIPB...."));
    assert!(!это_zipb(b"ZIPC...."));
}

#[test]
fn тест_полный_цикл_модуля() {
    let mut код = Vec::new();
    ИнстрV3::PushI64(2).закодировать(&mut код);
    ИнстрV3::PushI64(3).закодировать(&mut код);
    ИнстрV3::Add.закодировать(&mut код);
    ИнстрV3::Ret.закодировать(&mut код);

    let м = МодульV3 {
        флаги: 0,
        строки: vec!["главная".into()],
        функции: vec![ФункцияV3 {
            имя_индекс: 0,
            арность: 0,
            локалы: 4,
            флаги: 0,
            код,
        }],
    };
    let bytes = сериализовать_v3(&м);
    assert!(это_zipb(&bytes));
    let м2 = разобрать_v3(&bytes).unwrap();
    assert_eq!(м2.строки[0], "главная");
    assert_eq!(м2.функции.len(), 1);

    let vm = в_модуль_vm(&м2).unwrap();
    let р = Исполнитель::новый(vm).unwrap().выполнить().unwrap();
    assert_eq!(р, Значение::Целое(5));
}


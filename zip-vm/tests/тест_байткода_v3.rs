#[test]
fn тест_load_store_call() {
    let bytes = скомпилировать_в_байткод(&[
        ФункцияИсходник {
            имя: "сложить".into(),
            арность: 2,
            локалы: 4,
            асинхронная: false,
            совершенная: false,
            comptime: false,
            инструкции: vec![
                ИнстрV3::Load(0),
                ИнстрV3::Load(1),
                ИнстрV3::Add,
                ИнстрV3::Ret,
            ],
        },
        ФункцияИсходник {
            имя: "главная".into(),
            арность: 0,
            локалы: 4,
            асинхронная: false,
            совершенная: false,
            comptime: false,
            инструкции: vec![
                ИнстрV3::PushI64(2),
                ИнстрV3::PushI64(3),
                ИнстрV3::Call(0),
                ИнстрV3::Ret,
            ],
        },
    ]);
    let м = разобрать(&bytes).unwrap();
    // главная — по имени
    assert!(м.функции.iter().any(|ф| ф.имя == "главная"));
    let р = Исполнитель::новый(м).unwrap().выполнить().unwrap();
    assert_eq!(р, Значение::Целое(5));
}

#[test]
fn тест_сравнения_и_переход() {
    let mut код = Vec::new();
    ИнстрV3::PushI64(1).закодировать(&mut код);
    ИнстрV3::JumpIf(3).закодировать(&mut код); // -> PushI64(42) at index 3?
    // indices: 0 PushI64, 1 JumpIf, 2 PushI64(0), 3 PushI64(42), 4 Ret
    ИнстрV3::PushI64(0).закодировать(&mut код);
    ИнстрV3::Jump(4).закодировать(&mut код);
    ИнстрV3::PushI64(42).закодировать(&mut код);
    ИнстрV3::Ret.закодировать(&mut код);

    // Fix jump targets for instruction indices after encoding is tricky —
    // use high-level compile instead:
    let bytes = скомпилировать_в_байткод(&[ФункцияИсходник {
        имя: "главная".into(),
        арность: 0,
        локалы: 2,
        асинхронная: false,
        совершенная: true,
        comptime: false,
        инструкции: vec![
            ИнстрV3::PushI64(10),
            ИнстрV3::PushI64(3),
            ИнстрV3::Sub,
            ИнстрV3::Ret,
        ],
    }]);
    let м = разобрать_v3(&bytes).unwrap();
    assert_eq!(м.функции[0].флаги & 2, 2); // perfect bit
    let р = Исполнитель::новый(в_модуль_vm(&м).unwrap())
        .unwrap()
        .выполнить()
        .unwrap();
    assert_eq!(р, Значение::Целое(7));
}

#[test]
fn тест_опкод_из_байта() {
    assert_eq!(Опкод::из_байта(0x20), Some(Опкод::Add));
    assert_eq!(Опкод::из_байта(0x70), Some(Опкод::Pulse));
    assert_eq!(Опкод::из_байта(0xFF), None);
}

#[test]
fn тест_pulse_и_print_кодирование() {
    let mut код = Vec::new();
    ИнстрV3::Pulse { из: 1, в: 2 }.закодировать(&mut код);
    ИнстрV3::PerfectLock(3).закодировать(&mut код);
    ИнстрV3::PrintI64.закодировать(&mut код);
    assert_eq!(код[0], 0x70);
    assert_eq!(код[5], 0x71);
    assert!(код.contains(&0x92));
}

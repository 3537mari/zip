//! Тесты Идеи 5 — миелинизация (JIT горячих функций).

use zip_vm::{
    байткод_в_llvm_ir, сериализовать, разобрать, Исполнитель, Инструкция, Модуль, Функция,
    JitКомпилятор, ВЕРСИЯ, Значение,
};

fn модуль_сложение(порог: u64, вызовов: u32) -> Модуль {
    let mut код_главной = Vec::new();
    for _ in 0..вызовов {
        код_главной.push(Инструкция::PushI64(2));
        код_главной.push(Инструкция::PushI64(3));
        код_главной.push(Инструкция::Call(1));
    }
    код_главной.push(Инструкция::Ret);

    Модуль {
        версия: ВЕРСИЯ,
        флаги: 0,
        строки: vec!["главная".into(), "сложить".into()],
        функции: vec![
            Функция {
                имя: "главная".into(),
                параметры: 0,
                локальные: 8,
                размер_стека: 32,
                порог_горячности: 1000,
                код: код_главной,
            },
            Функция {
                имя: "сложить".into(),
                параметры: 2,
                локальные: 8,
                размер_стека: 32,
                порог_горячности: порог,
                код: vec![
                    Инструкция::Load(0),
                    Инструкция::Load(1),
                    Инструкция::Add,
                    Инструкция::Ret,
                ],
            },
        ],
    }
}

#[test]
fn тест_байткод_в_llvm_ir() {
    let ф = &модуль_сложение(1, 1).функции[1];
    let ir = байткод_в_llvm_ir(ф, 1).unwrap();
    assert!(ir.contains("@zip_fn_1"));
    assert!(ir.contains("dllexport"));
    assert!(ir.contains("add i64"));
}

#[test]
fn тест_jit_компиляции_простой_функции() {
    if !JitКомпилятор::доступен() {
        eprintln!("clang нет — пропуск JIT-компиляции");
        return;
    }
    let ф = модуль_сложение(1, 1).функции[1].clone();
    let mut jit = JitКомпилятор::новый();
    let f = jit.скомпилировать_функцию(1, &ф).expect("JIT compile");
    let r = unsafe { f(10, 32, 0, 0) };
    assert_eq!(r, 42);
}

#[test]
fn тест_транспарентность() {
    if !JitКомпилятор::доступен() {
        return;
    }
    // порог=3 → первые 2 интерпретация, с 3-го JIT
    let м = модуль_сложение(3, 5);
    let mut исп = Исполнитель::новый(м).unwrap();
    let р = исп.выполнить().unwrap();
    assert_eq!(р, Значение::Целое(5)); // последний Call: 2+3
    assert!(исп.горячие().contains(&1));
    assert!(исп.нативная(1), "ожидался нативный код после порога");
    assert_eq!(исп.счётчик(1), 5);
}

#[test]
fn тест_без_clang_не_падает() {
    std::env::set_var("ZIP_JIT", "0");
    let м = модуль_сложение(1, 3);
    let mut исп = Исполнитель::новый(м).unwrap();
    let р = исп.выполнить();
    std::env::remove_var("ZIP_JIT");
    assert!(р.is_ok(), "VM не должна падать без JIT: {:?}", р);
    assert!(!исп.нативная(1));
}

#[test]
fn тест_jit_ускоряет_цикл() {
    // clang должен реально запускаться (не только находиться в PATH).
    let clang_доступен = std::process::Command::new("clang")
        .arg("--version")
        .output()
        .map(|o| o.status.success())
        .unwrap_or(false);
    if !clang_доступен || !JitКомпилятор::доступен() {
        eprintln!("⚠️ clang не найден или ZIP_JIT=0 — JIT-тест пропущен");
        return;
    }
    // сумма i*i для i in 0..n ; r0=n, r1=sum, r2=i
    // 0..3 init; 4..7 cond; 8..18 body; 19..20 ret
    let код_цикла = vec![
        Инструкция::PushI64(0),
        Инструкция::Store(1),
        Инструкция::PushI64(0),
        Инструкция::Store(2),
        Инструкция::Load(2),
        Инструкция::Load(0),
        Инструкция::CmpLt,
        Инструкция::JumpIfNot(19),
        Инструкция::Load(2),
        Инструкция::Load(2),
        Инструкция::Mul,
        Инструкция::Load(1),
        Инструкция::Add,
        Инструкция::Store(1),
        Инструкция::Load(2),
        Инструкция::PushI64(1),
        Инструкция::Add,
        Инструкция::Store(2),
        Инструкция::Jump(4),
        Инструкция::Load(1),
        Инструкция::Ret,
    ];

    let n = 5_000i64;
    let mut код_главной = Vec::new();
    // warm-up: порог=2
    for _ in 0..2 {
        код_главной.push(Инструкция::PushI64(100));
        код_главной.push(Инструкция::Call(1));
    }
    // timed-ish: after JIT
    код_главной.push(Инструкция::PushI64(n));
    код_главной.push(Инструкция::Call(1));
    код_главной.push(Инструкция::Ret);

    let м = Модуль {
        версия: ВЕРСИЯ,
        флаги: 0,
        строки: vec!["главная".into(), "цикл".into()],
        функции: vec![
            Функция {
                имя: "главная".into(),
                параметры: 0,
                локальные: 8,
                размер_стека: 32,
                порог_горячности: 1000,
                код: код_главной,
            },
            Функция {
                имя: "цикл".into(),
                параметры: 1,
                локальные: 16,
                размер_стека: 64,
                порог_горячности: 2,
                код: код_цикла,
            },
        ],
    };

    let t0 = std::time::Instant::now();
    let mut исп = Исполнитель::новый(м).unwrap();
    let р = исп.выполнить().unwrap();
    let dt = t0.elapsed();

    let ожидаемо = (n - 1) * n * (2 * (n - 1) + 1) / 6; // sum of squares 0..n-1
    assert_eq!(р, Значение::Целое(ожидаемо));
    if !исп.нативная(1) {
        eprintln!("⚠️ JIT не активировался (clang/линкер) — ускорение пропущено");
        return;
    }
    eprintln!("[bench] JIT path {} мс, результат {}", dt.as_millis(), ожидаемо);

    // Интерпретация того же n без JIT
    std::env::set_var("ZIP_JIT", "0");
    let м2 = Модуль {
        версия: ВЕРСИЯ,
        флаги: 0,
        строки: vec!["главная".into(), "цикл".into()],
        функции: vec![
            Функция {
                имя: "главная".into(),
                параметры: 0,
                локальные: 8,
                размер_стека: 32,
                порог_горячности: 1000,
                код: vec![
                    Инструкция::PushI64(n),
                    Инструкция::Call(1),
                    Инструкция::Ret,
                ],
            },
            Функция {
                имя: "цикл".into(),
                параметры: 1,
                локальные: 16,
                размер_стека: 64,
                порог_горячности: 999999,
                код: vec![
                    Инструкция::PushI64(0),
                    Инструкция::Store(1),
                    Инструкция::PushI64(0),
                    Инструкция::Store(2),
                    Инструкция::Load(2),
                    Инструкция::Load(0),
                    Инструкция::CmpLt,
                    Инструкция::JumpIfNot(19),
                    Инструкция::Load(2),
                    Инструкция::Load(2),
                    Инструкция::Mul,
                    Инструкция::Load(1),
                    Инструкция::Add,
                    Инструкция::Store(1),
                    Инструкция::Load(2),
                    Инструкция::PushI64(1),
                    Инструкция::Add,
                    Инструкция::Store(2),
                    Инструкция::Jump(4),
                    Инструкция::Load(1),
                    Инструкция::Ret,
                ],
            },
        ],
    };
    let t1 = std::time::Instant::now();
    let р2 = Исполнитель::новый(м2).unwrap().выполнить().unwrap();
    let dt_interp = t1.elapsed();
    std::env::remove_var("ZIP_JIT");
    assert_eq!(р2, Значение::Целое(ожидаемо));
    eprintln!(
        "[bench] interp {} мс vs JIT-run {} мс",
        dt_interp.as_millis(),
        dt.as_millis()
    );
    // Не требуем строгого ускорения в CI (компиляция clang входит в dt),
    // но результаты должны совпадать.
}

#[test]
fn сериализация_не_ломается() {
    let м = модуль_сложение(10, 1);
    let b = сериализовать(&м).unwrap();
    let м2 = разобрать(&b).unwrap();
    assert_eq!(м2.функции[1].порог_горячности, 10);
}

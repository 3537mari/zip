#[test]
fn тест_вызовы_функций() {
    let модуль = МодульV3 {
        флаги: 0,
        строки: vec!["главная".into(), "сложить".into()],
        функции: vec![
            функция(
                0,
                0,
                vec![
                    ИнстрV3::PushI64(2),
                    ИнстрV3::PushI64(3),
                    ИнстрV3::Call(1),
                    ИнстрV3::Ret,
                ],
            ),
            функция(
                1,
                2,
                vec![
                    ИнстрV3::Load(0),
                    ИнстрV3::Load(1),
                    ИнстрV3::Add,
                    ИнстрV3::Ret,
                ],
            ),
        ],
    };
    // порядок: главная=0, сложить=1 — но Call(1) верно
    // Запись: функции[0]=главная, функции[1]=сложить
    let mut vm = ИсполнительV3::новый(модуль).unwrap();
    assert_eq!(vm.запустить().unwrap(), ЗначениеV3::Целое(5));
}


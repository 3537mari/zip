//! Тесты интерпретатора ZIP VM v3.

use zip_vm::байткод_v3::{сериализовать_v3, ИнстрV3, МодульV3, ФункцияV3};
use zip_vm::исполнитель_v3::{ИсполнительV3, ЗначениеV3};

fn функция(имя_индекс: u32, арность: u16, инструкции: Vec<ИнстрV3>) -> ФункцияV3 {
    let mut код = Vec::new();
    for и in &инструкции {
        и.закодировать(&mut код);
    }
    ФункцияV3 {
        имя_индекс,
        арность,
        локалы: 8,
        флаги: 0,
        код,
    }
}

fn модуль_одна(инструкции: Vec<ИнстрV3>) -> МодульV3 {
    МодульV3 {
        флаги: 0,
        строки: vec!["главная".into()],
        функции: vec![функция(0, 0, инструкции)],
    }
}

#[test]
fn тест_простая_арифметика() {
    let модуль = модуль_одна(vec![
        ИнстрV3::PushI64(2),
        ИнстрV3::PushI64(3),
        ИнстрV3::Add,
        ИнстрV3::Ret,
    ]);
    let mut vm = ИсполнительV3::новый(модуль).unwrap();
    assert_eq!(vm.запустить().unwrap(), ЗначениеV3::Целое(5));
}


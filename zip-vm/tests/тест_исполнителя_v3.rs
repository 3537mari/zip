#[test]
fn тест_roundtrip_сериализация() {
    let модуль = модуль_одна(vec![
        ИнстрV3::PushI64(7),
        ИнстрV3::PushI64(1),
        ИнстрV3::Sub,
        ИнстрV3::Ret,
    ]);
    let bytes = сериализовать_v3(&модуль);
    let м2 = zip_vm::разобрать_v3(&bytes).unwrap();
    let mut vm = ИсполнительV3::новый(м2).unwrap();
    assert_eq!(vm.запустить().unwrap(), ЗначениеV3::Целое(6));
}


use zip_vm::встроенные_v3::Встроенные;
use zip_vm::исполнитель_v3::ЗначениеV3;

#[test]
fn builtins_sys_write_существует() {
    let b = Встроенные::новый();
    assert!(b.существует("sys_write"));
    assert!(b.существует("выделить"));
    assert!(b.существует("напечатать_число_строкой"));
    let r = b
        .вызвать(
            "sys_write",
            &[
                ЗначениеV3::Целое(1),
                ЗначениеV3::Строка("RT\n".into()),
                ЗначениеV3::Целое(3),
            ],
        )
        .unwrap();
    assert_eq!(r, ЗначениеV3::Целое(3));
}

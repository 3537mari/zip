//! Нейрогенез — генерация функций из паттернов (Идея 3).
//!
//! Основание: мозг создаёт новые нейроны для обработки повторяющихся
//! сигналов. ZIP замечает повторяющиеся паттерны и генерирует
//! композитные глаголы.

use crate::промежуток::{
    ИдентификаторФункции, Инструкция, Регистр, Тип, ФункцияПП,
};
use std::collections::HashMap;

/// Паттерн в IR — последовательность инструкций.
#[derive(Debug, Clone, PartialEq, Eq, Hash)]
pub struct ПаттернIR {
    /// Последовательность сигнатур инструкций
    pub сигнатуры: Vec<СигнатураИнструкции>,
    /// Сколько раз встречается
    pub частота: usize,
}

/// Сигнатура инструкции (без конкретных регистров).
#[derive(Debug, Clone, PartialEq, Eq, Hash)]
pub enum СигнатураИнструкции {
    Вызов(String),
    Импульс,
    Зафиксировать,
    Умножить,
    Сложить,
    Вычесть,
    Разделить,
    Другое,
}

/// Найденный паттерн для генерации.
#[derive(Debug, Clone)]
pub struct НайденныйПаттерн {
    pub паттерн: ПаттернIR,
    pub функции_участники: Vec<ИдентификаторФункции>,
    pub примеры_использования: Vec<usize>,
}

/// Анализатор паттернов.
pub struct АнализаторПаттернов {
    минимальная_частота: usize,
    максимальная_длина: usize,
}

impl АнализаторПаттернов {
    pub fn новый() -> Self {
        Self {
            минимальная_частота: 2,
            максимальная_длина: 5,
        }
    }

    pub fn с_параметрами(мин_частота: usize, макс_длина: usize) -> Self {
        Self {
            минимальная_частота: мин_частота.max(1),
            максимальная_длина: макс_длина.max(2),
        }
    }

    /// Найти повторяющиеся паттерны во всех функциях.
    pub fn найти_паттерны(&self, функции: &[ФункцияПП]) -> Vec<НайденныйПаттерн> {
        let mut счётчик: HashMap<Vec<СигнатураИнструкции>, usize> = HashMap::new();

        for функция in функции {
            if функция.имя.starts_with("КОМПОЗИТ_") {
                continue;
            }
            let интересные = интересные_сигнатуры(&функция.тело, функции);
            for длина in 2..=self.максимальная_длина.min(интересные.len().max(2)) {
                if интересные.len() < длина {
                    continue;
                }
                for начало in 0..=(интересные.len() - длина) {
                    let окно = интересные[начало..начало + длина].to_vec();
                    // Композит имеет смысл только при ≥1 вызове.
                    if !окно
                        .iter()
                        .any(|с| matches!(с, СигнатураИнструкции::Вызов(_)))
                    {
                        continue;
                    }
                    *счётчик.entry(окно).or_insert(0) += 1;
                }
            }
        }

        let mut результат: Vec<_> = счётчик
            .into_iter()
            .filter(|(_, частота)| *частота >= self.минимальная_частота)
            .map(|(сигнатуры, частота)| НайденныйПаттерн {
                паттерн: ПаттернIR {
                    сигнатуры,
                    частота,
                },
                функции_участники: Vec::new(),
                примеры_использования: Vec::new(),
            })
            .collect();

        результат.sort_by(|а, б| {
            б.паттерн
                .частота
                .cmp(&а.паттерн.частота)
                .then_with(|| б.паттерн.сигнатуры.len().cmp(&а.паттерн.сигнатуры.len()))
        });
        результат
    }
}

impl Default for АнализаторПаттернов {
    fn default() -> Self {
        Self::новый()
    }
}

/// Генератор композитных функций.
pub struct ГенераторКомпозитов {
    счётчик: usize,
}

impl ГенераторКомпозитов {
    pub fn новый() -> Self {
        Self { счётчик: 0 }
    }

    /// Сгенерировать композитную функцию из паттерна.
    pub fn сгенерировать(
        &mut self,
        паттерн: &НайденныйПаттерн,
        функции: &[ФункцияПП],
    ) -> ФункцияПП {
        self.счётчик += 1;

        let имена: Vec<_> = паттерн
            .паттерн
            .сигнатуры
            .iter()
            .filter_map(|с| match с {
                СигнатураИнструкции::Вызов(имя) => Some(имя.clone()),
                _ => None,
            })
            .collect();

        let имя = if имена.is_empty() {
            format!("КОМПОЗИТ_{}", self.счётчик)
        } else {
            format!("КОМПОЗИТ_{}", имена.join("_"))
        };

        let рег_вход = Регистр(0);
        let рег_текущий = Регистр(1);
        let mut тело = vec![Инструкция::Переместить {
            назначение: рег_текущий,
            источник: рег_вход,
        }];

        for (i, сигнатура) in паттерн.паттерн.сигнатуры.iter().enumerate() {
            if let СигнатураИнструкции::Вызов(имя_ф) = сигнатура {
                if let Some(ф) = функции.iter().find(|ф| &ф.имя == имя_ф) {
                    let рег_рез = Регистр(10 + i as u32);
                    тело.push(Инструкция::Вызвать {
                        функция: ф.идентификатор,
                        аргументы: vec![рег_текущий],
                        результат: Some(рег_рез),
                        отметить_горячей: false,
                    });
                    тело.push(Инструкция::Импульс {
                        источник: рег_рез,
                        назначение: рег_текущий,
                    });
                }
            }
        }

        тело.push(Инструкция::Вернуть {
            значение: Some(рег_текущий),
        });

        let next_id = функции
            .iter()
            .map(|ф| ф.идентификатор.0)
            .max()
            .unwrap_or(0)
            + self.счётчик as u32;

        ФункцияПП {
            идентификатор: ИдентификаторФункции(next_id.max(10_000)),
            имя,
            параметры: vec![рег_вход],
            тип_возврата: Тип::Несовершенный,
            тело,
            ..ФункцияПП::default()
        }
    }
}

impl Default for ГенераторКомпозитов {
    fn default() -> Self {
        Self::новый()
    }
}

/// Применить нейрогенез к программе: найти паттерны и добавить композиты.
///
/// Возвращает имена созданных функций (для логов).
pub fn применить_нейрогенез(
    функции: &mut Vec<ФункцияПП>,
    мин_частота: usize,
    фильтр_паттерна: Option<&str>,
) -> Vec<(String, usize)> {
    let анализатор = АнализаторПаттернов::с_параметрами(мин_частота, 5);
    let паттерны = анализатор.найти_паттерны(функции);
    let mut генератор = ГенераторКомпозитов::новый();
    let mut созданные = Vec::new();
    let mut уже_есть: std::collections::HashSet<String> = функции
        .iter()
        .map(|ф| ф.имя.clone())
        .collect();

    for паттерн in паттерны.iter().take(10) {
        if let Some(имя_фильтр) = фильтр_паттерна {
            let содержит = паттерн.паттерн.сигнатуры.iter().any(|с| {
                matches!(с, СигнатураИнструкции::Вызов(и) if и.contains(имя_фильтр))
            });
            if !содержит {
                continue;
            }
        }

        let композит = генератор.сгенерировать(паттерн, функции);
        if уже_есть.contains(&композит.имя) {
            continue;
        }
        println!(
            "[нейрогенез] Создана функция: {} (частота: {})",
            композит.имя, паттерн.паттерн.частота
        );
        созданные.push((композит.имя.clone(), паттерн.паттерн.частота));
        уже_есть.insert(композит.имя.clone());
        функции.push(композит);
    }

    созданные
}

/// Собрать запросы `@нейрогенез` с функций и выполнить проход.
pub fn применить_из_флагов(функции: &mut Vec<ФункцияПП>) -> Vec<(String, usize)> {
    let запрос = функции.iter().find(|ф| ф.нейрогенез).map(|ф| {
        (
            ф.нейрогенез_порог.unwrap_or(2),
            ф.нейрогенез_фильтр.clone(),
        )
    });
    let Some((порог, фильтр)) = запрос else {
        return Vec::new();
    };
    применить_нейрогенез(функции, порог, фильтр.as_deref())
}

fn интересные_сигнатуры(
    тело: &[Инструкция],
    функции: &[ФункцияПП],
) -> Vec<СигнатураИнструкции> {
    тело.iter()
        .filter_map(|и| {
            let с = сигнатура_инструкции(и, функции);
            if matches!(с, СигнатураИнструкции::Другое) {
                None
            } else {
                Some(с)
            }
        })
        .collect()
}

fn сигнатура_инструкции(и: &Инструкция, функции: &[ФункцияПП]) -> СигнатураИнструкции {
    match и {
        Инструкция::Вызвать { функция, .. } => {
            let имя = функции
                .iter()
                .find(|ф| ф.идентификатор == *функция)
                .map(|ф| ф.имя.clone())
                .unwrap_or_else(|| format!("функция_{}", функция.0));
            СигнатураИнструкции::Вызов(имя)
        }
        Инструкция::Импульс { .. } => СигнатураИнструкции::Импульс,
        Инструкция::Зафиксировать { .. } => СигнатураИнструкции::Зафиксировать,
        Инструкция::Умножить { .. } => СигнатураИнструкции::Умножить,
        Инструкция::Сложить { .. } => СигнатураИнструкции::Сложить,
        Инструкция::Вычесть { .. } => СигнатураИнструкции::Вычесть,
        Инструкция::Разделить { .. } => СигнатураИнструкции::Разделить,
        _ => СигнатураИнструкции::Другое,
    }
}

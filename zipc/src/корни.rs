/// Описание корня.
#[derive(Debug, Clone)]
pub struct Корень {
    pub код: String,
    pub смысл: String,
    pub категория: КатегорияКорня,
    pub глагол: String,
    pub буфер: String,
    pub инструмент: String,
    pub примеры: Vec<String>,
}

fn к(
    код: &str,
    смысл: &str,
    категория: КатегорияКорня,
    глагол: &str,
    буфер: &str,
    инструмент: &str,
    примеры: &[&str],
) -> Корень {
    Корень {
        код: код.into(),
        смысл: смысл.into(),
        категория,
        глагол: глагол.into(),
        буфер: буфер.into(),
        инструмент: инструмент.into(),
        примеры: примеры.iter().map(|с| (*с).into()).collect(),
    }
}


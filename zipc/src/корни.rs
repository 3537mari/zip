fn индекс() -> &'static HashMap<String, Корень> {
    static ИНДЕКС: OnceLock<HashMap<String, Корень>> = OnceLock::new();
    ИНДЕКС.get_or_init(|| {
        полная_таблица()
            .into_iter()
            .map(|к| (к.код.clone(), к))
            .collect()
    })
}

/// Найти корень по коду.
pub fn найти_корень(код: &str) -> Option<Корень> {
    индекс().get(код).cloned()
}

/// Есть ли код в таблице 64.
pub fn известный_код(код: &str) -> bool {
    индекс().contains_key(код)
}

/// Все корни указанной категории.
pub fn корни_по_категории(категория: КатегорияКорня) -> Vec<Корень> {
    полная_таблица()
        .into_iter()
        .filter(|к| к.категория == категория)
        .collect()
}

/// Код корня: ровно 3 кириллических символа (согласные / слабые / знаки / гласные таблицы).
pub fn валидный_код_корня(код: &str) -> bool {
    let символы: Vec<char> = код.chars().collect();
    if символы.len() != 3 {
        return false;
    }
    символы.iter().all(|с| {
        crate::лексика::Лексер::это_корневая_буква_публ(*с)
    })
}

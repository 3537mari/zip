//! Рекурсивный спуск для ZIP.
//!
//! Приоритет: `()` > `!` > `~` > `>>`/`>>>` > `||`
//! - `>>` — правая ассоциативность
//! - `||` — левая ассоциативность

use crate::дерево::Узел;
use crate::лексика::{Лексер, ОшибкаЛексики, ПозиционныйТокен, Токен};

#[derive(Debug, Clone, PartialEq)]
pub struct ОшибкаПарсера {
    pub сообщение: String,
    pub строка: usize,
    pub столбец: usize,
}

impl std::fmt::Display for ОшибкаПарсера {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        write!(f, "{}", self.сообщение)
    }
}

impl std::error::Error for ОшибкаПарсера {}

impl From<ОшибкаЛексики> for ОшибкаПарсера {
    fn from(е: ОшибкаЛексики) -> Self {
        Self {
            сообщение: format!(
                "Ошибка лексики на строке {}: {}",
                е.строка, е.сообщение
            ),
            строка: е.строка,
            столбец: е.столбец,
        }
    }
}

pub struct Парсер {
    токены: Vec<ПозиционныйТокен>,
    позиция: usize,
}

impl Парсер {
    pub fn новый(исходник: &str) -> Result<Self, ОшибкаПарсера> {
        let токены = Лексер::новый(исходник).разобрать_с_позициями()?;
        Ok(Self {
            токены,
            позиция: 0,
        })
    }

    pub fn разобрать(&mut self) -> Result<Узел, ОшибкаПарсера> {
        let mut объявления = Vec::new();

        while !self.это(&Токен::КонецФайла) {
            объявления.push(self.разобрать_объявление_или_выражение()?);
        }

        Ok(Узел::Программа { объявления })
    }

    fn разобрать_объявление_или_выражение(&mut self) -> Result<Узел, ОшибкаПарсера> {
        if let Токен::Директива(имя) = self.текущий_токен() {
            if имя == "link" {
                return self.разобрать_внешний_вызов();
            }
            return Err(self.ошибка(format!(
                "Директива #{} пока не поддерживается парсером на строке {}",
                имя,
                self.текущая_строка()
            )));
        }

        if matches!(self.текущий_токен(), Токен::Корень(_))
            && self.заглянуть_это(1, &Токен::Равно)
        {
            return self.разобрать_объявление_корня();
        }

        self.разобрать_хор()
    }

    fn разобрать_объявление_корня(&mut self) -> Result<Узел, ОшибкаПарсера> {
        let корень = match self.съесть_любой() {
            Токен::Корень(к) => к,
            _ => {
                return Err(self.ошибка(format!(
                    "Ожидался корень из трёх согласных на строке {}",
                    self.текущая_строка()
                )))
            }
        };

        self.ожидать(
            &Токен::Равно,
            &format!(
                "Ожидался знак = после корня {} на строке {}",
                корень,
                self.текущая_строка()
            ),
        )?;

        self.ожидать(
            &Токен::ФигурнаяЛевая,
            &format!(
                "Ожидалась открывающая скобка {{ после объявления корня {} на строке {}",
                корень,
                self.текущая_строка()
            ),
        )?;

        let mut шаблоны = Vec::new();
        while !self.это(&Токен::ФигурнаяПравая) && !self.это(&Токен::КонецФайла) {
            let имя_шаблона = self.разобрать_имя_шаблона()?;
            self.ожидать(
                &Токен::Двоеточие,
                &format!(
                    "Ожидалось двоеточие : после имени шаблона {} на строке {}",
                    имя_шаблона,
                    self.текущая_строка()
                ),
            )?;
            let слово = self.разобрать_имя_идентификатора()?;
            шаблоны.push((имя_шаблона, слово));

            if self.это(&Токен::Запятая) {
                self.съесть_любой();
            } else {
                break;
            }
        }

        self.ожидать(
            &Токен::ФигурнаяПравая,
            &format!(
                "Ожидалась закрывающая скобка }} в объявлении корня {} на строке {}",
                корень,
                self.текущая_строка()
            ),
        )?;

        Ok(Узел::ОбъявлениеКорня { корень, шаблоны })
    }

    fn разобрать_имя_шаблона(&mut self) -> Result<String, ОшибкаПарсера> {
        let левая = self.разобрать_имя_идентификатора()?;
        if self.это(&Токен::Дефис) {
            self.съесть_любой();
            let правая = self.разобрать_имя_идентификатора()?;
            Ok(format!("{}-{}", левая, правая))
        } else {
            Ok(левая)
        }
    }

    fn разобрать_внешний_вызов(&mut self) -> Result<Узел, ОшибкаПарсера> {
        let строка = self.текущая_строка();
        match self.съесть_любой() {
            Токен::Директива(имя) if имя == "link" => {}
            _ => {
                return Err(self.ошибка(format!(
                    "Ожидалась директива #link на строке {}",
                    строка
                )))
            }
        }

        // Синтаксис: #link("библиотека") ГЛАГОЛ(...)
        self.ожидать(
            &Токен::СкобкаЛевая,
            &format!(
                "Ожидалась открывающая скобка ( после #link на строке {}",
                self.текущая_строка()
            ),
        )?;

        let библиотека = match self.съесть_любой() {
            Токен::Строка(с) => с,
            _ => {
                return Err(self.ошибка(format!(
                    "Ожидалась строка с именем библиотеки после #link на строке {}",
                    self.текущая_строка()
                )))
            }
        };

        self.ожидать(
            &Токен::СкобкаПравая,
            &format!(
                "Ожидалась закрывающая скобка ) после имени библиотеки #link на строке {}",
                self.текущая_строка()
            ),
        )?;

        let функция = self.разобрать_имя_идентификатора()?;
        let строка_скобки = self.текущая_строка();

        self.ожидать(
            &Токен::СкобкаЛевая,
            &format!(
                "Ожидалась открывающая скобка ( после функции {} внешнего вызова на строке {}",
                функция, строка_скобки
            ),
        )?;

        let аргументы = self.разобрать_список_аргументов(&функция, строка_скобки)?;

        Ok(Узел::ВнешнийВызов {
            библиотека,
            функция,
            аргументы,
        })
    }

    /// `||` — левая ассоциативность.
    fn разобрать_хор(&mut self) -> Result<Узел, ОшибкаПарсера> {
        let первый = self.разобрать_импульс()?;

        if !self.это(&Токен::Хор) {
            return Ok(первый);
        }

        let mut ветки = vec![первый];
        while self.это(&Токен::Хор) {
            self.съесть_любой();
            ветки.push(self.разобрать_импульс()?);
        }

        Ok(Узел::Хор { ветки })
    }

    /// `>>` / `>>>` — правая ассоциативность.
    fn разобрать_импульс(&mut self) -> Result<Узел, ОшибкаПарсера> {
        let левый = self.разобрать_постфикс()?;

        if self.это(&Токен::Импульс) || self.это(&Токен::СетьИмпульс) {
            self.съесть_любой();
            let правый = self.разобрать_импульс()?;
            return прикрепить_следующий(левый, правый);
        }

        Ok(левый)
    }

    fn разобрать_постфикс(&mut self) -> Result<Узел, ОшибкаПарсера> {
        let узел = self.разобрать_первичный(false)?;

        if self.это(&Токен::Фиксация) {
            let строка = self.текущая_строка();
            self.съесть_любой();
            let глагол = имя_глагола(&узел).ok_or_else(|| ОшибкаПарсера {
                сообщение: format!(
                    "Оператор ! ожидает глагол перед собой на строке {}",
                    строка
                ),
                строка,
                столбец: self.текущий_столбец(),
            })?;
            let данные = match узел {
                Узел::ВызовГлагола { аргументы, .. } => Узел::Блок(аргументы),
                другой => другой,
            };
            return Ok(Узел::Фиксация {
                глагол,
                данные: Box::new(данные),
            });
        }

        if self.это(&Токен::Поток) {
            let строка = self.текущая_строка();
            self.съесть_любой();
            let глагол = имя_глагола(&узел).ok_or_else(|| ОшибкаПарсера {
                сообщение: format!(
                    "Оператор ~ ожидает глагол перед собой на строке {}",
                    строка
                ),
                строка,
                столбец: self.текущий_столбец(),
            })?;
            let тело = if self.это(&Токен::ФигурнаяЛевая) {
                self.разобрать_блок()?
            } else {
                Узел::Блок(vec![])
            };
            return Ok(Узел::АсинхронныйПоток {
                глагол,
                тело: Box::new(тело),
            });
        }

        Ok(узел)
    }

    fn разобрать_первичный(&mut self, как_аргумент: bool) -> Result<Узел, ОшибкаПарсера> {
        match self.текущий_токен() {
            Токен::Целое(n) => {
                self.съесть_любой();
                Ok(Узел::Целое(n))
            }
            Токен::Вещественное(x) => {
                self.съесть_любой();
                Ok(Узел::Вещественное(x))
            }
            Токен::Строка(s) => {
                self.съесть_любой();
                Ok(Узел::Строка(s))
            }
            Токен::ФигурнаяЛевая => self.разобрать_блок(),
            Токен::СкобкаЛевая => {
                self.съесть_любой();
                let внутри = self.разобрать_хор()?;
                self.ожидать(
                    &Токен::СкобкаПравая,
                    &format!(
                        "Ожидалась закрывающая скобка ) для группировки на строке {}",
                        self.текущая_строка()
                    ),
                )?;
                Ok(внутри)
            }
            Токен::Корень(_) | Токен::Шаблон(_) | Токен::Слово(_) => {
                let имя = self.разобрать_имя_идентификатора()?;
                if self.это(&Токен::СкобкаЛевая) {
                    let строка = self.текущая_строка();
                    self.съесть_любой();
                    let аргументы = self.разобрать_список_аргументов(&имя, строка)?;
                    Ok(Узел::ВызовГлагола {
                        глагол: имя,
                        аргументы,
                        следующий: None,
                    })
                } else if как_аргумент {
                    Ok(Узел::Идентификатор(имя))
                } else {
                    Ok(Узел::ВызовГлагола {
                        глагол: имя,
                        аргументы: vec![],
                        следующий: None,
                    })
                }
            }
            другой => Err(self.ошибка(format!(
                "Неожиданный токен {:?} на строке {}",
                другой,
                self.текущая_строка()
            ))),
        }
    }

    /// Аргумент — полное выражение хора, но голое имя без `(` остаётся идентификатором.
    fn разобрать_аргумент(&mut self) -> Result<Узел, ОшибкаПарсера> {
        // Спецслучай: имя → идентификатор или вызов; далее постфиксы и цепочки.
        let узел = self.разобрать_постфикс_аргумента()?;

        if self.это(&Токен::Импульс) || self.это(&Токен::СетьИмпульс) {
            self.съесть_любой();
            let правый = self.разобрать_импульс()?;
            return прикрепить_следующий(узел, правый);
        }

        if self.это(&Токен::Хор) {
            let mut ветки = vec![узел];
            while self.это(&Токен::Хор) {
                self.съесть_любой();
                ветки.push(self.разобрать_импульс()?);
            }
            return Ok(Узел::Хор { ветки });
        }

        Ok(узел)
    }

    fn разобрать_постфикс_аргумента(&mut self) -> Result<Узел, ОшибкаПарсера> {
        let узел = self.разобрать_первичный(true)?;

        if self.это(&Токен::Фиксация) {
            let строка = self.текущая_строка();
            self.съесть_любой();
            let глагол = имя_глагола(&узел).ok_or_else(|| ОшибкаПарсера {
                сообщение: format!(
                    "Оператор ! ожидает глагол перед собой на строке {}",
                    строка
                ),
                строка,
                столбец: self.текущий_столбец(),
            })?;
            let данные = match узел {
                Узел::ВызовГлагола { аргументы, .. } => Узел::Блок(аргументы),
                Узел::Идентификатор(_) => Узел::Блок(vec![]),
                другой => другой,
            };
            return Ok(Узел::Фиксация {
                глагол,
                данные: Box::new(данные),
            });
        }

        if self.это(&Токен::Поток) {
            let строка = self.текущая_строка();
            self.съесть_любой();
            let глагол = имя_глагола(&узел).ok_or_else(|| ОшибкаПарсера {
                сообщение: format!(
                    "Оператор ~ ожидает глагол перед собой на строке {}",
                    строка
                ),
                строка,
                столбец: self.текущий_столбец(),
            })?;
            let тело = if self.это(&Токен::ФигурнаяЛевая) {
                self.разобрать_блок()?
            } else {
                Узел::Блок(vec![])
            };
            return Ok(Узел::АсинхронныйПоток {
                глагол,
                тело: Box::new(тело),
            });
        }

        Ok(узел)
    }

    fn разобрать_список_аргументов(
        &mut self,
        глагол: &str,
        строка_открытия: usize,
    ) -> Result<Vec<Узел>, ОшибкаПарсера> {
        let mut аргументы = Vec::new();

        if self.это(&Токен::СкобкаПравая) {
            self.съесть_любой();
            return Ok(аргументы);
        }

        loop {
            аргументы.push(self.разобрать_аргумент()?);
            if self.это(&Токен::Запятая) {
                self.съесть_любой();
                continue;
            }
            break;
        }

        self.ожидать(
            &Токен::СкобкаПравая,
            &format!(
                "Ожидалась закрывающая скобка ) после аргументов глагола {} на строке {}",
                глагол, строка_открытия
            ),
        )?;

        Ok(аргументы)
    }

    fn разобрать_блок(&mut self) -> Result<Узел, ОшибкаПарсера> {
        self.ожидать(
            &Токен::ФигурнаяЛевая,
            &format!(
                "Ожидалась открывающая скобка {{ блока на строке {}",
                self.текущая_строка()
            ),
        )?;

        let mut элементы = Vec::new();
        while !self.это(&Токен::ФигурнаяПравая) && !self.это(&Токен::КонецФайла) {
            элементы.push(self.разобрать_хор()?);
        }

        self.ожидать(
            &Токен::ФигурнаяПравая,
            &format!(
                "Ожидалась закрывающая скобка }} блока на строке {}",
                self.текущая_строка()
            ),
        )?;

        Ok(Узел::Блок(элементы))
    }

    fn разобрать_имя_идентификатора(&mut self) -> Result<String, ОшибкаПарсера> {
        match self.съесть_любой() {
            Токен::Корень(s) | Токен::Шаблон(s) | Токен::Слово(s) => Ok(s),
            _ => Err(self.ошибка(format!(
                "Ожидался идентификатор на строке {}",
                self.текущая_строка()
            ))),
        }
    }

    fn текущий(&self) -> &ПозиционныйТокен {
        self.токены
            .get(self.позиция)
            .expect("позиция парсера вне диапазона")
    }

    fn текущий_токен(&self) -> Токен {
        self.текущий().токен.clone()
    }

    fn текущая_строка(&self) -> usize {
        self.текущий().строка
    }

    fn текущий_столбец(&self) -> usize {
        self.текущий().столбец
    }

    fn это(&self, ожидаемый: &Токен) -> bool {
        &self.текущий_токен() == ожидаемый
    }

    fn заглянуть_это(&self, смещение: usize, ожидаемый: &Токен) -> bool {
        self.токены
            .get(self.позиция + смещение)
            .map(|п| &п.токен == ожидаемый)
            .unwrap_or(false)
    }

    fn съесть_любой(&mut self) -> Токен {
        let т = self.текущий_токен();
        if !matches!(т, Токен::КонецФайла) {
            self.позиция += 1;
        }
        т
    }

    fn ожидать(&mut self, ожидаемый: &Токен, сообщение: &str) -> Result<(), ОшибкаПарсера> {
        if self.это(ожидаемый) {
            self.съесть_любой();
            Ok(())
        } else {
            Err(self.ошибка(сообщение.to_string()))
        }
    }

    fn ошибка(&self, сообщение: String) -> ОшибкаПарсера {
        ОшибкаПарсера {
            сообщение,
            строка: self.текущая_строка(),
            столбец: self.текущий_столбец(),
        }
    }
}

fn имя_глагола(узел: &Узел) -> Option<String> {
    match узел {
        Узел::ВызовГлагола { глагол, .. } => Some(глагол.clone()),
        Узел::Идентификатор(имя) => Some(имя.clone()),
        _ => None,
    }
}

fn прикрепить_следующий(левый: Узел, правый: Узел) -> Result<Узел, ОшибкаПарсера> {
    match левый {
        Узел::ВызовГлагола {
            глагол,
            аргументы,
            следующий: None,
        } => Ok(Узел::ВызовГлагола {
            глагол,
            аргументы,
            следующий: Some(Box::new(правый)),
        }),
        Узел::Идентификатор(имя) => Ok(Узел::ВызовГлагола {
            глагол: имя,
            аргументы: vec![],
            следующий: Some(Box::new(правый)),
        }),
        другой => Err(ОшибкаПарсера {
            сообщение: format!(
                "Оператор >> ожидает вызов глагола слева, получено {:?}",
                другой
            ),
            строка: 1,
            столбец: 1,
        }),
    }
}

/// Удобная обёртка: исходник → AST.
pub fn разобрать_исходник(исходник: &str) -> Result<Узел, ОшибкаПарсера> {
    Парсер::новый(исходник)?.разобрать()
}

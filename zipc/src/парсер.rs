//! Рекурсивный спуск для ZIP.
//!
//! Поток: `()` > `!` > `~` > `>>`/`>>>` > `||`
//! Выражения (низкий → высокий приоритет):
//! или → и → не → сравнение → +/− → */ → унарный − → вызов/скобки

use crate::дерево::Узел;
use crate::лексика::{Лексер, ОшибкаЛексики, ПозиционныйТокен, Токен};

#[derive(Debug, Clone, PartialEq)]
pub struct ОшибкаПарсера {
    pub сообщение: String,
    pub строка: usize,
    pub столбец: usize,
}

impl std::fmt::Display for ОшибкаПарсера {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        write!(f, "{}", self.сообщение)
    }
}

impl std::error::Error for ОшибкаПарсера {}

impl From<ОшибкаЛексики> for ОшибкаПарсера {
    fn from(е: ОшибкаЛексики) -> Self {
        Self {
            сообщение: format!(
                "Ошибка лексики на строке {}: {}",
                е.строка, е.сообщение
            ),
            строка: е.строка,
            столбец: е.столбец,
        }
    }
}

pub struct Парсер {
    токены: Vec<ПозиционныйТокен>,
    позиция: usize,
}

impl Парсер {
    pub fn новый(исходник: &str) -> Result<Self, ОшибкаПарсера> {
        let токены = Лексер::новый(исходник).разобрать_с_позициями()?;
        Ok(Self {
            токены,
            позиция: 0,
        })
    }

    pub fn разобрать(&mut self) -> Result<Узел, ОшибкаПарсера> {
        let mut объявления = Vec::new();
        while !self.это(&Токен::КонецФайла) {
            объявления.push(self.разобрать_инструкцию()?);
        }
        Ok(Узел::Программа { объявления })
    }

    fn разобрать_инструкцию(&mut self) -> Result<Узел, ОшибкаПарсера> {
        match self.текущий_токен() {
            Токен::Директива(имя) if имя == "link" => self.разобрать_внешний_вызов(),
            Токен::Директива(имя) => Err(self.ошибка(format!(
                "Директива #{} пока не поддерживается парсером на строке {}",
                имя,
                self.текущая_строка()
            ))),
            Токен::Корень(_) if self.заглянуть_это(1, &Токен::Равно) => {
                self.разобрать_объявление_корня()
            }
            Токен::Если => self.разобрать_если(),
            Токен::Пока => self.разобрать_пока(),
            Токен::Для => self.разобрать_для(),
            Токен::Функция => self.разобрать_функцию(),
            Токен::Возврат => self.разобрать_возврат(),
            Токен::Прервать => {
                self.съесть_любой();
                Ok(Узел::Прервать)
            }
            Токен::Продолжить => {
                self.съесть_любой();
                Ok(Узел::Продолжить)
            }
            _ => self.разобрать_присваивание_или_поток(),
        }
    }

    fn разобрать_присваивание_или_поток(&mut self) -> Result<Узел, ОшибкаПарсера> {
        // имя = выражение  (не ==)
        if matches!(
            self.текущий_токен(),
            Токен::Слово(_) | Токен::Корень(_) | Токен::Шаблон(_)
        ) && self.заглянуть_это(1, &Токен::Равно)
        {
            let имя = self.разобрать_имя_идентификатора()?;
            self.съесть_любой(); // =
            let значение = self.разобрать_выражение()?;
            return Ok(Узел::Присваивание {
                имя,
                значение: Box::new(значение),
            });
        }
        self.разобрать_хор()
    }

    fn разобрать_если(&mut self) -> Result<Узел, ОшибкаПарсера> {
        self.съесть_любой(); // если
        self.ожидать(&Токен::СкобкаЛевая, "Ожидалась ( после если")?;
        let условие = self.разобрать_выражение()?;
        self.ожидать(&Токен::СкобкаПравая, "Ожидалась ) после условия если")?;
        let тогда = self.разобрать_блок_или_инструкцию()?;
        let иначе = if self.это(&Токен::Иначе) {
            self.съесть_любой();
            Some(Box::new(self.разобрать_блок_или_инструкцию()?))
        } else {
            None
        };
        Ok(Узел::Если {
            условие: Box::new(условие),
            тогда: Box::new(тогда),
            иначе,
        })
    }

    fn разобрать_пока(&mut self) -> Result<Узел, ОшибкаПарсера> {
        self.съесть_любой(); // пока
        self.ожидать(&Токен::СкобкаЛевая, "Ожидалась ( после пока")?;
        let условие = self.разобрать_выражение()?;
        self.ожидать(&Токен::СкобкаПравая, "Ожидалась ) после условия пока")?;
        let тело = self.разобрать_блок_или_инструкцию()?;
        Ok(Узел::Пока {
            условие: Box::new(условие),
            тело: Box::new(тело),
        })
    }

    fn разобрать_для(&mut self) -> Result<Узел, ОшибкаПарсера> {
        self.съесть_любой(); // для
        let переменная = self.разобрать_имя_идентификатора()?;
        self.ожидать(&Токен::В, "Ожидалось «в» в цикле для")?;
        let коллекция = self.разобрать_выражение()?;
        let тело = self.разобрать_блок_или_инструкцию()?;
        Ok(Узел::Для {
            переменная,
            коллекция: Box::new(коллекция),
            тело: Box::new(тело),
        })
    }

    fn разобрать_функцию(&mut self) -> Result<Узел, ОшибкаПарсера> {
        self.съесть_любой(); // функция
        let имя = self.разобрать_имя_идентификатора()?;
        self.ожидать(&Токен::СкобкаЛевая, "Ожидалась ( после имени функции")?;
        let mut параметры = Vec::new();
        if !self.это(&Токен::СкобкаПравая) {
            loop {
                let имя_п = self.разобрать_имя_идентификатора()?;
                let тип_п = if self.это(&Токен::Двоеточие) {
                    self.съесть_любой();
                    self.разобрать_имя_идентификатора()?
                } else {
                    String::new()
                };
                параметры.push((имя_п, тип_п));
                if self.это(&Токен::Запятая) {
                    self.съесть_любой();
                    continue;
                }
                break;
            }
        }
        self.ожидать(&Токен::СкобкаПравая, "Ожидалась ) списка параметров")?;
        let тип_возврата = if self.это(&Токен::Двоеточие) {
            self.съесть_любой();
            Some(self.разобрать_имя_идентификатора()?)
        } else {
            None
        };
        let тело = self.разобрать_блок()?;
        Ok(Узел::ОпределениеФункции {
            имя,
            параметры,
            тип_возврата,
            тело: Box::new(тело),
        })
    }

    fn разобрать_возврат(&mut self) -> Result<Узел, ОшибкаПарсера> {
        self.съесть_любой(); // возврат
        if self.это(&Токен::СкобкаЛевая) {
            self.съесть_любой();
            if self.это(&Токен::СкобкаПравая) {
                self.съесть_любой();
                return Ok(Узел::Возврат(None));
            }
            let зн = self.разобрать_выражение()?;
            self.ожидать(&Токен::СкобкаПравая, "Ожидалась ) после возврат(...)")?;
            return Ok(Узел::Возврат(Some(Box::new(зн))));
        }
        if matches!(
            self.текущий_токен(),
            Токен::ФигурнаяПравая
                | Токен::КонецФайла
                | Токен::Иначе
                | Токен::Прервать
                | Токен::Продолжить
        ) {
            return Ok(Узел::Возврат(None));
        }
        // возврат выражение
        if !matches!(
            self.текущий_токен(),
            Токен::Если
                | Токен::Пока
                | Токен::Для
                | Токен::Функция
                | Токен::Возврат
        ) {
            let зн = self.разобрать_выражение()?;
            return Ok(Узел::Возврат(Some(Box::new(зн))));
        }
        Ok(Узел::Возврат(None))
    }

    fn разобрать_блок_или_инструкцию(&mut self) -> Result<Узел, ОшибкаПарсера> {
        if self.это(&Токен::ФигурнаяЛевая) {
            self.разобрать_блок()
        } else {
            self.разобрать_инструкцию()
        }
    }

    fn разобрать_объявление_корня(&mut self) -> Result<Узел, ОшибкаПарсера> {
        let корень = match self.съесть_любой() {
            Токен::Корень(к) => к,
            _ => {
                return Err(self.ошибка(format!(
                    "Ожидался корень из трёх согласных на строке {}",
                    self.текущая_строка()
                )))
            }
        };

        self.ожидать(
            &Токен::Равно,
            &format!(
                "Ожидался знак = после корня {} на строке {}",
                корень,
                self.текущая_строка()
            ),
        )?;

        self.ожидать(
            &Токен::ФигурнаяЛевая,
            &format!(
                "Ожидалась открывающая скобка {{ после объявления корня {} на строке {}",
                корень,
                self.текущая_строка()
            ),
        )?;

        let mut шаблоны = Vec::new();
        while !self.это(&Токен::ФигурнаяПравая) && !self.это(&Токен::КонецФайла) {
            let имя_шаблона = self.разобрать_имя_шаблона()?;
            self.ожидать(
                &Токен::Двоеточие,
                &format!(
                    "Ожидалось двоеточие : после имени шаблона {} на строке {}",
                    имя_шаблона,
                    self.текущая_строка()
                ),
            )?;
            let слово = self.разобрать_имя_идентификатора()?;
            шаблоны.push((имя_шаблона, слово));

            if self.это(&Токен::Запятая) {
                self.съесть_любой();
            } else {
                break;
            }
        }

        self.ожидать(
            &Токен::ФигурнаяПравая,
            &format!(
                "Ожидалась закрывающая скобка }} в объявлении корня {} на строке {}",
                корень,
                self.текущая_строка()
            ),
        )?;

        Ok(Узел::ОбъявлениеКорня { корень, шаблоны })
    }

    fn разобрать_имя_шаблона(&mut self) -> Result<String, ОшибкаПарсера> {
        let левая = self.разобрать_имя_идентификатора()?;
        if self.это(&Токен::Дефис) {
            self.съесть_любой();
            let правая = self.разобрать_имя_идентификатора()?;
            Ok(format!("{}-{}", левая, правая))
        } else {
            Ok(левая)
        }
    }

    fn разобрать_внешний_вызов(&mut self) -> Result<Узел, ОшибкаПарсера> {
        let строка = self.текущая_строка();
        match self.съесть_любой() {
            Токен::Директива(имя) if имя == "link" => {}
            _ => {
                return Err(self.ошибка(format!(
                    "Ожидалась директива #link на строке {}",
                    строка
                )))
            }
        }

        self.ожидать(
            &Токен::СкобкаЛевая,
            &format!(
                "Ожидалась открывающая скобка ( после #link на строке {}",
                self.текущая_строка()
            ),
        )?;

        let библиотека = match self.съесть_любой() {
            Токен::Строка(с) => с,
            _ => {
                return Err(self.ошибка(format!(
                    "Ожидалась строка с именем библиотеки после #link на строке {}",
                    self.текущая_строка()
                )))
            }
        };

        self.ожидать(
            &Токен::СкобкаПравая,
            &format!(
                "Ожидалась закрывающая скобка ) после имени библиотеки #link на строке {}",
                self.текущая_строка()
            ),
        )?;

        let функция = self.разобрать_имя_идентификатора()?;
        let строка_скобки = self.текущая_строка();

        self.ожидать(
            &Токен::СкобкаЛевая,
            &format!(
                "Ожидалась открывающая скобка ( после функции {} внешнего вызова на строке {}",
                функция, строка_скобки
            ),
        )?;

        let аргументы = self.разобрать_список_аргументов(&функция, строка_скобки)?;

        Ok(Узел::ВнешнийВызов {
            библиотека,
            функция,
            аргументы,
        })
    }

    /// `||` — левая ассоциативность.
    fn разобрать_хор(&mut self) -> Result<Узел, ОшибкаПарсера> {
        let первый = self.разобрать_импульс()?;

        if !self.это(&Токен::Хор) {
            return Ok(первый);
        }

        let mut ветки = vec![первый];
        while self.это(&Токен::Хор) {
            self.съесть_любой();
            ветки.push(self.разобрать_импульс()?);
        }

        Ok(Узел::Хор { ветки })
    }

    /// `>>` / `>>>` — правая ассоциативность.
    fn разобрать_импульс(&mut self) -> Result<Узел, ОшибкаПарсера> {
        let левый = self.разобрать_постфикс()?;

        if self.это(&Токен::Импульс) || self.это(&Токен::СетьИмпульс) {
            self.съесть_любой();
            let правый = self.разобрать_импульс()?;
            return прикрепить_следующий(левый, правый);
        }

        Ok(левый)
    }

    fn разобрать_постфикс(&mut self) -> Result<Узел, ОшибкаПарсера> {
        let узел = self.разобрать_выражение()?;

        if self.это(&Токен::Фиксация) {
            let строка = self.текущая_строка();
            self.съесть_любой();
            let глагол = имя_глагола(&узел).ok_or_else(|| ОшибкаПарсера {
                сообщение: format!(
                    "Оператор ! ожидает глагол перед собой на строке {}",
                    строка
                ),
                строка,
                столбец: self.текущий_столбец(),
            })?;
            let данные = match узел {
                Узел::ВызовГлагола { аргументы, .. } => Узел::Блок(аргументы),
                Узел::ВызовФункции { аргументы, .. } => Узел::Блок(аргументы),
                другой => другой,
            };
            return Ok(Узел::Фиксация {
                глагол,
                данные: Box::new(данные),
            });
        }

        if self.это(&Токен::Поток) {
            let строка = self.текущая_строка();
            self.съесть_любой();
            let глагол = имя_глагола(&узел).ok_or_else(|| ОшибкаПарсера {
                сообщение: format!(
                    "Оператор ~ ожидает глагол перед собой на строке {}",
                    строка
                ),
                строка,
                столбец: self.текущий_столбец(),
            })?;
            let тело = if self.это(&Токен::ФигурнаяЛевая) {
                self.разобрать_блок()?
            } else {
                Узел::Блок(vec![])
            };
            return Ok(Узел::АсинхронныйПоток {
                глагол,
                тело: Box::new(тело),
            });
        }

        Ok(узел)
    }

    // --- Выражения по приоритету ---

    fn разобрать_выражение(&mut self) -> Result<Узел, ОшибкаПарсера> {
        self.разобрать_или()
    }

    fn разобрать_или(&mut self) -> Result<Узел, ОшибкаПарсера> {
        let mut левый = self.разобрать_и()?;
        while self.это(&Токен::Или) {
            self.съесть_любой();
            let правый = self.разобрать_и()?;
            левый = Узел::ЛогическоеИли(Box::new(левый), Box::new(правый));
        }
        Ok(левый)
    }

    fn разобрать_и(&mut self) -> Result<Узел, ОшибкаПарсера> {
        let mut левый = self.разобрать_не()?;
        while self.это(&Токен::И) {
            self.съесть_любой();
            let правый = self.разобрать_не()?;
            левый = Узел::ЛогическоеИ(Box::new(левый), Box::new(правый));
        }
        Ok(левый)
    }

    fn разобрать_не(&mut self) -> Result<Узел, ОшибкаПарсера> {
        if self.это(&Токен::Не) {
            self.съесть_любой();
            let операнд = self.разобрать_не()?;
            return Ok(Узел::ЛогическоеНе(Box::new(операнд)));
        }
        self.разобрать_сравнение()
    }

    fn разобрать_сравнение(&mut self) -> Result<Узел, ОшибкаПарсера> {
        let левый = self.разобрать_сложение()?;
        let оп = match self.текущий_токен() {
            Токен::РавноРавно => Some("=="),
            Токен::НеРавно => Some("!="),
            Токен::Больше => Some(">"),
            Токен::Меньше => Some("<"),
            Токен::БольшеРавно => Some(">="),
            Токен::МеньшеРавно => Some("<="),
            _ => None,
        };
        if let Some(оператор) = оп {
            self.съесть_любой();
            let правый = self.разобрать_сложение()?;
            Ok(Узел::Сравнение {
                оператор: оператор.into(),
                левый: Box::new(левый),
                правый: Box::new(правый),
            })
        } else {
            Ok(левый)
        }
    }

    fn разобрать_сложение(&mut self) -> Result<Узел, ОшибкаПарсера> {
        let mut левый = self.разобрать_умножение()?;
        loop {
            let оп = match self.текущий_токен() {
                Токен::Плюс => Some("+"),
                Токен::Дефис => Some("-"),
                _ => None,
            };
            if let Some(оператор) = оп {
                self.съесть_любой();
                let правый = self.разобрать_умножение()?;
                левый = Узел::БинарнаяОперация {
                    оператор: оператор.into(),
                    левый: Box::new(левый),
                    правый: Box::new(правый),
                };
            } else {
                break;
            }
        }
        Ok(левый)
    }

    fn разобрать_умножение(&mut self) -> Result<Узел, ОшибкаПарсера> {
        let mut левый = self.разобрать_унарный()?;
        loop {
            let оп = match self.текущий_токен() {
                Токен::Звезда => Some("*"),
                Токен::Слеш => Some("/"),
                _ => None,
            };
            if let Some(оператор) = оп {
                self.съесть_любой();
                let правый = self.разобрать_унарный()?;
                левый = Узел::БинарнаяОперация {
                    оператор: оператор.into(),
                    левый: Box::new(левый),
                    правый: Box::new(правый),
                };
            } else {
                break;
            }
        }
        Ok(левый)
    }

    fn разобрать_унарный(&mut self) -> Result<Узел, ОшибкаПарсера> {
        if self.это(&Токен::Дефис) {
            self.съесть_любой();
            let операнд = self.разобрать_унарный()?;
            return Ok(Узел::УнарныйМинус(Box::new(операнд)));
        }
        self.разобрать_первичный(false)
    }

    fn разобрать_первичный(&mut self, как_аргумент: bool) -> Result<Узел, ОшибкаПарсера> {
        match self.текущий_токен() {
            Токен::Истина => {
                self.съесть_любой();
                Ok(Узел::Истина)
            }
            Токен::Ложь => {
                self.съесть_любой();
                Ok(Узел::Ложь)
            }
            Токен::Целое(n) => {
                self.съесть_любой();
                Ok(Узел::Целое(n))
            }
            Токен::Вещественное(x) => {
                self.съесть_любой();
                Ok(Узел::Вещественное(x))
            }
            Токен::Строка(s) => {
                self.съесть_любой();
                Ok(Узел::Строка(s))
            }
            Токен::ФигурнаяЛевая => self.разобрать_блок(),
            Токен::СкобкаЛевая => {
                self.съесть_любой();
                // Группировка: полное выражение / хор
                let внутри = if self.выглядит_как_поток() {
                    self.разобрать_хор()?
                } else {
                    self.разобрать_выражение()?
                };
                self.ожидать(
                    &Токен::СкобкаПравая,
                    &format!(
                        "Ожидалась закрывающая скобка ) для группировки на строке {}",
                        self.текущая_строка()
                    ),
                )?;
                Ok(внутри)
            }
            Токен::Корень(_) | Токен::Шаблон(_) | Токен::Слово(_) => {
                let вид = self.текущий_токен();
                let имя = self.разобрать_имя_идентификатора()?;
                self.завершить_имя_или_вызов(имя, вид, как_аргумент)
            }
            // Ключевые слова как идентификаторы в выражениях/аргументах
            // (на уровне инструкций они уже разобраны отдельно).
            т if это_ключевое_имя(&т) => {
                let имя = т.to_string();
                self.съесть_любой();
                let вид = Токен::Слово(имя.clone());
                self.завершить_имя_или_вызов(имя, вид, как_аргумент)
            }
            другой => Err(self.ошибка(format!(
                "Неожиданный токен {:?} на строке {}",
                другой,
                self.текущая_строка()
            ))),
        }
    }

    fn завершить_имя_или_вызов(
        &mut self,
        имя: String,
        вид: Токен,
        как_аргумент: bool,
    ) -> Result<Узел, ОшибкаПарсера> {
        if self.это(&Токен::СкобкаЛевая) {
            let строка = self.текущая_строка();
            self.съесть_любой();
            let аргументы = self.разобрать_список_аргументов(&имя, строка)?;
            if matches!(вид, Токен::Слово(_)) {
                Ok(Узел::ВызовФункции { имя, аргументы })
            } else {
                Ok(Узел::ВызовГлагола {
                    глагол: имя,
                    аргументы,
                    следующий: None,
                })
            }
        } else if как_аргумент || matches!(вид, Токен::Слово(_)) {
            Ok(Узел::Идентификатор(имя))
        } else {
            Ok(Узел::ВызовГлагола {
                глагол: имя,
                аргументы: vec![],
                следующий: None,
            })
        }
    }

    fn выглядит_как_поток(&self) -> bool {
        // Эвристика: внутри скобок с >> / || — поток VSO
        let mut i = self.позиция;
        let mut глубина = 0usize;
        while let Some(п) = self.токены.get(i) {
            match &п.токен {
                Токен::СкобкаПравая if глубина == 0 => break,
                Токен::СкобкаЛевая => глубина += 1,
                Токен::СкобкаПравая => глубина = глубина.saturating_sub(1),
                Токен::Импульс | Токен::СетьИмпульс | Токен::Хор | Токен::Поток
                    if глубина == 0 =>
                {
                    return true;
                }
                Токен::КонецФайла => break,
                _ => {}
            }
            i += 1;
        }
        false
    }

    fn разобрать_аргумент(&mut self) -> Result<Узел, ОшибкаПарсера> {
        let узел = self.разобрать_постфикс_аргумента()?;

        if self.это(&Токен::Импульс) || self.это(&Токен::СетьИмпульс) {
            self.съесть_любой();
            let правый = self.разобрать_импульс()?;
            return прикрепить_следующий(узел, правый);
        }

        if self.это(&Токен::Хор) {
            let mut ветки = vec![узел];
            while self.это(&Токен::Хор) {
                self.съесть_любой();
                ветки.push(self.разобрать_импульс()?);
            }
            return Ok(Узел::Хор { ветки });
        }

        Ok(узел)
    }

    fn разобрать_постфикс_аргумента(&mut self) -> Result<Узел, ОшибкаПарсера> {
        let узел = self.разобрать_выражение_как_аргумент()?;

        if self.это(&Токен::Фиксация) {
            let строка = self.текущая_строка();
            self.съесть_любой();
            let глагол = имя_глагола(&узел).ok_or_else(|| ОшибкаПарсера {
                сообщение: format!(
                    "Оператор ! ожидает глагол перед собой на строке {}",
                    строка
                ),
                строка,
                столбец: self.текущий_столбец(),
            })?;
            let данные = match узел {
                Узел::ВызовГлагола { аргументы, .. } => Узел::Блок(аргументы),
                Узел::Идентификатор(_) => Узел::Блок(vec![]),
                другой => другой,
            };
            return Ok(Узел::Фиксация {
                глагол,
                данные: Box::new(данные),
            });
        }

        if self.это(&Токен::Поток) {
            let строка = self.текущая_строка();
            self.съесть_любой();
            let глагол = имя_глагола(&узел).ok_or_else(|| ОшибкаПарсера {
                сообщение: format!(
                    "Оператор ~ ожидает глагол перед собой на строке {}",
                    строка
                ),
                строка,
                столбец: self.текущий_столбец(),
            })?;
            let тело = if self.это(&Токен::ФигурнаяЛевая) {
                self.разобрать_блок()?
            } else {
                Узел::Блок(vec![])
            };
            return Ok(Узел::АсинхронныйПоток {
                глагол,
                тело: Box::new(тело),
            });
        }

        Ok(узел)
    }

    fn разобрать_выражение_как_аргумент(&mut self) -> Result<Узел, ОшибкаПарсера> {
        // Как разобрать_выражение, но голое имя → Идентификатор
        // Переиспользуем цепочку, подменив первичный режим через флаг в конце.
        // Для простоты: парсим или, а в первичном вызываем с как_аргумент=true
        // через отдельный вход.
        self.позиция_выражение_аргумент(true)
    }

    fn позиция_выражение_аргумент(&mut self, как_аргумент: bool) -> Result<Узел, ОшибкаПарсера> {
        // Дублируем разобрать_или..унарный с как_аргумент в первичном.
        fn или(п: &mut Парсер, как_аргумент: bool) -> Result<Узел, ОшибкаПарсера> {
            let mut левый = и(п, как_аргумент)?;
            while п.это(&Токен::Или) {
                п.съесть_любой();
                let правый = и(п, как_аргумент)?;
                левый = Узел::ЛогическоеИли(Box::new(левый), Box::new(правый));
            }
            Ok(левый)
        }
        fn и(п: &mut Парсер, как_аргумент: bool) -> Result<Узел, ОшибкаПарсера> {
            let mut левый = не(п, как_аргумент)?;
            while п.это(&Токен::И) {
                п.съесть_любой();
                let правый = не(п, как_аргумент)?;
                левый = Узел::ЛогическоеИ(Box::new(левый), Box::new(правый));
            }
            Ok(левый)
        }
        fn не(п: &mut Парсер, как_аргумент: bool) -> Result<Узел, ОшибкаПарсера> {
            if п.это(&Токен::Не) {
                п.съесть_любой();
                return Ok(Узел::ЛогическоеНе(Box::new(не(п, как_аргумент)?)));
            }
            сравнение(п, как_аргумент)
        }
        fn сравнение(п: &mut Парсер, как_аргумент: bool) -> Result<Узел, ОшибкаПарсера> {
            let левый = сложение(п, как_аргумент)?;
            let оп = match п.текущий_токен() {
                Токен::РавноРавно => Some("=="),
                Токен::НеРавно => Some("!="),
                Токен::Больше => Some(">"),
                Токен::Меньше => Some("<"),
                Токен::БольшеРавно => Some(">="),
                Токен::МеньшеРавно => Some("<="),
                _ => None,
            };
            if let Some(оператор) = оп {
                п.съесть_любой();
                let правый = сложение(п, как_аргумент)?;
                Ok(Узел::Сравнение {
                    оператор: оператор.into(),
                    левый: Box::new(левый),
                    правый: Box::new(правый),
                })
            } else {
                Ok(левый)
            }
        }
        fn сложение(п: &mut Парсер, как_аргумент: bool) -> Result<Узел, ОшибкаПарсера> {
            let mut левый = умножение(п, как_аргумент)?;
            loop {
                let оп = match п.текущий_токен() {
                    Токен::Плюс => Some("+"),
                    Токен::Дефис => Some("-"),
                    _ => None,
                };
                if let Some(оператор) = оп {
                    п.съесть_любой();
                    let правый = умножение(п, как_аргумент)?;
                    левый = Узел::БинарнаяОперация {
                        оператор: оператор.into(),
                        левый: Box::new(левый),
                        правый: Box::new(правый),
                    };
                } else {
                    break;
                }
            }
            Ok(левый)
        }
        fn умножение(п: &mut Парсер, как_аргумент: bool) -> Result<Узел, ОшибкаПарсера> {
            let mut левый = унарный(п, как_аргумент)?;
            loop {
                let оп = match п.текущий_токен() {
                    Токен::Звезда => Some("*"),
                    Токен::Слеш => Some("/"),
                    _ => None,
                };
                if let Some(оператор) = оп {
                    п.съесть_любой();
                    let правый = унарный(п, как_аргумент)?;
                    левый = Узел::БинарнаяОперация {
                        оператор: оператор.into(),
                        левый: Box::new(левый),
                        правый: Box::new(правый),
                    };
                } else {
                    break;
                }
            }
            Ok(левый)
        }
        fn унарный(п: &mut Парсер, как_аргумент: bool) -> Result<Узел, ОшибкаПарсера> {
            if п.это(&Токен::Дефис) {
                п.съесть_любой();
                return Ok(Узел::УнарныйМинус(Box::new(унарный(п, как_аргумент)?)));
            }
            п.разобрать_первичный(как_аргумент)
        }

        или(self, как_аргумент)
    }

    fn разобрать_список_аргументов(
        &mut self,
        глагол: &str,
        строка_открытия: usize,
    ) -> Result<Vec<Узел>, ОшибкаПарсера> {
        let mut аргументы = Vec::new();

        if self.это(&Токен::СкобкаПравая) {
            self.съесть_любой();
            return Ok(аргументы);
        }

        loop {
            аргументы.push(self.разобрать_аргумент()?);
            if self.это(&Токен::Запятая) {
                self.съесть_любой();
                continue;
            }
            break;
        }

        self.ожидать(
            &Токен::СкобкаПравая,
            &format!(
                "Ожидалась закрывающая скобка ) после аргументов глагола {} на строке {}",
                глагол, строка_открытия
            ),
        )?;

        Ok(аргументы)
    }

    fn разобрать_блок(&mut self) -> Result<Узел, ОшибкаПарсера> {
        self.ожидать(
            &Токен::ФигурнаяЛевая,
            &format!(
                "Ожидалась открывающая скобка {{ блока на строке {}",
                self.текущая_строка()
            ),
        )?;

        let mut элементы = Vec::new();
        while !self.это(&Токен::ФигурнаяПравая) && !self.это(&Токен::КонецФайла) {
            элементы.push(self.разобрать_инструкцию()?);
        }

        self.ожидать(
            &Токен::ФигурнаяПравая,
            &format!(
                "Ожидалась закрывающая скобка }} блока на строке {}",
                self.текущая_строка()
            ),
        )?;

        Ok(Узел::Блок(элементы))
    }

    fn разобрать_имя_идентификатора(&mut self) -> Result<String, ОшибкаПарсера> {
        match self.съесть_любой() {
            Токен::Корень(s) | Токен::Шаблон(s) | Токен::Слово(s) => Ok(s),
            _ => Err(self.ошибка(format!(
                "Ожидался идентификатор на строке {}",
                self.текущая_строка()
            ))),
        }
    }

    fn текущий(&self) -> &ПозиционныйТокен {
        self.токены
            .get(self.позиция)
            .expect("позиция парсера вне диапазона")
    }

    fn текущий_токен(&self) -> Токен {
        self.текущий().токен.clone()
    }

    fn текущая_строка(&self) -> usize {
        self.текущий().строка
    }

    fn текущий_столбец(&self) -> usize {
        self.текущий().столбец
    }

    fn это(&self, ожидаемый: &Токен) -> bool {
        &self.текущий_токен() == ожидаемый
    }

    fn заглянуть_это(&self, смещение: usize, ожидаемый: &Токен) -> bool {
        self.токены
            .get(self.позиция + смещение)
            .map(|п| &п.токен == ожидаемый)
            .unwrap_or(false)
    }

    fn съесть_любой(&mut self) -> Токен {
        let т = self.текущий_токен();
        if !matches!(т, Токен::КонецФайла) {
            self.позиция += 1;
        }
        т
    }

    fn ожидать(&mut self, ожидаемый: &Токен, сообщение: &str) -> Result<(), ОшибкаПарсера> {
        if self.это(ожидаемый) {
            self.съесть_любой();
            Ok(())
        } else {
            Err(self.ошибка(сообщение.to_string()))
        }
    }

    fn ошибка(&self, сообщение: String) -> ОшибкаПарсера {
        ОшибкаПарсера {
            сообщение,
            строка: self.текущая_строка(),
            столбец: self.текущий_столбец(),
        }
    }
}

fn это_ключевое_имя(т: &Токен) -> bool {
    matches!(
        т,
        Токен::Если
            | Токен::Иначе
            | Токен::Пока
            | Токен::Для
            | Токен::В
            | Токен::Возврат
            | Токен::Прервать
            | Токен::Продолжить
            | Токен::Функция
            | Токен::Тип
            | Токен::Модуль
            | Токен::Импорт
            | Токен::И
            | Токен::Или
            | Токен::Не
    )
}

fn имя_глагола(узел: &Узел) -> Option<String> {
    match узел {
        Узел::ВызовГлагола { глагол, .. } => Some(глагол.clone()),
        Узел::ВызовФункции { имя, .. } => Some(имя.clone()),
        Узел::Идентификатор(имя) => Some(имя.clone()),
        _ => None,
    }
}

fn прикрепить_следующий(левый: Узел, правый: Узел) -> Result<Узел, ОшибкаПарсера> {
    match левый {
        Узел::ВызовГлагола {
            глагол,
            аргументы,
            следующий: None,
        } => Ok(Узел::ВызовГлагола {
            глагол,
            аргументы,
            следующий: Some(Box::new(правый)),
        }),
        Узел::ВызовФункции { имя, аргументы } => Ok(Узел::ВызовГлагола {
            глагол: имя,
            аргументы,
            следующий: Some(Box::new(правый)),
        }),
        Узел::Идентификатор(имя) => Ok(Узел::ВызовГлагола {
            глагол: имя,
            аргументы: vec![],
            следующий: Some(Box::new(правый)),
        }),
        другой => Err(ОшибкаПарсера {
            сообщение: format!(
                "Оператор >> ожидает вызов глагола слева, получено {:?}",
                другой
            ),
            строка: 1,
            столбец: 1,
        }),
    }
}

/// Удобная обёртка: исходник → AST.
pub fn разобрать_исходник(исходник: &str) -> Result<Узел, ОшибкаПарсера> {
    Парсер::новый(исходник)?.разобрать()
}

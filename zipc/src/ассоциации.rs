//! Граф ассоциаций между корнями и глаголами (Идея 6).
//!
//! Основание: мозг хранит понятия как сеть ассоциаций.
//! В ZIP это позволяет:
//! - умное автодополнение
//! - поиск по смыслу
//! - автоматический рефакторинг

use std::collections::{HashMap, HashSet};

/// Тип связи между сущностями.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum ТипСвязи {
    /// Семантическая связь (СПР ↔ «вычисления»)
    Ассоциация,
    /// Противоположность (СПР ↔ РПС)
    Противоположность,
    /// Следствие (СПР → ЧТВ)
    Следствие,
    /// Причина (ЧТВ ← СПР)
    Причина,
    /// Категория (СПР в «математика»)
    Категория,
    /// Аналог в других языках (СПР ↔ «add»)
    Аналог,
}

impl ТипСвязи {
    pub fn метка(&self) -> &'static str {
        match self {
            Self::Ассоциация => "ассоциация",
            Self::Противоположность => "противоположность",
            Self::Следствие => "следствие",
            Self::Причина => "причина",
            Self::Категория => "категория",
            Self::Аналог => "аналог",
        }
    }

    pub fn иконка(&self) -> &'static str {
        match self {
            Self::Ассоциация => "🔗",
            Self::Противоположность => "⚔️",
            Self::Следствие => "→",
            Self::Причина => "←",
            Self::Категория => "📁",
            Self::Аналог => "🌐",
        }
    }
}

/// Узел графа — сущность языка.

//! Анализ владения импульсами (аналог Polonius) — идея R1.
//!
//! Модель:
//! - Каждый регистр: `Владеет` / `Передан` / `Завершён` / `НеИнициализирован`
//! - `>>` (`Импульс`) и аргументы `Вызвать` переводят `Владеет → Передан`
//! - `!` (`Зафиксировать`) → `Завершён` (чтение можно, повторная передача — нет)
//! - `Переместить` — копия: источник остаётся владельцем
//!
//! Анализ — прямой dataflow по CFG; на join — meet (пересечение),
//! поэтому use-after-move на любом пути ловится без ложных lexical-запретов
//! внутри несвязанных веток.

use crate::промежуток::{Инструкция, Метка, Регистр, ФункцияПП};
use std::collections::{BTreeMap, BTreeSet, HashMap, VecDeque};

/// Состояние владения регистром.
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash)]
pub enum СостояниеВладения {
    Владеет,
    Передан,
    Завершён,
    НеИнициализирован,
}

impl СостояниеВладения {
    fn можно_читать(self) -> bool {
        matches!(
            self,
            СостояниеВладения::Владеет | СостояниеВладения::Завершён
        )
    }

    fn можно_передать(self) -> bool {
        matches!(self, СостояниеВладения::Владеет)
    }
}

/// Точка программы = индекс инструкции в теле функции.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, PartialOrd, Ord)]
pub struct Точка(pub u32);

/// Ошибка владения.
#[derive(Debug, Clone)]
pub struct ОшибкаВладения {
    pub регистр: Регистр,
    pub точка: Точка,
    pub сообщение: String,
    pub подсказка: Option<String>,
    pub путь: Vec<Точка>,
}

type Состояние = BTreeMap<Регистр, СостояниеВладения>;

/// Анализатор владения.
pub struct АнализаторВладения {
    ошибки: Vec<ОшибкаВладения>,
    передачи: HashMap<Регистр, Vec<Точка>>,
}

impl Default for АнализаторВладения {
    fn default() -> Self {
        Self::новый()
    }
}

impl АнализаторВладения {
    pub fn новый() -> Self {
        Self {
            ошибки: Vec::new(),
            передачи: HashMap::new(),
        }
    }

    pub fn проанализировать(
        &mut self,
        функция: &ФункцияПП,
    ) -> Result<(), Vec<ОшибкаВладения>> {
        self.ошибки.clear();
        self.передачи.clear();

        let n = функция.тело.len();
        if n == 0 {
            return Ok(());
        }

        let метки = карта_меток(&функция.тело);
        let mut вход: Vec<Option<Состояние>> = vec![None; n];
        let mut очередь = VecDeque::new();

        let mut старт = Состояние::new();
        for п in &функция.параметры {
            старт.insert(*п, СостояниеВладения::Владеет);
        }
        вход[0] = Some(старт);
        очередь.push_back(0usize);
        let mut итерации = vec![0u32; n];

        while let Some(i) = очередь.pop_front() {
            if итерации[i] > (n as u32).saturating_mul(4).max(8) {
                continue;
            }
            итерации[i] += 1;

            let before = вход[i].clone().unwrap_or_default();
            let after = применить(&функция.тело[i], before);

            for s in преемники(i, &функция.тело, &метки) {
                if s >= n {
                    continue;
                }
                let merged = meet_состояние(вход[s].as_ref(), &after);
                if вход[s].as_ref() != Some(&merged) {
                    вход[s] = Some(merged);
                    очередь.push_back(s);
                }
            }
        }

        // Сбор ошибок + путей передачи на стабильном входном состоянии
        for i in 0..n {
            let before = вход[i].clone().unwrap_or_default();
            self.проверить_и_записать(Точка(i as u32), &функция.тело[i], &before);
        }

        if self.ошибки.is_empty() {
            Ok(())
        } else {
            // дедуп одинаковых сообщений в той же точке
            self.ошибки.sort_by_key(|о| (о.точка.0, о.регистр.0));
            self.ошибки.dedup_by(|a, b| {
                a.точка == b.точка && a.регистр == b.регистр && a.сообщение == b.сообщение
            });
            Err(self.ошибки.clone())
        }
    }

    fn проверить_и_записать(&mut self, точка: Точка, ин: &Инструкция, st: &Состояние) {
        match ин {
            Инструкция::Импульс { источник, .. } => {
                let s = состояние(st, *источник);
                self.требовать_передачу(*источник, точка, st);
                if s == СостояниеВладения::Владеет {
                    self.передачи.entry(*источник).or_default().push(точка);
                }
            }
            Инструкция::Зафиксировать { регистр } => {
                let s = состояние(st, *регистр);
                if s != СостояниеВладения::Владеет {
                    if s == СостояниеВладения::Завершён {
                        self.ошибки.push(ОшибкаВладения {
                            регистр: *регистр,
                            точка,
                            сообщение: format!(
                                "Регистр r{} уже зафиксирован через ! и не может быть изменён",
                                регистр.0
                            ),
                            подсказка: Some(
                                "PERFECT-значения неизменяемы (эпигенетика)".into(),
                            ),
                            путь: self.путь(*регистр),
                        });
                    } else {
                        self.требовать_передачу(*регистр, точка, st);
                    }
                }
            }
            Инструкция::Вызвать { аргументы, .. }
            | Инструкция::ВнешнийВызов { аргументы, .. } => {
                let уникальные: BTreeSet<_> = аргументы.iter().copied().collect();
                for арг in уникальные {
                    let s = состояние(st, арг);
                    if s == СостояниеВладения::Завершён {
                        continue; // чтение PERFECT
                    }
                    self.требовать_передачу(арг, точка, st);
                    if s == СостояниеВладения::Владеет {
                        self.передачи.entry(арг).or_default().push(точка);
                    }
                }
            }
            Инструкция::ЗапуститьХор { аргументы, .. } => {
                for арг in аргументы {
                    self.требовать_передачу(*арг, точка, st);
                    if состояние(st, *арг) == СостояниеВладения::Владеет {
                        self.передачи.entry(*арг).or_default().push(точка);
                    }
                }
            }
            Инструкция::Переместить { источник, .. }
            | Инструкция::Копировать { источник, .. }
            | Инструкция::Печать {
                значение: источник, ..
            } => {
                self.требовать_чтение(*источник, точка, st);
            }
            Инструкция::Загрузить { адрес, .. } => self.требовать_чтение(*адрес, точка, st),
            Инструкция::Сохранить { адрес, значение } => {
                self.требовать_чтение(*адрес, точка, st);
                self.требовать_чтение(*значение, точка, st);
            }
            Инструкция::Сложить { а, б, .. }
            | Инструкция::Вычесть { а, б, .. }
            | Инструкция::Умножить { а, б, .. }
            | Инструкция::Разделить { а, б, .. }
            | Инструкция::Сравнить { а, б, .. } => {
                self.требовать_чтение(*а, точка, st);
                self.требовать_чтение(*б, точка, st);
            }
            Инструкция::ВетвлениеИмпульса { условие, .. } => {
                self.требовать_чтение(*условие, точка, st);
            }
            Инструкция::СобратьХор { регистры } => {
                for р in регистры {
                    self.требовать_чтение(*р, точка, st);
                }
            }
            Инструкция::Вернуть { значение: Some(р) } => {
                self.требовать_чтение(*р, точка, st);
            }
            _ => {}
        }
    }

    fn требовать_чтение(&mut self, регистр: Регистр, точка: Точка, st: &Состояние) {
        let s = состояние(st, регистр);
        if s.можно_читать() {
            return;
        }
        let (сообщение, подсказка) = match s {
            СостояниеВладения::Передан => (
                format!(
                    "Регистр r{} уже передан через >> и не может быть использован",
                    регистр.0
                ),
                Some(
                    "Скопируйте значение через присваивание/`Переместить` до передачи".into(),
                ),
            ),
            СостояниеВладения::НеИнициализирован => (
                format!("Регистр r{} используется до инициализации", регистр.0),
                Some("Инициализируйте регистр перед использованием".into()),
            ),
            другой => (
                format!("Регистр r{} недоступен ({:?})", регистр.0, другой),
                None,
            ),
        };
        self.ошибки.push(ОшибкаВладения {
            регистр,
            точка,
            сообщение,
            подсказка,
            путь: self.путь(регистр),
        });
    }

    fn требовать_передачу(&mut self, регистр: Регистр, точка: Точка, st: &Состояние) {
        let s = состояние(st, регистр);
        if s.можно_передать() {
            return;
        }
        let (сообщение, подсказка) = match s {
            СостояниеВладения::Передан => (
                format!(
                    "Регистр r{} уже передан через >> и не может быть использован",
                    регистр.0
                ),
                Some(
                    "Используйте оператор перемещения `Переместить` для копии".into(),
                ),
            ),
            СостояниеВладения::Завершён => (
                format!(
                    "Регистр r{} зафиксирован через ! и не может быть передан",
                    регистр.0
                ),
                Some("PERFECT-значения неизменяемы (эпигенетика)".into()),
            ),
            СостояниеВладения::НеИнициализирован => (
                format!("Регистр r{} используется до инициализации", регистр.0),
                Some("Инициализируйте регистр перед использованием".into()),
            ),
            другой => (
                format!(
                    "Регистр r{} нельзя передать (состояние {:?})",
                    регистр.0, другой
                ),
                None,
            ),
        };
        self.ошибки.push(ОшибкаВладения {
            регистр,
            точка,
            сообщение,
            подсказка,
            путь: self.путь(регистр),
        });
    }

    fn путь(&self, регистр: Регистр) -> Vec<Точка> {
        self.передачи.get(&регистр).cloned().unwrap_or_default()
    }
}

/// Чистый трансфер состояния (без диагностики).
fn применить(ин: &Инструкция, mut st: Состояние) -> Состояние {
    match ин {
        Инструкция::Импульс {
            источник,
            назначение,
        } => {
            st.insert(*источник, СостояниеВладения::Передан);
            st.insert(*назначение, СостояниеВладения::Владеет);
        }
        Инструкция::Зафиксировать { регистр } => {
            if st.get(регистр) == Some(&СостояниеВладения::Владеет) {
                st.insert(*регистр, СостояниеВладения::Завершён);
            }
        }
        Инструкция::Вызвать {
            аргументы,
            результат,
            ..
        }
        | Инструкция::ВнешнийВызов {
            аргументы,
            результат,
            ..
        } => {
            let уникальные: BTreeSet<_> = аргументы.iter().copied().collect();
            for арг in уникальные {
                if st.get(&арг) == Some(&СостояниеВладения::Владеет) {
                    st.insert(арг, СостояниеВладения::Передан);
                }
            }
            if let Some(р) = результат {
                st.insert(*р, СостояниеВладения::Владеет);
            }
        }
        Инструкция::ЗапуститьХор { аргументы, .. } => {
            for арг in аргументы {
                if st.get(арг) == Some(&СостояниеВладения::Владеет) {
                    st.insert(*арг, СостояниеВладения::Передан);
                }
            }
        }
        Инструкция::Переместить {
            назначение,
            источник: _,
        }
        | Инструкция::Копировать {
            назначение,
            источник: _,
        }
        | Инструкция::КонстантаЦелое { назначение, .. }
        | Инструкция::КонстантаВещественное { назначение, .. }
        | Инструкция::КонстантаСтрока { назначение, .. }
        | Инструкция::Выделить { назначение, .. }
        | Инструкция::Загрузить { назначение, .. } => {
            st.insert(*назначение, СостояниеВладения::Владеет);
        }
        Инструкция::Сложить { назначение, .. }
        | Инструкция::Вычесть { назначение, .. }
        | Инструкция::Умножить { назначение, .. }
        | Инструкция::Разделить { назначение, .. }
        | Инструкция::Сравнить { назначение, .. } => {
            st.insert(*назначение, СостояниеВладения::Владеет);
        }
        Инструкция::ОжиданиеИмпульса { регистр } => {
            st.insert(*регистр, СостояниеВладения::Владеет);
        }
        _ => {}
    }
    st
}

fn состояние(st: &Состояние, р: Регистр) -> СостояниеВладения {
    st.get(&р)
        .copied()
        .unwrap_or(СостояниеВладения::НеИнициализирован)
}

pub fn проанализировать_функции(функции: &[ФункцияПП]) -> Vec<ОшибкаВладения> {
    let mut все = Vec::new();
    let mut а = АнализаторВладения::новый();
    for ф in функции {
        if let Err(о) = а.проанализировать(ф) {
            все.extend(о);
        }
    }
    все
}

pub fn форматировать_ошибки(ошибки: &[ОшибкаВладения]) -> String {
    let mut out = String::from("Найдены ошибки владения:\n");
    for о in ошибки {
        out.push_str(&format!("  {} (точка {})\n", о.сообщение, о.точка.0));
        if let Some(п) = &о.подсказка {
            out.push_str(&format!("    💡 {}\n", п));
        }
        if !о.путь.is_empty() {
            let pts: Vec<_> = о.путь.iter().map(|t| t.0.to_string()).collect();
            out.push_str(&format!("    путь передачи: {}\n", pts.join(" → ")));
        }
    }
    out
}

fn карта_меток(тело: &[Инструкция]) -> HashMap<Метка, usize> {
    let mut m = HashMap::new();
    for (i, ин) in тело.iter().enumerate() {
        if let Инструкция::Метка { идентификатор } = ин {
            m.insert(*идентификатор, i);
        }
    }
    m
}

fn преемники(
    i: usize,
    тело: &[Инструкция],
    метки: &HashMap<Метка, usize>,
) -> Vec<usize> {
    match &тело[i] {
        Инструкция::Вернуть { .. } => vec![],
        Инструкция::Перейти { метка } => метки.get(метка).copied().into_iter().collect(),
        Инструкция::ВетвлениеИмпульса { истина, ложь, .. } => {
            let mut s = Vec::new();
            if let Some(t) = метки.get(истина) {
                s.push(*t);
            }
            if let Some(e) = метки.get(ложь) {
                s.push(*e);
            }
            if s.is_empty() && i + 1 < тело.len() {
                s.push(i + 1);
            }
            s
        }
        _ if i + 1 < тело.len() => vec![i + 1],
        _ => vec![],
    }
}

fn meet_состояние(old: Option<&Состояние>, new: &Состояние) -> Состояние {
    match old {
        None => new.clone(),
        Some(o) => {
            let mut keys: BTreeSet<Регистр> = o.keys().copied().collect();
            keys.extend(new.keys().copied());
            let mut out = Состояние::new();
            for k in keys {
                let a = o
                    .get(&k)
                    .copied()
                    .unwrap_or(СостояниеВладения::НеИнициализирован);
                let b = new
                    .get(&k)
                    .copied()
                    .unwrap_or(СостояниеВладения::НеИнициализирован);
                out.insert(k, meet_одно(a, b));
            }
            out
        }
    }
}

fn meet_одно(a: СостояниеВладения, b: СостояниеВладения) -> СостояниеВладения {
    use СостояниеВладения::*;
    match (a, b) {
        (x, y) if x == y => x,
        (НеИнициализирован, _) | (_, НеИнициализирован) => НеИнициализирован,
        (Передан, _) | (_, Передан) => Передан,
        (Завершён, Владеет) | (Владеет, Завершён) | (Завершён, Завершён) => Завершён,
        (Владеет, Владеет) => Владеет,
    }
}

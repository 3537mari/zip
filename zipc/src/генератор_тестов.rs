//! Генератор тестов из аннотаций `@тест` (Идея 20).

use crate::промежуток::ФункцияПП;

/// Сгенерированный тест.
#[derive(Debug, Clone)]
pub struct Тест {
    pub имя: String,
    pub функция: String,
    pub аргументы: Vec<i64>,
    pub ожидаемый_результат: Option<i64>,
    pub категория: КатегорияТеста,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum КатегорияТеста {
    Случайный,
    Граница,
    Ноль,
    Отрицательный,
    Максимум,
}

/// Генератор тестов.
pub struct ГенераторТестов {
    состояние_гпсч: u64,
}

impl ГенераторТестов {
    pub fn новый() -> Self {
        Self {
            состояние_гпсч: 12345,
        }
    }

    pub fn с_семенем(семя: u64) -> Self {
        Self {
            состояние_гпсч: семя,
        }
    }

    /// LCG.
    fn следующее(&mut self) -> u64 {
        self.состояние_гпсч = self
            .состояние_гпсч
            .wrapping_mul(1103515245)
            .wrapping_add(12345);
        self.состояние_гпсч
    }

    fn случайное_в_диапазоне(&mut self, мин: i64, макс: i64) -> i64 {
        let ширина = (макс - мин).saturating_add(1).max(1) as u64;
        let р = self.следующее() % ширина;
        мин.saturating_add(р as i64)
    }

    /// Сгенерировать тесты для одной функции с `@тест`.
    pub fn сгенерировать(&mut self, функция: &ФункцияПП) -> Vec<Тест> {
        let количество = функция.тест_случай.unwrap_or(100);
        let (мин, макс) = функция.тест_диапазон.unwrap_or((0, 1000));
        let количество_аргументов = функция.параметры.len().max(1);

        let mut тесты = Vec::new();

        for i in 0..количество {
            let аргументы: Vec<i64> = (0..количество_аргументов)
                .map(|_| self.случайное_в_диапазоне(мин, макс))
                .collect();
            тесты.push(Тест {
                имя: format!("{}_случайный_{}", функция.имя, i + 1),
                функция: функция.имя.clone(),
                аргументы,
                ожидаемый_результат: None,
                категория: КатегорияТеста::Случайный,
            });
        }

        if функция.тест_границы {
            тесты.push(Тест {
                имя: format!("{}_граница_нули", функция.имя),
                функция: функция.имя.clone(),
                аргументы: vec![0; количество_аргументов],
                ожидаемый_результат: None,
                категория: КатегорияТеста::Ноль,
            });
            тесты.push(Тест {
                имя: format!("{}_граница_минимум", функция.имя),
                функция: функция.имя.clone(),
                аргументы: vec![мин; количество_аргументов],
                ожидаемый_результат: None,
                категория: КатегорияТеста::Граница,
            });
            тесты.push(Тест {
                имя: format!("{}_граница_максимум", функция.имя),
                функция: функция.имя.clone(),
                аргументы: vec![макс; количество_аргументов],
                ожидаемый_результат: None,
                категория: КатегорияТеста::Максимум,
            });
            if мин < 0 {
                тесты.push(Тест {
                    имя: format!("{}_граница_отрицательные", функция.имя),
                    функция: функция.имя.clone(),
                    аргументы: vec![-1; количество_аргументов],
                    ожидаемый_результат: None,
                    категория: КатегорияТеста::Отрицательный,
                });
            }
        }

        тесты
    }

    /// Все функции с `@тест`.
    pub fn сгенерировать_все(&mut self, функции: &[ФункцияПП]) -> Vec<Тест> {
        let mut все = Vec::new();
        for функция in функции {
            if функция.тест_случай.is_some() && функция.имя != "главная" {
                все.extend(self.сгенерировать(функция));
            }
        }
        все
    }
}

/// ZIP-исходник: функции из оригинала + `главная` с вызовами тестов.
pub fn собрать_исходник_тестов(исходник: &str, тесты: &[Тест]) -> String {
    let база = убрать_функцию_главная(исходник);

    let mut out = String::new();
    out.push_str("// Автоматически сгенерированные тесты (Идея 20)\n\n");
    out.push_str(&база);
    if !out.ends_with('\n') {
        out.push('\n');
    }
    out.push_str("\nфункция главная() {\n");
    for тест in тесты {
        let аргументы = тест
            .аргументы
            .iter()
            .map(|а| а.to_string())
            .collect::<Vec<_>>()
            .join(", ");
        out.push_str(&format!("    // {}\n", тест.имя));
        out.push_str(&format!(
            "    ПечатьЧисло({}({}))\n",
            тест.функция, аргументы
        ));
    }
    out.push_str("}\n");
    out
}

/// Удалить объявление `функция главная(...) { ... }` (скобочный баланс).
fn убрать_функцию_главная(исходник: &str) -> String {
    const МЕТКА: &str = "функция главная";
    let Some(start) = исходник.find(МЕТКА) else {
        return исходник.to_string();
    };
    let после = &исходник[start + МЕТКА.len()..];
    let Some(откр_отн) = после.find('{') else {
        return исходник.to_string();
    };
    let тело_старт = start + МЕТКА.len() + откр_отн;
    let bytes = исходник.as_bytes();
    let mut глубина = 0i32;
    let mut конец = None;
    for (i, &b) in bytes.iter().enumerate().skip(тело_старт) {
        match b {
            b'{' => глубина += 1,
            b'}' => {
                глубина -= 1;
                if глубина == 0 {
                    конец = Some(i + 1);
                    break;
                }
            }
            _ => {}
        }
    }
    let Some(end) = конец else {
        return исходник.to_string();
    };
    let mut out = String::with_capacity(исходник.len());
    out.push_str(&исходник[..start]);
    out.push_str(&исходник[end..]);
    out
}

//! Интерпретатор IR для вычислений на этапе компиляции (R2 — comptime).
//!
//! Чистые вычисления без I/O и async. Результат подставляется константой.

use crate::промежуток::{
    ИдентификаторФункции, Инструкция, Метка, Регистр, ФункцияПП,
};
use std::collections::HashMap;
use std::fmt;

const МАКС_ШАГОВ: u64 = 1_000_000;

#[derive(Debug, Clone, PartialEq)]
pub enum ЗначениеВремени {
    Целое(i64),
    Вещественное(f64),
    Строка(String),
    Булево(bool),
}

impl ЗначениеВремени {
    pub fn как_i64(&self) -> Result<i64, ОшибкаВремени> {
        match self {
            ЗначениеВремени::Целое(n) => Ok(*n),
            ЗначениеВремени::Булево(b) => Ok(if *b { 1 } else { 0 }),
            ЗначениеВремени::Вещественное(x) => Ok(*x as i64),
            ЗначениеВремени::Строка(_) => Err(ОшибкаВремени::НесовместимыеТипы),
        }
    }
}

impl fmt::Display for ЗначениеВремени {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            ЗначениеВремени::Целое(n) => write!(f, "{}", n),
            ЗначениеВремени::Вещественное(x) => write!(f, "{}", x),
            ЗначениеВремени::Строка(s) => write!(f, "\"{}\"", s),
            ЗначениеВремени::Булево(b) => write!(f, "{}", b),
        }
    }
}

#[derive(Debug, Clone)]
pub enum ОшибкаВремени {
    НетВозврата,
    НесовместимыеТипы,
    ФункцияНеНайдена(u32),
    РегистрНеИнициализирован(u32),
    НеподдерживаемаяИнструкция(String),
    БесконечныйЦикл,
    ДелениеНаНоль,
    Сообщение(String),
}

impl fmt::Display for ОшибкаВремени {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            ОшибкаВремени::НетВозврата => write!(f, "нет return"),
            ОшибкаВремени::НесовместимыеТипы => write!(f, "несовместимые типы"),
            ОшибкаВремени::ФункцияНеНайдена(id) => write!(f, "функция id={} не найдена", id),
            ОшибкаВремени::РегистрНеИнициализирован(r) => {
                write!(f, "регистр r{} не инициализирован", r)
            }
            ОшибкаВремени::НеподдерживаемаяИнструкция(s) => {
                write!(f, "неподдерживаемая инструкция: {}", s)
            }
            ОшибкаВремени::БесконечныйЦикл => {
                write!(f, "превышен лимит шагов (возможный бесконечный цикл)")
            }
            ОшибкаВремени::ДелениеНаНоль => write!(f, "деление на ноль"),
            ОшибкаВремени::Сообщение(s) => write!(f, "{}", s),
        }
    }
}

/// Запись о свёрнутом вызове (для логов).
#[derive(Debug, Clone)]
pub struct СвёрткаComptime {
    pub имя: String,
    pub аргументы: Vec<i64>,
    pub результат: ЗначениеВремени,
}

pub struct КомпиляторВремени {
    функции: HashMap<ИдентификаторФункции, ФункцияПП>,
}

impl КомпиляторВремени {
    pub fn новый(функции: &[ФункцияПП]) -> Self {
        let mut map = HashMap::new();
        for ф in функции {
            map.insert(ф.идентификатор, ф.clone());
        }
        Self { функции: map }
    }

    pub fn выполнить(
        &self,
        функция: &ФункцияПП,
        аргументы: Vec<ЗначениеВремени>,
    ) -> Result<ЗначениеВремени, ОшибкаВремени> {
        self.выполнить_кадр(функция, аргументы, 0)
    }

    pub fn функция(&self, id: ИдентификаторФункции) -> Option<&ФункцияПП> {
        self.функции.get(&id)
    }

    pub fn выполнить_по_id(
        &self,
        id: ИдентификаторФункции,
        аргументы: Vec<ЗначениеВремени>,
    ) -> Result<ЗначениеВремени, ОшибкаВремени> {
        let ф = self
            .функции
            .get(&id)
            .ok_or(ОшибкаВремени::ФункцияНеНайдена(id.0))?;
        self.выполнить(ф, аргументы)
    }

    fn выполнить_кадр(
        &self,
        функция: &ФункцияПП,
        аргументы: Vec<ЗначениеВремени>,
        глубина: u32,
    ) -> Result<ЗначениеВремени, ОшибкаВремени> {
        if глубина > 10_000 {
            return Err(ОшибкаВремени::БесконечныйЦикл);
        }

        let mut регистры: HashMap<Регистр, ЗначениеВремени> = HashMap::new();
        for (i, пар) in функция.параметры.iter().enumerate() {
            if let Some(арг) = аргументы.get(i) {
                регистры.insert(*пар, арг.clone());
            }
        }

        let метки = карта_меток(&функция.тело);
        let mut pc: usize = 0;
        let mut шаги = 0u64;

        while pc < функция.тело.len() {
            шаги += 1;
            if шаги > МАКС_ШАГОВ {
                return Err(ОшибкаВремени::БесконечныйЦикл);
            }

            match &функция.тело[pc] {
                Инструкция::Метка { .. } => {
                    pc += 1;
                }
                Инструкция::Перейти { метка } => {
                    pc = *метки
                        .get(метка)
                        .ok_or_else(|| ОшибкаВремени::Сообщение(format!("нет метки {:?}", метка)))?;
                }
                Инструкция::ВетвлениеИмпульса {
                    условие,
                    истина,
                    ложь,
                } => {
                    let v = получить(&регистры, *условие)?.как_i64()?;
                    let цель = if v != 0 { истина } else { ложь };
                    pc = *метки.get(цель).ok_or_else(|| {
                        ОшибкаВремени::Сообщение(format!("нет метки {:?}", цель))
                    })?;
                }
                Инструкция::Вернуть { значение } => {
                    return match значение {
                        Some(р) => Ok(получить(&регистры, *р)?),
                        None => Ok(ЗначениеВремени::Целое(0)),
                    };
                }
                Инструкция::КонстантаЦелое { назначение, значение } => {
                    регистры.insert(*назначение, ЗначениеВремени::Целое(*значение));
                    pc += 1;
                }
                Инструкция::КонстантаВещественное { назначение, значение } => {
                    регистры.insert(*назначение, ЗначениеВремени::Вещественное(*значение));
                    pc += 1;
                }
                Инструкция::КонстантаСтрока { назначение, значение } => {
                    регистры.insert(*назначение, ЗначениеВремени::Строка(значение.clone()));
                    pc += 1;
                }
                Инструкция::Переместить {
                    назначение,
                    источник,
                }
                | Инструкция::Копировать {
                    назначение,
                    источник,
                } => {
                    let з = получить(&регистры, *источник)?;
                    регистры.insert(*назначение, з);
                    pc += 1;
                }
                Инструкция::Сложить { назначение, а, б } => {
                    let x = получить(&регистры, *а)?.как_i64()?;
                    let y = получить(&регистры, *б)?.как_i64()?;
                    регистры.insert(*назначение, ЗначениеВремени::Целое(x + y));
                    pc += 1;
                }
                Инструкция::Вычесть { назначение, а, б } => {
                    let x = получить(&регистры, *а)?.как_i64()?;
                    let y = получить(&регистры, *б)?.как_i64()?;
                    регистры.insert(*назначение, ЗначениеВремени::Целое(x - y));
                    pc += 1;
                }
                Инструкция::Умножить { назначение, а, б } => {
                    let x = получить(&регистры, *а)?.как_i64()?;
                    let y = получить(&регистры, *б)?.как_i64()?;
                    регистры.insert(*назначение, ЗначениеВремени::Целое(x * y));
                    pc += 1;
                }
                Инструкция::Разделить { назначение, а, б } => {
                    let x = получить(&регистры, *а)?.как_i64()?;
                    let y = получить(&регистры, *б)?.как_i64()?;
                    if y == 0 {
                        return Err(ОшибкаВремени::ДелениеНаНоль);
                    }
                    регистры.insert(*назначение, ЗначениеВремени::Целое(x / y));
                    pc += 1;
                }
                Инструкция::Сравнить {
                    оператор,
                    назначение,
                    а,
                    б,
                } => {
                    let x = получить(&регистры, *а)?.как_i64()?;
                    let y = получить(&регистры, *б)?.как_i64()?;
                    let r = match оператор.as_str() {
                        "==" => x == y,
                        "!=" => x != y,
                        "<" => x < y,
                        ">" => x > y,
                        "<=" => x <= y,
                        ">=" => x >= y,
                        _ => return Err(ОшибкаВремени::НесовместимыеТипы),
                    };
                    регистры.insert(
                        *назначение,
                        ЗначениеВремени::Целое(if r { 1 } else { 0 }),
                    );
                    pc += 1;
                }
                Инструкция::Вызвать {
                    функция: fid,
                    аргументы: арги,
                    результат,
                    ..
                } => {
                    let ф = self
                        .функции
                        .get(fid)
                        .ok_or(ОшибкаВремени::ФункцияНеНайдена(fid.0))?;
                    let mut vals = Vec::new();
                    for р in арги {
                        vals.push(получить(&регистры, *р)?);
                    }
                    let рез = self.выполнить_кадр(ф, vals, глубина + 1)?;
                    if let Some(р) = результат {
                        регистры.insert(*р, рез);
                    }
                    pc += 1;
                }
                Инструкция::Импульс {
                    источник,
                    назначение,
                } => {
                    let з = получить(&регистры, *источник)?;
                    регистры.insert(*назначение, з);
                    регистры.remove(источник);
                    pc += 1;
                }
                Инструкция::Зафиксировать { .. } | Инструкция::ОжиданиеИмпульса { .. } => {
                    pc += 1;
                }
                другая => {
                    return Err(ОшибкаВремени::НеподдерживаемаяИнструкция(format!(
                        "{:?}",
                        другая
                    )));
                }
            }
        }
        Err(ОшибкаВремени::НетВозврата)
    }
}

fn получить(
    регистры: &HashMap<Регистр, ЗначениеВремени>,
    р: Регистр,
) -> Result<ЗначениеВремени, ОшибкаВремени> {
    регистры
        .get(&р)
        .cloned()
        .ok_or(ОшибкаВремени::РегистрНеИнициализирован(р.0))
}

fn карта_меток(тело: &[Инструкция]) -> HashMap<Метка, usize> {
    let mut m = HashMap::new();
    for (i, ин) in тело.iter().enumerate() {
        if let Инструкция::Метка { идентификатор } = ин {
            m.insert(*идентификатор, i);
        }
    }
    m
}

/// Свернуть вызовы `@comptime`-функций с константными аргументами в константы.
/// Удаляет comptime-функции из модуля, если на них не осталось вызовов.
pub fn свернуть_comptime_вызовы(
    функции: &mut Vec<ФункцияПП>,
) -> Result<Vec<СвёрткаComptime>, ОшибкаВремени> {
    let интерпретатор = КомпиляторВремени::новый(функции);
    let comptime_ids: std::collections::HashSet<_> = функции
        .iter()
        .filter(|ф| ф.comptime)
        .map(|ф| ф.идентификатор)
        .collect();
    if comptime_ids.is_empty() {
        return Ok(Vec::new());
    }

    let mut журнал = Vec::new();

    for i in 0..функции.len() {
        if функции[i].comptime {
            continue;
        }
        let тело = std::mem::take(&mut функции[i].тело);
        let (новое, свёртки) = свернуть_тело(тело, &comptime_ids, &интерпретатор)?;
        функции[i].тело = новое;
        журнал.extend(свёртки);
    }

    // Убрать comptime-функции, если на них нет вызовов из runtime-кода
    // (рекурсивные Call внутри самих comptime не считаются).
    let mut ещё_нужны = std::collections::HashSet::new();
    for ф in функции.iter().filter(|ф| !ф.comptime) {
        for ин in &ф.тело {
            if let Инструкция::Вызвать { функция, .. } = ин {
                ещё_нужны.insert(*функция);
            }
        }
    }
    функции.retain(|ф| !ф.comptime || ещё_нужны.contains(&ф.идентификатор));

    Ok(журнал)
}

fn свернуть_тело(
    тело: Vec<Инструкция>,
    comptime_ids: &std::collections::HashSet<ИдентификаторФункции>,
    интерпретатор: &КомпиляторВремени,
) -> Result<(Vec<Инструкция>, Vec<СвёрткаComptime>), ОшибкаВремени> {
    let mut константы: HashMap<Регистр, i64> = HashMap::new();
    let mut out = Vec::new();
    let mut журнал = Vec::new();

    for ин in тело {
        match ин {
            Инструкция::КонстантаЦелое { назначение, значение } => {
                константы.insert(назначение, значение);
                out.push(Инструкция::КонстантаЦелое {
                    назначение,
                    значение,
                });
            }
            Инструкция::Переместить {
                назначение,
                источник,
            } => {
                if let Some(v) = константы.get(&источник).copied() {
                    константы.insert(назначение, v);
                } else {
                    константы.remove(&назначение);
                }
                out.push(Инструкция::Переместить {
                    назначение,
                    источник,
                });
            }
            Инструкция::Копировать {
                назначение,
                источник,
            } => {
                if let Some(v) = константы.get(&источник).copied() {
                    константы.insert(назначение, v);
                } else {
                    константы.remove(&назначение);
                }
                out.push(Инструкция::Копировать {
                    назначение,
                    источник,
                });
            }
            Инструкция::Сложить { назначение, а, б } => {
                свернуть_бинп(&mut out, &mut константы, назначение, а, б, |x, y| x + y, ин);
            }
            Инструкция::Вычесть { назначение, а, б } => {
                свернуть_бинп(&mut out, &mut константы, назначение, а, б, |x, y| x - y, ин);
            }
            Инструкция::Умножить { назначение, а, б } => {
                свернуть_бинп(&mut out, &mut константы, назначение, а, б, |x, y| x * y, ин);
            }
            Инструкция::Разделить { назначение, а, б } => {
                if let (Some(x), Some(y)) = (константы.get(&а).copied(), константы.get(&б).copied())
                {
                    if y != 0 {
                        константы.insert(назначение, x / y);
                        out.push(Инструкция::КонстантаЦелое {
                            назначение,
                            значение: x / y,
                        });
                    } else {
                        константы.remove(&назначение);
                        out.push(ин);
                    }
                } else {
                    константы.remove(&назначение);
                    out.push(ин);
                }
            }
            Инструкция::Вызвать {
                функция,
                аргументы,
                результат,
                отметить_горячей,
            } if comptime_ids.contains(&функция) => {
                let mut args_i = Vec::new();
                let mut все_конст = true;
                for р in &аргументы {
                    if let Some(v) = константы.get(р).copied() {
                        args_i.push(v);
                    } else {
                        все_конст = false;
                        break;
                    }
                }
                if все_конст {
                    let ф = интерпретатор
                        .функция(функция)
                        .ok_or(ОшибкаВремени::ФункцияНеНайдена(функция.0))?;
                    let имя = ф.имя.clone();
                    let args: Vec<_> = args_i
                        .iter()
                        .map(|n| ЗначениеВремени::Целое(*n))
                        .collect();
                    let рез = интерпретатор.выполнить_по_id(функция, args)?;
                    let n = рез.как_i64()?;
                    журнал.push(СвёрткаComptime {
                        имя,
                        аргументы: args_i,
                        результат: ЗначениеВремени::Целое(n),
                    });
                    if let Some(р) = результат {
                        константы.insert(р, n);
                        out.push(Инструкция::КонстантаЦелое {
                            назначение: р,
                            значение: n,
                        });
                    }
                } else {
                    if let Some(р) = результат {
                        константы.remove(&р);
                    }
                    out.push(Инструкция::Вызвать {
                        функция,
                        аргументы,
                        результат,
                        отметить_горячей,
                    });
                }
            }
            другая => {
                // Инструкции, пишущие в регистр — инвалидируем назначение, если известно
                if let Some(назн) = назначение_инструкции(&другая) {
                    константы.remove(&назн);
                }
                out.push(другая);
            }
        }
    }
    Ok((out, журнал))
}

fn свернуть_бинп(
    out: &mut Vec<Инструкция>,
    константы: &mut HashMap<Регистр, i64>,
    назначение: Регистр,
    а: Регистр,
    б: Регистр,
    op: impl Fn(i64, i64) -> i64,
    ин: Инструкция,
) {
    if let (Some(x), Some(y)) = (константы.get(&а).copied(), константы.get(&б).copied()) {
        let v = op(x, y);
        константы.insert(назначение, v);
        out.push(Инструкция::КонстантаЦелое {
            назначение,
            значение: v,
        });
    } else {
        константы.remove(&назначение);
        out.push(ин);
    }
}

fn назначение_инструкции(ин: &Инструкция) -> Option<Регистр> {
    match ин {
        Инструкция::КонстантаЦелое { назначение, .. }
        | Инструкция::КонстантаВещественное { назначение, .. }
        | Инструкция::КонстантаСтрока { назначение, .. }
        | Инструкция::Переместить { назначение, .. }
        | Инструкция::Копировать { назначение, .. }
        | Инструкция::Сложить { назначение, .. }
        | Инструкция::Вычесть { назначение, .. }
        | Инструкция::Умножить { назначение, .. }
        | Инструкция::Разделить { назначение, .. }
        | Инструкция::Сравнить { назначение, .. }
        | Инструкция::Загрузить { назначение, .. }
        | Инструкция::Выделить { назначение, .. } => Some(*назначение),
        Инструкция::Вызвать {
            результат: Some(р), ..
        }
        | Инструкция::ВнешнийВызов {
            результат: Some(р), ..
        } => Some(*р),
        Инструкция::Импульс { назначение, .. } => Some(*назначение),
        _ => None,
    }
}

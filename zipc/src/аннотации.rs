//! Реестр встроенных аннотаций (Идея 2 — эпигенетика).
//!
//! Аннотации влияют на оптимизацию, безопасность, параллелизм,
//! фоновые процессы и автогенерацию тестов — без изменения логики ZIP.

use crate::дерево::Узел;
use crate::промежуток::ФункцияПП;
use std::collections::HashMap;

/// Все встроенные аннотации.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum ВстроеннаяАннотация {
    /// `@пластичность(порог = N)` — авто-оптимизация горячих путей
    Пластичность,
    /// `@comptime` — вычисления на этапе компиляции
    Comptime,
    /// `@ускорить(уровень = 3)` — агрессивная оптимизация
    Ускорить,
    /// `@кэшировать(размер = N)` — кэш результатов
    Кэшировать,
    /// `@шифровать(алгоритм = "...")` — шифрование данных
    Шифровать,
    /// `@параллелить(потоков = N)` — автопараллелизм
    Параллелить,
    /// `@сон(интервал = "5m")` — авто-прунинг
    Сон,
    /// `@тест(случай = N)` — автогенерация тестов
    Тест,
    /// R5: `@проверить_шаблон(шаблон = "Нечто(_)")`
    ПроверитьШаблон,
}

impl ВстроеннаяАннотация {
    pub fn из_имени(имя: &str) -> Option<Self> {
        match имя {
            "пластичность" => Some(Self::Пластичность),
            "comptime" | "комптайм" => Some(Self::Comptime),
            "ускорить" => Some(Self::Ускорить),
            "кэшировать" => Some(Self::Кэшировать),
            "шифровать" => Some(Self::Шифровать),
            "параллелить" => Some(Self::Параллелить),
            "сон" => Some(Self::Сон),
            "тест" => Some(Self::Тест),
            "проверить_шаблон" => Some(Self::ПроверитьШаблон),
            _ => None,
        }
    }

    pub fn имя(&self) -> &'static str {
        match self {
            Self::Пластичность => "пластичность",
            Self::Comptime => "comptime",
            Self::Ускорить => "ускорить",
            Self::Кэшировать => "кэшировать",
            Self::Шифровать => "шифровать",
            Self::Параллелить => "параллелить",
            Self::Сон => "сон",
            Self::Тест => "тест",
            Self::ПроверитьШаблон => "проверить_шаблон",
        }
    }

    /// Применить аннотацию к функции ПП.
    pub fn применить(
        &self,
        функция: &mut ФункцияПП,
        параметры: &HashMap<String, String>,
    ) -> Result<(), String> {
        match self {
            Self::Пластичность => {
                let порог = параметры
                    .get("порог")
                    .and_then(|с| с.parse().ok())
                    .unwrap_or(1000u64);
                функция.порог_горячности = порог;
                // Обратная совместимость с Идеей 4
                функция.агрессивная_оптимизация = true;
            }
            Self::Comptime => {
                функция.comptime = true;
            }
            Self::Ускорить => {
                let уровень = параметры
                    .get("уровень")
                    .and_then(|с| с.parse().ok())
                    .unwrap_or(3u8);
                функция.агрессивная_оптимизация = true;
                функция.уровень_оптимизации = уровень.min(3);
            }
            Self::Кэшировать => {
                let размер = параметры
                    .get("размер")
                    .and_then(|с| с.parse().ok())
                    .unwrap_or(1024usize);
                функция.кэшировать = true;
                функция.размер_кэша = размер;
            }
            Self::Шифровать => {
                let алгоритм = параметры
                    .get("алгоритм")
                    .cloned()
                    .unwrap_or_else(|| "AES-GCM".to_string());
                функция.шифровать = true;
                функция.алгоритм_шифрования = алгоритм;
            }
            Self::Параллелить => {
                let потоков = параметры
                    .get("потоков")
                    .and_then(|с| с.parse().ok())
                    .unwrap_or(4u8);
                функция.параллелить = true;
                функция.количество_потоков = потоков.max(1);
            }
            Self::Сон => {
                let интервал = параметры
                    .get("интервал")
                    .cloned()
                    .unwrap_or_else(|| "5m".to_string());
                функция.сон = true;
                функция.интервал_сна = интервал;
            }
            Self::Тест => {
                let случай = параметры
                    .get("случай")
                    .and_then(|с| с.parse().ok())
                    .unwrap_or(100usize);
                let диапазон = параметры
                    .get("диапазон")
                    .and_then(|с| разобрать_диапазон(с));
                let границы = параметры
                    .get("границы")
                    .map(|с| {
                        matches!(
                            с.as_str(),
                            "истина" | "да" | "true" | "1" | "yes"
                        )
                    })
                    .unwrap_or(false);
                функция.тест_случай = Some(случай);
                функция.тест_диапазон = диапазон;
                функция.тест_границы = границы;
            }
            Self::ПроверитьШаблон => {
                let шаблон = параметры
                    .get("шаблон")
                    .cloned()
                    .unwrap_or_else(|| "_".to_string());
                функция.проверить_шаблон = Some(шаблон);
            }
        }
        Ok(())
    }
}

/// Узел-параметр аннотации → строка для `применить`.
pub fn значение_в_строку(узел: &Узел) -> String {
    match узел {
        Узел::Целое(n) => n.to_string(),
        Узел::Вещественное(x) => x.to_string(),
        Узел::Строка(s) => s.clone(),
        Узел::Истина => "истина".into(),
        Узел::Ложь => "ложь".into(),
        Узел::Идентификатор(и) => и.clone(),
        Узел::Диапазон { начало, конец } => {
            format!("{}..{}", значение_в_строку(начало), значение_в_строку(конец))
        }
        другой => format!("{:?}", другой),
    }
}

/// Идея 20: `"0..1000"` / `0..1000` → `(мин, макс)`.
pub fn разобрать_диапазон(с: &str) -> Option<(i64, i64)> {
    let с = с.trim().trim_matches('"').trim();
    let (а, б) = с.split_once("..")?;
    let мин = а.trim().parse().ok()?;
    let макс = б.trim().parse().ok()?;
    if мин <= макс {
        Some((мин, макс))
    } else {
        Some((макс, мин))
    }
}

/// Применить список AST-аннотаций к функции; неизвестные — ошибка.
pub fn применить_аннотации(
    функция: &mut ФункцияПП,
    аннотации: &[crate::дерево::Аннотация],
) -> Result<(), String> {
    for ан in аннотации {
        let Some(встроенная) = ВстроеннаяАннотация::из_имени(&ан.имя) else {
            return Err(format!("Неизвестная аннотация: @{}", ан.имя));
        };
        let mut параметры = HashMap::new();
        for (ключ, значение) in &ан.параметры {
            параметры.insert(ключ.clone(), значение_в_строку(значение));
        }
        встроенная.применить(функция, &параметры)?;
    }
    Ok(())
}

/// Краткое описание применённых эпигенетических флагов (для логов компилятора).
pub fn описание_флагов(ф: &ФункцияПП) -> Vec<String> {
    let mut out = Vec::new();
    if ф.агрессивная_оптимизация && ф.уровень_оптимизации > 0 {
        out.push(format!("@ускорить({})", ф.уровень_оптимизации));
    }
    if ф.кэшировать {
        out.push(format!("@кэшировать({})", ф.размер_кэша));
    }
    if ф.шифровать {
        out.push(format!("@шифровать({})", ф.алгоритм_шифрования));
    }
    if ф.параллелить {
        out.push(format!("@параллелить({})", ф.количество_потоков));
    }
    if ф.сон {
        out.push(format!("@сон({})", ф.интервал_сна));
    }
    if let Some(n) = ф.тест_случай {
        let mut части = vec![format!("случай = {}", n)];
        if let Some((а, б)) = ф.тест_диапазон {
            части.push(format!("диапазон = \"{}..{}\"", а, б));
        }
        if ф.тест_границы {
            части.push("границы = да".into());
        }
        out.push(format!("@тест({})", части.join(", ")));
    }
    if ф.comptime {
        out.push("@comptime".into());
    }
    if let Some(ш) = &ф.проверить_шаблон {
        out.push(format!("@проверить_шаблон({})", ш));
    }
    out
}

/// R5: разобрать шаблон вида `Нечто(_)`, `Успех(_)`, …
pub fn разобрать_шаблон_тега(шаблон: &str) -> Option<&'static str> {
    let s = шаблон.trim();
    let база = s.split('(').next()?.trim();
    match база {
        "Нечто" => Some("нечто"),
        "Ничто" => Some("ничто"),
        "Успех" => Some("успех"),
        "Ошибка" => Some("ошибка"),
        _ => None,
    }
}

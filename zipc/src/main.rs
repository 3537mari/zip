//! Точка входа компилятора ZIP.

#[path = "лексика.rs"]
mod лексика;

use лексика::{Лексер, Токен};

fn main() {
    let исходник = r#"
// Пример VSO-цепочки
САПАР(матрица, веса) >> ЧАТАВ!
"#;

    match Лексер::новый(исходник).разобрать() {
        Ok(токены) => {
            println!("ZIP лексер — распознанные токены:");
            for токен in токены {
                println!("  {:?}", токен);
            }
        }
        Err(ошибка) => {
            eprintln!("{}", ошибка);
            std::process::exit(1);
        }
    }

    let _ = Токен::КонецФайла;
}

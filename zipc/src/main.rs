#[path = "лексика.rs"]
mod лексика;

fn main() {
    let исходник = "СПР = { А-А: САПАР }\nЖАВАТ(1) >> САПАР >> ЧАТАВ!";
    
    println!("=== ТЕСТ ЛЕКСЕРА ZIP ===");
    println!("Исходник:\n{}\n", исходник);
    
    let mut лексер = лексика::Лексер::новый(исходник);
    match лексер.разобрать() {
        Ok(токены) => {
            println!("Распознано токенов: {}", токены.len());
            for (i, токен) in токены.iter().enumerate() {
                println!("  [{}] строка {} столбец {}: {:?}", 
                    i, токен.строка, токен.столбец, токен.токен);
            }
        }
        Err(ошибка) => {
            eprintln!("ОШИБКА: {}", ошибка);
            std::process::exit(1);
        }
    }
}

#[path = "лексика.rs"]
mod лексика;

#[path = "дерево.rs"]
mod дерево;

#[path = "парсер.rs"]
mod парсер;

use парсер::разобрать_исходник;

fn main() {
    let примеры = [
        "САПАР(1, 2) >> ЧАТАВ!",
        "ЖАВАТ~ { САПАР >> ЧАТАВ } || САГАН~",
        r#"СПР = { А-А: САПАР, И-А: СИПРА }"#,
    ];

    for исходник in примеры {
        println!("=== исходник ===\n{}\n", исходник);
        match разобрать_исходник(исходник) {
            Ok(ast) => println!("{:#?}\n", ast),
            Err(е) => eprintln!("ошибка: {}\n", е),
        }
    }
}

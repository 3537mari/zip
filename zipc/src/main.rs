mod нативный;

use нативный::скомпилировать_в_ассемблер;
use промежуток::сгенерировать_из_исходника;

fn main() {
    let исходник = "САПАР >> ЧАТАВ!";
    println!("=== исходник ===\n{}\n", исходник);

    match сгенерировать_из_исходника(исходник) {
        Ok(функции) => {
            println!("=== ПП (IR) ===");
            for ф in &функции {
                println!(
                    "fn {} id={} async={} perfect={}\n  {:?}",
                    ф.имя, ф.идентификатор.0, ф.асинхронная, ф.совершенная, ф.тело
                );
            }
        }
        Err(е) => eprintln!("IR ошибка: {}", е),
    }

    match скомпилировать_в_ассемблер(исходник) {
        Ok(asm) => {
            println!("\n=== ассемблер x86-64 ===\n{}", asm);
        }
        Err(е) => eprintln!("ASM ошибка: {}", е),
    }
}

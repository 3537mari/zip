//! ИИ-советник — анализ кода через LLM (Идея 19).
//!
//! Режимы:
//! - Локальная модель (через ollama)
//! - OpenAI API
//! - Anthropic API
//! - Fallback: статистический анализ без LLM

use crate::промежуток::{Инструкция, ФункцияПП};
use anyhow::{bail, Context, Result};
use serde::Serialize;
use std::collections::HashMap;
use std::process::Command;

/// Провайдер LLM.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum ПровайдерLLM {
    Ollama,
    OpenAI,
    Anthropic,
    Статистический,
}

impl ПровайдерLLM {
    pub fn из_строки(с: &str) -> Option<Self> {
        match с.to_lowercase().as_str() {
            "ollama" => Some(Self::Ollama),
            "openai" => Some(Self::OpenAI),
            "anthropic" => Some(Self::Anthropic),
            "stat" | "статистический" | "stats" => Some(Self::Статистический),
            _ => None,
        }
    }
}

/// Рекомендация от ИИ.
#[derive(Debug, Clone, Serialize)]
pub struct Рекомендация {
    pub функция: String,
    pub категория: КатегорияРекомендации,
    pub описание: String,
    pub пример_до: Option<String>,
    pub пример_после: Option<String>,
    pub ожидаемый_прирост: f64,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize)]
#[serde(rename_all = "snake_case")]
pub enum КатегорияРекомендации {
    Оптимизация,
    Безопасность,
    Читаемость,
    Параллелизм,
    Кэширование,
}

/// ИИ-советник.
pub struct ИИСоветник {
    провайдер: ПровайдерLLM,
    модель: String,
}

impl ИИСоветник {
    pub fn новый(провайдер: ПровайдерLLM) -> Self {
        let модель = match провайдер {
            ПровайдерLLM::Ollama => "llama3.2".to_string(),
            ПровайдерLLM::OpenAI => "gpt-4o-mini".to_string(),
            ПровайдерLLM::Anthropic => "claude-3-5-haiku-20241022".to_string(),
            ПровайдерLLM::Статистический => "стат".to_string(),
        };
        Self { провайдер, модель }
    }

    pub fn установить_модель(&mut self, модель: String) {
        self.модель = модель;
    }

    pub fn модель(&self) -> &str {
        &self.модель
    }

    pub fn провайдер(&self) -> ПровайдерLLM {
        self.провайдер
    }

    /// Проанализировать функции и выдать рекомендации.
    pub fn проанализировать(&self, функции: &[ФункцияПП]) -> Result<Vec<Рекомендация>> {
        match self.провайдер {
            ПровайдерLLM::Статистический => self.статистический_анализ(функции),
            ПровайдерLLM::Ollama => self.ollama_анализ(функции),
            ПровайдерLLM::OpenAI => self.openai_анализ(функции),
            ПровайдерLLM::Anthropic => self.anthropic_анализ(функции),
        }
    }

    /// Статистический анализ без LLM.
    fn статистический_анализ(&self, функции: &[ФункцияПП]) -> Result<Vec<Рекомендация>> {
        let mut рекомендации = Vec::new();
        let оценки = оценить_частоту_вызовов(функции);

        for функция in функции {
            if функция.имя == "главная" || функция.имя.starts_with("КОМПОЗИТ_") {
                continue;
            }

            let вызовов = функция
                .счётчик_вызовов
                .max(*оценки.get(&функция.имя).unwrap_or(&0));

            if вызовов > 1000 && !функция.агрессивная_оптимизация {
                рекомендации.push(Рекомендация {
                    функция: функция.имя.clone(),
                    категория: КатегорияРекомендации::Оптимизация,
                    описание: format!(
                        "Функция вызывается ≈{} раз. Добавьте @пластичность(порог = 100)",
                        вызовов
                    ),
                    пример_до: Some("функция ф(х) { ... }".to_string()),
                    пример_после: Some(
                        "@пластичность(порог = 100)\nфункция ф(х) { ... }".to_string(),
                    ),
                    ожидаемый_прирост: 5.0,
                });
            }

            if функция.асинхронная
                && функция
                    .тело
                    .iter()
                    .any(|и| matches!(и, Инструкция::Вызвать { .. }))
            {
                рекомендации.push(Рекомендация {
                    функция: функция.имя.clone(),
                    категория: КатегорияРекомендации::Параллелизм,
                    описание: "Асинхронная функция с блокирующими вызовами. \
Рассмотрите хор || для параллельного выполнения"
                        .to_string(),
                    пример_до: Some("ЖАВАТ~ { САПАР(1) >> ЧАТАВ! }".to_string()),
                    пример_после: Some(
                        "ЖАВАТ~ { САПАР(1) >> ЧАТАВ! }\n|| САГАН~ { ... }".to_string(),
                    ),
                    ожидаемый_прирост: 2.5,
                });
            }

            let подряд_вызовов = функция
                .тело
                .windows(3)
                .filter(|окно| {
                    окно.iter()
                        .all(|и| matches!(и, Инструкция::Вызвать { .. }))
                })
                .count();
            if подряд_вызовов >= 3 {
                рекомендации.push(Рекомендация {
                    функция: функция.имя.clone(),
                    категория: КатегорияРекомендации::Оптимизация,
                    описание: format!(
                        "Найдено {} цепочек из 3+ вызовов подряд. \
Рассмотрите @нейрогенез для автогенерации композита",
                        подряд_вызовов
                    ),
                    пример_до: None,
                    пример_после: None,
                    ожидаемый_прирост: 1.5,
                });
            }

            // Цепочки интересных вызовов (через промежуточные ops) — тоже кандидат.
            let вызовов_в_теле = функция
                .тело
                .iter()
                .filter(|и| matches!(и, Инструкция::Вызвать { .. }))
                .count();
            if вызовов_в_теле >= 3 && !функция.нейрогенез {
                рекомендации.push(Рекомендация {
                    функция: функция.имя.clone(),
                    категория: КатегорияРекомендации::Оптимизация,
                    описание: format!(
                        "В теле {} вызовов — кандидат на @нейрогенез(порог = 2)",
                        вызовов_в_теле
                    ),
                    пример_до: None,
                    пример_после: Some("@нейрогенез(порог = 2)\nфункция …".to_string()),
                    ожидаемый_прирост: 1.5,
                });
            }

            let имя_нижн = функция.имя.to_lowercase();
            if (имя_нижн.contains("парол")
                || имя_нижн.contains("ключ")
                || имя_нижн.contains("секрет"))
                && !функция.шифровать
            {
                рекомендации.push(Рекомендация {
                    функция: функция.имя.clone(),
                    категория: КатегорияРекомендации::Безопасность,
                    описание: "Функция работает с чувствительными данными. \
Добавьте @шифровать для постквантовой защиты"
                        .to_string(),
                    пример_до: None,
                    пример_после: Some(
                        "@шифровать(алгоритм = \"AES-256-GCM\")\n\
функция проверить_пароль(...) { ... }"
                            .to_string(),
                    ),
                    ожидаемый_прирост: 1.0,
                });
            }

            if функция.тело.len() > 20
                && !функция.кэшировать
                && !функция.агрессивная_оптимизация
                && вызовов > 10
            {
                рекомендации.push(Рекомендация {
                    функция: функция.имя.clone(),
                    категория: КатегорияРекомендации::Кэширование,
                    описание: "Крупная часто вызываемая функция — рассмотрите @кэшировать"
                        .to_string(),
                    пример_до: None,
                    пример_после: Some("@кэшировать(размер = 1024)\nфункция …".to_string()),
                    ожидаемый_прирост: 2.0,
                });
            }
        }

        рекомендации.sort_by(|а, б| {
            б.ожидаемый_прирост
                .partial_cmp(&а.ожидаемый_прирост)
                .unwrap_or(std::cmp::Ordering::Equal)
        });

        Ok(рекомендации)
    }

    fn ollama_анализ(&self, функции: &[ФункцияПП]) -> Result<Vec<Рекомендация>> {
        let ollama_доступен = Command::new("ollama").arg("--version").output().is_ok();
        if !ollama_доступен {
            eprintln!("⚠️ Ollama не найден. Установите: https://ollama.com");
            eprintln!("   Использую статистический анализ");
            return self.статистический_анализ(функции);
        }

        let mut prompt = String::from(
            "Проанализируй функции ZIP-программы и дай рекомендации \
по оптимизации. Формат ответа:\n\
ФУНКЦИЯ: <имя>\n\
КАТЕГОРИЯ: <оптимизация|безопасность|параллелизм>\n\
ОПИСАНИЕ: <текст>\n\n",
        );
        for функция in функции.iter().take(10) {
            prompt.push_str(&format!(
                "Функция: {}\n- Вызовов: {}\n- Инструкций: {}\n\n",
                функция.имя,
                функция.счётчик_вызовов,
                функция.тело.len()
            ));
        }

        let вывод = Command::new("ollama")
            .arg("run")
            .arg(&self.модель)
            .arg(&prompt)
            .output()
            .context("Не могу запустить Ollama")?;
        if !вывод.status.success() {
            bail!("Ollama вернул ошибку");
        }

        let текст = String::from_utf8_lossy(&вывод.stdout);
        let рекомендации = self.парсить_ответ(&текст);
        if рекомендации.is_empty() {
            return self.статистический_анализ(функции);
        }
        Ok(рекомендации)
    }

    fn openai_анализ(&self, функции: &[ФункцияПП]) -> Result<Vec<Рекомендация>> {
        // MVP: fallback на статистический (нужен OPENAI_API_KEY + HTTP).
        let _ = std::env::var("OPENAI_API_KEY");
        self.статистический_анализ(функции)
    }

    fn anthropic_анализ(&self, функции: &[ФункцияПП]) -> Result<Vec<Рекомендация>> {
        let _ = std::env::var("ANTHROPIC_API_KEY");
        self.статистический_анализ(функции)
    }

    /// Парсить ответ LLM.
    pub fn парсить_ответ(&self, текст: &str) -> Vec<Рекомендация> {
        let mut рекомендации = Vec::new();
        let mut текущая: Option<Рекомендация> = None;

        for строка in текст.lines() {
            let строка_trimmed = строка.trim();

            if let Some(имя) = строка_trimmed.strip_prefix("ФУНКЦИЯ:") {
                if let Some(р) = текущая.take() {
                    рекомендации.push(р);
                }
                текущая = Some(Рекомендация {
                    функция: имя.trim().to_string(),
                    категория: КатегорияРекомендации::Оптимизация,
                    описание: String::new(),
                    пример_до: None,
                    пример_после: None,
                    ожидаемый_прирост: 1.5,
                });
            } else if let Some(кат) = строка_trimmed.strip_prefix("КАТЕГОРИЯ:") {
                if let Some(р) = текущая.as_mut() {
                    р.категория = match кат.trim().to_lowercase().as_str() {
                        "безопасность" => КатегорияРекомендации::Безопасность,
                        "параллелизм" => КатегорияРекомендации::Параллелизм,
                        "кэширование" => КатегорияРекомендации::Кэширование,
                        "читаемость" => КатегорияРекомендации::Читаемость,
                        _ => КатегорияРекомендации::Оптимизация,
                    };
                }
            } else if let Some(опис) = строка_trimmed.strip_prefix("ОПИСАНИЕ:") {
                if let Some(р) = текущая.as_mut() {
                    р.описание = опис.trim().to_string();
                }
            } else if let Some(пр_до) = строка_trimmed.strip_prefix("ДО:") {
                if let Some(р) = текущая.as_mut() {
                    р.пример_до = Some(пр_до.trim().to_string());
                }
            } else if let Some(пр_после) = строка_trimmed.strip_prefix("ПОСЛЕ:") {
                if let Some(р) = текущая.as_mut() {
                    р.пример_после = Some(пр_после.trim().to_string());
                }
            } else if let Some(прирост) = строка_trimmed.strip_prefix("ПРИРОСТ:") {
                if let Some(р) = текущая.as_mut() {
                    let очищ = прирост
                        .trim()
                        .trim_end_matches('x')
                        .trim_end_matches('X')
                        .trim_end_matches('×');
                    if let Ok(значение) = очищ.parse::<f64>() {
                        р.ожидаемый_прирост = значение;
                    }
                }
            }
        }

        if let Some(р) = текущая.take() {
            рекомендации.push(р);
        }
        рекомендации
    }

    /// Форматировать рекомендации для вывода в консоль.
    pub fn форматировать(&self, рекомендации: &[Рекомендация]) -> String {
        let mut вывод = String::new();
        if рекомендации.is_empty() {
            вывод.push_str("✓ Рекомендаций нет — код оптимален\n");
            return вывод;
        }

        вывод.push_str(&format!(
            "=== ИИ-СОВЕТНИК: {} рекомендаций ===\n\n",
            рекомендации.len()
        ));

        for (i, р) in рекомендации.iter().enumerate() {
            let иконка = match р.категория {
                КатегорияРекомендации::Оптимизация => "⚡",
                КатегорияРекомендации::Безопасность => "🔒",
                КатегорияРекомендации::Читаемость => "📖",
                КатегорияРекомендации::Параллелизм => "⚙️",
                КатегорияРекомендации::Кэширование => "💾",
            };
            вывод.push_str(&format!(
                "{}. {} {} (прирост ×{:.1})\n",
                i + 1,
                иконка,
                р.функция,
                р.ожидаемый_прирост
            ));
            вывод.push_str(&format!("   {}\n", р.описание));
            if let Some(до) = &р.пример_до {
                вывод.push_str(&format!("   ДО:\n   {}\n", до));
            }
            if let Some(после) = &р.пример_после {
                вывод.push_str(&format!("   ПОСЛЕ:\n   {}\n", после));
            }
            вывод.push('\n');
        }
        вывод
    }
}

/// Оценка частоты: статические вызовы × эвристика границ циклов.
fn оценить_частоту_вызовов(функции: &[ФункцияПП]) -> HashMap<String, u64> {
    let id_в_имя: HashMap<_, _> = функции
        .iter()
        .map(|ф| (ф.идентификатор, ф.имя.clone()))
        .collect();
    let mut оценки: HashMap<String, u64> = HashMap::new();

    for функция in функции {
        let множитель = оценка_множителя_цикла(&функция.тело);
        for и in &функция.тело {
            if let Инструкция::Вызвать { функция: id, .. } = и {
                if let Some(имя) = id_в_имя.get(id) {
                    *оценки.entry(имя.clone()).or_insert(0) += множитель;
                }
            }
        }
    }
    оценки
}

fn оценка_множителя_цикла(тело: &[Инструкция]) -> u64 {
    let макс_константа = тело
        .iter()
        .filter_map(|и| match и {
            Инструкция::КонстантаЦелое { значение, .. } if *значение > 1 => Some(*значение as u64),
            _ => None,
        })
        .max()
        .unwrap_or(1);
    // Цикл `0..N` обычно даёт константу N; учитываем умеренно.
    if макс_константа >= 100 {
        макс_константа
    } else {
        1
    }
}

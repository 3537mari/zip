//! SIMD-оптимизации для горячих циклов (AVX-512 / AVX2 / NEON).
//!
//! Анализирует IR на обратные рёбра циклов и долю арифметики;
//! фактическая векторизация — через LLVM (`loop-vectorize`, `slp-vectorizer`)
//! и флаги clang (`-march=native`, `-mavx512f` при `--simd`).

use crate::промежуток::{Инструкция, Метка, ФункцияПП};

/// Обнаружить векторизуемые циклы в IR.
pub struct АнализаторSIMD {
    /// Минимальное число инструкций в теле цикла.
    pub минимальная_длина_цикла: usize,
    /// Минимальная доля арифметики (0..=100).
    pub мин_доля_арифметики: usize,
}

impl АнализаторSIMD {
    pub fn новый() -> Self {
        Self {
            минимальная_длина_цикла: 4,
            мин_доля_арифметики: 25,
        }
    }

    pub fn с_параметрами(мин_длина: usize, мин_доля: usize) -> Self {
        Self {
            минимальная_длина_цикла: мин_длина.max(2),
            мин_доля_арифметики: мин_доля.min(100),
        }
    }

    /// Найти циклы, которые можно векторизовать.
    pub fn найти_векторизуемые(&self, функция: &ФункцияПП) -> Vec<ВекторизуемыйЦикл> {
        let mut результат = Vec::new();
        let тело = &функция.тело;

        // карта: id метки → индекс в теле
        let mut метки: std::collections::HashMap<u32, usize> = std::collections::HashMap::new();
        for (i, инстр) in тело.iter().enumerate() {
            if let Инструкция::Метка { идентификатор } = инстр {
                метки.insert(идентификатор.0, i);
            }
        }

        for (i, инстр) in тело.iter().enumerate() {
            let цель = match инстр {
                Инструкция::Перейти { метка } => Some(*метка),
                Инструкция::ВетвлениеИмпульса { истина, ложь, .. } => {
                    // обратное ребро — прыжок «назад»
                    let mut назад = None;
                    if let Some(&idx) = метки.get(&истина.0) {
                        if idx < i {
                            назад = Some(*истина);
                        }
                    }
                    if назад.is_none() {
                        if let Some(&idx) = метки.get(&ложь.0) {
                            if idx < i {
                                назад = Some(*ложь);
                            }
                        }
                    }
                    назад
                }
                _ => None,
            };

            let Some(метка) = цель else { continue };
            let Some(&начало) = метки.get(&метка.0) else {
                continue;
            };
            if начало >= i {
                continue;
            }
            let длина = i - начало + 1;
            if длина < self.минимальная_длина_цикла {
                continue;
            }
            let окно = &тело[начало..=i];
            if !self.проверить_векторизуемость(окно) {
                continue;
            }
            // Не дублировать вложенные одинаковые начала
            if результат.iter().any(|ц: &ВекторизуемыйЦикл| ц.начало == начало) {
                continue;
            }
            результат.push(ВекторизуемыйЦикл {
                начало,
                конец: i,
                длина,
                тип_simd: выбрать_simd_инструкции(длина),
                метка_начала: метка,
            });
        }

        результат
    }

    fn проверить_векторизуемость(&self, инструкции: &[Инструкция]) -> bool {
        if инструкции.is_empty() {
            return false;
        }
        let mut арифметика = 0usize;
        let mut вызовы = 0usize;
        let mut всего_значимых = 0usize;
        for и in инструкции {
            match и {
                Инструкция::Сложить { .. }
                | Инструкция::Умножить { .. }
                | Инструкция::Вычесть { .. }
                | Инструкция::Разделить { .. } => {
                    арифметика += 1;
                    всего_значимых += 1;
                }
                Инструкция::Вызвать { .. } | Инструкция::ВнешнийВызов { .. } => {
                    вызовы += 1;
                    всего_значимых += 1;
                }
                Инструкция::Метка { .. }
                | Инструкция::Перейти { .. }
                | Инструкция::ВетвлениеИмпульса { .. }
                | Инструкция::КонстантаЦелое { .. }
                | Инструкция::Переместить { .. }
                | Инструкция::Сравнить { .. } => {}
                _ => {
                    всего_значимых += 1;
                }
            }
        }
        if вызовы > 0 {
            return false;
        }
        if арифметика == 0 {
            return false;
        }
        let база = всего_значимых.max(арифметика);
        арифметика * 100 / база >= self.мин_доля_арифметики
    }
}

impl Default for АнализаторSIMD {
    fn default() -> Self {
        Self::новый()
    }
}

#[derive(Debug, Clone)]
pub struct ВекторизуемыйЦикл {
    pub начало: usize,
    pub конец: usize,
    pub длина: usize,
    pub тип_simd: ТипSIMD,
    pub метка_начала: Метка,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum ТипSIMD {
    AVX2,
    AVX512,
    NEON,
}

fn выбрать_simd_инструкции(длина_цикла: usize) -> ТипSIMD {
    if cfg!(target_arch = "aarch64") {
        return ТипSIMD::NEON;
    }
    if длина_цикла >= 12 {
        ТипSIMD::AVX512
    } else {
        ТипSIMD::AVX2
    }
}

/// Аннотировать функции: вернуть число найденных SIMD-циклов.
pub fn аннотировать_функции(функции: &[ФункцияПП]) -> (usize, Vec<String>) {
    let анализатор = АнализаторSIMD::новый();
    let mut всего = 0usize;
    let mut лог = Vec::new();
    for ф in функции {
        let циклы = анализатор.найти_векторизуемые(ф);
        всего += циклы.len();
        for ц in &циклы {
            лог.push(format!(
                "[simd] {} цикл [{},{}] len={} {:?}",
                ф.имя, ц.начало, ц.конец, ц.длина, ц.тип_simd
            ));
        }
    }
    (всего, лог)
}

/// Флаги clang для явной SIMD-сборки.
pub fn флаги_clang_simd() -> Vec<&'static str> {
    if cfg!(target_arch = "x86_64") {
        vec![
            "-march=native",
            "-mavx2",
            "-mavx512f",
            "-mavx512vl",
            "-mavx512dq",
        ]
    } else if cfg!(target_arch = "aarch64") {
        vec!["-march=native"]
    } else {
        vec!["-march=native"]
    }
}

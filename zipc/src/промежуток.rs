//! Промежуточное представление (IR) языка ZIP.
//! Близко к байт-коду: регистры, метки, импульсные операции.

use crate::дерево::Узел;
use std::collections::HashMap;

#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub struct Регистр(pub u32);

#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub struct Метка(pub u32);

#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub struct ИдентификаторФункции(pub u32);

#[derive(Debug, Clone, PartialEq, Eq)]
pub enum Тип {
    Целое64,
    Вещественное64,
    Указатель(Box<Тип>),
    Тензор(Vec<usize>),
    /// PERFECT — неизменяемый после `!`
    Совершенный,
    /// IMPERFECT — потоковый
    Несовершенный,
}

#[derive(Debug, Clone, PartialEq)]
pub enum Инструкция {
    // Память
    Выделить {
        назначение: Регистр,
        размер: usize,
    },
    Загрузить {
        назначение: Регистр,
        адрес: Регистр,
    },
    Сохранить {
        адрес: Регистр,
        значение: Регистр,
    },
    Переместить {
        назначение: Регистр,
        источник: Регистр,
    },

    // Арифметика
    Сложить {
        назначение: Регистр,
        а: Регистр,
        б: Регистр,
    },
    Вычесть {
        назначение: Регистр,
        а: Регистр,
        б: Регистр,
    },
    Умножить {
        назначение: Регистр,
        а: Регистр,
        б: Регистр,
    },
    Разделить {
        назначение: Регистр,
        а: Регистр,
        б: Регистр,
    },

    // Константы (удобство генерации из AST)
    КонстантаЦелое {
        назначение: Регистр,
        значение: i64,
    },
    КонстантаВещественное {
        назначение: Регистр,
        значение: f64,
    },
    КонстантаСтрока {
        назначение: Регистр,
        значение: String,
    },

    /// Встроенный вывод: печать / печать_строки / печать_число.
    Печать {
        режим: РежимПечати,
        значение: Регистр,
    },

    // Импульсные операции (ядро ZIP)
    Импульс {
        источник: Регистр,
        назначение: Регистр,
    },
    ОжиданиеИмпульса {
        регистр: Регистр,
    },
    ВетвлениеИмпульса {
        условие: Регистр,
        истина: Метка,
        ложь: Метка,
    },

    // Хор
    ЗапуститьХор {
        функция: ИдентификаторФункции,
        аргументы: Vec<Регистр>,
    },
    СобратьХор {
        регистры: Vec<Регистр>,
    },

    // Фиксация
    Зафиксировать {
        регистр: Регистр,
    },

    // FFI
    ВнешнийВызов {
        библиотека: String,
        функция: String,
        аргументы: Vec<Регистр>,
        результат: Option<Регистр>,
    },

    // Вызов глагола ZIP
    Вызвать {
        функция: ИдентификаторФункции,
        аргументы: Vec<Регистр>,
        результат: Option<Регистр>,
    },

    // Управление
    Перейти {
        метка: Метка,
    },
    Вернуть {
        значение: Option<Регистр>,
    },
    Метка {
        идентификатор: Метка,
    },
}

/// Режим встроенной печати.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum РежимПечати {
    БезНовойСтроки, // печать / printf %s
    СоСтрокой,      // печать_строки / puts
    Число,          // печать_число / printf %lld
}

#[derive(Debug, Clone, PartialEq)]
pub struct ФункцияПП {
    pub идентификатор: ИдентификаторФункции,
    pub имя: String,
    pub параметры: Vec<Регистр>,
    pub тип_возврата: Тип,
    pub тело: Vec<Инструкция>,
    pub асинхронная: bool,
    pub совершенная: bool,
}

#[derive(Debug, Clone, PartialEq)]
pub struct ОшибкаПП {
    pub сообщение: String,
}

impl std::fmt::Display for ОшибкаПП {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        write!(f, "{}", self.сообщение)
    }
}

impl std::error::Error for ОшибкаПП {}

pub struct ГенераторПП {
    функции: Vec<ФункцияПП>,
    следующий_регистр: u32,
    следующая_метка: u32,
    следующая_функция: u32,
    имена_функций: HashMap<String, ИдентификаторФункции>,
    /// Типы значений в регистрах (для проверки Совершенный/Несовершенный).
    типы_регистров: HashMap<Регистр, Тип>,
}

impl ГенераторПП {
    pub fn новый() -> Self {
        Self {
            функции: Vec::new(),
            следующий_регистр: 0,
            следующая_метка: 0,
            следующая_функция: 0,
            имена_функций: HashMap::new(),
            типы_регистров: HashMap::new(),
        }
    }

    pub fn сгенерировать(&mut self, дерево: &Узел) -> Result<Vec<ФункцияПП>, ОшибкаПП> {
        self.функции.clear();
        self.следующий_регистр = 0;
        self.следующая_метка = 0;
        self.следующая_функция = 0;
        self.имена_функций.clear();
        self.типы_регистров.clear();

        // Главная функция программы
        let главная_id = self.новая_функция_id();
        let mut тело_главной = Vec::new();
        let вход = self.новый_регистр(Тип::Несовершенный);

        match дерево {
            Узел::Программа { объявления } => {
                for узел in объявления {
                    let результат = self.сгенерировать_узел(узел, &mut тело_главной, Some(вход))?;
                    if let Some(рег) = результат {
                        тело_главной.push(Инструкция::Переместить {
                            назначение: вход,
                            источник: рег,
                        });
                    }
                }
            }
            другой => {
                let _ = self.сгенерировать_узел(другой, &mut тело_главной, Some(вход))?;
            }
        }

        // Код выхода процесса — 0 (результат потока остаётся во внутренних регистрах).
        let код_выхода = self.новый_регистр(Тип::Целое64);
        тело_главной.push(Инструкция::КонстантаЦелое {
            назначение: код_выхода,
            значение: 0,
        });
        тело_главной.push(Инструкция::Вернуть {
            значение: Some(код_выхода),
        });
        let _ = вход;

        self.функции.push(ФункцияПП {
            идентификатор: главная_id,
            имя: "главная".into(),
            параметры: vec![],
            тип_возврата: Тип::Несовершенный,
            тело: тело_главной,
            асинхронная: false,
            совершенная: false,
        });

        // главная (id=0) — первая в списке
        self.функции.sort_by_key(|ф| ф.идентификатор.0);
        Ok(self.функции.clone())
    }

    fn сгенерировать_узел(
        &mut self,
        узел: &Узел,
        тело: &mut Vec<Инструкция>,
        импульс_входа: Option<Регистр>,
    ) -> Result<Option<Регистр>, ОшибкаПП> {
        match узел {
            Узел::Программа { объявления } => {
                let mut последний = None;
                for дочерний in объявления {
                    последний = self.сгенерировать_узел(дочерний, тело, импульс_входа)?;
                }
                Ok(последний)
            }

            Узел::ОбъявлениеКорня { .. } => {
                // Метаданные корня пока не порождают код.
                Ok(None)
            }

            Узел::Целое(n) => {
                let р = self.новый_регистр(Тип::Целое64);
                тело.push(Инструкция::КонстантаЦелое {
                    назначение: р,
                    значение: *n,
                });
                Ok(Some(р))
            }

            Узел::Вещественное(x) => {
                let р = self.новый_регистр(Тип::Вещественное64);
                тело.push(Инструкция::КонстантаВещественное {
                    назначение: р,
                    значение: *x,
                });
                Ok(Some(р))
            }

            Узел::Строка(с) => {
                let р = self.новый_регистр(Тип::Указатель(Box::new(Тип::Целое64)));
                тело.push(Инструкция::КонстантаСтрока {
                    назначение: р,
                    значение: с.clone(),
                });
                Ok(Some(р))
            }

            Узел::Идентификатор(_) => {
                let р = self.новый_регистр(Тип::Несовершенный);
                тело.push(Инструкция::Выделить {
                    назначение: р,
                    размер: 8,
                });
                Ok(Some(р))
            }

            Узел::Блок(элементы) => {
                let mut последний = импульс_входа;
                for эл in элементы {
                    последний = self.сгенерировать_узел(эл, тело, последний)?.or(последний);
                }
                Ok(последний)
            }

            Узел::ВызовГлагола {
                глагол,
                аргументы,
                следующий,
            } => {
                let fn_id = self.обеспечить_функцию_глагола(глагол, false, false)?;
                let mut регистры_арг = Vec::new();

                if let Some(вход) = импульс_входа {
                    регистры_арг.push(вход);
                }
                for арг in аргументы {
                    if let Some(р) = self.сгенерировать_узел(арг, тело, None)? {
                        регистры_арг.push(р);
                    }
                }

                let результат = self.новый_регистр(Тип::Несовершенный);
                тело.push(Инструкция::Вызвать {
                    функция: fn_id,
                    аргументы: регистры_арг,
                    результат: Some(результат),
                });

                if let Some(след) = следующий {
                    // >> — импульс: передаём результат дальше по цепочке
                    let после_импульса = self.новый_регистр(Тип::Несовершенный);
                    тело.push(Инструкция::Импульс {
                        источник: результат,
                        назначение: после_импульса,
                    });
                    return self.сгенерировать_узел(след, тело, Some(после_импульса));
                }

                Ok(Some(результат))
            }

            Узел::Фиксация { глагол, данные } => {
                // Проверка типов: нельзя зафиксировать уже совершенное «как несовершенное наоборот»
                // и нельзя смешивать Совершенный ← из чужого Несовершенный некорректно.
                let fn_id = self.обеспечить_функцию_глагола(глагол, false, true)?;

                let данные_рег = if let Some(вход) = импульс_входа {
                    self.проверить_можно_зафиксировать(вход)?;
                    вход
                } else if let Some(р) = self.сгенерировать_узел(данные, тело, None)? {
                    self.проверить_можно_зафиксировать(р)?;
                    р
                } else {
                    self.новый_регистр(Тип::Несовершенный)
                };

                тело.push(Инструкция::Вызвать {
                    функция: fn_id,
                    аргументы: vec![данные_рег],
                    результат: Some(данные_рег),
                });
                тело.push(Инструкция::Зафиксировать {
                    регистр: данные_рег,
                });
                self.типы_регистров
                    .insert(данные_рег, Тип::Совершенный);

                // Пометим функцию глагола как совершенную
                if let Some(ф) = self.функции.iter_mut().find(|ф| ф.идентификатор == fn_id) {
                    ф.совершенная = true;
                    ф.тип_возврата = Тип::Совершенный;
                }

                Ok(Some(данные_рег))
            }

            Узел::АсинхронныйПоток { глагол, тело: тело_узла } => {
                let fn_id = self.обеспечить_функцию_глагола(глагол, true, false)?;
                if let Some(ф) = self.функции.iter_mut().find(|ф| ф.идентификатор == fn_id) {
                    ф.асинхронная = true;
                    ф.тип_возврата = Тип::Несовершенный;
                }

                // Тело асинхронного потока — в отдельной функции-обёртке
                let mut тело_потока = Vec::new();
                let вход = self.новый_регистр(Тип::Несовершенный);
                let _ = self.сгенерировать_узел(тело_узла, &mut тело_потока, Some(вход))?;
                тело_потока.push(Инструкция::Вернуть {
                    значение: Some(вход),
                });

                let обёртка_id = self.новая_функция_id();
                self.функции.push(ФункцияПП {
                    идентификатор: обёртка_id,
                    имя: format!("{}_поток", глагол),
                    параметры: vec![вход],
                    тип_возврата: Тип::Несовершенный,
                    тело: тело_потока,
                    асинхронная: true,
                    совершенная: false,
                });

                let результат = self.новый_регистр(Тип::Несовершенный);
                let арг = импульс_входа.unwrap_or(результат);
                тело.push(Инструкция::ЗапуститьХор {
                    функция: обёртка_id,
                    аргументы: vec![арг],
                });
                // также отмечаем исходный глагол
                let _ = fn_id;
                Ok(Some(результат))
            }

            Узел::Хор { ветки } => {
                let mut регистры = Vec::new();
                for ветка in ветки {
                    match ветка {
                        Узел::АсинхронныйПоток { глагол, тело: тело_в } => {
                            let обёртка_id = self.новая_функция_id();
                            let mut тело_ветки = Vec::new();
                            let вход = self.новый_регистр(Тип::Несовершенный);
                            let _ =
                                self.сгенерировать_узел(тело_в, &mut тело_ветки, Some(вход))?;
                            тело_ветки.push(Инструкция::Вернуть {
                                значение: Some(вход),
                            });
                            self.функции.push(ФункцияПП {
                                идентификатор: обёртка_id,
                                имя: format!("{}_хор", глагол),
                                параметры: vec![вход],
                                тип_возврата: Тип::Несовершенный,
                                тело: тело_ветки,
                                асинхронная: true,
                                совершенная: false,
                            });
                            let р = self.новый_регистр(Тип::Несовершенный);
                            тело.push(Инструкция::ЗапуститьХор {
                                функция: обёртка_id,
                                аргументы: импульс_входа.into_iter().collect(),
                            });
                            регистры.push(р);
                        }
                        другой => {
                            if let Some(р) =
                                self.сгенерировать_узел(другой, тело, импульс_входа)?
                            {
                                let fn_id = self.новая_функция_id();
                                self.функции.push(ФункцияПП {
                                    идентификатор: fn_id,
                                    имя: format!("хор_{}", fn_id.0),
                                    параметры: vec![],
                                    тип_возврата: Тип::Несовершенный,
                                    тело: vec![Инструкция::Вернуть {
                                        значение: Some(р),
                                    }],
                                    асинхронная: true,
                                    совершенная: false,
                                });
                                тело.push(Инструкция::ЗапуститьХор {
                                    функция: fn_id,
                                    аргументы: vec![р],
                                });
                                регистры.push(р);
                            }
                        }
                    }
                }
                тело.push(Инструкция::СобратьХор {
                    регистры: регистры.clone(),
                });
                Ok(регистры.last().copied())
            }

            Узел::ВнешнийВызов {
                библиотека,
                функция,
                аргументы,
            } => {
                let mut регистры_арг = Vec::new();
                for арг in аргументы {
                    if let Some(р) = self.сгенерировать_узел(арг, тело, None)? {
                        регистры_арг.push(р);
                    }
                }
                let результат = self.новый_регистр(Тип::Несовершенный);
                тело.push(Инструкция::ВнешнийВызов {
                    библиотека: библиотека.clone(),
                    функция: функция.clone(),
                    аргументы: регистры_арг,
                    результат: Some(результат),
                });
                Ok(Some(результат))
            }

            Узел::Истина => {
                let р = self.новый_регистр(Тип::Целое64);
                тело.push(Инструкция::КонстантаЦелое {
                    назначение: р,
                    значение: 1,
                });
                Ok(Some(р))
            }
            Узел::Ложь => {
                let р = self.новый_регистр(Тип::Целое64);
                тело.push(Инструкция::КонстантаЦелое {
                    назначение: р,
                    значение: 0,
                });
                Ok(Some(р))
            }
            Узел::Если {
                условие,
                тогда,
                иначе,
            } => {
                let _ = self.сгенерировать_узел(условие, тело, None)?;
                let р_тогда = self.сгенерировать_узел(тогда, тело, импульс_входа)?;
                if let Some(ветка) = иначе {
                    let _ = self.сгенерировать_узел(ветка, тело, импульс_входа)?;
                }
                Ok(р_тогда)
            }
            Узел::Пока { условие, тело: тело_ц } => {
                let _ = self.сгенерировать_узел(условие, тело, None)?;
                self.сгенерировать_узел(тело_ц, тело, импульс_входа)
            }
            Узел::Для {
                коллекция,
                тело: тело_ц,
                ..
            } => {
                let _ = self.сгенерировать_узел(коллекция, тело, None)?;
                self.сгенерировать_узел(тело_ц, тело, импульс_входа)
            }
            Узел::Возврат(зн) => {
                let рег = if let Some(в) = зн {
                    self.сгенерировать_узел(в, тело, None)?
                } else {
                    None
                };
                тело.push(Инструкция::Вернуть { значение: рег });
                Ok(рег)
            }
            Узел::Прервать | Узел::Продолжить => Ok(None),
            Узел::ОпределениеФункции {
                имя,
                тело: тело_ф,
                ..
            } => {
                let id = self.новая_функция_id();
                let mut тело_новой = Vec::new();
                let вход = self.новый_регистр(Тип::Несовершенный);
                let _ = self.сгенерировать_узел(тело_ф, &mut тело_новой, Some(вход))?;
                if !тело_новой
                    .iter()
                    .any(|и| matches!(и, Инструкция::Вернуть { .. }))
                {
                    тело_новой.push(Инструкция::Вернуть {
                        значение: Some(вход),
                    });
                }
                self.имена_функций.insert(имя.clone(), id);
                self.функции.push(ФункцияПП {
                    идентификатор: id,
                    имя: имя.clone(),
                    параметры: vec![вход],
                    тип_возврата: Тип::Несовершенный,
                    тело: тело_новой,
                    асинхронная: false,
                    совершенная: false,
                });
                Ok(None)
            }
            Узел::ВызовФункции { имя, аргументы } => {
                if let Some(режим) = режим_печати(имя) {
                    if аргументы.len() != 1 {
                        return Err(ОшибкаПП {
                            сообщение: format!(
                                "встроенная {} ожидает ровно 1 аргумент",
                                имя
                            ),
                        });
                    }
                    let зн = self
                        .сгенерировать_узел(&аргументы[0], тело, None)?
                        .ok_or_else(|| ОшибкаПП {
                            сообщение: format!("пустой аргумент у {}", имя),
                        })?;
                    тело.push(Инструкция::Печать {
                        режим,
                        значение: зн,
                    });
                    return Ok(Some(зн));
                }

                let fn_id = if let Some(id) = self.имена_функций.get(имя).copied() {
                    id
                } else {
                    self.обеспечить_функцию_глагола(имя, false, false)?
                };
                let mut регистры_арг = Vec::new();
                for арг in аргументы {
                    if let Some(р) = self.сгенерировать_узел(арг, тело, None)? {
                        регистры_арг.push(р);
                    }
                }
                let результат = self.новый_регистр(Тип::Несовершенный);
                тело.push(Инструкция::Вызвать {
                    функция: fn_id,
                    аргументы: регистры_арг,
                    результат: Some(результат),
                });
                Ok(Some(результат))
            }
            Узел::ЛогическоеИ(а, б) | Узел::ЛогическоеИли(а, б) => {
                let _ = self.сгенерировать_узел(а, тело, None)?;
                self.сгенерировать_узел(б, тело, None)
            }
            Узел::ЛогическоеНе(а) | Узел::УнарныйМинус(а) => {
                self.сгенерировать_узел(а, тело, None)
            }
            Узел::Сравнение { левый, правый, .. }
            | Узел::БинарнаяОперация { левый, правый, .. } => {
                let _ = self.сгенерировать_узел(левый, тело, None)?;
                self.сгенерировать_узел(правый, тело, None)
            }
            Узел::Присваивание { значение, .. } => {
                self.сгенерировать_узел(значение, тело, None)
            }
        }
    }

    fn обеспечить_функцию_глагола(
        &mut self,
        имя: &str,
        асинхронная: bool,
        совершенная: bool,
    ) -> Result<ИдентификаторФункции, ОшибкаПП> {
        if let Some(id) = self.имена_функций.get(имя) {
            // Обновим флаги, если требуется
            if let Some(ф) = self.функции.iter_mut().find(|ф| ф.идентификатор == *id) {
                ф.асинхронная |= асинхронная;
                ф.совершенная |= совершенная;
                if совершенная {
                    ф.тип_возврата = Тип::Совершенный;
                }
            }
            return Ok(*id);
        }

        let id = self.новая_функция_id();
        let параметр = Регистр(self.следующий_регистр);
        self.следующий_регистр += 1;
        self.типы_регистров
            .insert(параметр, Тип::Несовершенный);

        let тип_возврата = if совершенная {
            Тип::Совершенный
        } else {
            Тип::Несовершенный
        };

        let mut тело = vec![
            Инструкция::ОжиданиеИмпульса {
                регистр: параметр,
            },
            Инструкция::Вернуть {
                значение: Some(параметр),
            },
        ];
        if совершенная {
            тело.insert(
                1,
                Инструкция::Зафиксировать {
                    регистр: параметр,
                },
            );
        }

        self.функции.push(ФункцияПП {
            идентификатор: id,
            имя: имя.to_string(),
            параметры: vec![параметр],
            тип_возврата,
            тело,
            асинхронная,
            совершенная,
        });
        self.имена_функций.insert(имя.to_string(), id);
        Ok(id)
    }

    fn проверить_можно_зафиксировать(&self, регистр: Регистр) -> Result<(), ОшибкаПП> {
        match self.типы_регистров.get(&регистр) {
            Some(Тип::Совершенный) => Err(ОшибкаПП {
                сообщение: format!(
                    "Нельзя применить Совершенный к уже Совершенному регистру r{}",
                    регистр.0
                ),
            }),
            Some(Тип::Несовершенный)
            | Some(Тип::Целое64)
            | Some(Тип::Вещественное64)
            | Some(Тип::Указатель(_))
            | Some(Тип::Тензор(_))
            | None => Ok(()),
        }
    }

    /// Явная проверка совместимости типов потока.
    /// Нельзя понижать Совершенный до Несовершенного и нельзя повторно «натягивать»
    /// семантику Совершенный на несовместимый поток.
    pub fn проверить_совместимость(от: &Тип, к: &Тип) -> Result<(), ОшибкаПП> {
        match (от, к) {
            (Тип::Совершенный, Тип::Несовершенный) => Err(ОшибкаПП {
                сообщение: "Нельзя применить Совершенный к Несовершенному".into(),
            }),
            (Тип::Несовершенный, Тип::Совершенный) => Ok(()), // фиксация `!` допустима
            _ => Ok(()),
        }
    }

    fn новый_регистр(&mut self, тип: Тип) -> Регистр {
        let р = Регистр(self.следующий_регистр);
        self.следующий_регистр += 1;
        self.типы_регистров.insert(р, тип);
        р
    }

    fn новая_метка(&mut self) -> Метка {
        let м = Метка(self.следующая_метка);
        self.следующая_метка += 1;
        м
    }

    fn новая_функция_id(&mut self) -> ИдентификаторФункции {
        let id = ИдентификаторФункции(self.следующая_функция);
        self.следующая_функция += 1;
        id
    }
}

impl Default for ГенераторПП {
    fn default() -> Self {
        Self::новый()
    }
}

/// Исходник ZIP → функции ПП.
pub fn сгенерировать_из_исходника(исходник: &str) -> Result<Vec<ФункцияПП>, String> {
    let дерево = crate::парсер::разобрать_исходник(исходник).map_err(|е| е.сообщение)?;
    let mut ген = ГенераторПП::новый();
    ген.сгенерировать(&дерево).map_err(|е| е.сообщение)
}

/// Нормализация имён встроенной печати (строчные и PascalCase).
pub fn режим_печати(имя: &str) -> Option<РежимПечати> {
    match имя {
        "печать" | "Печать" => Some(РежимПечати::БезНовойСтроки),
        "печать_строки" | "ПечатьСтроки" | "Печать_строки" => Some(РежимПечати::СоСтрокой),
        "печать_число" | "ПечатьЧисло" | "Печать_число" => Some(РежимПечати::Число),
        _ => None,
    }
}

#[allow(dead_code)]
fn _использовать_метку(г: &mut ГенераторПП) -> Метка {
    г.новая_метка()
}

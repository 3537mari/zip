/// Имя типа ZIP → IR `Тип` (R3).
pub fn строка_в_тип(имя: &str) -> Тип {
    match имя {
        "Целое" | "Целое64" | "Число" | "Флаг" | "Булево" => Тип::Целое64,
        "Вещественное" | "Вещественное64" => Тип::Вещественное64,
        "Строка" => Тип::Указатель(Box::new(Тип::Целое64)),
        "Тензор" => Тип::Тензор(vec![]),
        "Множество" => Тип::Множество(Box::new(Тип::Несовершенный)),
        "Итератор" => Тип::Итератор(Box::new(Тип::Несовершенный)),
        "Нечто" => Тип::Нечто(Box::new(Тип::Несовершенный)),
        "Ничто" => Тип::Ничто,
        "Успех" => Тип::Успех(Box::new(Тип::Несовершенный)),
        "Ошибка" => Тип::Ошибка(Box::new(Тип::Несовершенный)),
        "Эфемерное" => Тип::Эфемерное(Box::new(Тип::Несовершенный), 0),
        "Единица" => Тип::Единица(Box::new(Тип::Несовершенный), String::new()),
        "Диапазон" => Тип::Диапазон,
        _ => Тип::Несовершенный,
    }
}

fn типы_совместимы_специализации(аргументы: &[Тип], ожидаемые: &[Тип]) -> bool {
    if аргументы.len() != ожидаемые.len() {
        return false;
    }
    аргументы
        .iter()
        .zip(ожидаемые.iter())
        .all(|(а, о)| тип_подходит_специализации(а, о))
}

fn тип_подходит_специализации(факт: &Тип, ожид: &Тип) -> bool {
    if факт == ожид {
        return true;
    }
    match (факт, ожид) {
        (Тип::Указатель(_), Тип::Указатель(_)) => true,
        (Тип::Тензор(_), Тип::Тензор(_)) => true,
        (Тип::Множество(_), Тип::Множество(_)) => true,
        (Тип::Итератор(_), Тип::Итератор(_)) => true,
        (Тип::Нечто(_), Тип::Нечто(_)) => true,
        (Тип::Успех(_), Тип::Успех(_)) => true,
        (Тип::Ошибка(_), Тип::Ошибка(_)) => true,
        (Тип::Эфемерное(_, _), Тип::Эфемерное(_, _)) => true,
        (Тип::Единица(_, _), Тип::Единица(_, _)) => true,
        _ => false,
    }
}


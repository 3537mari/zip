#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash)]
pub struct Регистр(pub u32);

#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub struct Метка(pub u32);

#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub struct ИдентификаторФункции(pub u32);

#[derive(Debug, Clone, PartialEq, Eq)]
pub enum Тип {
    Целое64,
    Вещественное64,
    Указатель(Box<Тип>),
    Тензор(Vec<usize>),
    /// PERFECT — неизменяемый после `!`
    Совершенный,
    /// IMPERFECT — потоковый
    Несовершенный,

    // Идея 8 — типы по гласным-шаблонам
    /// И-А: множество / буфер
    Множество(Box<Тип>),
    /// Ы-А: итератор
    Итератор(Box<Тип>),
    /// Э-А: эфемерное значение (TTL, секунды)
    Эфемерное(Box<Тип>, u64),
    /// Ю-А: величина с единицей измерения
    Единица(Box<Тип>, String),
    /// Я-А: ядро / центр
    Ядро(Box<Тип>),
    /// О-О: инструмент (имя мишкаля)
    Инструмент(String),
    /// Е-А: свойство
    Свойство(Box<Тип>),
    /// Ё-А: особая форма
    ОсобаяФорма(Box<Тип>),

    // Идеи 14–15: размеченные объединения
    /// Нечто<T> — опциональное значение
    Нечто(Box<Тип>),
    /// Ничто — отсутствие значения
    Ничто,
    /// Успех<T> — успешный результат
    Успех(Box<Тип>),
    /// Ошибка<E> — ошибка
    Ошибка(Box<Тип>),

    /// R4: диапазон как Copy-тип (ручка в куче VM)
    Диапазон,
}

/// IR-тип по мишкалю (Идея 8).
pub fn тип_по_шаблону(шаблон: &str, базовый: Тип) -> Тип {
    use crate::лексика::{тип_шаблона, ТипШаблона};
    // Идеи 12–13: имена STD-обёрток
    match шаблон {
        "эфемерное" | "zip_создать_ttl" => {
            return Тип::Эфемерное(Box::new(базовый), 0);
        }
        "измерить" | "zip_создать_измерение" | "измерить_сложить" | "zip_измерения_сложить" => {
            return Тип::Единица(Box::new(базовый), "измерение".into());
        }
        "соединить_строки" | "zip_соединить_строки" => {
            return Тип::Указатель(Box::new(Тип::Целое64));
        }
        _ => {}
    }
    match тип_шаблона(шаблон) {
        Some(ТипШаблона::Множество) => Тип::Множество(Box::new(базовый)),
        Some(ТипШаблона::Итератор) => Тип::Итератор(Box::new(базовый)),
        Some(ТипШаблона::Эфемерное) => Тип::Эфемерное(Box::new(базовый), 300),
        Some(ТипШаблона::Единица) => Тип::Единица(Box::new(базовый), "базовая".into()),
        Some(ТипШаблона::Ядро) => Тип::Ядро(Box::new(базовый)),
        Some(ТипШаблона::Инструмент) => Тип::Инструмент(шаблон.to_string()),
        Some(ТипШаблона::Свойство) => Тип::Свойство(Box::new(базовый)),
        Some(ТипШаблона::ОсобаяФорма) => Тип::ОсобаяФорма(Box::new(базовый)),
        Some(ТипШаблона::Указатель) => Тип::Указатель(Box::new(базовый)),
        Some(ТипШаблона::Глагол) | None => базовый,
    }
}

#[derive(Debug, Clone, PartialEq)]
pub enum Инструкция {
    // Память
    Выделить {
        назначение: Регистр,
        размер: usize,
    },
    Загрузить {
        назначение: Регистр,
        адрес: Регистр,
    },
    Сохранить {
        адрес: Регистр,
        значение: Регистр,
    },
    Переместить {
        назначение: Регистр,
        источник: Регистр,
    },
    /// R4: копирование Copy-типа (диапазон) — не move
    Копировать {
        назначение: Регистр,
        источник: Регистр,
    },

    // Арифметика
    Сложить {
        назначение: Регистр,
        а: Регистр,
        б: Регистр,
    },
    Вычесть {
        назначение: Регистр,
        а: Регистр,
        б: Регистр,
    },
    Умножить {
        назначение: Регистр,
        а: Регистр,
        б: Регистр,
    },
    Разделить {
        назначение: Регистр,
        а: Регистр,
        б: Регистр,
    },
    Сравнить {
        оператор: String, // == != < > <= >=
        назначение: Регистр,
        а: Регистр,
        б: Регистр,
    },

    // Константы (удобство генерации из AST)
    КонстантаЦелое {
        назначение: Регистр,
        значение: i64,
    },
    КонстантаВещественное {
        назначение: Регистр,
        значение: f64,
    },
    КонстантаСтрока {
        назначение: Регистр,
        значение: String,
    },

    /// Встроенный вывод: печать / печать_строки / печать_число.
    Печать {
        режим: РежимПечати,
        значение: Регистр,
    },

    // Импульсные операции (ядро ZIP)
    Импульс {
        источник: Регистр,
        назначение: Регистр,
    },
    ОжиданиеИмпульса {
        регистр: Регистр,
    },
    ВетвлениеИмпульса {
        условие: Регистр,
        истина: Метка,
        ложь: Метка,
    },

    // Хор
    ЗапуститьХор {
        функция: ИдентификаторФункции,
        аргументы: Vec<Регистр>,
    },
    СобратьХор {
        регистры: Vec<Регистр>,
    },

    // Фиксация
    Зафиксировать {
        регистр: Регистр,
    },

    /// Идея 17: загрузка глобального слота агента.
    ЗагрузитьГлобал {
        назначение: Регистр,
        имя: String,
    },
    /// Идея 17: сохранение в глобальный слот агента.
    СохранитьГлобал {
        имя: String,
        значение: Регистр,
    },

    // FFI
    ВнешнийВызов {
        библиотека: String,
        функция: String,
        аргументы: Vec<Регистр>,
        результат: Option<Регистр>,
    },

    // Вызов глагола ZIP
    Вызвать {
        функция: ИдентификаторФункции,
        аргументы: Vec<Регистр>,
        результат: Option<Регистр>,
        /// Идея 4: пометить вызов как кандидат на горячий путь (метаданные).
        отметить_горячей: bool,
    },

    // Управление
    Перейти {
        метка: Метка,
    },
    Вернуть {
        значение: Option<Регистр>,
    },
    Метка {
        идентификатор: Метка,
    },
}


//! Лексер языка ZIP (Zero-Immunity-Pulse).
//! Токены исходного кода — только кириллица (латиница в идентификаторах запрещена).

#[derive(Debug, Clone, PartialEq)]
pub enum Токен {
    // Операторы потока
    Импульс,     // >>
    Хор,         // ||
    СетьИмпульс, // >>>
    Фиксация,    // !
    Поток,       // ~

    // Разделители
    Равно,          // =
    Двоеточие,      // :
    СкобкаЛевая,    // (
    СкобкаПравая,   // )
    ФигурнаяЛевая,  // {
    ФигурнаяПравая, // }
    Запятая,        // ,

    // Данные
    Корень(String),      // 3 согласные: СПР, ЧТВ
    Шаблон(String),      // морф. форма корня: САПАР, СИПРА
    Слово(String),       // любой идентификатор на кириллице
    Целое(i64),
    Вещественное(f64),
    Строка(String),

    // Директивы
    Директива(String), // #include, #define, #link

    // Конец
    КонецФайла,
}

#[derive(Debug, Clone, PartialEq)]
pub struct ОшибкаЛексики {
    pub сообщение: String,
    pub строка: usize,
    pub столбец: usize,
}

impl std::fmt::Display for ОшибкаЛексики {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        write!(
            f,
            "ошибка лексики ({}:{}): {}",
            self.строка, self.столбец, self.сообщение
        )
    }
}

impl std::error::Error for ОшибкаЛексики {}

pub struct Лексер {
    исходник: Vec<char>,
    позиция: usize,
    строка: usize,
    столбец: usize,
}

const СОГЛАСНЫЕ: &str = "БВГДЖЗЙКЛМНПРСТФХЦЧШЩбвгджзйклмнпрстфхцчшщ";
/// Полные гласные-модификаторы шаблонов (мишкаль).
const ГЛАСНЫЕ: &str = "АЕЁИОУЫЭаеёиоуыэ";
/// Слабые буквы корня (как Ю в СЮЗ) + йот — входят в скелет из 3 букв.
const СЛАБЫЕ: &str = "ЮЯюя";
/// Мягкий/твёрдый знак — часть корня (ЦПЬ).
const ЗНАКИ: &str = "ЬЪьъ";

impl Лексер {
    pub fn новый(исходник: &str) -> Self {
        Self {
            исходник: исходник.chars().collect(),
            позиция: 0,
            строка: 1,
            столбец: 1,
        }
    }

    pub fn разобрать(&mut self) -> Result<Vec<Токен>, ОшибкаЛексики> {
        let mut токены = Vec::new();

        loop {
            self.пропустить_пробелы_и_комментарии()?;

            if self.конец() {
                токены.push(Токен::КонецФайла);
                break;
            }

            let токен = self.следующий_токен()?;
            токены.push(токен);
        }

        Ok(токены)
    }

    fn следующий_токен(&mut self) -> Result<Токен, ОшибкаЛексики> {
        let символ = self.текущий().unwrap();

        // Операторы и разделители
        match символ {
            '>' => return self.прочитать_импульс(),
            '|' => return self.прочитать_хор(),
            '!' => {
                self.вперёд();
                return Ok(Токен::Фиксация);
            }
            '~' => {
                self.вперёд();
                return Ok(Токен::Поток);
            }
            '=' => {
                self.вперёд();
                return Ok(Токен::Равно);
            }
            ':' => {
                self.вперёд();
                return Ok(Токен::Двоеточие);
            }
            '(' => {
                self.вперёд();
                return Ok(Токен::СкобкаЛевая);
            }
            ')' => {
                self.вперёд();
                return Ok(Токен::СкобкаПравая);
            }
            '{' => {
                self.вперёд();
                return Ok(Токен::ФигурнаяЛевая);
            }
            '}' => {
                self.вперёд();
                return Ok(Токен::ФигурнаяПравая);
            }
            ',' => {
                self.вперёд();
                return Ok(Токен::Запятая);
            }
            '"' => return self.прочитать_строку(),
            '#' => return self.прочитать_директиву(),
            _ => {}
        }

        if символ.is_ascii_digit() {
            return self.прочитать_число();
        }

        if это_латиница(символ) {
            return Err(self.ошибка(
                "Недопустимый символ: латиница не разрешена".into(),
            ));
        }

        if это_кириллица(символ) {
            return self.прочитать_идентификатор();
        }

        Err(self.ошибка(format!("неожиданный символ '{}'", символ)))
    }

    fn прочитать_импульс(&mut self) -> Result<Токен, ОшибкаЛексики> {
        let строка = self.строка;
        let столбец = self.столбец;
        self.вперёд(); // первый >

        if self.текущий() != Some('>') {
            return Err(ОшибкаЛексики {
                сообщение: "ожидался оператор >> или >>>".into(),
                строка,
                столбец,
            });
        }
        self.вперёд(); // второй >

        if self.текущий() == Some('>') {
            self.вперёд(); // третий >
            return Ok(Токен::СетьИмпульс);
        }

        Ok(Токен::Импульс)
    }

    fn прочитать_хор(&mut self) -> Result<Токен, ОшибкаЛексики> {
        let строка = self.строка;
        let столбец = self.столбец;
        self.вперёд(); // первый |

        if self.текущий() != Some('|') {
            return Err(ОшибкаЛексики {
                сообщение: "ожидался оператор ||".into(),
                строка,
                столбец,
            });
        }
        self.вперёд();
        Ok(Токен::Хор)
    }

    fn прочитать_строку(&mut self) -> Result<Токен, ОшибкаЛексики> {
        let строка = self.строка;
        let столбец = self.столбец;
        self.вперёд(); // открывающая "

        let mut буфер = String::new();
        while let Some(с) = self.текущий() {
            if с == '"' {
                self.вперёд();
                return Ok(Токен::Строка(буфер));
            }
            if с == '\n' {
                break;
            }
            if с == '\\' {
                self.вперёд();
                match self.текущий() {
                    Some('н') => {
                        буфер.push('\n');
                        self.вперёд();
                    }
                    Some('т') => {
                        буфер.push('\t');
                        self.вперёд();
                    }
                    Some('\\') => {
                        буфер.push('\\');
                        self.вперёд();
                    }
                    Some('"') => {
                        буфер.push('"');
                        self.вперёд();
                    }
                    Some(другой) => {
                        if это_латиница(другой) {
                            return Err(ОшибкаЛексики {
                                сообщение: "Недопустимый символ: латиница не разрешена"
                                    .into(),
                                строка,
                                столбец,
                            });
                        }
                        буфер.push(другой);
                        self.вперёд();
                    }
                    None => break,
                }
                continue;
            }
            if это_латиница(с) {
                return Err(ОшибкаЛексики {
                    сообщение: "Недопустимый символ: латиница не разрешена".into(),
                    строка,
                    столбец,
                });
            }
            буфер.push(с);
            self.вперёд();
        }

        Err(ОшибкаЛексики {
            сообщение: "незакрытая строка".into(),
            строка,
            столбец,
        })
    }

    fn прочитать_директиву(&mut self) -> Result<Токен, ОшибкаЛексики> {
        let строка = self.строка;
        let столбец = self.столбец;
        self.вперёд(); // #

        let mut имя = String::new();
        while let Some(с) = self.текущий() {
            if с.is_ascii_alphabetic() || с == '_' {
                имя.push(с);
                self.вперёд();
            } else {
                break;
            }
        }

        if имя.is_empty() {
            return Err(ОшибкаЛексики {
                сообщение: "пустая директива после #".into(),
                строка,
                столбец,
            });
        }

        match имя.as_str() {
            "include" | "define" | "link" => Ok(Токен::Директива(имя)),
            _ => Err(ОшибкаЛексики {
                сообщение: format!(
                    "неизвестная директива '#{}' (допустимы: #include, #define, #link)",
                    имя
                ),
                строка,
                столбец,
            }),
        }
    }

    fn прочитать_число(&mut self) -> Result<Токен, ОшибкаЛексики> {
        let строка = self.строка;
        let столбец = self.столбец;
        let mut буфер = String::new();
        let mut точка = false;

        while let Some(с) = self.текущий() {
            if с.is_ascii_digit() {
                буфер.push(с);
                self.вперёд();
            } else if с == '.' && !точка {
                // Проверяем, что после точки идёт цифра (не оператор)
                if matches!(self.заглянуть(1), Some(d) if d.is_ascii_digit()) {
                    точка = true;
                    буфер.push(с);
                    self.вперёд();
                } else {
                    break;
                }
            } else {
                break;
            }
        }

        if точка {
            буфер.parse::<f64>().map(Токен::Вещественное).map_err(|_| {
                ОшибкаЛексики {
                    сообщение: format!("некорректное вещественное число '{}'", буфер),
                    строка,
                    столбец,
                }
            })
        } else {
            буфер.parse::<i64>().map(Токен::Целое).map_err(|_| ОшибкаЛексики {
                сообщение: format!("некорректное целое число '{}'", буфер),
                строка,
                столбец,
            })
        }
    }

    fn прочитать_идентификатор(&mut self) -> Result<Токен, ОшибкаЛексики> {
        let строка = self.строка;
        let столбец = self.столбец;
        let mut буфер = String::new();

        while let Some(с) = self.текущий() {
            if это_латиница(с) {
                return Err(ОшибкаЛексики {
                    сообщение: "Недопустимый символ: латиница не разрешена".into(),
                    строка,
                    столбец,
                });
            }
            if это_кириллица(с) || с.is_ascii_digit() || с == '_' {
                // Цифры и _ после начала допустимы в общем слове, но корень/шаблон — только буквы
                буфер.push(с);
                self.вперёд();
            } else {
                break;
            }
        }

        if буфер.chars().any(|с| с.is_ascii_digit() || с == '_') {
            return Ok(Токен::Слово(буфер));
        }

        Ok(классифицировать_идентификатор(буфер))
    }

    fn пропустить_пробелы_и_комментарии(&mut self) -> Result<(), ОшибкаЛексики> {
        loop {
            while let Some(с) = self.текущий() {
                if с == ' ' || с == '\t' || с == '\r' {
                    self.вперёд();
                } else if с == '\n' {
                    self.вперёд();
                } else {
                    break;
                }
            }

            if self.текущий() == Some('/') && self.заглянуть(1) == Some('/') {
                self.вперёд();
                self.вперёд();
                while let Some(с) = self.текущий() {
                    if с == '\n' {
                        break;
                    }
                    self.вперёд();
                }
                continue;
            }

            break;
        }
        Ok(())
    }

    fn текущий(&self) -> Option<char> {
        self.исходник.get(self.позиция).copied()
    }

    fn заглянуть(&self, смещение: usize) -> Option<char> {
        self.исходник.get(self.позиция + смещение).copied()
    }

    fn конец(&self) -> bool {
        self.позиция >= self.исходник.len()
    }

    fn вперёд(&mut self) {
        if let Some(с) = self.текущий() {
            if с == '\n' {
                self.строка += 1;
                self.столбец = 1;
            } else {
                self.столбец += 1;
            }
            self.позиция += 1;
        }
    }

    fn ошибка(&self, сообщение: String) -> ОшибкаЛексики {
        ОшибкаЛексики {
            сообщение,
            строка: self.строка,
            столбец: self.столбец,
        }
    }
}

fn это_согласная(с: char) -> bool {
    СОГЛАСНЫЕ.contains(с)
}

fn это_гласная(с: char) -> bool {
    ГЛАСНЫЕ.contains(с) || СЛАБЫЕ.contains(с)
}

fn это_полная_гласная(с: char) -> bool {
    ГЛАСНЫЕ.contains(с)
}

fn это_знак(с: char) -> bool {
    ЗНАКИ.contains(с)
}

/// Буква корневого скелета: согласная, слабая (Ю/Я) или ь/ъ.
fn это_скелетная(с: char) -> bool {
    это_согласная(с) || СЛАБЫЕ.contains(с) || это_знак(с)
}

fn это_кириллица(с: char) -> bool {
    это_согласная(с) || это_гласная(с) || это_знак(с)
}

fn это_латиница(с: char) -> bool {
    с.is_ascii_alphabetic()
}

/// Классификация: 3 согласные → Корень;
/// форма с гласными и скелетом из 3 согласных → Шаблон;
/// иначе → Слово.
fn классифицировать_идентификатор(слово: String) -> Токен {
    let буквы: Vec<char> = слово.chars().collect();

    if буквы.is_empty() {
        return Токен::Слово(слово);
    }

    let все_скелетные = буквы.iter().all(|&с| это_скелетная(с));
    if все_скелетные && буквы.len() == 3 {
        return Токен::Корень(слово);
    }

    // Шаблон: есть гласные, скелет ровно из 3 букв (САПАР→СПР, СИПРА→СПР, ЦАПАТ→ЦПЬ)
    let скелет: String = буквы
        .iter()
        .copied()
        .filter(|&с| это_скелетная(с))
        .collect();
    // Шаблон отличается от корня наличием полной гласной-модификатора.
    let есть_модификатор = буквы.iter().any(|&с| это_полная_гласная(с));
    let только_буквы_алфавита = буквы.iter().all(|&с| это_кириллица(с));

    if только_буквы_алфавита && есть_модификатор && скелет.chars().count() == 3 {
        // CVCV… или типичные мишкали длиной 4–6
        if буквы.len() >= 4 && буквы.len() <= 6 {
            return Токен::Шаблон(слово);
        }
    }

    Токен::Слово(слово)
}


//! Лексер языка ZIP.
//! Только кириллица в идентификаторах. Латиница в коде — ошибка.
//! (В строковых литералах и именах директив `#link` латиница допускается как данные.)

use std::fmt;

/// Токены языка ZIP.
#[derive(Debug, Clone, PartialEq)]
pub enum Токен {
    // Операторы потока
    Импульс,     // >>
    Хор,         // ||
    СетьИмпульс, // >>>
    Фиксация,    // !
    Поток,       // ~

    // Разделители
    Равно,          // =
    Двоеточие,      // :
    Дефис,          // - (А-А, И-А) / минус
    СкобкаЛевая,    // (
    СкобкаПравая,   // )
    ФигурнаяЛевая,  // {
    ФигурнаяПравая, // }
    Запятая,        // ,
    Кавычка,        // " (служебный; строки отдаются как Строка)
    Плюс,           // +
    Звезда,         // *
    Слеш,           // /

    // Управление потоком
    Если,       // если
    Иначе,      // иначе
    Пока,       // пока
    Для,        // для
    В,          // в
    Возврат,    // возврат
    Прервать,   // прервать
    Продолжить, // продолжить

    // Определения
    Функция, // функция
    Тип,     // тип
    Модуль,  // модуль
    Импорт,  // импорт

    // Встроенный вывод
    Печать,       // печать
    ПечатьСтроки, // печать_строки
    ПечатьЧисло,  // печать_число

    // Булевы
    Истина, // истина
    Ложь,   // ложь
    И,      // и
    Или,    // или
    Не,     // не

    // Сравнения
    РавноРавно,  // ==
    НеРавно,     // !=
    Больше,      // >
    Меньше,      // <
    БольшеРавно, // >=
    МеньшеРавно, // <=

    // Данные
    Корень(String), // 3 согласные: СПР, ЧТВ
    Шаблон(String), // мишкаль: САПАР, СИПРА, СПОРО
    Слово(String),  // любой идентификатор на кириллице
    Целое(i64),
    Вещественное(f64),
    Строка(String),

    // Директивы
    Директива(String), // #include, #define, #link

    // Конец
    КонецФайла,
}

impl fmt::Display for Токен {
    fn fmt(&self, ф: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Токен::Импульс => write!(ф, ">>"),
            Токен::Хор => write!(ф, "||"),
            Токен::СетьИмпульс => write!(ф, ">>>"),
            Токен::Фиксация => write!(ф, "!"),
            Токен::Поток => write!(ф, "~"),
            Токен::Равно => write!(ф, "="),
            Токен::Двоеточие => write!(ф, ":"),
            Токен::Дефис => write!(ф, "-"),
            Токен::СкобкаЛевая => write!(ф, "("),
            Токен::СкобкаПравая => write!(ф, ")"),
            Токен::ФигурнаяЛевая => write!(ф, "{{"),
            Токен::ФигурнаяПравая => write!(ф, "}}"),
            Токен::Запятая => write!(ф, ","),
            Токен::Кавычка => write!(ф, "\""),
            Токен::Плюс => write!(ф, "+"),
            Токен::Звезда => write!(ф, "*"),
            Токен::Слеш => write!(ф, "/"),
            Токен::Если => write!(ф, "если"),
            Токен::Иначе => write!(ф, "иначе"),
            Токен::Пока => write!(ф, "пока"),
            Токен::Для => write!(ф, "для"),
            Токен::В => write!(ф, "в"),
            Токен::Возврат => write!(ф, "возврат"),
            Токен::Прервать => write!(ф, "прервать"),
            Токен::Продолжить => write!(ф, "продолжить"),
            Токен::Функция => write!(ф, "функция"),
            Токен::Тип => write!(ф, "тип"),
            Токен::Модуль => write!(ф, "модуль"),
            Токен::Импорт => write!(ф, "импорт"),
            Токен::Печать => write!(ф, "печать"),
            Токен::ПечатьСтроки => write!(ф, "печать_строки"),
            Токен::ПечатьЧисло => write!(ф, "печать_число"),
            Токен::Истина => write!(ф, "истина"),
            Токен::Ложь => write!(ф, "ложь"),
            Токен::И => write!(ф, "и"),
            Токен::Или => write!(ф, "или"),
            Токен::Не => write!(ф, "не"),
            Токен::РавноРавно => write!(ф, "=="),
            Токен::НеРавно => write!(ф, "!="),
            Токен::Больше => write!(ф, ">"),
            Токен::Меньше => write!(ф, "<"),
            Токен::БольшеРавно => write!(ф, ">="),
            Токен::МеньшеРавно => write!(ф, "<="),
            Токен::Корень(с) => write!(ф, "Корень({})", с),
            Токен::Шаблон(с) => write!(ф, "Шаблон({})", с),
            Токен::Слово(с) => write!(ф, "Слово({})", с),
            Токен::Целое(н) => write!(ф, "Целое({})", н),
            Токен::Вещественное(н) => write!(ф, "Вещественное({})", н),
            Токен::Строка(с) => write!(ф, "Строка({:?})", с),
            Токен::Директива(с) => write!(ф, "Директива({})", с),
            Токен::КонецФайла => write!(ф, "КонецФайла"),
        }
    }
}

/// Токен с позицией в исходнике.
#[derive(Debug, Clone, PartialEq)]
pub struct ТокенСПозицией {
    pub токен: Токен,
    pub строка: usize,
    pub столбец: usize,
}

/// Совместимое имя для парсера и внешних API.
pub type ПозиционныйТокен = ТокенСПозицией;

/// Ошибка лексического анализа.
#[derive(Debug, Clone, PartialEq)]
pub struct ОшибкаЛексики {
    pub сообщение: String,
    pub строка: usize,
    pub столбец: usize,
}

impl fmt::Display for ОшибкаЛексики {
    fn fmt(&self, ф: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(
            ф,
            "Ошибка лексики [{}:{}]: {}",
            self.строка, self.столбец, self.сообщение
        )
    }
}

impl std::error::Error for ОшибкаЛексики {}

/// Лексер языка ZIP.
pub struct Лексер {
    символы: Vec<char>,
    позиция: usize,
    строка: usize,
    столбец: usize,
}

impl Лексер {
    pub fn новый(исходник: &str) -> Self {
        Self {
            символы: исходник.chars().collect(),
            позиция: 0,
            строка: 1,
            столбец: 1,
        }
    }

    fn текущий(&self) -> Option<char> {
        self.символы.get(self.позиция).copied()
    }

    /// Символ на `н` позиций вперёд (0 = текущий).
    fn заглянуть(&self, н: usize) -> Option<char> {
        self.символы.get(self.позиция + н).copied()
    }

    fn продвинуть(&mut self) {
        if let Some(с) = self.текущий() {
            if с == '\n' {
                self.строка += 1;
                self.столбец = 1;
            } else {
                self.столбец += 1;
            }
            self.позиция += 1;
        }
    }

    fn пропустить_пробелы(&mut self) {
        loop {
            match self.текущий() {
                // UTF-8 BOM (часто добавляет Windows/редакторы)
                Some('\u{FEFF}') => self.продвинуть(),
                Some(с) if с.is_whitespace() => self.продвинуть(),
                Some('/') if self.заглянуть(1) == Some('/') => {
                    while let Some(с) = self.текущий() {
                        if с == '\n' {
                            break;
                        }
                        self.продвинуть();
                    }
                }
                _ => break,
            }
        }
    }

    fn это_согласная(с: char) -> bool {
        matches!(
            с,
            'Б' | 'В'
                | 'Г'
                | 'Д'
                | 'Ж'
                | 'З'
                | 'Й'
                | 'К'
                | 'Л'
                | 'М'
                | 'Н'
                | 'П'
                | 'Р'
                | 'С'
                | 'Т'
                | 'Ф'
                | 'Х'
                | 'Ц'
                | 'Ч'
                | 'Ш'
                | 'Щ'
                | 'б'
                | 'в'
                | 'г'
                | 'д'
                | 'ж'
                | 'з'
                | 'й'
                | 'к'
                | 'л'
                | 'м'
                | 'н'
                | 'п'
                | 'р'
                | 'с'
                | 'т'
                | 'ф'
                | 'х'
                | 'ц'
                | 'ч'
                | 'ш'
                | 'щ'
        )
    }

    /// Полные гласные-модификаторы мишкаля.
    fn это_полная_гласная(с: char) -> bool {
        matches!(
            с,
            'А' | 'Е'
                | 'Ё'
                | 'И'
                | 'О'
                | 'У'
                | 'Ы'
                | 'Э'
                | 'а'
                | 'е'
                | 'ё'
                | 'и'
                | 'о'
                | 'у'
                | 'ы'
                | 'э'
        )
    }

    /// Слабые буквы корня (Ю в СЮЗ) + йотированные.
    fn это_слабая(с: char) -> bool {
        matches!(с, 'Ю' | 'Я' | 'ю' | 'я')
    }

    fn это_знак(с: char) -> bool {
        matches!(с, 'Ь' | 'Ъ' | 'ь' | 'ъ')
    }

    fn это_гласная(с: char) -> bool {
        Self::это_полная_гласная(с) || Self::это_слабая(с)
    }

    fn это_русская(с: char) -> bool {
        Self::это_согласная(с) || Self::это_гласная(с) || Self::это_знак(с)
    }

    fn это_скелетная(с: char) -> bool {
        Self::это_согласная(с) || Self::это_слабая(с) || Self::это_знак(с)
    }

    fn распознать_слово(&mut self) -> Result<String, ОшибкаЛексики> {
        let начало = self.позиция;
        let строка = self.строка;
        let столбец = self.столбец;
        while let Some(с) = self.текущий() {
            if с.is_ascii_alphabetic() {
                return Err(ОшибкаЛексики {
                    сообщение: "Недопустимый символ: латиница не разрешена".into(),
                    строка,
                    столбец,
                });
            }
            if Self::это_русская(с) || с == '_' {
                self.продвинуть();
            } else {
                break;
            }
        }
        Ok(self.символы[начало..self.позиция].iter().collect())
    }

    fn распознать_число(&mut self) -> Result<Токен, ОшибкаЛексики> {
        let начало = self.позиция;
        let начало_строка = self.строка;
        let начало_столбец = self.столбец;

        while let Some(с) = self.текущий() {
            if с.is_ascii_digit() {
                self.продвинуть();
            } else {
                break;
            }
        }

        if self.текущий() == Some('.')
            && self.заглянуть(1).map(|с| с.is_ascii_digit()).unwrap_or(false)
        {
            self.продвинуть();
            while let Some(с) = self.текущий() {
                if с.is_ascii_digit() {
                    self.продвинуть();
                } else {
                    break;
                }
            }
            let текст: String = self.символы[начало..self.позиция].iter().collect();
            let значение = текст.parse::<f64>().map_err(|_| ОшибкаЛексики {
                сообщение: format!("Некорректное вещественное число: {}", текст),
                строка: начало_строка,
                столбец: начало_столбец,
            })?;
            return Ok(Токен::Вещественное(значение));
        }

        let текст: String = self.символы[начало..self.позиция].iter().collect();
        let значение = текст.parse::<i64>().map_err(|_| ОшибкаЛексики {
            сообщение: format!("Некорректное целое число: {}", текст),
            строка: начало_строка,
            столбец: начало_столбец,
        })?;
        Ok(Токен::Целое(значение))
    }

    fn распознать_строку(&mut self) -> Result<Токен, ОшибкаЛексики> {
        let начало_строка = self.строка;
        let начало_столбец = self.столбец;
        self.продвинуть(); // "

        let mut результат = String::new();
        loop {
            match self.текущий() {
                Some('"') => {
                    self.продвинуть();
                    return Ok(Токен::Строка(результат));
                }
                Some('\n') | None => {
                    return Err(ОшибкаЛексики {
                        сообщение: "Незакрытая строка".into(),
                        строка: начало_строка,
                        столбец: начало_столбец,
                    });
                }
                Some(с) => {
                    // В строках латиница допустима (имена библиотек и т.п.)
                    результат.push(с);
                    self.продвинуть();
                }
            }
        }
    }

    fn распознать_директиву(&mut self) -> Result<Токен, ОшибкаЛексики> {
        let начало_строка = self.строка;
        let начало_столбец = self.столбец;
        self.продвинуть(); // #

        let mut имя = String::new();
        while let Some(с) = self.текущий() {
            if с.is_ascii_alphabetic() || с == '_' {
                имя.push(с);
                self.продвинуть();
            } else {
                break;
            }
        }

        if имя.is_empty() {
            return Err(ОшибкаЛексики {
                сообщение: "Директива без имени".into(),
                строка: начало_строка,
                столбец: начало_столбец,
            });
        }

        match имя.as_str() {
            "include" | "define" | "link" => Ok(Токен::Директива(имя)),
            _ => Err(ОшибкаЛексики {
                сообщение: format!(
                    "Неизвестная директива '#{}' (допустимы: #include, #define, #link)",
                    имя
                ),
                строка: начало_строка,
                столбец: начало_столбец,
            }),
        }
    }

    /// Ключевые слова → специальные токены; иначе корень/шаблон/слово.
    fn классифицировать_слово(слово: String) -> Токен {
        match слово.as_str() {
            "если" => return Токен::Если,
            "иначе" => return Токен::Иначе,
            "пока" => return Токен::Пока,
            "для" => return Токен::Для,
            "в" => return Токен::В,
            "возврат" => return Токен::Возврат,
            "прервать" => return Токен::Прервать,
            "продолжить" => return Токен::Продолжить,
            "функция" => return Токен::Функция,
            "тип" => return Токен::Тип,
            "модуль" => return Токен::Модуль,
            "импорт" => return Токен::Импорт,
            "печать" => return Токен::Печать,
            "печать_строки" => return Токен::ПечатьСтроки,
            "печать_число" => return Токен::ПечатьЧисло,
            "истина" => return Токен::Истина,
            "ложь" => return Токен::Ложь,
            "и" => return Токен::И,
            "или" => return Токен::Или,
            "не" => return Токен::Не,
            _ => {}
        }

        let символы: Vec<char> = слово.chars().collect();
        if символы.is_empty() {
            return Токен::Слово(слово);
        }

        if символы.iter().any(|с| *с == '_' || с.is_ascii_digit()) {
            return Токен::Слово(слово);
        }

        let заглавная_форма = символы.iter().all(|с| {
            !с.is_lowercase() || Self::это_знак(*с) // ь/ъ не «строчные слова»
        }) && символы.iter().any(|с| с.is_uppercase());

        if !заглавная_форма {
            return Токен::Слово(слово);
        }

        if символы.len() == 3 && символы.iter().all(|с| Self::это_скелетная(*с)) {
            return Токен::Корень(слово);
        }

        // CVCV (4 буквы) — классический мишкаль из спецификации
        if символы.len() == 4
            && Self::это_согласная(символы[0])
            && Self::это_гласная(символы[1])
            && Self::это_согласная(символы[2])
            && Self::это_гласная(символы[3])
        {
            return Токен::Шаблон(слово);
        }

        // САПАР / СИПРА / СПОРО / ЧАТАВ — скелет из 3 + гласные-модификаторы
        let скелет: usize = символы.iter().filter(|с| Self::это_скелетная(**с)).count();
        let есть_модификатор = символы.iter().any(|с| Self::это_полная_гласная(*с));
        if есть_модификатор && скелет == 3 && (4..=6).contains(&символы.len()) {
            return Токен::Шаблон(слово);
        }

        Токен::Слово(слово)
    }

    /// Разобрать исходник → токены с позициями.
    pub fn разобрать(&mut self) -> Result<Vec<ТокенСПозицией>, ОшибкаЛексики> {
        let mut токены = Vec::new();

        loop {
            self.пропустить_пробелы();

            let строка = self.строка;
            let столбец = self.столбец;

            let токен = match self.текущий() {
                None => {
                    токены.push(ТокенСПозицией {
                        токен: Токен::КонецФайла,
                        строка,
                        столбец,
                    });
                    break;
                }

                Some('>') => {
                    self.продвинуть();
                    if self.текущий() == Some('>') {
                        self.продвинуть();
                        if self.текущий() == Some('>') {
                            self.продвинуть();
                            Токен::СетьИмпульс
                        } else {
                            Токен::Импульс
                        }
                    } else if self.текущий() == Some('=') {
                        self.продвинуть();
                        Токен::БольшеРавно
                    } else {
                        Токен::Больше
                    }
                }
                Some('<') => {
                    self.продвинуть();
                    if self.текущий() == Some('=') {
                        self.продвинуть();
                        Токен::МеньшеРавно
                    } else {
                        Токен::Меньше
                    }
                }
                Some('|') => {
                    self.продвинуть();
                    if self.текущий() == Some('|') {
                        self.продвинуть();
                        Токен::Хор
                    } else {
                        return Err(ОшибкаЛексики {
                            сообщение: "Ожидалось '||'".into(),
                            строка,
                            столбец,
                        });
                    }
                }
                Some('!') => {
                    self.продвинуть();
                    if self.текущий() == Some('=') {
                        self.продвинуть();
                        Токен::НеРавно
                    } else {
                        Токен::Фиксация
                    }
                }
                Some('~') => {
                    self.продвинуть();
                    Токен::Поток
                }
                Some('=') => {
                    self.продвинуть();
                    if self.текущий() == Some('=') {
                        self.продвинуть();
                        Токен::РавноРавно
                    } else {
                        Токен::Равно
                    }
                }
                Some(':') => {
                    self.продвинуть();
                    Токен::Двоеточие
                }
                Some('-') => {
                    self.продвинуть();
                    Токен::Дефис
                }
                Some('+') => {
                    self.продвинуть();
                    Токен::Плюс
                }
                Some('*') => {
                    self.продвинуть();
                    Токен::Звезда
                }
                Some('/') => {
                    // `//` уже обработан в пропустить_пробелы; одиночный `/` — деление
                    self.продвинуть();
                    Токен::Слеш
                }
                Some('(') => {
                    self.продвинуть();
                    Токен::СкобкаЛевая
                }
                Some(')') => {
                    self.продвинуть();
                    Токен::СкобкаПравая
                }
                Some('{') => {
                    self.продвинуть();
                    Токен::ФигурнаяЛевая
                }
                Some('}') => {
                    self.продвинуть();
                    Токен::ФигурнаяПравая
                }
                Some(',') => {
                    self.продвинуть();
                    Токен::Запятая
                }
                Some('"') => self.распознать_строку()?,
                Some('#') => self.распознать_директиву()?,
                Some(с) if с.is_ascii_digit() => self.распознать_число()?,
                Some(с) if Self::это_русская(с) => {
                    let слово = self.распознать_слово()?;
                    Self::классифицировать_слово(слово)
                }
                Some(с) if с.is_ascii_alphabetic() => {
                    return Err(ОшибкаЛексики {
                        сообщение: "Недопустимый символ: латиница не разрешена".into(),
                        строка,
                        столбец,
                    });
                }
                Some(с) => {
                    return Err(ОшибкаЛексики {
                        сообщение: format!("Неизвестный символ '{}'", с),
                        строка,
                        столбец,
                    });
                }
            };

            токены.push(ТокенСПозицией {
                токен,
                строка,
                столбец,
            });
        }

        Ok(токены)
    }

    /// Совместимость с парсером.
    pub fn разобрать_с_позициями(&mut self) -> Result<Vec<ПозиционныйТокен>, ОшибкаЛексики> {
        self.разобрать()
    }

    /// Только значения токенов (для простых тестов).
    pub fn разобрать_токены(&mut self) -> Result<Vec<Токен>, ОшибкаЛексики> {
        Ok(self
            .разобрать()?
            .into_iter()
            .map(|т| т.токен)
            .collect())
    }
}

#[cfg(test)]
mod тесты {
    use super::*;

    fn разобрать(исходник: &str) -> Vec<Токен> {
        Лексер::новый(исходник).разобрать_токены().unwrap()
    }

    #[test]
    fn тест_корень() {
        assert_eq!(разобрать("СПР")[0], Токен::Корень("СПР".into()));
    }

    #[test]
    fn тест_шаблон_сапар() {
        assert_eq!(разобрать("САПАР")[0], Токен::Шаблон("САПАР".into()));
    }

    #[test]
    fn тест_шаблон_cvcv() {
        // 4-буквенный мишкаль СГСГ
        assert_eq!(разобрать("САПА")[0], Токен::Шаблон("САПА".into()));
    }

    #[test]
    fn тест_импульс() {
        assert_eq!(разобрать(">>")[0], Токен::Импульс);
    }

    #[test]
    fn тест_сеть_импульс() {
        assert_eq!(разобрать(">>>")[0], Токен::СетьИмпульс);
    }

    #[test]
    fn тест_хор() {
        assert_eq!(разобрать("||")[0], Токен::Хор);
    }

    #[test]
    fn тест_фиксация() {
        assert_eq!(разобрать("!")[0], Токен::Фиксация);
    }

    #[test]
    fn тест_поток() {
        assert_eq!(разобрать("~")[0], Токен::Поток);
    }

    #[test]
    fn тест_целое() {
        assert_eq!(разобрать("42")[0], Токен::Целое(42));
    }

    #[test]
    fn тест_вещественное() {
        assert_eq!(разобрать("3.14")[0], Токен::Вещественное(3.14));
    }

    #[test]
    fn тест_строка() {
        assert_eq!(
            разобрать("\"привет мир\"")[0],
            Токен::Строка("привет мир".into())
        );
    }

    #[test]
    fn тест_комментарий() {
        assert_eq!(
            разобрать("// это комментарий\nСПР")[0],
            Токен::Корень("СПР".into())
        );
    }

    #[test]
    fn тест_директива() {
        assert_eq!(разобрать("#link")[0], Токен::Директива("link".into()));
    }

    #[test]
    fn тест_латиница_запрещена() {
        let ошибка = Лексер::новый("hello").разобрать().unwrap_err();
        assert!(ошибка.сообщение.contains("латиница") || ошибка.сообщение.contains("Латиница"));
    }

    #[test]
    fn тест_полная_программа() {
        let исходник = "СПР = { А-А: САПАР }\nЖАВАТ(1) >> САПАР >> ЧАТАВ!";
        let токены = разобрать(исходник);
        assert!(токены.len() > 10);
        assert!(токены.iter().any(|т| matches!(т, Токен::Дефис)));
    }

    #[test]
    fn тест_позиции() {
        let токены = Лексер::новый("СПР\nЧТВ").разобрать().unwrap();
        assert_eq!(токены[0].строка, 1);
        assert_eq!(токены[1].строка, 2);
    }

    #[test]
    fn тест_смешанный_поток() {
        let токены = разобрать("САПАР(1, 2) >> ЧАТАВ!");
        assert_eq!(токены[0], Токен::Шаблон("САПАР".into()));
        assert_eq!(токены[1], Токен::СкобкаЛевая);
        assert_eq!(токены[2], Токен::Целое(1));
        assert_eq!(токены[3], Токен::Запятая);
        assert_eq!(токены[4], Токен::Целое(2));
        assert_eq!(токены[5], Токен::СкобкаПравая);
        assert_eq!(токены[6], Токен::Импульс);
        assert_eq!(токены[7], Токен::Шаблон("ЧАТАВ".into()));
        assert_eq!(токены[8], Токен::Фиксация);
    }
}

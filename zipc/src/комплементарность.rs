//! Комплементарные корни (Идея 1).
//!
//! Основание: в ДНК A-T, G-C комплементарны. В ZIP каждый корень
//! имеет обратный корень (перестановка крайних согласных).

use crate::лексика::Лексер;
use std::collections::HashMap;

/// Таблица комплементарности: прямой корень ↔ обратный.
///
/// ПРАВИЛО: обратный корень = перестановка 1-й и 3-й согласных.
/// Например: СПР → РПС, ЧТВ → ВТЧ.
pub fn обратный_корень(корень: &str) -> Option<String> {
    let символы: Vec<char> = корень.chars().collect();
    if символы.len() != 3 {
        return None;
    }
    if !символы.iter().all(|с| Лексер::это_согласная_публ(*с)) {
        return None;
    }
    Some(format!("{}{}{}", символы[2], символы[1], символы[0]))
}

/// Смысл обратного / прямого корня (краткая семантика).
pub fn смысл_обратного(корень: &str) -> &'static str {
    match корень {
        "СПР" => "счёт",
        "РПС" => "расчёт (обратный счёт)",
        "ЧТВ" => "запись / чтение памяти",
        "ВТЧ" => "чтение / обратная запись",
        "ЖВТ" => "жизнь / рождение",
        "ТВЖ" => "смерть / завершение",
        "ПХД" => "поток",
        "ДХП" => "остановка",
        "СГН" => "сигнал",
        "НГС" => "тишина",
        "ТРГ" => "торговля",
        "ГРТ" => "отмена сделки",
        "ЦПЬ" => "цепь",
        "ЬПЦ" => "разрыв цепи",
        "СЮЗ" => "связь",
        "ЗЮС" => "разрыв связи",
        "ВДТ" => "видеть",
        "ТДВ" => "скрыть",
        "КРП" => "шифрование",
        "ПРК" => "дешифровка",
        _ => "обратная операция",
    }
}

/// Комплементарный глагол / мишкаль: САПАР → РАПАС.
///
/// Правило: поменять местами первую и последнюю согласные слова
/// (гласные и средние согласные остаются на своих позициях).
pub fn обратный_глагол(глагол: &str) -> Option<String> {
    let mut символы: Vec<char> = глагол.chars().collect();
    if символы.len() < 3 {
        return None;
    }
    let согласные: Vec<usize> = символы
        .iter()
        .enumerate()
        .filter(|(_, с)| Лексер::это_согласная_публ(**с))
        .map(|(i, _)| i)
        .collect();
    if согласные.len() < 2 {
        return None;
    }
    let a = согласные[0];
    let b = *согласные.last().unwrap();
    символы.swap(a, b);
    Some(символы.into_iter().collect())
}

/// Встроенная таблица комплементарных глаголов (двусторонняя).
pub fn таблица_комплементарных() -> HashMap<String, String> {
    let mut map = HashMap::new();

    let глаголы = [
        // СПР
        ("САПАР", "РАПАС"),
        ("СИПРА", "РИПСА"),
        ("СПОРО", "РОПОС"),
        // ЧТВ
        ("ЧАТАВ", "ВАТАЧ"),
        ("ЧИТВА", "ВИТЧА"),
        // ЖВТ
        ("ЖАВАТ", "ТАВАЖ"),
        // ПХД
        ("ПАХАД", "ДАХАП"),
        // СГН
        ("САГАН", "НАГАС"),
        // ТРГ
        ("ТАРАГ", "ГАРАТ"),
        // ЦПЬ / цепь
        ("ЦАПАЬ", "ЬАПАЦ"),
        // СЮЗ
        ("САЯЗ", "ЗАЯС"),
        // ВДТ
        ("ВАДАТ", "ТАДАВ"),
        // КРП
        ("КАРАП", "ПАРАК"),
    ];

    for (прямой, обратный) in глаголы {
        // Предпочитаем алгоритмическую пару, если она строится
        let обр = обратный_глагол(прямой).unwrap_or_else(|| обратный.to_string());
        map.insert(прямой.to_string(), обр.clone());
        map.insert(обр, прямой.to_string());
    }

    map
}

/// Пара (прямой шаблон → обратный) для объявления корня.
pub fn обратные_шаблоны_корня(
    по_типу: &std::collections::HashMap<crate::лексика::ТипШаблона, String>,
) -> Vec<(crate::лексика::ТипШаблона, String)> {
    let mut out = Vec::new();
    for (тип, имя) in по_типу {
        if let Some(обр) = обратный_глагол(имя) {
            out.push((*тип, обр));
        }
    }
    out
}

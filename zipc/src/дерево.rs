//! Абстрактное синтаксическое дерево языка ZIP.

use crate::лексика::ТипШаблона;
use std::collections::HashMap;

/// Аннотация `@имя(...)` (`@пластичность`, `@comptime`, …).
#[derive(Debug, Clone, PartialEq)]
pub struct Аннотация {
    pub имя: String,
    pub параметры: HashMap<String, Узел>,
}

/// R3: один вариант специализированного глагола.
#[derive(Debug, Clone, PartialEq)]
pub struct ВариантГлагола {
    pub типы_параметров: Vec<String>,
    pub тип_возврата: Option<String>,
    pub тело: Box<Узел>,
    pub параметры: Vec<String>,
}

#[derive(Debug, Clone, PartialEq)]
pub enum Узел {
    /// Программа — последовательность объявлений и потоков.
    Программа {
        объявления: Vec<Узел>,
    },

    /// Объявление корня: `СПР = { А-А: САПАР, И-А: СИПРА, … }`.
    ОбъявлениеКорня {
        корень: String,
        /// Ключ шаблона → слово (`"А-А"` → `"САПАР"`).
        шаблоны: Vec<(String, String)>,
        /// Типизированное отображение (Идея 8 — 10 гласных).
        по_типу: HashMap<ТипШаблона, String>,
        /// Идея 1: обратный корень (СПР → РПС), если построен.
        обратный_корень: Option<String>,
        /// Идея 1: комплементарные мишкали `(ТипШаблона, РАПАС)`.
        обратные_шаблоны: Vec<(ТипШаблона, String)>,
    },

    /// Вызов глагола: `САПАР(аргументы)` и цепочка после `>>`.
    ВызовГлагола {
        глагол: String,
        аргументы: Vec<Узел>,
        следующий: Option<Box<Узел>>,
    },

    /// Фиксация PERFECT: `ЧАТАВ!`.
    Фиксация {
        глагол: String,
        данные: Box<Узел>,
    },

    /// Асинхронный поток IMPERFECT: `ЖАВАТ~ { ... }`.
    АсинхронныйПоток {
        глагол: String,
        тело: Box<Узел>,
    },

    /// Параллельный хор: `ветка1 || ветка2 || ветка3`.
    Хор {
        ветки: Vec<Узел>,
    },

    /// Литералы и имена.
    Целое(i64),
    Вещественное(f64),
    Строка(String),
    Идентификатор(String),

    /// Блок `{ ... }`.
    Блок(Vec<Узел>),

    /// FFI: `#link("libp2p") САЯЗ(функция, аргументы)`.
    ВнешнийВызов {
        библиотека: String,
        функция: String,
        аргументы: Vec<Узел>,
    },

    /// Нативный runtime: `#runtime("bench_gemm")` → clang -O3 по C-зеркалу STD.
    Runtime {
        имя: String,
    },

    // --- Управление потоком ---
    Если {
        условие: Box<Узел>,
        тогда: Box<Узел>,
        иначе: Option<Box<Узел>>,
    },
    Пока {
        условие: Box<Узел>,
        тело: Box<Узел>,
    },
    /// Цикл `для x в 0..N` (коллекция — `Диапазон`).
    Для {
        переменная: String,
        коллекция: Box<Узел>,
        тело: Box<Узел>,
    },
    /// Цикл `для x в СЫПРА(...)` / итератор коллекции (Идея 11).
    ДляИтератор {
        переменная: String,
        итератор: Box<Узел>,
        тело: Box<Узел>,
    },
    /// Диапазон `начало..конец` (полуинтервал [начало, конец)).
    Диапазон {
        начало: Box<Узел>,
        конец: Box<Узел>,
    },
    Возврат(Option<Box<Узел>>),
    Прервать,
    Продолжить,

    // --- Определения и вызовы ---
    ОпределениеФункции {
        имя: String,
        параметры: Vec<(String, String)>, // (имя, тип)
        тип_возврата: Option<String>,
        тело: Box<Узел>,
        /// Аннотации перед `функция` (напр. `@пластичность(порог = 100)`).
        аннотации: Vec<Аннотация>,
        /// R6: объявление без тела — внешняя/перегруженная FFI-функция.
        внешняя: bool,
        /// R6: библиотека из предшествующего `#link("...")`.
        библиотека: Option<String>,
    },
    /// R6: `#link("lib")` без вызова — контекст для последующих внешних функций.
    СвязатьБиблиотеку {
        имя: String,
    },
    /// R3: несколько реализаций одного глагола по типам аргументов.
    СпециализацияГлагола {
        имя: String,
        варианты: Vec<ВариантГлагола>,
    },
    /// Идея 16: декларативный поток данных.
    ПотокДанных {
        имя: String,
        источник: Box<Узел>,
        /// Имена фильтров (для отладки) + выражения преобразований.
        преобразования: Vec<(String, Узел)>,
        приёмник: Box<Узел>,
    },
    /// Идея 17: автономный агент с состоянием.
    Агент {
        имя: String,
        /// (имя, тип, начальное значение)
        состояние: Vec<(String, String, Box<Узел>)>,
        методы: Vec<Узел>,
    },
    /// Идея 17: `реагировать(событие) { … }` / реакция в теле.
    Реагировать {
        событие: Box<Узел>,
        тело: Option<Box<Узел>>,
    },
    /// Идея 17: `отправить("…")`.
    Отправить {
        сообщение: Box<Узел>,
    },
    /// Идея 17: `объект.поле`.
    ДоступКПолю {
        объект: Box<Узел>,
        поле: String,
    },
    /// Идея 17: `объект.метод(аргументы)`.
    ВызовМетода {
        объект: Box<Узел>,
        метод: String,
        аргументы: Vec<Узел>,
    },
    ВызовФункции {
        имя: String,
        аргументы: Vec<Узел>,
    },

    // --- Логика и сравнения ---
    ЛогическоеИ(Box<Узел>, Box<Узел>),
    ЛогическоеИли(Box<Узел>, Box<Узел>),
    ЛогическоеНе(Box<Узел>),
    Сравнение {
        оператор: String,
        левый: Box<Узел>,
        правый: Box<Узел>,
    },
    Истина,
    Ложь,

    // Идеи 14–15: размеченные объединения
    Нечто {
        значение: Box<Узел>,
    },
    Ничто,
    Успех {
        значение: Box<Узел>,
    },
    Ошибка {
        значение: Box<Узел>,
    },
    /// Проверка: `выражение — Тип` (Нечто / Ничто / Успех / Ошибка)
    ПроверкаТипа {
        выражение: Box<Узел>,
        тип: String,
    },

    // --- Арифметика и присваивание ---
    БинарнаяОперация {
        оператор: String,
        левый: Box<Узел>,
        правый: Box<Узел>,
    },
    УнарныйМинус(Box<Узел>),
    Присваивание {
        имя: String,
        значение: Box<Узел>,
    },
}

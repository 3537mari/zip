//! Абстрактное синтаксическое дерево языка ZIP.

use crate::лексика::ТипШаблона;
use std::collections::HashMap;

/// Аннотация `@имя(...)` (`@пластичность`, `@comptime`, …).
#[derive(Debug, Clone, PartialEq)]
pub struct Аннотация {
    pub имя: String,
    pub параметры: HashMap<String, Узел>,
}

#[derive(Debug, Clone, PartialEq)]
pub enum Узел {
    /// Программа — последовательность объявлений и потоков.
    Программа {
        объявления: Vec<Узел>,
    },

    /// Объявление корня: `СПР = { А-А: САПАР, И-А: СИПРА, … }`.
    ОбъявлениеКорня {
        корень: String,
        /// Ключ шаблона → слово (`"А-А"` → `"САПАР"`).
        шаблоны: Vec<(String, String)>,
        /// Типизированное отображение (Идея 8 — 10 гласных).
        по_типу: HashMap<ТипШаблона, String>,
        /// Идея 1: обратный корень (СПР → РПС), если построен.
        обратный_корень: Option<String>,
        /// Идея 1: комплементарные мишкали `(ТипШаблона, РАПАС)`.
        обратные_шаблоны: Vec<(ТипШаблона, String)>,
    },

    /// Вызов глагола: `САПАР(аргументы)` и цепочка после `>>`.
    ВызовГлагола {
        глагол: String,
        аргументы: Vec<Узел>,
        следующий: Option<Box<Узел>>,
    },

    /// Фиксация PERFECT: `ЧАТАВ!`.
    Фиксация {
        глагол: String,
        данные: Box<Узел>,
    },

    /// Асинхронный поток IMPERFECT: `ЖАВАТ~ { ... }`.
    АсинхронныйПоток {
        глагол: String,
        тело: Box<Узел>,
    },

    /// Параллельный хор: `ветка1 || ветка2 || ветка3`.
    Хор {
        ветки: Vec<Узел>,
    },

    /// Литералы и имена.
    Целое(i64),
    Вещественное(f64),
    Строка(String),
    Идентификатор(String),

    /// Блок `{ ... }`.
    Блок(Vec<Узел>),

    /// FFI: `#link("libp2p") САЯЗ(функция, аргументы)`.
    ВнешнийВызов {
        библиотека: String,
        функция: String,
        аргументы: Vec<Узел>,
    },

    /// Нативный runtime: `#runtime("bench_gemm")` → clang -O3 по C-зеркалу STD.
    Runtime {
        имя: String,
    },

    // --- Управление потоком ---
    Если {
        условие: Box<Узел>,
        тогда: Box<Узел>,
        иначе: Option<Box<Узел>>,
    },
    Пока {
        условие: Box<Узел>,
        тело: Box<Узел>,
    },
    /// Цикл `для x в 0..N` (коллекция — `Диапазон`).
    Для {
        переменная: String,
        коллекция: Box<Узел>,
        тело: Box<Узел>,
    },
    /// Цикл `для x в СЫПРА(...)` / итератор коллекции (Идея 11).
    ДляИтератор {
        переменная: String,
        итератор: Box<Узел>,
        тело: Box<Узел>,
    },
    /// Диапазон `начало..конец` (полуинтервал [начало, конец)).
    Диапазон {
        начало: Box<Узел>,
        конец: Box<Узел>,
    },
    Возврат(Option<Box<Узел>>),
    Прервать,
    Продолжить,

    // --- Определения и вызовы ---
    ОпределениеФункции {
        имя: String,
        параметры: Vec<(String, String)>, // (имя, тип)
        тип_возврата: Option<String>,
        тело: Box<Узел>,
        /// Аннотации перед `функция` (напр. `@пластичность(порог = 100)`).
        аннотации: Vec<Аннотация>,
    },
    ВызовФункции {
        имя: String,
        аргументы: Vec<Узел>,
    },

    // --- Логика и сравнения ---
    ЛогическоеИ(Box<Узел>, Box<Узел>),
    ЛогическоеИли(Box<Узел>, Box<Узел>),
    ЛогическоеНе(Box<Узел>),
    Сравнение {
        оператор: String,
        левый: Box<Узел>,
        правый: Box<Узел>,
    },
    Истина,
    Ложь,

    // --- Арифметика и присваивание ---
    БинарнаяОперация {
        оператор: String,
        левый: Box<Узел>,
        правый: Box<Узел>,
    },
    УнарныйМинус(Box<Узел>),
    Присваивание {
        имя: String,
        значение: Box<Узел>,
    },
}

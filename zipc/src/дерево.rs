//! Абстрактное синтаксическое дерево языка ZIP.

#[derive(Debug, Clone, PartialEq)]
pub enum Узел {
    /// Программа — последовательность объявлений и потоков.
    Программа {
        объявления: Vec<Узел>,
    },

    /// Объявление корня: `СПР = { А-А: САПАР, И-А: СИПРА }`.
    ОбъявлениеКорня {
        корень: String,
        шаблоны: Vec<(String, String)>, // (имя шаблона, слово)
    },

    /// Вызов глагола: `САПАР(аргументы)` и цепочка после `>>`.
    ВызовГлагола {
        глагол: String,
        аргументы: Vec<Узел>,
        следующий: Option<Box<Узел>>,
    },

    /// Фиксация PERFECT: `ЧАТАВ!`.
    Фиксация {
        глагол: String,
        данные: Box<Узел>,
    },

    /// Асинхронный поток IMPERFECT: `ЖАВАТ~ { ... }`.
    АсинхронныйПоток {
        глагол: String,
        тело: Box<Узел>,
    },

    /// Параллельный хор: `ветка1 || ветка2 || ветка3`.
    Хор {
        ветки: Vec<Узел>,
    },

    /// Литералы и имена.
    Целое(i64),
    Вещественное(f64),
    Строка(String),
    Идентификатор(String),

    /// Блок `{ ... }`.
    Блок(Vec<Узел>),

    /// FFI: `#link("libp2p") САЯЗ(функция, аргументы)`.
    ВнешнийВызов {
        библиотека: String,
        функция: String,
        аргументы: Vec<Узел>,
    },
}
